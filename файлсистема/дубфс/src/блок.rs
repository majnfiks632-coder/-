// Блочное устройство — нижний слой ДубФС.
//
// Предоставляет два вида устройств:
//   * `БлокУстройство` — трейт, который реализуют все драйверы;
//   * `БлокУстройствоВПамяти` — ОЗУ-имитация для тестов.
//
// Размер блока для ДубФС — 4096 байт. Это значение зашито в суперблок и
// проверяется при монтировании.

use alloc::vec;
use alloc::vec::Vec;
use core::cell::RefCell;

use crate::ошибки::ОшибкаВвода;

/// Размер блока ДубФС по умолчанию.
pub const РАЗМЕР_БЛОКА: usize = 4096;

/// Универсальный интерфейс блочного устройства.
///
/// Все методы работают с блоками целиком: ни байт меньше, ни байт больше.
/// Это сильно упрощает запись журнала, потому что не нужно беспокоиться о
/// частичных записях.
///
/// Реализации обязаны быть «синхронными» — после возврата из `записать_блок`
/// данные должны быть доставлены до контроллера; если есть кэш записи, его
/// нужно сбрасывать в `синхронизировать`.
pub trait БлокУстройство {
    /// Размер блока в байтах. Должен быть кратен 512.
    fn размер_блока(&self) -> usize;

    /// Сколько блоков помещается на устройстве.
    fn всего_блоков(&self) -> u64;

    /// Прочитать целый блок.
    fn прочитать_блок(&self, номер: u64, буфер: &mut [u8]) -> Result<(), ОшибкаВвода>;

    /// Записать целый блок.
    fn записать_блок(&self, номер: u64, данные: &[u8]) -> Result<(), ОшибкаВвода>;

    /// Сбросить буферы. Вызывается после ПОДТВЕРЖДЕНИЯ транзакции и при размонтировании.
    fn синхронизировать(&self) -> Result<(), ОшибкаВвода>;
}

/// ОЗУ-имитация блочного устройства, удобная для тестов.
///
/// Внутри хранит весь диск как `Vec<u8>` за `RefCell`, чтобы и `&self`
/// функции могли писать (как у настоящих устройств).
pub struct БлокУстройствоВПамяти {
    байт_на_блок: usize,
    блоков: u64,
    данные: RefCell<Vec<u8>>,
    /// Счётчики обращений: полезны для тестирования журналирования и
    /// для оценки того, не делает ли алгоритм лишних обращений к диску.
    pub чтений: RefCell<u64>,
    pub записей: RefCell<u64>,
    pub синхронизаций: RefCell<u64>,
}

impl БлокУстройствоВПамяти {
    pub fn новое(блоков: u64) -> Self {
        Self::с_размером_блока(блоков, РАЗМЕР_БЛОКА)
    }

    pub fn с_размером_блока(блоков: u64, размер_блока: usize) -> Self {
        assert!(размер_блока >= 512 && размер_блока.is_power_of_two());
        let размер = (блоков as usize)
            .checked_mul(размер_блока)
            .expect("размер диска переполняет usize");
        Self {
            байт_на_блок: размер_блока,
            блоков,
            данные: RefCell::new(vec![0u8; размер]),
            чтений: RefCell::new(0),
            записей: RefCell::new(0),
            синхронизаций: RefCell::new(0),
        }
    }

    /// Снять копию состояния (полезно для тестов восстановления после сбоя).
    pub fn снимок(&self) -> Vec<u8> {
        self.данные.borrow().clone()
    }

    /// Восстановить ранее снятое состояние.
    pub fn восстановить(&self, снимок: &[u8]) {
        let mut д = self.данные.borrow_mut();
        assert_eq!(снимок.len(), д.len(), "размер снимка не совпадает с размером диска");
        д.copy_from_slice(снимок);
    }

    fn проверить_номер(&self, номер: u64) -> Result<(), ОшибкаВвода> {
        if номер >= self.блоков {
            Err(ОшибкаВвода::НесуществующийБлок)
        } else {
            Ok(())
        }
    }
}

impl БлокУстройство for БлокУстройствоВПамяти {
    fn размер_блока(&self) -> usize {
        self.байт_на_блок
    }

    fn всего_блоков(&self) -> u64 {
        self.блоков
    }

    fn прочитать_блок(&self, номер: u64, буфер: &mut [u8]) -> Result<(), ОшибкаВвода> {
        self.проверить_номер(номер)?;
        if буфер.len() != self.байт_на_блок {
            return Err(ОшибкаВвода::ОшибкаЧтения);
        }
        let начало = (номер as usize) * self.байт_на_блок;
        буфер.copy_from_slice(&self.данные.borrow()[начало..начало + self.байт_на_блок]);
        *self.чтений.borrow_mut() += 1;
        Ok(())
    }

    fn записать_блок(&self, номер: u64, данные: &[u8]) -> Result<(), ОшибкаВвода> {
        self.проверить_номер(номер)?;
        if данные.len() != self.байт_на_блок {
            return Err(ОшибкаВвода::ОшибкаЗаписи);
        }
        let начало = (номер as usize) * self.байт_на_блок;
        self.данные.borrow_mut()[начало..начало + self.байт_на_блок].copy_from_slice(данные);
        *self.записей.borrow_mut() += 1;
        Ok(())
    }

    fn синхронизировать(&self) -> Result<(), ОшибкаВвода> {
        *self.синхронизаций.borrow_mut() += 1;
        Ok(())
    }
}

#[cfg(test)]
mod тесты {
    use super::*;

    #[test]
    fn чтение_возвращает_то_что_записали() {
        let устройство = БлокУстройствоВПамяти::новое(8);
        let мои_данные = [42u8; РАЗМЕР_БЛОКА];
        устройство.записать_блок(3, &мои_данные).unwrap();

        let mut буфер = [0u8; РАЗМЕР_БЛОКА];
        устройство.прочитать_блок(3, &mut буфер).unwrap();
        assert_eq!(буфер, мои_данные);
    }

    #[test]
    fn неверный_номер_блока_отвергается() {
        let устройство = БлокУстройствоВПамяти::новое(4);
        let mut буфер = [0u8; РАЗМЕР_БЛОКА];
        let итог = устройство.прочитать_блок(4, &mut буфер);
        assert!(matches!(итог, Err(ОшибкаВвода::НесуществующийБлок)));
    }

    #[test]
    fn снимок_и_восстановление() {
        let устройство = БлокУстройствоВПамяти::новое(4);
        устройство.записать_блок(0, &[1u8; РАЗМЕР_БЛОКА]).unwrap();
        let снимок = устройство.снимок();
        устройство.записать_блок(0, &[2u8; РАЗМЕР_БЛОКА]).unwrap();
        устройство.восстановить(&снимок);
        let mut буфер = [0u8; РАЗМЕР_БЛОКА];
        устройство.прочитать_блок(0, &mut буфер).unwrap();
        assert_eq!(буфер, [1u8; РАЗМЕР_БЛОКА]);
    }
}
