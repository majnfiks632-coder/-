use core::fmt;

/// Общая ошибка ДубФС. Обёрткой над несколькими источниками.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ОшибкаФС {
    /// Ошибка ввода-вывода блочного устройства: неверный номер блока,
    /// устройство «отвалилось» и т.п.
    Ввод(ОшибкаВвода),
    /// На диске нет свободных блоков.
    НетСвободныхБлоков,
    /// На диске нет свободных inodes.
    НетСвободныхИнодов,
    /// Неверная магия суперблока.
    НеДубФС,
    /// Несовместимая версия on-disk формата.
    НесовместимаяВерсия { ожидалась: u32, найдена: u32 },
    /// Контрольная сумма блока не совпала.
    КонтрольнаяСумма { блок: u64 },
    /// Журнал повреждён (битый заголовок, нет ПОДТВЕРЖДЕНИЯ).
    ЖурналПовреждён,
    /// Журнал слишком мал для очередной транзакции.
    ЖурналПереполнен,
    /// Запрошенная запись не найдена в каталоге.
    НеНайдено,
    /// Запись с таким именем уже есть.
    УжеСуществует,
    /// Тип inode не соответствует операции (например, чтение каталога как файл).
    НеверныйТип,
    /// Каталог не пуст и удалить его нельзя.
    КаталогНеПуст,
    /// Имя файла слишком длинное (>255 байт UTF-8).
    ИмяСлишкомДлинное,
    /// Запрошенное смещение за пределами файла.
    ВнеДиапазона,
    /// Файл слишком велик для текущей схемы (превышены прямые/косвенные блоки).
    ФайлСлишкомВелик,
    /// Внутренняя инвариантная ошибка (баг). Сообщает строкой.
    Внутренняя(&'static str),
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ОшибкаВвода {
    НесуществующийБлок,
    ОшибкаЧтения,
    ОшибкаЗаписи,
}

impl fmt::Display for ОшибкаФС {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            ОшибкаФС::Ввод(в) => write!(f, "ошибка устройства: {}", в),
            ОшибкаФС::НетСвободныхБлоков => write!(f, "нет свободных блоков на диске"),
            ОшибкаФС::НетСвободныхИнодов => write!(f, "нет свободных inodes"),
            ОшибкаФС::НеДубФС => write!(f, "это не ДубФС (магия суперблока не совпадает)"),
            ОшибкаФС::НесовместимаяВерсия { ожидалась, найдена } => {
                write!(f, "несовместимая версия диска: ожидалась {}, найдена {}", ожидалась, найдена)
            }
            ОшибкаФС::КонтрольнаяСумма { блок } => write!(f, "контрольная сумма блока {} не совпала", блок),
            ОшибкаФС::ЖурналПовреждён => write!(f, "журнал повреждён"),
            ОшибкаФС::ЖурналПереполнен => write!(f, "журнал переполнен — увеличьте `СБ.журнал_длина`"),
            ОшибкаФС::НеНайдено => write!(f, "запись не найдена"),
            ОшибкаФС::УжеСуществует => write!(f, "запись с таким именем уже существует"),
            ОшибкаФС::НеверныйТип => write!(f, "тип inode не соответствует операции"),
            ОшибкаФС::КаталогНеПуст => write!(f, "каталог не пуст"),
            ОшибкаФС::ИмяСлишкомДлинное => write!(f, "имя файла слишком длинное"),
            ОшибкаФС::ВнеДиапазона => write!(f, "смещение вне диапазона файла"),
            ОшибкаФС::ФайлСлишкомВелик => write!(f, "файл слишком велик для текущей схемы"),
            ОшибкаФС::Внутренняя(сообщение) => write!(f, "внутренняя ошибка ДубФС: {}", сообщение),
        }
    }
}

impl fmt::Display for ОшибкаВвода {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            ОшибкаВвода::НесуществующийБлок => write!(f, "номер блока вне границ устройства"),
            ОшибкаВвода::ОшибкаЧтения => write!(f, "ошибка чтения блока"),
            ОшибкаВвода::ОшибкаЗаписи => write!(f, "ошибка записи блока"),
        }
    }
}

impl From<ОшибкаВвода> for ОшибкаФС {
    fn from(в: ОшибкаВвода) -> Self {
        ОшибкаФС::Ввод(в)
    }
}

pub type Резюме<Т> = Result<Т, ОшибкаФС>;
