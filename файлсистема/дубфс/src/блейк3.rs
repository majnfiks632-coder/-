// BLAKE3-256 — переносимая референсная реализация (no_std, без unsafe).
//
// Цель: дать ДубФС криптостойкую (в смысле столкновений) контрольную
// сумму, не таща в ядро внешний крейт со SIMD/asm. Реализация
// соответствует официальной спецификации BLAKE3 v1.0:
// https://github.com/BLAKE3-team/BLAKE3-specs/blob/master/blake3.pdf
//
// Поддерживается весь обязательный путь: дерево чанков по 1024 байта,
// 8 раундов сжимающей функции с перестановкой, флаги CHUNK_START /
// CHUNK_END / PARENT / ROOT. KDF и keyed-hash здесь не реализованы —
// они файловой системе не нужны.
//
// Всё операции — на u32-словах, little-endian. Без heap-аллокаций
// сверх внутреннего стека дерева (максимум 54 узла = ~2 КиБ в стеке).

#![allow(clippy::needless_range_loop)]

/// Длина выхода в байтах: 256-битный хеш = 32 байта.
pub const ДЛИНА_ВЫХОДА: usize = 32;

/// Длина одного блока компрессии (внутренняя единица сжатия).
const ДЛИНА_БЛОКА: usize = 64;
/// Длина чанка (16 блоков).
const ДЛИНА_ЧАНКА: usize = 1024;

const CHUNK_START: u32 = 1 << 0;
const CHUNK_END: u32 = 1 << 1;
const PARENT: u32 = 1 << 2;
const ROOT: u32 = 1 << 3;

/// Стандартные начальные значения BLAKE3 (совпадают с IV SHA-256).
const IV: [u32; 8] = [
    0x6A09_E667, 0xBB67_AE85, 0x3C6E_F372, 0xA54F_F53A,
    0x510E_527F, 0x9B05_688C, 0x1F83_D9AB, 0x5BE0_CD19,
];

/// Перестановка слов сообщения между раундами.
const MSG_PERMUTATION: [usize; 16] = [2, 6, 3, 10, 7, 0, 4, 13, 1, 11, 12, 5, 9, 14, 15, 8];

/// G-функция (микс четырёх слов).
#[inline(always)]
fn g(s: &mut [u32; 16], a: usize, b: usize, c: usize, d: usize, mx: u32, my: u32) {
    s[a] = s[a].wrapping_add(s[b]).wrapping_add(mx);
    s[d] = (s[d] ^ s[a]).rotate_right(16);
    s[c] = s[c].wrapping_add(s[d]);
    s[b] = (s[b] ^ s[c]).rotate_right(12);
    s[a] = s[a].wrapping_add(s[b]).wrapping_add(my);
    s[d] = (s[d] ^ s[a]).rotate_right(8);
    s[c] = s[c].wrapping_add(s[d]);
    s[b] = (s[b] ^ s[c]).rotate_right(7);
}

/// Один раунд из 8 G-вызовов: 4 «по столбцам», 4 «по диагоналям».
#[inline(always)]
fn раунд(s: &mut [u32; 16], m: &[u32; 16]) {
    g(s, 0, 4, 8, 12, m[0], m[1]);
    g(s, 1, 5, 9, 13, m[2], m[3]);
    g(s, 2, 6, 10, 14, m[4], m[5]);
    g(s, 3, 7, 11, 15, m[6], m[7]);
    g(s, 0, 5, 10, 15, m[8], m[9]);
    g(s, 1, 6, 11, 12, m[10], m[11]);
    g(s, 2, 7, 8, 13, m[12], m[13]);
    g(s, 3, 4, 9, 14, m[14], m[15]);
}

/// Перестановка слов сообщения для следующего раунда.
#[inline(always)]
fn переставить(m: &[u32; 16]) -> [u32; 16] {
    let mut новое = [0u32; 16];
    for i in 0..16 {
        новое[i] = m[MSG_PERMUTATION[i]];
    }
    новое
}

/// Сжимающая функция BLAKE3.
///
/// Вход:
///   * `cv` — текущее цепочечное значение (8 слов);
///   * `block` — 16 слов блока;
///   * `counter` — счётчик чанка;
///   * `block_len` — реальная длина блока в байтах (1..=64);
///   * `flags` — комбинация CHUNK_START / CHUNK_END / PARENT / ROOT.
///
/// Возвращает все 16 слов после 7 раундов и финального XOR.
fn сжать(
    cv: &[u32; 8],
    block: &[u32; 16],
    counter: u64,
    block_len: u32,
    flags: u32,
) -> [u32; 16] {
    let mut s: [u32; 16] = [
        cv[0], cv[1], cv[2], cv[3],
        cv[4], cv[5], cv[6], cv[7],
        IV[0], IV[1], IV[2], IV[3],
        counter as u32,
        (counter >> 32) as u32,
        block_len,
        flags,
    ];
    let mut m = *block;
    раунд(&mut s, &m); m = переставить(&m); // 1
    раунд(&mut s, &m); m = переставить(&m); // 2
    раунд(&mut s, &m); m = переставить(&m); // 3
    раунд(&mut s, &m); m = переставить(&m); // 4
    раунд(&mut s, &m); m = переставить(&m); // 5
    раунд(&mut s, &m); m = переставить(&m); // 6
    раунд(&mut s, &m);                      // 7

    for i in 0..8 {
        s[i] ^= s[i + 8];
        s[i + 8] ^= cv[i];
    }
    s
}

/// Прочитать 64 байта блока как 16 u32 в little-endian.
#[inline]
fn слова_блока(block: &[u8; ДЛИНА_БЛОКА]) -> [u32; 16] {
    let mut слова = [0u32; 16];
    for i in 0..16 {
        слова[i] = u32::from_le_bytes(
            block[i * 4..(i + 1) * 4].try_into().unwrap()
        );
    }
    слова
}

/// Вычислить корневой выход дерева — это «root output» BLAKE3:
/// первые 32 байта (8 слов) выхода последней сжимающей функции с
/// флагом ROOT.
fn корневой_хеш(
    cv: &[u32; 8],
    block: &[u32; 16],
    counter: u64,
    block_len: u32,
    flags: u32,
) -> [u8; ДЛИНА_ВЫХОДА] {
    let s = сжать(cv, block, counter, block_len, flags | ROOT);
    let mut выход = [0u8; ДЛИНА_ВЫХОДА];
    for i in 0..8 {
        выход[i * 4..(i + 1) * 4].copy_from_slice(&s[i].to_le_bytes());
    }
    выход
}

/// «Не корневое» цепочечное значение чанка/родителя — первые 8 слов
/// после сжимающей функции без флага ROOT.
fn нерутовый_cv(
    cv: &[u32; 8],
    block: &[u32; 16],
    counter: u64,
    block_len: u32,
    flags: u32,
) -> [u32; 8] {
    let s = сжать(cv, block, counter, block_len, flags);
    [s[0], s[1], s[2], s[3], s[4], s[5], s[6], s[7]]
}

/// Состояние одного чанка. Чанк может быть длиной от 0 до 1024 байт.
struct СостояниеЧанка {
    cv: [u32; 8],
    /// Сколько блоков уже сжато в этом чанке (0..16).
    обработано_блоков: u32,
    /// Накопленный «хвостовой» блок (последние 0..64 байт).
    буфер: [u8; ДЛИНА_БЛОКА],
    в_буфере: usize,
    /// Номер чанка в дереве — счётчик BLAKE3.
    номер: u64,
}

impl СостояниеЧанка {
    fn новый(номер: u64) -> Self {
        Self {
            cv: IV,
            обработано_блоков: 0,
            буфер: [0u8; ДЛИНА_БЛОКА],
            в_буфере: 0,
            номер,
        }
    }

    fn длина(&self) -> usize {
        self.обработано_блоков as usize * ДЛИНА_БЛОКА + self.в_буфере
    }

    fn флаг_старт(&self) -> u32 {
        if self.обработано_блоков == 0 {
            CHUNK_START
        } else {
            0
        }
    }

    /// Дописать байты в чанк. Возможны переполнения буфера —
    /// когда буфер заполняется на 64 байта, мы сжимаем его как
    /// внутренний (не хвостовой) блок. Хвостовой блок останется
    /// в буфере до finalize.
    fn обновить(&mut self, mut вход: &[u8]) {
        while !вход.is_empty() {
            // Если буфер уже полон — сначала сжать его как внутренний блок.
            if self.в_буфере == ДЛИНА_БЛОКА {
                let слова = слова_блока(&self.буфер);
                let флаги = self.флаг_старт();
                self.cv = нерутовый_cv(&self.cv, &слова, self.номер, ДЛИНА_БЛОКА as u32, флаги);
                self.обработано_блоков += 1;
                self.в_буфере = 0;
                self.буфер = [0u8; ДЛИНА_БЛОКА];
            }
            let можно = ДЛИНА_БЛОКА - self.в_буфере;
            let n = можно.min(вход.len());
            self.буфер[self.в_буфере..self.в_буфере + n].copy_from_slice(&вход[..n]);
            self.в_буфере += n;
            вход = &вход[n..];
        }
    }

    /// Получить нерутовое CV всего чанка. Используется, когда в дереве
    /// есть и другие чанки/родители, и этот чанк не финальный.
    fn нерутовый_cv(&self) -> [u32; 8] {
        let слова = слова_блока(&self.буфер);
        let флаги = self.флаг_старт() | CHUNK_END;
        нерутовый_cv(&self.cv, &слова, self.номер, self.в_буфере as u32, флаги)
    }

    /// Получить корневой выход — если чанк единственный в дереве.
    fn корневой_хеш(&self) -> [u8; ДЛИНА_ВЫХОДА] {
        let слова = слова_блока(&self.буфер);
        let флаги = self.флаг_старт() | CHUNK_END;
        корневой_хеш(&self.cv, &слова, self.номер, self.в_буфере as u32, флаги)
    }
}

/// Собрать «родительский» блок из двух CV (восемь + восемь слов).
fn родительский_блок(левый: &[u32; 8], правый: &[u32; 8]) -> [u32; 16] {
    let mut m = [0u32; 16];
    m[..8].copy_from_slice(левый);
    m[8..].copy_from_slice(правый);
    m
}

/// Нерутовое CV родителя двух поддеревьев.
fn нерутовый_родитель(левый: &[u32; 8], правый: &[u32; 8]) -> [u32; 8] {
    let m = родительский_блок(левый, правый);
    нерутовый_cv(&IV, &m, 0, ДЛИНА_БЛОКА as u32, PARENT)
}

/// Корневой родитель — корень дерева, если у нас больше одного чанка.
fn корневой_родитель(левый: &[u32; 8], правый: &[u32; 8]) -> [u8; ДЛИНА_ВЫХОДА] {
    let m = родительский_блок(левый, правый);
    корневой_хеш(&IV, &m, 0, ДЛИНА_БЛОКА as u32, PARENT)
}

/// Хешер с потоковым API. После создания вызывайте `обновить` нужное
/// количество раз и затем `финализировать` — получите 32 байта.
pub struct Хешер {
    /// Стек CV поддеревьев. Размер 54 — теоретический максимум для
    /// 2^64 чанков (на практике меньше), хватает с большим запасом.
    стек: [[u32; 8]; 54],
    глубина_стека: usize,
    /// Текущий чанк, в который дописываются байты.
    чанк: СостояниеЧанка,
    /// Сколько чанков уже завершено и сложено в стек.
    готовых_чанков: u64,
}

impl Хешер {
    pub fn новый() -> Self {
        Self {
            стек: [[0u32; 8]; 54],
            глубина_стека: 0,
            чанк: СостояниеЧанка::новый(0),
            готовых_чанков: 0,
        }
    }

    /// Свернуть стек: пока количество готовых чанков делится на 2 —
    /// сжимаем верхние две вершины в одного родителя. Это и есть
    /// механика «бинарного счётчика», описанная в спецификации.
    fn свернуть_стек(&mut self, новое_всего: u64) {
        let mut всего = новое_всего;
        while всего & 1 == 0 {
            // Объединяем верхние два CV в стеке.
            let правый = self.стек[self.глубина_стека - 1];
            let левый = self.стек[self.глубина_стека - 2];
            let родитель = нерутовый_родитель(&левый, &правый);
            self.глубина_стека -= 2;
            self.стек[self.глубина_стека] = родитель;
            self.глубина_стека += 1;
            всего >>= 1;
        }
    }

    pub fn обновить(&mut self, mut данные: &[u8]) {
        while !данные.is_empty() {
            // Если текущий чанк заполнен — закрываем его, кладём CV в стек,
            // открываем следующий.
            if self.чанк.длина() == ДЛИНА_ЧАНКА {
                let cv = self.чанк.нерутовый_cv();
                self.стек[self.глубина_стека] = cv;
                self.глубина_стека += 1;
                self.готовых_чанков += 1;
                self.свернуть_стек(self.готовых_чанков);
                self.чанк = СостояниеЧанка::новый(self.готовых_чанков);
            }
            let можно = ДЛИНА_ЧАНКА - self.чанк.длина();
            let n = можно.min(данные.len());
            self.чанк.обновить(&данные[..n]);
            данные = &данные[n..];
        }
    }

    /// Завершить хеш и получить 32 байта результата.
    pub fn финализировать(&self) -> [u8; ДЛИНА_ВЫХОДА] {
        // Если в стеке нет ничего — корень это сам чанк (возможно пустой).
        if self.глубина_стека == 0 {
            return self.чанк.корневой_хеш();
        }

        // Иначе самый правый элемент дерева — это либо CV текущего чанка
        // (если в нём есть данные), либо последний CV из стека. Идём
        // вверх по стеку, объединяя пары PARENT-узлов; самый верх —
        // это уже ROOT-родитель.
        let (правый_хвост, mut осталось_в_стеке) = if self.чанк.длина() > 0 {
            (self.чанк.нерутовый_cv(), self.глубина_стека)
        } else {
            // Текущий чанк пуст: возьмём вершину стека как «правый хвост».
            (self.стек[self.глубина_стека - 1], self.глубина_стека - 1)
        };

        // Сворачиваем оставшийся стек справа налево.
        let mut правый = правый_хвост;
        while осталось_в_стеке > 1 {
            let левый = self.стек[осталось_в_стеке - 1];
            правый = нерутовый_родитель(&левый, &правый);
            осталось_в_стеке -= 1;
        }
        // Самый верхний родитель — корневой.
        let левый = self.стек[0];
        корневой_родитель(&левый, &правый)
    }
}

impl Default for Хешер {
    fn default() -> Self {
        Self::новый()
    }
}

/// Удобный one-shot: BLAKE3-хеш всех данных за один вызов.
pub fn хеш(данные: &[u8]) -> [u8; ДЛИНА_ВЫХОДА] {
    let mut h = Хешер::новый();
    h.обновить(данные);
    h.финализировать()
}

#[cfg(test)]
mod тесты {
    use super::*;

    /// Известные тестовые векторы из официального файла test_vectors.json.
    /// Берём только первые 32 байта (DEFAULT_OUTPUT_LEN) и hex-декодируем
    /// здесь же, чтобы не тащить hex-крейт.
    fn hex_to_bytes(s: &str) -> [u8; 32] {
        let s = s.as_bytes();
        let mut out = [0u8; 32];
        for i in 0..32 {
            let hi = (s[2 * i] as char).to_digit(16).unwrap() as u8;
            let lo = (s[2 * i + 1] as char).to_digit(16).unwrap() as u8;
            out[i] = (hi << 4) | lo;
        }
        out
    }

    /// Стандартный «изобразительный» вход BLAKE3-test-vectors:
    /// байт `i` равен `i mod 251` для `i = 0..N`.
    fn typical_input(n: usize) -> alloc::vec::Vec<u8> {
        (0..n).map(|i| (i % 251) as u8).collect()
    }

    #[test]
    fn пустая_строка() {
        // BLAKE3("") = af1349b9f5f9a1a6a0404dea36dcc9499bcb25c9adc112b7cc9a93cae41f3262
        let want = hex_to_bytes("af1349b9f5f9a1a6a0404dea36dcc9499bcb25c9adc112b7cc9a93cae41f3262");
        assert_eq!(хеш(b""), want);
    }

    #[test]
    fn один_байт() {
        // BLAKE3([0x00]) = 2d3adedff11b61f14c886e35afa036736dcd87a74d27b5c1510225d0f592e213
        let want = hex_to_bytes("2d3adedff11b61f14c886e35afa036736dcd87a74d27b5c1510225d0f592e213");
        assert_eq!(хеш(&[0u8]), want);
    }

    #[test]
    fn ровно_один_блок_64() {
        // input_len=64, byte i = i % 251
        let want = hex_to_bytes("4eed7141ea4a5cd4b788606bd23f46e212af9cacebacdc7d1f4c6dc7f2511b98");
        assert_eq!(хеш(&typical_input(64)), want);
    }

    #[test]
    fn ровно_один_чанк_1024() {
        // input_len=1024
        let want = hex_to_bytes("42214739f095a406f3fc83deb889744ac00df831c10daa55189b5d121c855af7");
        assert_eq!(хеш(&typical_input(1024)), want);
    }

    #[test]
    fn два_чанка_2048() {
        // input_len=2048 — корень это PARENT(CV0, CV1) c флагом ROOT
        let want = hex_to_bytes("e776b6028c7cd22a4d0ba182a8bf62205d2ef576467e838ed6f2529b85fba24a");
        assert_eq!(хеш(&typical_input(2048)), want);
    }

    #[test]
    fn четыре_чанка_4096() {
        // input_len=4096 — типичный размер блока ДубФС
        let want = hex_to_bytes("015094013f57a5277b59d8475c0501042c0b642e531b0a1c8f58d2163229e969");
        assert_eq!(хеш(&typical_input(4096)), want);
    }

    #[test]
    fn нечетные_размеры() {
        // Размер не кратный ни блоку, ни чанку — типичный для маленьких файлов.
        let want = hex_to_bytes("5fade288bf27444bee55ba2babb98c3c922c1e84c2e445e7d1f6da24756f5060");
        assert_eq!(хеш(&typical_input(3000)), want);
    }

    #[test]
    fn восемь_чанков_8192() {
        // Глубокое дерево: 8192 байт = 8 чанков, корень на третьем уровне.
        let want = hex_to_bytes("aae792484c8efe4f19e2ca7d371d8c467ffb10748d8a5a1ae579948f718a2a63");
        assert_eq!(хеш(&typical_input(8192)), want);
    }

    #[test]
    fn потоковый_равен_однопроходному() {
        let данные = typical_input(8000);
        let однопроходный = хеш(&данные);
        let mut h = Хешер::новый();
        // Кормим в хешер маленькими кусочками
        for chunk in данные.chunks(37) {
            h.обновить(chunk);
        }
        assert_eq!(h.финализировать(), однопроходный);
    }
}
