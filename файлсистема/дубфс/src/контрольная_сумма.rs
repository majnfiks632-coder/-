// Контрольные суммы блоков.
//
// На этапе 5 это **заглушка**, основанная на FNV-1a 256 бит. Хеш не
// криптографически стойкий, но достаточен для обнаружения битовых
// повреждений на диске. Полный BLAKE3 будет подключён на этапе 9
// «Криптография» — публичный API не изменится.

/// Длина контрольной суммы в байтах. Совпадает с размером BLAKE3-256.
pub const ДЛИНА_СУММЫ: usize = 32;

pub type Сумма = [u8; ДЛИНА_СУММЫ];

/// Нулевая сумма — используется как «не вычислено» в свежих блоках.
pub const НУЛЕВАЯ_СУММА: Сумма = [0u8; ДЛИНА_СУММЫ];

/// Подсчитать контрольную сумму блока.
///
/// Алгоритм: 4 параллельных FNV-1a (по 64 бит) с разными смещениями
/// инициализации; результат конкатенируется в 32 байта. Это даёт
/// разумную «диффузию» битов даже на регулярных входах вроде нулевых блоков.
///
/// **TODO(этап 9):** заменить на настоящий BLAKE3-256.
pub fn посчитать(данные: &[u8]) -> Сумма {
    let основания: [u64; 4] = [
        0xCBF2_9CE4_8422_2325,
        0x84F0_5C84_8C04_AE13,
        0x9E37_79B9_7F4A_7C15,
        0x517C_C1B7_2722_0A95,
    ];
    let простое: u64 = 0x100_0000_01B3;

    let mut состояние = основания;
    for (индекс_байта, байт) in данные.iter().enumerate() {
        let i = индекс_байта & 3;
        состояние[i] ^= *байт as u64;
        состояние[i] = состояние[i].wrapping_mul(простое);
    }

    let mut результат = [0u8; ДЛИНА_СУММЫ];
    for (i, слово) in состояние.iter().enumerate() {
        результат[i * 8..(i + 1) * 8].copy_from_slice(&слово.to_le_bytes());
    }
    результат
}

/// Проверить контрольную сумму блока, в котором последние 32 байта — это
/// поле для самой суммы, занулённое на момент подсчёта.
///
/// Удобный шаблон: блок `[ ... payload ... | контрольная_сумма ]`.
/// При записи мы зануляем последние 32 байта, считаем сумму payload,
/// записываем её в последние 32 байта и сбрасываем на диск.
///
/// При чтении вызываем эту функцию: она копирует блок, зануляет хвост,
/// считает сумму и сравнивает с хвостом. Безопасно, без аллокаций сверх
/// одного `Сумма`.
pub fn проверить_с_хвостом(блок: &[u8]) -> bool {
    if блок.len() < ДЛИНА_СУММЫ {
        return false;
    }
    let (тело, хвост) = блок.split_at(блок.len() - ДЛИНА_СУММЫ);
    // Подсчитаем сумму от тела + 32 нуля.
    let основания: [u64; 4] = [
        0xCBF2_9CE4_8422_2325,
        0x84F0_5C84_8C04_AE13,
        0x9E37_79B9_7F4A_7C15,
        0x517C_C1B7_2722_0A95,
    ];
    let простое: u64 = 0x100_0000_01B3;

    let mut состояние = основания;
    for (индекс_байта, байт) in тело.iter().enumerate() {
        let i = индекс_байта & 3;
        состояние[i] ^= *байт as u64;
        состояние[i] = состояние[i].wrapping_mul(простое);
    }
    // 32 нулевых байта продолжают подсчёт после тела.
    for j in 0..ДЛИНА_СУММЫ {
        let i = (тело.len() + j) & 3;
        состояние[i] = состояние[i].wrapping_mul(простое);
    }

    let mut ожидаемая = [0u8; ДЛИНА_СУММЫ];
    for (i, слово) in состояние.iter().enumerate() {
        ожидаемая[i * 8..(i + 1) * 8].copy_from_slice(&слово.to_le_bytes());
    }

    ожидаемая == хвост
}

/// Записать контрольную сумму в хвост блока.
///
/// Вход — целый блок `[ ... payload ... | 32 байта под сумму ]`. Хвост
/// зануляется, считается сумма payload + 32 нулей, записывается в хвост.
pub fn записать_в_хвост(блок: &mut [u8]) {
    assert!(блок.len() >= ДЛИНА_СУММЫ);
    let len = блок.len();
    блок[len - ДЛИНА_СУММЫ..].fill(0);
    let сумма = посчитать(блок);
    блок[len - ДЛИНА_СУММЫ..].copy_from_slice(&сумма);
}

#[cfg(test)]
mod тесты {
    use super::*;

    #[test]
    fn разные_данные_дают_разные_суммы() {
        let а = посчитать(&[1u8; 100]);
        let б = посчитать(&[2u8; 100]);
        assert_ne!(а, б);
    }

    #[test]
    fn одинаковые_данные_дают_одинаковые_суммы() {
        let а = посчитать("привет, мир".as_bytes());
        let б = посчитать("привет, мир".as_bytes());
        assert_eq!(а, б);
    }

    #[test]
    fn хвост_проверяется_корректно() {
        let mut блок = [0u8; 4096];
        for (i, b) in блок.iter_mut().enumerate().take(4064) {
            *b = (i as u8).wrapping_mul(31);
        }
        записать_в_хвост(&mut блок);
        assert!(проверить_с_хвостом(&блок));

        // Изменим один байт payload — проверка должна провалиться.
        блок[10] ^= 0xFF;
        assert!(!проверить_с_хвостом(&блок));
    }
}
