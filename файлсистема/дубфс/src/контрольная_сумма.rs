// Контрольные суммы блоков ДубФС.
//
// С версии 0.1.0+ это **настоящий BLAKE3-256** (см. модуль `блейк3`).
// Раньше здесь была заглушка на FNV-1a, оставшаяся с этапа 5; теперь
// мы соответствуем тому, что обещаем в README и документации:
// криптостойкая 256-битная контрольная сумма каждого блока.
//
// Публичный API (`посчитать`, `проверить_с_хвостом`, `записать_в_хвост`,
// константы `ДЛИНА_СУММЫ`, `НУЛЕВАЯ_СУММА`, тип `Сумма`) совместим с
// прежним: при чтении старых томов с FNV-1a-хешами проверка не пройдёт,
// поэтому при первом монтировании ДубФС теперь надо переинициализировать
// том (или явно прогнать `записать_в_хвост` на каждый блок). Для
// текущей версии ОС это безопасно — ДубФС создаётся в ОЗУ при загрузке.

use crate::блейк3;

/// Длина контрольной суммы в байтах. Совпадает с размером BLAKE3-256.
pub const ДЛИНА_СУММЫ: usize = блейк3::ДЛИНА_ВЫХОДА;

pub type Сумма = [u8; ДЛИНА_СУММЫ];

/// Нулевая сумма — используется как «не вычислено» в свежих блоках.
pub const НУЛЕВАЯ_СУММА: Сумма = [0u8; ДЛИНА_СУММЫ];

/// Подсчитать BLAKE3-256-сумму блока данных.
///
/// Алгоритм: официальный BLAKE3 (RFC-стиль ⩾7 раундов с
/// перестановкой, дерево чанков по 1024 байта). Реализация лежит
/// в модуле `блейк3` и no-std-friendly. Криптостойкая, без unsafe.
pub fn посчитать(данные: &[u8]) -> Сумма {
    блейк3::хеш(данные)
}

/// Проверить контрольную сумму блока, в котором последние 32 байта —
/// поле для самой суммы, занулённое на момент подсчёта.
///
/// Удобный шаблон: блок `[ ... payload ... | контрольная_сумма ]`.
/// При записи мы зануляем последние 32 байта, считаем сумму всего
/// блока (где хвост уже нули), записываем её в последние 32 байта и
/// сбрасываем на диск.
///
/// При чтении вызываем эту функцию: она копирует блок, сравнивает
/// последние 32 байта с подсчитанной по «занулённому хвостом»
/// версии. Без heap-аллокаций.
pub fn проверить_с_хвостом(блок: &[u8]) -> bool {
    if блок.len() < ДЛИНА_СУММЫ {
        return false;
    }
    let (тело, хвост) = блок.split_at(блок.len() - ДЛИНА_СУММЫ);

    // Считаем BLAKE3 от тела + 32 нулевых байта (без alloc).
    let mut h = блейк3::Хешер::новый();
    h.обновить(тело);
    h.обновить(&НУЛЕВАЯ_СУММА);
    let ожидаемая = h.финализировать();

    ожидаемая.as_slice() == хвост
}

/// Записать контрольную сумму в хвост блока.
///
/// Вход — целый блок `[ ... payload ... | 32 байта под сумму ]`. Хвост
/// зануляется, считается сумма всего блока (где хвост — нули),
/// записывается в хвост.
pub fn записать_в_хвост(блок: &mut [u8]) {
    assert!(блок.len() >= ДЛИНА_СУММЫ);
    let len = блок.len();
    блок[len - ДЛИНА_СУММЫ..].fill(0);
    let сумма = посчитать(блок);
    блок[len - ДЛИНА_СУММЫ..].copy_from_slice(&сумма);
}

#[cfg(test)]
mod тесты {
    use super::*;

    #[test]
    fn разные_данные_дают_разные_суммы() {
        let а = посчитать(&[1u8; 100]);
        let б = посчитать(&[2u8; 100]);
        assert_ne!(а, б);
    }

    #[test]
    fn одинаковые_данные_дают_одинаковые_суммы() {
        let а = посчитать("привет, мир".as_bytes());
        let б = посчитать("привет, мир".as_bytes());
        assert_eq!(а, б);
    }

    #[test]
    fn хвост_проверяется_корректно() {
        let mut блок = [0u8; 4096];
        for (i, b) in блок.iter_mut().enumerate().take(4064) {
            *b = (i as u8).wrapping_mul(31);
        }
        записать_в_хвост(&mut блок);
        assert!(проверить_с_хвостом(&блок));

        // Изменим один байт payload — проверка должна провалиться.
        блок[10] ^= 0xFF;
        assert!(!проверить_с_хвостом(&блок));
    }

    #[test]
    fn пустая_строка_совпадает_с_blake3() {
        // af1349b9... — стандартный BLAKE3 от пустой строки.
        let s = посчитать(b"");
        // Первые 4 байта BLAKE3("") в little-endian = AF 13 49 B9.
        assert_eq!(&s[..4], &[0xAF, 0x13, 0x49, 0xB9]);
    }
}
