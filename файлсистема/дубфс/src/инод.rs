// Inode ДубФС.
//
// On-disk: 256 байт ровно, чтобы 16 inodes помещались в один блок 4 КиБ.
// Состав:
//
//   тип_и_режим   u32       4
//   флаги         u32       4
//   размер        u64       8
//   время_создания u64      8
//   время_изменения u64     8
//   время_доступа  u64      8
//   ссылок        u32       4
//   хозяин        u32       4
//   группа        u32       4
//   блоков_занято u64       8
//   прямые_блоки  [u64;12]  96
//   косвенный     u64       8
//   двойной_косвенный u64   8
//   зарезервировано [u8;32] 32
//   контрольная_сумма [u8;32] 32
//                            -----
//                            244 + 32 = 244 + хвост 32 + (256-244-32 = -20...)
//
// 244 + 32 = 276 — больше чем 256. Поэтому уплотняем: убираем флаги и
// два «времени» — оставляем только время_изменения. Будет:
//
//   тип_и_режим   u32        4
//   флаги         u32        4
//   размер        u64        8
//   время_изменения u64      8
//   ссылок        u32        4
//   хозяин        u32        4
//   группа        u32        4
//   зарезервировано1 u32     4         (для выравнивания)
//   блоков_занято u64        8
//   прямые_блоки  [u64;12]  96
//   косвенный     u64        8
//   двойной_косвенный u64    8
//   зарезервировано [u8;64] 64
//   контрольная_сумма [u8;32] 32
//                             -----
//                             256 байт ровно ✓

use crate::контрольная_сумма::ДЛИНА_СУММЫ;
use crate::ошибки::{ОшибкаФС, Резюме};

pub const РАЗМЕР_ИНОДА: usize = 256;
pub const ИНОДОВ_В_БЛОКЕ_4К: usize = 4096 / РАЗМЕР_ИНОДА; // 16

pub const ПРЯМЫХ_БЛОКОВ: usize = 12;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(u8)]
pub enum ТипИнода {
    Свободен = 0,
    ОбычныйФайл = 1,
    Каталог = 2,
    СимволическаяСсылка = 3,
    СпециальноеУстройство = 4,
}

impl ТипИнода {
    pub fn из_u8(в: u8) -> Резюме<Self> {
        Ok(match в {
            0 => Self::Свободен,
            1 => Self::ОбычныйФайл,
            2 => Self::Каталог,
            3 => Self::СимволическаяСсылка,
            4 => Self::СпециальноеУстройство,
            _ => return Err(ОшибкаФС::Внутренняя("неизвестный тип inode")),
        })
    }
}

pub const РЕЖИМ_ЧТЕНИЕ_ХОЗЯИН: u16 = 0o400;
pub const РЕЖИМ_ЗАПИСЬ_ХОЗЯИН: u16 = 0o200;
pub const РЕЖИМ_ИСПОЛНЕНИЕ_ХОЗЯИН: u16 = 0o100;
pub const РЕЖИМ_ЧТЕНИЕ_ГРУППА: u16 = 0o040;
pub const РЕЖИМ_ЗАПИСЬ_ГРУППА: u16 = 0o020;
pub const РЕЖИМ_ИСПОЛНЕНИЕ_ГРУППА: u16 = 0o010;
pub const РЕЖИМ_ЧТЕНИЕ_ОСТАЛЬНЫЕ: u16 = 0o004;
pub const РЕЖИМ_ЗАПИСЬ_ОСТАЛЬНЫЕ: u16 = 0o002;
pub const РЕЖИМ_ИСПОЛНЕНИЕ_ОСТАЛЬНЫЕ: u16 = 0o001;

pub const РЕЖИМ_ОБЫЧНЫЙ_ФАЙЛ: u16 = 0o644;
pub const РЕЖИМ_КАТАЛОГ: u16 = 0o755;

#[derive(Debug, Clone, Copy)]
pub struct Инод {
    pub тип: ТипИнода,
    pub режим: u16,
    pub флаги: u32,
    pub размер: u64,
    pub время_изменения: u64,
    pub ссылок: u32,
    pub хозяин: u32,
    pub группа: u32,
    pub блоков_занято: u64,
    pub прямые_блоки: [u64; ПРЯМЫХ_БЛОКОВ],
    pub косвенный: u64,
    pub двойной_косвенный: u64,
}

impl Инод {
    pub fn пустой() -> Self {
        Self {
            тип: ТипИнода::Свободен,
            режим: 0,
            флаги: 0,
            размер: 0,
            время_изменения: 0,
            ссылок: 0,
            хозяин: 0,
            группа: 0,
            блоков_занято: 0,
            прямые_блоки: [0; ПРЯМЫХ_БЛОКОВ],
            косвенный: 0,
            двойной_косвенный: 0,
        }
    }

    pub fn новый_файл(время: u64) -> Self {
        Self {
            тип: ТипИнода::ОбычныйФайл,
            режим: РЕЖИМ_ОБЫЧНЫЙ_ФАЙЛ,
            время_изменения: время,
            ссылок: 1,
            ..Self::пустой()
        }
    }

    pub fn новый_каталог(время: u64) -> Self {
        Self {
            тип: ТипИнода::Каталог,
            режим: РЕЖИМ_КАТАЛОГ,
            время_изменения: время,
            ссылок: 2, // «.» и ссылка из родителя
            ..Self::пустой()
        }
    }

    /// Сериализовать inode в 256 байт. Хвостовая контрольная сумма
    /// **не** включена — целостность гарантируется блоком таблицы inodes,
    /// который сам защищён контрольной суммой; на этом этапе делать «вложенные»
    /// суммы перебор.
    pub fn записать_в_буфер(&self, буфер: &mut [u8]) {
        assert_eq!(буфер.len(), РАЗМЕР_ИНОДА);
        буфер.fill(0);
        let тип = self.тип as u8;
        let тр: u32 = (тип as u32) | ((self.режим as u32) << 8);
        буфер[0..4].copy_from_slice(&тр.to_le_bytes());
        буфер[4..8].copy_from_slice(&self.флаги.to_le_bytes());
        буфер[8..16].copy_from_slice(&self.размер.to_le_bytes());
        буфер[16..24].copy_from_slice(&self.время_изменения.to_le_bytes());
        буфер[24..28].copy_from_slice(&self.ссылок.to_le_bytes());
        буфер[28..32].copy_from_slice(&self.хозяин.to_le_bytes());
        буфер[32..36].copy_from_slice(&self.группа.to_le_bytes());
        // 36..40 — резерв
        буфер[40..48].copy_from_slice(&self.блоков_занято.to_le_bytes());
        for (i, блок) in self.прямые_блоки.iter().enumerate() {
            let начало = 48 + i * 8;
            буфер[начало..начало + 8].copy_from_slice(&блок.to_le_bytes());
        }
        // 48 + 96 = 144
        буфер[144..152].copy_from_slice(&self.косвенный.to_le_bytes());
        буфер[152..160].copy_from_slice(&self.двойной_косвенный.to_le_bytes());
        // 160..(256-32 = 224) — резерв
        // 224..256 — место под локальную сумму, оставляем нулями (см. примечание выше)
        let _ = ДЛИНА_СУММЫ; // подавим неиспользуемый импорт
    }

    pub fn прочитать_из_буфера(буфер: &[u8]) -> Резюме<Self> {
        if буфер.len() != РАЗМЕР_ИНОДА {
            return Err(ОшибкаФС::Внутренняя("неверный размер буфера inode"));
        }
        let тр = u32::from_le_bytes(буфер[0..4].try_into().unwrap());
        let тип = ТипИнода::из_u8((тр & 0xFF) as u8)?;
        let режим = ((тр >> 8) & 0xFFFF) as u16;
        let флаги = u32::from_le_bytes(буфер[4..8].try_into().unwrap());
        let размер = u64::from_le_bytes(буфер[8..16].try_into().unwrap());
        let время_изменения = u64::from_le_bytes(буфер[16..24].try_into().unwrap());
        let ссылок = u32::from_le_bytes(буфер[24..28].try_into().unwrap());
        let хозяин = u32::from_le_bytes(буфер[28..32].try_into().unwrap());
        let группа = u32::from_le_bytes(буфер[32..36].try_into().unwrap());
        let блоков_занято = u64::from_le_bytes(буфер[40..48].try_into().unwrap());
        let mut прямые_блоки = [0u64; ПРЯМЫХ_БЛОКОВ];
        for i in 0..ПРЯМЫХ_БЛОКОВ {
            let начало = 48 + i * 8;
            прямые_блоки[i] = u64::from_le_bytes(буфер[начало..начало + 8].try_into().unwrap());
        }
        let косвенный = u64::from_le_bytes(буфер[144..152].try_into().unwrap());
        let двойной_косвенный = u64::from_le_bytes(буфер[152..160].try_into().unwrap());
        Ok(Self {
            тип,
            режим,
            флаги,
            размер,
            время_изменения,
            ссылок,
            хозяин,
            группа,
            блоков_занято,
            прямые_блоки,
            косвенный,
            двойной_косвенный,
        })
    }
}

#[cfg(test)]
mod тесты {
    use super::*;

    #[test]
    fn запись_и_чтение_совпадают() {
        let mut образец = Инод::новый_файл(1_000_000);
        образец.размер = 12345;
        образец.прямые_блоки[0] = 100;
        образец.прямые_блоки[5] = 105;
        образец.косвенный = 200;
        образец.двойной_косвенный = 300;
        let mut буфер = [0u8; РАЗМЕР_ИНОДА];
        образец.записать_в_буфер(&mut буфер);
        let восстановлен = Инод::прочитать_из_буфера(&буфер).unwrap();
        assert_eq!(восстановлен.тип, ТипИнода::ОбычныйФайл);
        assert_eq!(восстановлен.размер, 12345);
        assert_eq!(восстановлен.прямые_блоки[0], 100);
        assert_eq!(восстановлен.прямые_блоки[5], 105);
        assert_eq!(восстановлен.косвенный, 200);
        assert_eq!(восстановлен.двойной_косвенный, 300);
        assert_eq!(восстановлен.ссылок, 1);
        assert_eq!(восстановлен.режим, РЕЖИМ_ОБЫЧНЫЙ_ФАЙЛ);
    }

    #[test]
    fn пустой_сериализуется_как_свободен() {
        let образец = Инод::пустой();
        let mut буфер = [0u8; РАЗМЕР_ИНОДА];
        образец.записать_в_буфер(&mut буфер);
        let восстановлен = Инод::прочитать_из_буфера(&буфер).unwrap();
        assert_eq!(восстановлен.тип, ТипИнода::Свободен);
        assert_eq!(восстановлен.размер, 0);
    }

    #[test]
    fn размер_иноды_ровно_256() {
        // Чтобы 16 inodes помещались в блок 4 КиБ.
        assert_eq!(РАЗМЕР_ИНОДА, 256);
        assert_eq!(ИНОДОВ_В_БЛОКЕ_4К, 16);
    }
}
