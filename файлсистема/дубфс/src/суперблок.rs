// Содержит самоописание файловой системы: где какой раздел лежит, какова
// версия on-disk формата, и т.п. Суперблок занимает блок 0 диска и защищён
// контрольной суммой в последних 32 байтах блока.

use crate::блок::БлокУстройство;
use crate::контрольная_сумма::{проверить_с_хвостом, записать_в_хвост, ДЛИНА_СУММЫ};
use crate::ошибки::{ОшибкаФС, Резюме};

pub const МАГИЯ_СБ: u64 = 0xD0BA_F500_0BE5_0001;
pub const ВЕРСИЯ_ФОРМАТА: u32 = 1;

pub const ФЛАГ_ЧИСТО: u32 = 1 << 0;
pub const ФЛАГ_ЖУРНАЛ_НЕПРОИГРАН: u32 = 1 << 1;

pub const МЕТКА_ДЛИНА: usize = 32;

/// In-memory представление суперблока. На диск записывается «упаковано»
/// в `записать(...)`; читается из `прочитать(...)`. Текстовое представление
/// и `Debug` намеренно не реализованы — их роль выполняют поля.
#[derive(Debug, Clone, Copy)]
pub struct Суперблок {
    pub магия: u64,
    pub версия_диска: u32,
    pub флаги: u32,
    pub размер_блока: u32,
    pub всего_блоков: u64,
    pub всего_inodes: u64,
    pub свободных_блоков: u64,
    pub свободных_inodes: u64,
    pub битмап_блоков_начало: u64,
    pub битмап_блоков_длина: u64,
    pub битмап_inodes_начало: u64,
    pub битмап_inodes_длина: u64,
    pub таблица_inodes_начало: u64,
    pub таблица_inodes_длина: u64,
    pub журнал_начало: u64,
    pub журнал_длина: u64,
    pub данные_начало: u64,
    pub inode_корня: u64,
    pub последний_монтаж: u64,
    pub счётчик_монтажей: u64,
    pub метка: [u8; МЕТКА_ДЛИНА],
}

impl Суперблок {
    /// Записать суперблок в выделенный буфер блока. Хвостовая контрольная
    /// сумма выставляется автоматически.
    pub fn записать_в_буфер(&self, буфер: &mut [u8]) {
        буфер.fill(0);
        буфер[0..8].copy_from_slice(&self.магия.to_le_bytes());
        буфер[8..12].copy_from_slice(&self.версия_диска.to_le_bytes());
        буфер[12..16].copy_from_slice(&self.флаги.to_le_bytes());
        буфер[16..20].copy_from_slice(&self.размер_блока.to_le_bytes());
        буфер[24..32].copy_from_slice(&self.всего_блоков.to_le_bytes());
        буфер[32..40].copy_from_slice(&self.всего_inodes.to_le_bytes());
        буфер[40..48].copy_from_slice(&self.свободных_блоков.to_le_bytes());
        буфер[48..56].copy_from_slice(&self.свободных_inodes.to_le_bytes());
        буфер[56..64].copy_from_slice(&self.битмап_блоков_начало.to_le_bytes());
        буфер[64..72].copy_from_slice(&self.битмап_блоков_длина.to_le_bytes());
        буфер[72..80].copy_from_slice(&self.битмап_inodes_начало.to_le_bytes());
        буфер[80..88].copy_from_slice(&self.битмап_inodes_длина.to_le_bytes());
        буфер[88..96].copy_from_slice(&self.таблица_inodes_начало.to_le_bytes());
        буфер[96..104].copy_from_slice(&self.таблица_inodes_длина.to_le_bytes());
        буфер[104..112].copy_from_slice(&self.журнал_начало.to_le_bytes());
        буфер[112..120].copy_from_slice(&self.журнал_длина.to_le_bytes());
        буфер[120..128].copy_from_slice(&self.данные_начало.to_le_bytes());
        буфер[128..136].copy_from_slice(&self.inode_корня.to_le_bytes());
        буфер[136..144].copy_from_slice(&self.последний_монтаж.to_le_bytes());
        буфер[144..152].copy_from_slice(&self.счётчик_монтажей.to_le_bytes());
        буфер[152..152 + МЕТКА_ДЛИНА].copy_from_slice(&self.метка);
        // байты 184..(размер блока - ДЛИНА_СУММЫ) — резерв (нули).
        записать_в_хвост(буфер);
    }

    /// Прочитать суперблок из буфера. Проверяет магию и контрольную сумму.
    pub fn прочитать_из_буфера(буфер: &[u8]) -> Резюме<Self> {
        if буфер.len() < 184 + ДЛИНА_СУММЫ {
            return Err(ОшибкаФС::Внутренняя("буфер для чтения суперблока меньше 184+32 байт"));
        }
        if !проверить_с_хвостом(буфер) {
            return Err(ОшибкаФС::КонтрольнаяСумма { блок: 0 });
        }
        let магия = u64::from_le_bytes(буфер[0..8].try_into().unwrap());
        if магия != МАГИЯ_СБ {
            return Err(ОшибкаФС::НеДубФС);
        }
        let версия_диска = u32::from_le_bytes(буфер[8..12].try_into().unwrap());
        if версия_диска != ВЕРСИЯ_ФОРМАТА {
            return Err(ОшибкаФС::НесовместимаяВерсия {
                ожидалась: ВЕРСИЯ_ФОРМАТА,
                найдена: версия_диска,
            });
        }
        let мут_метка: &[u8; МЕТКА_ДЛИНА] = (&буфер[152..152 + МЕТКА_ДЛИНА]).try_into().unwrap();
        Ok(Self {
            магия,
            версия_диска,
            флаги: u32::from_le_bytes(буфер[12..16].try_into().unwrap()),
            размер_блока: u32::from_le_bytes(буфер[16..20].try_into().unwrap()),
            всего_блоков: u64::from_le_bytes(буфер[24..32].try_into().unwrap()),
            всего_inodes: u64::from_le_bytes(буфер[32..40].try_into().unwrap()),
            свободных_блоков: u64::from_le_bytes(буфер[40..48].try_into().unwrap()),
            свободных_inodes: u64::from_le_bytes(буфер[48..56].try_into().unwrap()),
            битмап_блоков_начало: u64::from_le_bytes(буфер[56..64].try_into().unwrap()),
            битмап_блоков_длина: u64::from_le_bytes(буфер[64..72].try_into().unwrap()),
            битмап_inodes_начало: u64::from_le_bytes(буфер[72..80].try_into().unwrap()),
            битмап_inodes_длина: u64::from_le_bytes(буфер[80..88].try_into().unwrap()),
            таблица_inodes_начало: u64::from_le_bytes(буфер[88..96].try_into().unwrap()),
            таблица_inodes_длина: u64::from_le_bytes(буфер[96..104].try_into().unwrap()),
            журнал_начало: u64::from_le_bytes(буфер[104..112].try_into().unwrap()),
            журнал_длина: u64::from_le_bytes(буфер[112..120].try_into().unwrap()),
            данные_начало: u64::from_le_bytes(буфер[120..128].try_into().unwrap()),
            inode_корня: u64::from_le_bytes(буфер[128..136].try_into().unwrap()),
            последний_монтаж: u64::from_le_bytes(буфер[136..144].try_into().unwrap()),
            счётчик_монтажей: u64::from_le_bytes(буфер[144..152].try_into().unwrap()),
            метка: *мут_метка,
        })
    }

    /// Прочитать суперблок с устройства (блок 0).
    pub fn прочитать_с_устройства(устройство: &dyn БлокУстройство) -> Резюме<Self> {
        let размер = устройство.размер_блока();
        let mut буфер = alloc::vec![0u8; размер];
        устройство.прочитать_блок(0, &mut буфер)?;
        Self::прочитать_из_буфера(&буфер)
    }

    /// Записать суперблок на устройство.
    pub fn записать_на_устройство(&self, устройство: &dyn БлокУстройство) -> Резюме<()> {
        let размер = устройство.размер_блока();
        let mut буфер = alloc::vec![0u8; размер];
        self.записать_в_буфер(&mut буфер);
        устройство.записать_блок(0, &буфер)?;
        Ok(())
    }
}

#[cfg(test)]
mod тесты {
    use super::*;

    #[test]
    fn запись_и_чтение_совпадают() {
        let образец = Суперблок {
            магия: МАГИЯ_СБ,
            версия_диска: ВЕРСИЯ_ФОРМАТА,
            флаги: ФЛАГ_ЧИСТО,
            размер_блока: 4096,
            всего_блоков: 1024,
            всего_inodes: 256,
            свободных_блоков: 1000,
            свободных_inodes: 240,
            битмап_блоков_начало: 1,
            битмап_блоков_длина: 1,
            битмап_inodes_начало: 2,
            битмап_inodes_длина: 1,
            таблица_inodes_начало: 3,
            таблица_inodes_длина: 16,
            журнал_начало: 19,
            журнал_длина: 32,
            данные_начало: 51,
            inode_корня: 1,
            последний_монтаж: 1_700_000_000,
            счётчик_монтажей: 7,
            метка: {
                // 32-байтная метка с UTF-8 содержимым.
                let mut м = [0u8; МЕТКА_ДЛИНА];
                let байты = "тестовая метка".as_bytes();
                м[..байты.len()].copy_from_slice(байты);
                м
            },
        };
        let mut буфер = [0u8; 4096];
        образец.записать_в_буфер(&mut буфер);

        let восстановлен = Суперблок::прочитать_из_буфера(&буфер).expect("чтение");
        assert_eq!(восстановлен.магия, образец.магия);
        assert_eq!(восстановлен.всего_блоков, образец.всего_блоков);
        assert_eq!(восстановлен.журнал_длина, образец.журнал_длина);
        assert_eq!(восстановлен.метка, образец.метка);
    }

    #[test]
    fn портятый_блок_отвергается() {
        let образец = Суперблок {
            магия: МАГИЯ_СБ,
            версия_диска: ВЕРСИЯ_ФОРМАТА,
            флаги: 0,
            размер_блока: 4096,
            всего_блоков: 1024,
            всего_inodes: 256,
            свободных_блоков: 1000,
            свободных_inodes: 240,
            битмап_блоков_начало: 1,
            битмап_блоков_длина: 1,
            битмап_inodes_начало: 2,
            битмап_inodes_длина: 1,
            таблица_inodes_начало: 3,
            таблица_inodes_длина: 16,
            журнал_начало: 19,
            журнал_длина: 32,
            данные_начало: 51,
            inode_корня: 1,
            последний_монтаж: 0,
            счётчик_монтажей: 0,
            метка: [0; МЕТКА_ДЛИНА],
        };
        let mut буфер = [0u8; 4096];
        образец.записать_в_буфер(&mut буфер);
        // Поломаем поле «всего_блоков» — контрольная сумма не сойдётся.
        буфер[24] ^= 0xFF;
        let итог = Суперблок::прочитать_из_буфера(&буфер);
        assert!(matches!(итог, Err(ОшибкаФС::КонтрольнаяСумма { .. })));
    }

    #[test]
    fn неверная_магия_отвергается() {
        let mut буфер = [0u8; 4096];
        // Вытащим валидную сумму для нулевого тела с другой магией.
        буфер[0..8].copy_from_slice(&0xDEAD_BEEF_u64.to_le_bytes());
        записать_в_хвост_внешний(&mut буфер);
        let итог = Суперблок::прочитать_из_буфера(&буфер);
        assert!(matches!(итог, Err(ОшибкаФС::НеДубФС)));
    }

    fn записать_в_хвост_внешний(буфер: &mut [u8]) {
        crate::контрольная_сумма::записать_в_хвост(буфер);
    }
}
