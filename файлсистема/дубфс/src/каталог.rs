// MVP-формат: каталог — это файл, чьё содержимое — последовательность
// записей `(хэш_имени, инод, длина_имени, тип, имя)`, отсортированная по
// хэшу. Поиск — двоичный по `хэш_имени`. При коллизии (что для 64-битного
// хэша редкость, но возможно) сравниваются полные имена.
//
// В будущем (этап 9) этот модуль будет заменён на B+-дерево; интерфейс
// (`найти`, `вставить`, `удалить`, `перечислить`) спроектирован так,
// чтобы переход прошёл без изменений в коде ФС.

use alloc::string::String;
use alloc::vec::Vec;

use crate::ошибки::{ОшибкаФС, Резюме};

pub const МАКС_ДЛИНА_ИМЕНИ: usize = 255;

/// Заголовок одной записи каталога. Имя идёт сразу после, выравнивается
/// до 8 байт.
const РАЗМЕР_ЗАГОЛОВКА: usize = 24;

#[derive(Debug, Clone)]
pub struct ЗаписьКаталога {
    pub хэш_имени: u64,
    pub инод: u64,
    pub тип: u8,
    pub имя: String,
}

/// 64-битный хэш UTF-8 имени, используемый как ключ.
///
/// **TODO(этап 9):** заменить на BLAKE3-128 верхние 64 бита, чтобы коллизии
/// можно было считать исключительной ситуацией.
pub fn хэшировать_имя(имя: &str) -> u64 {
    let mut состояние: u64 = 0xCBF2_9CE4_8422_2325;
    let простое: u64 = 0x100_0000_01B3;
    for &байт in имя.as_bytes() {
        состояние ^= байт as u64;
        состояние = состояние.wrapping_mul(простое);
    }
    состояние
}

fn выровнять_8(x: usize) -> usize {
    (x + 7) & !7
}

/// Сериализовать массив записей в линейный буфер.
pub fn сериализовать(записи: &[ЗаписьКаталога]) -> Vec<u8> {
    let mut буфер = Vec::new();
    // 8 байт — количество записей.
    буфер.extend_from_slice(&(записи.len() as u64).to_le_bytes());
    for запись in записи {
        let длина_имени = запись.имя.as_bytes().len() as u16;
        let общая_длина = РАЗМЕР_ЗАГОЛОВКА + выровнять_8(длина_имени as usize);
        буфер.reserve(общая_длина);
        буфер.extend_from_slice(&запись.хэш_имени.to_le_bytes());
        буфер.extend_from_slice(&запись.инод.to_le_bytes());
        буфер.extend_from_slice(&длина_имени.to_le_bytes());
        буфер.push(запись.тип);
        буфер.push(0); // зарезервировано
        // 8 + 8 + 2 + 1 + 1 = 20 — нужно ещё 4 байта до 24 заголовка.
        буфер.extend_from_slice(&[0u8; 4]);
        буфер.extend_from_slice(запись.имя.as_bytes());
        let нужно_выравнивания = выровнять_8(длина_имени as usize) - длина_имени as usize;
        for _ in 0..нужно_выравнивания {
            буфер.push(0);
        }
    }
    буфер
}

/// Прочитать массив записей из линейного буфера.
pub fn десериализовать(буфер: &[u8]) -> Резюме<Vec<ЗаписьКаталога>> {
    if буфер.len() < 8 {
        return Err(ОшибкаФС::Внутренняя("слишком короткий буфер каталога"));
    }
    let число = u64::from_le_bytes(буфер[0..8].try_into().unwrap());
    let mut поз = 8usize;
    let mut записи = Vec::with_capacity(число as usize);
    for _ in 0..число {
        if поз + РАЗМЕР_ЗАГОЛОВКА > буфер.len() {
            return Err(ОшибкаФС::Внутренняя("обрезанный заголовок записи каталога"));
        }
        let хэш = u64::from_le_bytes(буфер[поз..поз + 8].try_into().unwrap());
        let инод = u64::from_le_bytes(буфер[поз + 8..поз + 16].try_into().unwrap());
        let длина_имени = u16::from_le_bytes(буфер[поз + 16..поз + 18].try_into().unwrap()) as usize;
        let тип = буфер[поз + 18];
        // байт 19 — резерв; 20..24 — резерв
        поз += РАЗМЕР_ЗАГОЛОВКА;
        if поз + длина_имени > буфер.len() {
            return Err(ОшибкаФС::Внутренняя("обрезанное имя в записи каталога"));
        }
        let имя_байты = &буфер[поз..поз + длина_имени];
        let имя = core::str::from_utf8(имя_байты)
            .map_err(|_| ОшибкаФС::Внутренняя("имя не UTF-8"))?;
        записи.push(ЗаписьКаталога {
            хэш_имени: хэш,
            инод,
            тип,
            имя: имя.into(),
        });
        поз += выровнять_8(длина_имени);
    }
    Ok(записи)
}

/// Двоичный поиск по хэшу. При коллизиях сравнивает имена.
/// Возвращает индекс записи в массиве (или ошибку «не найдено»).
pub fn найти<'а>(записи: &'а [ЗаписьКаталога], имя: &str) -> Резюме<usize> {
    let хэш = хэшировать_имя(имя);
    let mut низ: i64 = 0;
    let mut верх: i64 = записи.len() as i64 - 1;
    while низ <= верх {
        let середина = ((низ + верх) / 2) as usize;
        if записи[середина].хэш_имени < хэш {
            низ = середина as i64 + 1;
        } else if записи[середина].хэш_имени > хэш {
            верх = середина as i64 - 1;
        } else {
            // Нашли совпадение хэша; найдём блок одинаковых хэшей и
            // среди них — конкретное имя.
            let mut л = середина;
            while л > 0 && записи[л - 1].хэш_имени == хэш {
                л -= 1;
            }
            let mut п = середина;
            while п + 1 < записи.len() && записи[п + 1].хэш_имени == хэш {
                п += 1;
            }
            for i in л..=п {
                if записи[i].имя == имя {
                    return Ok(i);
                }
            }
            return Err(ОшибкаФС::НеНайдено);
        }
    }
    Err(ОшибкаФС::НеНайдено)
}

/// Вставить запись с проверкой на дубликат.
pub fn вставить(записи: &mut Vec<ЗаписьКаталога>, новая: ЗаписьКаталога) -> Резюме<()> {
    if новая.имя.as_bytes().len() > МАКС_ДЛИНА_ИМЕНИ {
        return Err(ОшибкаФС::ИмяСлишкомДлинное);
    }
    if найти(записи, &новая.имя).is_ok() {
        return Err(ОшибкаФС::УжеСуществует);
    }
    let позиция = записи
        .binary_search_by(|с| с.хэш_имени.cmp(&новая.хэш_имени).then_with(|| с.имя.cmp(&новая.имя)))
        .unwrap_or_else(|p| p);
    записи.insert(позиция, новая);
    Ok(())
}

/// Удалить запись по имени.
pub fn удалить(записи: &mut Vec<ЗаписьКаталога>, имя: &str) -> Резюме<ЗаписьКаталога> {
    let индекс = найти(записи, имя)?;
    Ok(записи.remove(индекс))
}

#[cfg(test)]
mod тесты {
    use super::*;
    use alloc::string::ToString;

    fn з(имя: &str, инод: u64) -> ЗаписьКаталога {
        ЗаписьКаталога {
            хэш_имени: хэшировать_имя(имя),
            инод,
            тип: 1,
            имя: имя.to_string(),
        }
    }

    #[test]
    fn вставка_и_поиск() {
        let mut записи = Vec::new();
        вставить(&mut записи, з("привет", 10)).unwrap();
        вставить(&mut записи, з("дубина", 11)).unwrap();
        вставить(&mut записи, з("ос", 12)).unwrap();
        let i_дубина = найти(&записи, "дубина").unwrap();
        assert_eq!(записи[i_дубина].инод, 11);
    }

    #[test]
    fn дубликат_отвергается() {
        let mut записи = Vec::new();
        вставить(&mut записи, з("файл", 10)).unwrap();
        let итог = вставить(&mut записи, з("файл", 11));
        assert!(matches!(итог, Err(ОшибкаФС::УжеСуществует)));
    }

    #[test]
    fn удаление() {
        let mut записи = Vec::new();
        вставить(&mut записи, з("а", 10)).unwrap();
        вставить(&mut записи, з("б", 11)).unwrap();
        вставить(&mut записи, з("в", 12)).unwrap();
        let убран = удалить(&mut записи, "б").unwrap();
        assert_eq!(убран.инод, 11);
        assert!(matches!(найти(&записи, "б"), Err(ОшибкаФС::НеНайдено)));
        assert!(найти(&записи, "а").is_ok());
        assert!(найти(&записи, "в").is_ok());
    }

    #[test]
    fn сериализация_round_trip() {
        let mut записи = Vec::new();
        вставить(&mut записи, з("один", 1)).unwrap();
        вставить(&mut записи, з("два", 2)).unwrap();
        вставить(&mut записи, з("очень длинное имя файла с пробелами", 3)).unwrap();
        let байты = сериализовать(&записи);
        let назад = десериализовать(&байты).unwrap();
        assert_eq!(назад.len(), записи.len());
        for (i, запись) in записи.iter().enumerate() {
            assert_eq!(назад[i].имя, запись.имя);
            assert_eq!(назад[i].инод, запись.инод);
            assert_eq!(назад[i].хэш_имени, запись.хэш_имени);
        }
    }

    #[test]
    fn слишком_длинное_имя_отвергается() {
        let mut записи = Vec::new();
        let имя: String = (0..МАКС_ДЛИНА_ИМЕНИ + 1).map(|_| 'я').collect();
        let итог = вставить(
            &mut записи,
            ЗаписьКаталога {
                хэш_имени: хэшировать_имя(&имя),
                инод: 1,
                тип: 1,
                имя,
            },
        );
        assert!(matches!(итог, Err(ОшибкаФС::ИмяСлишкомДлинное)));
    }
}
