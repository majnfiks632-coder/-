// Битмап-аллокатор. Используется и для блоков данных, и для inodes.
//
// On-disk: блоки битмапа лежат подряд; в каждом блоке младший байт
// первой 8-байтовой группы — биты 0..7 (бит 0 — это младший бит первого
// байта). Бит 1 значит «занято».
//
// Аллокатор работает поблочно: при выделении читает первый блок битмапа
// со свободным битом, ставит бит, записывает блок обратно. Это намеренно
// медленно — на этапе 5 нам важна корректность, а не скорость; ускорение
// (in-memory кэш свободных) добавим в этапе 9.

use alloc::vec;

use crate::блок::БлокУстройство;
use crate::ошибки::{ОшибкаФС, Резюме};

pub struct Битмап {
    /// Номер первого блока на диске.
    pub начало: u64,
    /// Сколько блоков занимает битмап.
    pub длина_блоков: u64,
    /// Сколько всего бит описывает битмап.
    pub всего_бит: u64,
    pub размер_блока: usize,
}

impl Битмап {
    pub fn новый(начало: u64, длина_блоков: u64, всего_бит: u64, размер_блока: usize) -> Self {
        debug_assert!(всего_бит <= длина_блоков * (размер_блока as u64) * 8);
        Self {
            начало,
            длина_блоков,
            всего_бит,
            размер_блока,
        }
    }

    /// Прочитать одну страницу битмапа в буфер размером `размер_блока`.
    fn прочитать_страницу(
        &self,
        устройство: &dyn БлокУстройство,
        номер_страницы: u64,
        буфер: &mut [u8],
    ) -> Резюме<()> {
        if номер_страницы >= self.длина_блоков {
            return Err(ОшибкаФС::Внутренняя("номер страницы битмапа за пределами"));
        }
        устройство.прочитать_блок(self.начало + номер_страницы, буфер)?;
        Ok(())
    }

    fn записать_страницу(
        &self,
        устройство: &dyn БлокУстройство,
        номер_страницы: u64,
        буфер: &[u8],
    ) -> Резюме<()> {
        if номер_страницы >= self.длина_блоков {
            return Err(ОшибкаФС::Внутренняя("номер страницы битмапа за пределами"));
        }
        устройство.записать_блок(self.начало + номер_страницы, буфер)?;
        Ok(())
    }

    /// Установить бит в значение `занято`. Возвращает прежнее значение.
    pub fn установить(&self, устройство: &dyn БлокУстройство, индекс: u64, занято: bool) -> Резюме<bool> {
        if индекс >= self.всего_бит {
            return Err(ОшибкаФС::Внутренняя("индекс бита за пределами битмапа"));
        }
        let бит_на_страницу = (self.размер_блока as u64) * 8;
        let страница = индекс / бит_на_страницу;
        let бит_на_странице = индекс % бит_на_страницу;
        let байт = (бит_на_странице / 8) as usize;
        let маска = 1u8 << (бит_на_странице % 8);

        let mut буфер = vec![0u8; self.размер_блока];
        self.прочитать_страницу(устройство, страница, &mut буфер)?;
        let прежний = (буфер[байт] & маска) != 0;
        if занято {
            буфер[байт] |= маска;
        } else {
            буфер[байт] &= !маска;
        }
        if прежний != занято {
            self.записать_страницу(устройство, страница, &буфер)?;
        }
        Ok(прежний)
    }

    /// Прочитать значение бита.
    pub fn прочитать(&self, устройство: &dyn БлокУстройство, индекс: u64) -> Резюме<bool> {
        if индекс >= self.всего_бит {
            return Err(ОшибкаФС::Внутренняя("индекс бита за пределами битмапа"));
        }
        let бит_на_страницу = (self.размер_блока as u64) * 8;
        let страница = индекс / бит_на_страницу;
        let бит_на_странице = индекс % бит_на_страницу;
        let байт = (бит_на_странице / 8) as usize;
        let маска = 1u8 << (бит_на_странице % 8);
        let mut буфер = vec![0u8; self.размер_блока];
        self.прочитать_страницу(устройство, страница, &mut буфер)?;
        Ok((буфер[байт] & маска) != 0)
    }

    /// Найти первый свободный бит и пометить его. Возвращает индекс.
    pub fn выделить(&self, устройство: &dyn БлокУстройство) -> Резюме<u64> {
        let mut буфер = vec![0u8; self.размер_блока];
        for страница in 0..self.длина_блоков {
            self.прочитать_страницу(устройство, страница, &mut буфер)?;
            for (байт_индекс, байт) in буфер.iter_mut().enumerate() {
                if *байт != 0xFF {
                    let бит = первый_нулевой_бит(*байт);
                    let глобальный = страница * (self.размер_блока as u64) * 8
                        + (байт_индекс as u64) * 8
                        + (бит as u64);
                    if глобальный >= self.всего_бит {
                        return Err(ОшибкаФС::НетСвободныхБлоков);
                    }
                    *байт |= 1u8 << бит;
                    self.записать_страницу(устройство, страница, &буфер)?;
                    return Ok(глобальный);
                }
            }
        }
        Err(ОшибкаФС::НетСвободныхБлоков)
    }

    /// Освободить бит. Возвращает прежнее значение (для отлова двойного освобождения).
    pub fn освободить(&self, устройство: &dyn БлокУстройство, индекс: u64) -> Резюме<bool> {
        self.установить(устройство, индекс, false)
    }

    /// Сосчитать количество занятых бит. O(всего бит / 8) — для тестов и
    /// проверки целостности; не вызывается на горячем пути.
    pub fn посчитать_занятые(&self, устройство: &dyn БлокУстройство) -> Резюме<u64> {
        let mut итог: u64 = 0;
        let mut буфер = vec![0u8; self.размер_блока];
        let всего_страниц = self.длина_блоков;
        let всего_байт_итого = (self.всего_бит + 7) / 8;
        let mut посмотрено_байт: u64 = 0;
        for страница in 0..всего_страниц {
            self.прочитать_страницу(устройство, страница, &mut буфер)?;
            for &байт in буфер.iter() {
                if посмотрено_байт >= всего_байт_итого {
                    break;
                }
                итог += байт.count_ones() as u64;
                посмотрено_байт += 1;
            }
        }
        // Внутри последнего байта могут быть «лишние» биты сверх всего_бит —
        // вычтем их.
        let лишних = (всего_байт_итого * 8).saturating_sub(self.всего_бит);
        if лишних > 0 {
            // Прочитаем последний байт ещё раз, отлично, сосчитаем биты выше всего_бит.
            let последняя_страница = (всего_байт_итого - 1) / (self.размер_блока as u64);
            let позиция_в_странице = ((всего_байт_итого - 1) % (self.размер_блока as u64)) as usize;
            self.прочитать_страницу(устройство, последняя_страница, &mut буфер)?;
            let маска_лишних: u8 = 0xFFu8 << (8 - лишних);
            итог -= (буфер[позиция_в_странице] & маска_лишних).count_ones() as u64;
        }
        Ok(итог)
    }

    /// Полная инициализация: записать нули, кроме первых N зарезервированных
    /// бит (например, бит 0 inode-битмапа всегда занят, а бит блока 0 —
    /// суперблок — тоже занят).
    pub fn проинициализировать(
        &self,
        устройство: &dyn БлокУстройство,
        зарезервировано_бит: u64,
    ) -> Резюме<()> {
        let mut буфер = vec![0u8; self.размер_блока];
        for страница in 0..self.длина_блоков {
            буфер.fill(0);
            self.записать_страницу(устройство, страница, &буфер)?;
        }
        for индекс in 0..зарезервировано_бит {
            self.установить(устройство, индекс, true)?;
        }
        Ok(())
    }
}

/// Найти позицию первого нулевого бита в байте. Гарантируется, что
/// `байт != 0xFF` (иначе функция возвращает 8 — что заведомо некорректно).
fn первый_нулевой_бит(байт: u8) -> u32 {
    (!байт).trailing_zeros()
}

#[cfg(test)]
mod тесты {
    use super::*;
    use crate::блок::{БлокУстройствоВПамяти, РАЗМЕР_БЛОКА};

    fn устройство(блоков: u64) -> БлокУстройствоВПамяти {
        БлокУстройствоВПамяти::новое(блоков)
    }

    #[test]
    fn выделение_подряд() {
        let устр = устройство(8);
        let bm = Битмап::новый(0, 1, 64, РАЗМЕР_БЛОКА);
        bm.проинициализировать(&устр, 0).unwrap();
        for ожидаемый in 0..16u64 {
            let индекс = bm.выделить(&устр).unwrap();
            assert_eq!(индекс, ожидаемый);
        }
    }

    #[test]
    fn освобождение_возвращает_бит() {
        let устр = устройство(8);
        let bm = Битмап::новый(0, 1, 64, РАЗМЕР_БЛОКА);
        bm.проинициализировать(&устр, 0).unwrap();
        let _ = bm.выделить(&устр).unwrap();
        let второй = bm.выделить(&устр).unwrap();
        bm.освободить(&устр, второй).unwrap();
        let снова = bm.выделить(&устр).unwrap();
        assert_eq!(снова, второй);
    }

    #[test]
    fn нет_места_возвращает_ошибку() {
        let устр = устройство(8);
        let bm = Битмап::новый(0, 1, 4, РАЗМЕР_БЛОКА);
        bm.проинициализировать(&устр, 0).unwrap();
        for _ in 0..4 {
            bm.выделить(&устр).unwrap();
        }
        let итог = bm.выделить(&устр);
        assert!(matches!(итог, Err(ОшибкаФС::НетСвободныхБлоков)));
    }

    #[test]
    fn зарезервированные_не_выдаются() {
        let устр = устройство(8);
        let bm = Битмап::новый(0, 1, 16, РАЗМЕР_БЛОКА);
        bm.проинициализировать(&устр, 3).unwrap();
        let первый = bm.выделить(&устр).unwrap();
        assert_eq!(первый, 3);
    }

    #[test]
    fn счётчик_занятых_корректен() {
        let устр = устройство(8);
        let bm = Битмап::новый(0, 1, 100, РАЗМЕР_БЛОКА);
        bm.проинициализировать(&устр, 5).unwrap();
        for _ in 0..7 {
            bm.выделить(&устр).unwrap();
        }
        assert_eq!(bm.посчитать_занятые(&устр).unwrap(), 12);
    }
}
