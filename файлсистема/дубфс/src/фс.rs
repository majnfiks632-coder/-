    #[test]
    fn выживает_сбой_питания() {
        let устр = БлокУстройствоВПамяти::новое(512);
        let параметры = ПараметрыСоздания {
            метка: "сбой".into(),
            время_создания: 1,
            ..Default::default()
        };
        let mut фс = ДубФС::создать(&устр, параметры).unwrap();
        фс.создать_файл("/важный.txt", 1).unwrap();
        фс.записать_файл("/важный.txt", 0, "мои сохранения".as_bytes()).unwrap();
        // *Не* размонтируем чисто — имитируем сбой.
        drop(фс);
        // Пере-смонтируем: должно проиграть журнал и восстановить состояние.
        let фс = ДубФС::смонтировать(&устр).unwrap();
        let назад = фс.прочитать_файл("/важный.txt", 0, 100).unwrap();
        assert_eq!(назад, "мои сохранения".as_bytes());
    }

