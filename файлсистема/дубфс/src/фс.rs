    #[test]
    fn удаление_файла_освобождает_inode_и_блоки() {
        let (устр, параметры) = создать_тестовую();
        let mut фс = ДубФС::создать(&устр, параметры).unwrap();
        // Снимок берём *после* создания файла (но до записи в него), чтобы
        // блок, занятый под запись каталога корня, не считался утечкой —
        // в текущем MVP усечение каталога не освобождает его блоки.
        фс.создать_файл("/удалю.txt", 1).unwrap();
        let стат_до = фс.статистика().unwrap();
        let большой = vec![1u8; 30_000];
        фс.записать_файл("/удалю.txt", 0, &большой).unwrap();
        let стат_после_создания = фс.статистика().unwrap();
        assert!(стат_после_создания.свободных_блоков < стат_до.свободных_блоков);

        фс.удалить("/удалю.txt").unwrap();
        let стат_после_удаления = фс.статистика().unwrap();
        // Все блоки данных файла должны быть освобождены, и inode тоже.
        assert_eq!(стат_после_удаления.свободных_блоков, стат_до.свободных_блоков);
        assert_eq!(стат_после_удаления.свободных_inodes, стат_до.свободных_inodes + 1);
    }

