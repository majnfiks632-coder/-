// Тонкий «мостик» между ядром и крейтом служб `dubina-services-drivers`.
//
// Раньше каркас драйверов и реализации (`таймер-ядра`, `клавиатура-ps2`)
// жили прямо в этом модуле. Теперь весь код вынесен в отдельный
// workspace-crate `службы/драйверы`, а здесь остался только re-export —
// чтобы все существующие пути типа `crate::драйверы::клавиатура` и
// `crate::драйверы::глобальный_реестр()` продолжали работать без правок
// остального ядра.
//
// Зачем такой шаг: это первый этап на пути к настоящему микроядру.
// `dubina-services-drivers` уже сейчас — отдельный crate с собственным
// `Cargo.toml`, который зависит только от `core`/`alloc`/`spin` и **не**
// видит остальных модулей ядра. Когда появится ring 3 (этап 7), этот
// crate будет линковаться в пользовательскую службу, а ядро останется
// общаться с ним только через IPC-сообщения и реестр по строковому имени.
//
// Все идентификаторы и сообщения — на русском.

#![allow(dead_code)]

