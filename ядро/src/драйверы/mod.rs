// Каркас драйверов ядра.
//
// Чтобы добавить новый драйвер, нужно:
//   1) Реализовать `trait Драйвер`.
//   2) Зарегистрировать его в реестре через `зарегистрировать()`.
//   3) Привязать к IRQ через `привязать_ирк(ирк, имя_драйвера)`.
//
// При срабатывании IRQ маршрутизатор найдёт драйвер по таблице и вызовет
// `драйвер.обработать_прерывание()`.
//
// Все идентификаторы и сообщения — на русском.

#![allow(dead_code)]

// Драйвер PS/2-клавиатуры использует x86 inline asm (`in al, dx`) и привязан
// к конкретному устройству IBM PC. На aarch64 он не имеет смысла — там клавиатуру
// будет давать USB HID или DT-совместимый контроллер. Поэтому ограничиваемся x86_64.
#[cfg(target_arch = "x86_64")]
#[path = "клавиатура.rs"]
pub mod клавиатура;

use alloc::boxed::Box;
use alloc::vec::Vec;
use spin::Mutex;

/// Трейт, который должен реализовать каждый драйвер.
pub trait Драйвер: Send + Sync {
    /// Краткое имя для диагностики.
    fn имя(&self) -> &'static str;

    /// Однократная инициализация при регистрации.
    fn инициализировать(&mut self) -> Result<(), &'static str>;

    /// Вызывается при прерывании, на которое подписан драйвер.
    /// Реализация по умолчанию — ничего не делает.
    fn обработать_прерывание(&mut self) {}

    /// Корректное завершение работы драйвера (опционально).
    fn завершить(&mut self) {}
}

/// Запись в реестре драйверов.
pub struct Запись {
    pub имя: &'static str,
    pub драйвер: Box<dyn Драйвер>,
}

/// Реестр драйверов — глобальная коллекция.
pub struct Реестр {
    записи: Vec<Запись>,
}

impl Реестр {
    pub const fn пустой() -> Self {
        Self {
            записи: Vec::new(),
        }
    }

    /// Зарегистрировать новый драйвер.
    pub fn зарегистрировать(
        &mut self,
        mut драйвер: Box<dyn Драйвер>,
    ) -> Result<(), &'static str> {
        let имя = драйвер.имя();
        if self.записи.iter().any(|з| з.имя == имя) {
            return Err("драйвер с таким именем уже зарегистрирован");
        }
        драйвер.инициализировать()?;
        self.записи.push(Запись { имя, драйвер });
        Ok(())
    }

    pub fn найти_изм<'а>(&'а mut self, имя: &str) -> Option<&'а mut (dyn Драйвер + 'а)> {
        for запись in self.записи.iter_mut() {
            if запись.имя == имя {
                return Some(запись.драйвер.as_mut());
            }
        }
        None
    }

    pub fn количество(&self) -> usize {
        self.записи.len()
    }

    pub fn имена(&self) -> impl Iterator<Item = &'static str> + '_ {
        self.записи.iter().map(|з| з.имя)
    }
}

/// Глобальный реестр.
static РЕЕСТР: Mutex<Реестр> = Mutex::new(Реестр::пустой());

pub fn глобальный_реестр() -> &'static Mutex<Реестр> {
    &РЕЕСТР
}

/// Удобная обёртка: зарегистрировать драйвер в глобальном реестре.
pub fn зарегистрировать(драйвер: Box<dyn Драйвер>) -> Result<(), &'static str> {
    РЕЕСТР.lock().зарегистрировать(драйвер)
}

/// Пустой драйвер — для самопроверки. Считает, сколько раз его дёрнули.
pub struct ТестовыйДрайвер {
    pub имя_драйвера: &'static str,
    pub срабатываний: core::sync::atomic::AtomicU64,
}

impl ТестовыйДрайвер {
    pub const fn новый(имя: &'static str) -> Self {
        Self {
            имя_драйвера: имя,
            срабатываний: core::sync::atomic::AtomicU64::new(0),
        }
    }
}

impl Драйвер for ТестовыйДрайвер {
    fn имя(&self) -> &'static str {
        self.имя_драйвера
    }

    fn инициализировать(&mut self) -> Result<(), &'static str> {
        Ok(())
    }

    fn обработать_прерывание(&mut self) {
        self.срабатываний
            .fetch_add(1, core::sync::atomic::Ordering::Relaxed);
    }
}
