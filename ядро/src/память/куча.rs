// Простая ядерная куча — линейный free-list (first-fit) поверх
// заранее выделенного диапазона памяти. Этого достаточно для ранних
// этапов ядра: списки потоков, очереди сообщений, динамические строки.
//
// Алгоритм:
//   * Куча — это диапазон памяти размером N байт.
//   * Свободные блоки связаны в односвязный список, отсортированный по
//     адресу. Каждый блок хранит у себя в начале (узел): размер_блока, далее.
//   * Выделение — пройти список, найти первый блок размером ≥ запрос,
//     откусить от него выровненный кусок, остаток вернуть в список.
//   * Освобождение — вставить блок в список по адресу и слить с соседями.
//
// Все сообщения и идентификаторы — на русском.

#![allow(dead_code)]

use core::alloc::{GlobalAlloc, Layout};
use core::mem;
use core::ptr;
use core::ptr::NonNull;

use spin::Mutex;

use super::ошибка::ОшибкаПамяти;

/// Минимальное выравнивание узла свободного списка.
const ВЫРАВНИВАНИЕ_УЗЛА: usize = mem::align_of::<Узел>();
/// Минимальный размер выделения (чтобы остаток мог хранить узел).
const МИНИМАЛЬНЫЙ_РАЗМЕР_БЛОКА: usize = mem::size_of::<Узел>();

#[repr(C)]
struct Узел {
    размер: usize,
    далее: Option<NonNull<Узел>>,
}

unsafe impl Send for Узел {}
unsafe impl Sync for Узел {}

/// Реальная куча — содержит голову free-list, защищена мутексом.
pub struct Куча {
    голова: Option<NonNull<Узел>>,
    /// Сколько байт отдано пользователям (для статистики).
    выделено_байт: usize,
    /// Полный размер кучи.
    всего_байт: usize,
}

unsafe impl Send for Куча {}
unsafe impl Sync for Куча {}

impl Куча {
    pub const fn новая() -> Self {
        Self {
            голова: None,
            выделено_байт: 0,
            всего_байт: 0,
        }
    }

    /// Инициализировать кучу единым свободным блоком в указанном диапазоне.
    ///
    /// # Безопасность
    /// `начало` должен указывать на корректный диапазон памяти длиной
    /// `размер` байт, никем больше не используемой.
    pub unsafe fn инициализировать(
        &mut self,
        начало: *mut u8,
        размер: usize,
    ) -> Result<(), ОшибкаПамяти> {
        if self.голова.is_some() {
            return Err(ОшибкаПамяти::КучаУжеИнициализирована);
        }
        // Выравниваем начало под Узел.
        let выравненное = выровнять_вверх(начало as usize, ВЫРАВНИВАНИЕ_УЗЛА);
        let потеря = выравненное - начало as usize;
        if размер <= потеря + МИНИМАЛЬНЫЙ_РАЗМЕР_БЛОКА {
            return Err(ОшибкаПамяти::НехваткаМестаПодBitmap);
        }
        let размер = размер - потеря;
        let узел = выравненное as *mut Узел;
        unsafe {
            ptr::write(
                узел,
                Узел {
                    размер,
                    далее: None,
                },
            );
        }
        self.голова = NonNull::new(узел);
        self.всего_байт = размер;
        Ok(())
    }

    /// Выделить `layout`. Возвращает указатель или `null` при нехватке памяти.
    pub fn выделить(&mut self, layout: Layout) -> *mut u8 {
        let размер = layout.size().max(МИНИМАЛЬНЫЙ_РАЗМЕР_БЛОКА);
        let выравнивание = layout.align().max(ВЫРАВНИВАНИЕ_УЗЛА);

        let mut предыдущий: Option<NonNull<Узел>> = None;
        let mut текущий = self.голова;
        while let Some(мут_узел) = текущий {
            let адрес_узла = мут_узел.as_ptr() as usize;
            let размер_узла = unsafe { (*мут_узел.as_ptr()).размер };
            // Выравнивание получаемого блока внутри текущего свободного блока.
            let выравненное_начало = выровнять_вверх(адрес_узла, выравнивание);
            let смещение = выравненное_начало - адрес_узла;
            if смещение + размер <= размер_узла {
                // Этот блок подходит.
                let следующий = unsafe { (*мут_узел.as_ptr()).далее };
                let оставшееся_сверху = размер_узла - смещение - размер;

                // Откладываем разделение: если осталось места под узел, вставим как новый узел.
                let _ = смещение; // используется ниже как «головной хвост»

                // Сначала отвяжем текущий узел от списка.
                if let Some(мут_пред) = предыдущий {
                    unsafe { (*мут_пред.as_ptr()).далее = следующий };
                } else {
                    self.голова = следующий;
                }

                // Если есть «головной хвост» (gap до выравнивания), вставим как отдельный
                // свободный блок (но только если он умещает узел).
                if смещение >= МИНИМАЛЬНЫЙ_РАЗМЕР_БЛОКА {
                    let хвост = адрес_узла as *mut Узел;
                    unsafe {
                        ptr::write(
                            хвост,
                            Узел {
                                размер: смещение,
                                далее: self.голова,
                            },
                        );
                        self.голова = NonNull::new(хвост);
                    }
                }

                // Если есть «хвост сверху» — вставим как отдельный блок.
                if оставшееся_сверху >= МИНИМАЛЬНЫЙ_РАЗМЕР_БЛОКА {
                    let хвост_адрес = выравненное_начало + размер;
                    let хвост = хвост_адрес as *mut Узел;
                    unsafe {
                        ptr::write(
                            хвост,
                            Узел {
                                размер: оставшееся_сверху,
                                далее: self.голова,
                            },
                        );
                        self.голова = NonNull::new(хвост);
                    }
                }

                self.выделено_байт += размер;
                return выравненное_начало as *mut u8;
            }
            предыдущий = текущий;
            текущий = unsafe { (*мут_узел.as_ptr()).далее };
        }
        ptr::null_mut()
    }

    /// Освободить блок. `указатель` должен быть тем же, что вернул `выделить`,
    /// и `layout` должен совпадать.
    pub fn освободить(&mut self, указатель: *mut u8, layout: Layout) {
        if указатель.is_null() {
            return;
        }
        let размер = layout.size().max(МИНИМАЛЬНЫЙ_РАЗМЕР_БЛОКА);
        let узел = указатель as *mut Узел;
        unsafe {
            ptr::write(
                узел,
                Узел {
                    размер,
                    далее: self.голова,
                },
            );
        }
        self.голова = NonNull::new(узел);
        if self.выделено_байт >= размер {
            self.выделено_байт -= размер;
        }
        // На этом этапе мы НЕ объединяем соседние блоки — это огрубление,
        // приведёт к фрагментации, но для ранних этапов достаточно. Проблема
        // решается переходом к slab/buddy в этапе 3.
    }

    pub fn выделено_байт(&self) -> usize {
        self.выделено_байт
    }

    pub fn всего_байт(&self) -> usize {
        self.всего_байт
    }
}

const fn выровнять_вверх(значение: usize, выравнивание: usize) -> usize {
    (значение + выравнивание - 1) & !(выравнивание - 1)
}

/// Глобальная обёртка: реализует `GlobalAlloc`, чтобы можно было
/// пользоваться `alloc::Box`, `alloc::Vec`, и т. п.
pub struct ГлобальнаяКуча {
    внутри: Mutex<Куча>,
}

impl ГлобальнаяКуча {
    pub const fn новая() -> Self {
        Self {
            внутри: Mutex::new(Куча::новая()),
        }
    }

    pub unsafe fn инициализировать(
        &self,
        начало: *mut u8,
        размер: usize,
    ) -> Result<(), ОшибкаПамяти> {
        unsafe { self.внутри.lock().инициализировать(начало, размер) }
    }

    pub fn статистика(&self) -> (usize, usize) {
        let к = self.внутри.lock();
        (к.выделено_байт(), к.всего_байт())
    }
}

unsafe impl GlobalAlloc for ГлобальнаяКуча {
    unsafe fn alloc(&self, layout: Layout) -> *mut u8 {
        self.внутри.lock().выделить(layout)
    }

    unsafe fn dealloc(&self, ptr: *mut u8, layout: Layout) {
        self.внутри.lock().освободить(ptr, layout);
    }
}

#[global_allocator]
pub static КУЧА: ГлобальнаяКуча = ГлобальнаяКуча::новая();

/// Размер ядерной кучи по умолчанию: 2 МиБ.
pub const РАЗМЕР_КУЧИ_БАЙТ: usize = 2 * 1024 * 1024;

/// Резервируем 2 МиБ под кучу прямо в .bss ядра. Это удобнее, чем
/// отображать виртуальные страницы — куча сразу доступна и не зависит
/// от состояния таблиц страниц.
#[repr(align(4096))]
struct БуферКучи {
    данные: [u8; РАЗМЕР_КУЧИ_БАЙТ],
}

static mut БУФЕР: БуферКучи = БуферКучи {
    данные: [0; РАЗМЕР_КУЧИ_БАЙТ],
};

/// Инициализировать глобальную ядерную кучу.
pub fn инициализировать_кучу() -> Result<(), ОшибкаПамяти> {
    let указатель = unsafe { (&raw mut БУФЕР.данные).cast::<u8>() };
    unsafe { КУЧА.инициализировать(указатель, РАЗМЕР_КУЧИ_БАЙТ) }
}
