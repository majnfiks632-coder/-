// Физический аллокатор страниц 4 КиБ на основе bitmap.
//
// Карта памяти приходит от загрузчика. Каждая помеченная как доступная
// область разбивается на страницы; в общей bitmap каждой странице соответствует
// один бит: 0 — занято, 1 — свободно.
//
// Конкретно для x86_64 встроенный размер bitmap рассчитан на 4 ГиБ
// физической памяти (1 048 576 страниц = 131 072 байта = 128 КиБ).
//
// Для aarch64 на этом этапе используется тот же размер.
//
// Все сообщения об ошибках — на русском (см. `super::ошибка::ОшибкаПамяти`).

use core::sync::atomic::{AtomicBool, Ordering};

use spin::Mutex;

use super::ошибка::ОшибкаПамяти;
use super::{ФизАдрес, РАЗМЕР_СТРАНИЦЫ};

/// Поддерживаем до 4 ГиБ физической памяти на этом этапе.
pub const МАКС_СТРАНИЦ: usize = (4 * 1024 * 1024 * 1024) / РАЗМЕР_СТРАНИЦЫ;

const БАЙТОВ_В_БИТМАП: usize = МАКС_СТРАНИЦ / 8;

/// Глобальный аллокатор. Защищён мутексом, без прерываний пока что
/// (прерывания включим в этапе 2.4).
pub static АЛЛОКАТОР: Mutex<АллокаторСтраниц> = Mutex::new(АллокаторСтраниц::новый());

static ИНИЦИАЛИЗИРОВАН: AtomicBool = AtomicBool::new(false);

/// Простой bitmap-аллокатор физических страниц.
pub struct АллокаторСтраниц {
    /// Каждый бит = 1 — страница свободна.
    битмап: [u8; БАЙТОВ_В_БИТМАП],
    /// Сколько всего страниц управляется (определяется при инициализации).
    всего_страниц: usize,
    /// Сколько страниц сейчас свободно.
    свободно_страниц: usize,
    /// Подсказка: следующая возможная свободная страница (для ускорения поиска).
    подсказка: usize,
}

impl АллокаторСтраниц {
    pub const fn новый() -> Self {
        Self {
            битмап: [0; БАЙТОВ_В_БИТМАП],
            всего_страниц: 0,
            свободно_страниц: 0,
            подсказка: 0,
        }
    }

    /// Помечает диапазон страниц `[начало; начало + страниц)` как занятый
    /// (0 в bitmap). Используется при инициализации, чтобы исключить
    /// области под ядро, начальный загрузчик, MMIO и т. п.
    fn пометить_занято(&mut self, начало: usize, страниц: usize) {
        for смещение in 0..страниц {
            let страница = начало + смещение;
            if страница >= МАКС_СТРАНИЦ {
                break;
            }
            let байт_индекс = страница / 8;
            let бит_индекс = страница % 8;
            let маска = 1u8 << бит_индекс;
            if self.битмап[байт_индекс] & маска != 0 {
                self.битмап[байт_индекс] &= !маска;
                if self.свободно_страниц > 0 {
                    self.свободно_страниц -= 1;
                }
            }
        }
    }

    /// Помечает диапазон страниц как свободный (1 в bitmap).
    fn пометить_свободно(&mut self, начало: usize, страниц: usize) {
        for смещение in 0..страниц {
            let страница = начало + смещение;
            if страница >= МАКС_СТРАНИЦ {
                break;
            }
            let байт_индекс = страница / 8;
            let бит_индекс = страница % 8;
            let маска = 1u8 << бит_индекс;
            if self.битмап[байт_индекс] & маска == 0 {
                self.битмап[байт_индекс] |= маска;
                self.свободно_страниц += 1;
                if страница >= self.всего_страниц {
                    self.всего_страниц = страница + 1;
                }
            }
        }
    }

    /// Регистрирует доступную область памяти, выровняв её на границы страниц.
    pub fn добавить_область(&mut self, база: u64, длина: u64) {
        if длина == 0 {
            return;
        }
        let начало = ФизАдрес::новый(база).округлить_вверх().значение();
        let конец = ФизАдрес::новый(база + длина).округлить_вниз().значение();
        if конец <= начало {
            return;
        }
        let первая = (начало / РАЗМЕР_СТРАНИЦЫ as u64) as usize;
        let страниц = ((конец - начало) / РАЗМЕР_СТРАНИЦЫ as u64) as usize;
        self.пометить_свободно(первая, страниц);
    }

    /// Вычитает из учёта область занятого диапазона (например, ядра, заголовков загрузчика).
    pub fn зарезервировать_область(&mut self, база: u64, длина: u64) {
        if длина == 0 {
            return;
        }
        let начало = ФизАдрес::новый(база).округлить_вниз().значение();
        let конец = ФизАдрес::новый(база + длина).округлить_вверх().значение();
        if конец <= начало {
            return;
        }
        let первая = (начало / РАЗМЕР_СТРАНИЦЫ as u64) as usize;
        let страниц = ((конец - начало) / РАЗМЕР_СТРАНИЦЫ as u64) as usize;
        self.пометить_занято(первая, страниц);
    }

    /// Выделить одну физическую страницу 4 КиБ.
    pub fn выделить_страницу(&mut self) -> Result<ФизАдрес, ОшибкаПамяти> {
        if self.свободно_страниц == 0 {
            return Err(ОшибкаПамяти::НетСвободныхСтраниц);
        }
        // Линейный поиск с подсказкой.
        let всего_байтов = (self.всего_страниц + 7) / 8;
        for сдвиг in 0..всего_байтов {
            let байт_индекс = (self.подсказка + сдвиг) % всего_байтов;
            let байт = self.битмап[байт_индекс];
            if байт == 0 {
                continue;
            }
            let бит_индекс = байт.trailing_zeros() as usize;
            let страница = байт_индекс * 8 + бит_индекс;
            if страница >= self.всего_страниц {
                continue;
            }
            self.битмап[байт_индекс] &= !(1u8 << бит_индекс);
            self.свободно_страниц -= 1;
            self.подсказка = байт_индекс;
            return Ok(ФизАдрес::новый((страница * РАЗМЕР_СТРАНИЦЫ) as u64));
        }
        Err(ОшибкаПамяти::НетСвободныхСтраниц)
    }

    /// Освободить одну физическую страницу.
    pub fn освободить_страницу(&mut self, адрес: ФизАдрес) -> Result<(), ОшибкаПамяти> {
        if !адрес.выравнен_на_страницу() {
            return Err(ОшибкаПамяти::НеВыровнен);
        }
        let страница = (адрес.значение() / РАЗМЕР_СТРАНИЦЫ as u64) as usize;
        if страница >= МАКС_СТРАНИЦ {
            return Err(ОшибкаПамяти::АдресВнеДиапазона);
        }
        let байт_индекс = страница / 8;
        let бит_индекс = страница % 8;
        let маска = 1u8 << бит_индекс;
        if self.битмап[байт_индекс] & маска != 0 {
            return Err(ОшибкаПамяти::ДвойноеОсвобождение);
        }
        self.битмап[байт_индекс] |= маска;
        self.свободно_страниц += 1;
        if страница >= self.всего_страниц {
            self.всего_страниц = страница + 1;
        }
        Ok(())
    }

    pub fn всего_страниц(&self) -> usize {
        self.всего_страниц
    }

    pub fn свободно_страниц(&self) -> usize {
        self.свободно_страниц
    }

    pub fn всего_байтов(&self) -> u64 {
        self.всего_страниц as u64 * РАЗМЕР_СТРАНИЦЫ as u64
    }

    pub fn свободно_байтов(&self) -> u64 {
        self.свободно_страниц as u64 * РАЗМЕР_СТРАНИЦЫ as u64
    }
}

/// Получить статус «инициализирован».
pub fn инициализирован() -> bool {
    ИНИЦИАЛИЗИРОВАН.load(Ordering::Acquire)
}

/// Зафиксировать инициализацию (вызывается из `арх::*`).
pub fn пометить_инициализированным() {
    ИНИЦИАЛИЗИРОВАН.store(true, Ordering::Release);
}

#[cfg(test)]
mod тесты {
    use super::*;

    #[test]
    fn выделить_и_освободить() {
        let mut а = АллокаторСтраниц::новый();
        // 1 МиБ доступной памяти, начиная с 1 МиБ.
        а.добавить_область(0x10_0000, 0x10_0000);
        let было = а.свободно_страниц();
        let стр = а.выделить_страницу().unwrap();
        assert_eq!(а.свободно_страниц(), было - 1);
        а.освободить_страницу(стр).unwrap();
        assert_eq!(а.свободно_страниц(), было);
    }

    #[test]
    fn двойное_освобождение_ошибка() {
        let mut а = АллокаторСтраниц::новый();
        а.добавить_область(0x10_0000, 0x10_0000);
        let стр = а.выделить_страницу().unwrap();
        а.освободить_страницу(стр).unwrap();
        assert_eq!(
            а.освободить_страницу(стр),
            Err(ОшибкаПамяти::ДвойноеОсвобождение)
        );
    }

    #[test]
    fn резервирование_удаляет_страницы() {
        let mut а = АллокаторСтраниц::новый();
        а.добавить_область(0x10_0000, 0x10_0000);
        let было = а.свободно_страниц();
        а.зарезервировать_область(0x10_0000, РАЗМЕР_СТРАНИЦЫ as u64 * 4);
        assert_eq!(а.свободно_страниц(), было - 4);
    }
}
