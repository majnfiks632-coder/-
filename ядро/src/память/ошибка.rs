// Ошибки подсистемы памяти. Все сообщения — на русском.

use core::fmt;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ОшибкаПамяти {
    /// Запросили выделение, но свободных страниц не осталось.
    НетСвободныхСтраниц,
    /// Освобождают страницу, которая уже свободна (двойное освобождение).
    ДвойноеОсвобождение,
    /// Адрес выходит за пределы управляемой области.
    АдресВнеДиапазона,
    /// Адрес не выровнен на размер страницы.
    НеВыровнен,
    /// Карта памяти от загрузчика отсутствует или повреждена.
    НетКартыПамяти,
    /// Внутренний массив-bitmap слишком мал для предоставленной памяти.
    НехваткаМестаПодBitmap,
    /// Куча уже инициализирована повторно.
    КучаУжеИнициализирована,
    /// Куча запрашивает память до своей инициализации.
    КучаНеИнициализирована,
    /// Запрошен слишком большой размер выделения.
    СлишкомБольшоеВыделение,
}

impl fmt::Display for ОшибкаПамяти {
    fn fmt(&self, ф: &mut fmt::Formatter<'_>) -> fmt::Result {
        let текст = match self {
            ОшибкаПамяти::НетСвободныхСтраниц => "нет свободных физических страниц",
            ОшибкаПамяти::ДвойноеОсвобождение => "повторное освобождение страницы",
            ОшибкаПамяти::АдресВнеДиапазона => "физический адрес вне диапазона",
            ОшибкаПамяти::НеВыровнен => "адрес не выровнен на размер страницы",
            ОшибкаПамяти::НетКартыПамяти => "загрузчик не передал карту памяти",
            ОшибкаПамяти::НехваткаМестаПодBitmap => {
                "не хватает встроенного места под битмап страниц"
            }
            ОшибкаПамяти::КучаУжеИнициализирована => "ядерная куча уже инициализирована",
            ОшибкаПамяти::КучаНеИнициализирована => {
                "ядерная куча используется до инициализации"
            }
            ОшибкаПамяти::СлишкомБольшоеВыделение => "слишком большой размер выделения",
        };
        ф.write_str(текст)
    }
}
