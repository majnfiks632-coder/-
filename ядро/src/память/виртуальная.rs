#![allow(dead_code)]

use super::ошибка::ОшибкаПамяти;
use super::{ВиртАдрес, ФизАдрес};

/// Флаги отображения страницы. Архитектурно-нейтральное представление,
/// архитектурный код преобразует это в нужные биты PTE.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub struct ФлагиСтраницы(u32);

impl ФлагиСтраницы {
    pub const ПУСТО: Self = Self(0);
    /// Страница присутствует и доступна.
    pub const ПРИСУТСТВУЕТ: Self = Self(1 << 0);
    /// Доступна для записи (иначе только чтение).
    pub const ЗАПИСЬ: Self = Self(1 << 1);
    /// Доступна из режима пользователя (иначе только ядро).
    pub const ПОЛЬЗОВАТЕЛЬ: Self = Self(1 << 2);
    /// Кэширование запрещено (важно для MMIO).
    pub const БЕЗ_КЭША: Self = Self(1 << 3);
    /// Доступна для исполнения (на x86_64 нужно снимать NX).
    pub const ИСПОЛНЕНИЕ: Self = Self(1 << 4);
    /// Глобальная страница (TLB не сбрасывается при переключении CR3).
    pub const ГЛОБАЛЬНАЯ: Self = Self(1 << 5);

    pub const fn биты(self) -> u32 {
        self.0
    }

    pub const fn содержит(self, другой: Self) -> bool {
        self.0 & другой.0 == другой.0
    }
}

impl core::ops::BitOr for ФлагиСтраницы {
    type Output = Self;
    fn bitor(self, другой: Self) -> Self {
        Self(self.0 | другой.0)
    }
}

impl core::ops::BitOrAssign for ФлагиСтраницы {
    fn bitor_assign(&mut self, другой: Self) {
        self.0 |= другой.0;
    }
}

/// Универсальный интерфейс к таблице страниц текущего адресного пространства.
pub trait ТаблицаСтраниц {
    /// Отобразить виртуальную страницу `винт` на физическую `физ` с заданными флагами.
    fn отобразить(
        &mut self,
        винт: ВиртАдрес,
        физ: ФизАдрес,
        флаги: ФлагиСтраницы,
    ) -> Result<(), ОшибкаПамяти>;

    /// Снять отображение виртуальной страницы. Возвращает физическую страницу,
    /// которая ранее была отображена (для дальнейшего освобождения вызывающим).
    fn снять_отображение(&mut self, винт: ВиртАдрес) -> Result<ФизАдрес, ОшибкаПамяти>;

    /// Узнать, на какую физическую страницу отображён данный виртуальный адрес.
    fn перевести(&self, винт: ВиртАдрес) -> Option<ФизАдрес>;
}
