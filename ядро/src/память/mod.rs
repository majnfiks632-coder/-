/// Размер обычной страницы (4 КиБ) — одинаков на всех поддерживаемых архитектурах.
pub const РАЗМЕР_СТРАНИЦЫ: usize = 4096;

/// Тип адреса, обозначающий физический адрес. На уровне ядра физические
/// адреса принципиально отличаются от виртуальных — мы не позволяем их
/// смешивать без преобразования.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
#[repr(transparent)]
pub struct ФизАдрес(pub u64);

impl ФизАдрес {
    pub const fn новый(адрес: u64) -> Self {
        Self(адрес)
    }

    pub const fn значение(self) -> u64 {
        self.0
    }

    pub const fn выравнен_на_страницу(self) -> bool {
        self.0 & ((РАЗМЕР_СТРАНИЦЫ as u64) - 1) == 0
    }

    pub const fn округлить_вверх(self) -> Self {
        let маска = (РАЗМЕР_СТРАНИЦЫ as u64) - 1;
        Self((self.0 + маска) & !маска)
    }

    pub const fn округлить_вниз(self) -> Self {
        let маска = (РАЗМЕР_СТРАНИЦЫ as u64) - 1;
        Self(self.0 & !маска)
    }
}

/// Виртуальный адрес — то, что видит процесс или ядро после трансляции через MMU.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
#[repr(transparent)]
pub struct ВиртАдрес(pub u64);

impl ВиртАдрес {
    pub const fn новый(адрес: u64) -> Self {
        Self(адрес)
    }

    pub const fn значение(self) -> u64 {
        self.0
    }

    pub const fn выравнен_на_страницу(self) -> bool {
        self.0 & ((РАЗМЕР_СТРАНИЦЫ as u64) - 1) == 0
    }

    pub const fn округлить_вниз(self) -> Self {
        let маска = (РАЗМЕР_СТРАНИЦЫ as u64) - 1;
        Self(self.0 & !маска)
    }
}
