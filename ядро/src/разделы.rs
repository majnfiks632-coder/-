// Парсер таблицы разделов диска: MBR (DOS) и GPT (UEFI).
//
// На современных машинах (включая ASUS X552E с UEFI) основной формат — GPT.
// MBR используется как fallback на старых машинах или внутри protective MBR
// (первый сектор всегда MBR, у GPT там стоит маркер тип 0xEE на весь диск).
//
// Структура GPT:
//   * Сектор 0: protective MBR (тип 0xEE, охватывает весь диск)
//   * Сектор 1: GPT Header (магия "EFI PART", CRC32, ссылка на массив записей)
//   * Сектор 2..N: массив GPT Partition Entry (по умолчанию 128 записей × 128 байт = 32 КиБ)
//
// Каждая запись: 16-байтовый GUID типа, 16-байтовый GUID раздела,
// LBA начала и конца, флаги, имя UTF-16LE (72 байта = 36 символов).
//
// Особо важные GUID-ы типа:
//   * EFI System (ESP):  C12A7328-F81F-11D2-BA4B-00A0C93EC93B
//   * Microsoft Basic:   EBD0A0A2-B9E5-4433-87C0-68B6B72699C7
//   * Linux filesystem:  0FC63DAF-8483-4772-8E79-3D69D8477DE4
//   * Linux swap:        0657FD6D-A4AB-43C4-84E5-0933C84B4F4F

#![allow(dead_code)]

use crate::println;
use crate::ахки;

const МАГИЯ_GPT: [u8; 8] = *b"EFI PART";
const СИГНАТУРА_MBR: u16 = 0xAA55;

const РАЗДЕЛОВ_МАКС: usize = 16;

/// Тип файловой системы / назначение раздела.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ТипРаздела {
    EFISystem,
    Microsoft,    // FAT/NTFS
    Linux,
    LinuxSwap,
    BiosBoot,
    Неизвестно,
}

impl ТипРаздела {
    pub fn имя(&self) -> &'static str {
        match self {
            ТипРаздела::EFISystem => "EFI System Partition (ESP)",
            ТипРаздела::Microsoft => "Microsoft Basic Data (FAT/NTFS)",
            ТипРаздела::Linux => "Linux filesystem",
            ТипРаздела::LinuxSwap => "Linux swap",
            ТипРаздела::BiosBoot => "BIOS Boot",
            ТипРаздела::Неизвестно => "неизвестный",
        }
    }
}

/// Описание одного раздела диска.
#[derive(Debug, Clone, Copy)]
pub struct Раздел {
    pub номер: u8,
    pub лба_начало: u64,
    pub лба_конец: u64,    // включительно
    pub тип: ТипРаздела,
    pub guid_типа: [u8; 16],
    pub guid_раздела: [u8; 16],
    pub имя: [u8; 72],     // имя в UTF-16LE
    pub флаги: u64,
}

impl Раздел {
    pub fn размер_секторов(&self) -> u64 {
        if self.лба_конец >= self.лба_начало {
            self.лба_конец - self.лба_начало + 1
        } else {
            0
        }
    }

    pub fn размер_мб(&self, сектор: u32) -> u64 {
        self.размер_секторов() * сектор as u64 / (1024 * 1024)
    }

    pub fn имя_строкой(&self, выход: &mut [u8]) -> usize {
        // имя — UTF-16LE, до 36 символов. Конвертируем в latin1, остальное — '?'.
        let mut вых_i = 0;
        for пара in self.имя.chunks(2) {
            if пара.len() < 2 || вых_i + 1 >= выход.len() { break; }
            let cu = (пара[0] as u16) | ((пара[1] as u16) << 8);
            if cu == 0 { break; }
            if cu < 128 {
                выход[вых_i] = cu as u8;
            } else {
                выход[вых_i] = b'?';
            }
            вых_i += 1;
        }
        вых_i
    }
}

/// Разобранная таблица разделов.
#[derive(Debug, Clone, Copy)]
pub struct ТаблицаРазделов {
    pub gpt: bool,
    pub количество: u8,
    pub разделы: [Option<Раздел>; РАЗДЕЛОВ_МАКС],
}

// ==========================================================================
// Чтение заголовка GPT
// ==========================================================================

#[repr(C, packed)]
struct ЗаголовокGPT {
    магия: [u8; 8],
    ревизия: u32,
    размер_заголовка: u32,
    crc32_заголовка: u32,
    rsv: u32,
    мой_лба: u64,
    альт_лба: u64,
    первый_лба: u64,
    последний_лба: u64,
    диск_guid: [u8; 16],
    запись_лба: u64,
    количество_записей: u32,
    размер_записи: u32,
    crc32_записей: u32,
}

#[repr(C, packed)]
struct ЗаписьGPT {
    тип_guid: [u8; 16],
    раздел_guid: [u8; 16],
    лба_начало: u64,
    лба_конец: u64,
    флаги: u64,
    имя: [u8; 72],
}

/// EFI System Partition GUID: C12A7328-F81F-11D2-BA4B-00A0C93EC93B (mixed-endian)
const GUID_EFI_SYSTEM: [u8; 16] = [
    0x28, 0x73, 0x2A, 0xC1, 0x1F, 0xF8, 0xD2, 0x11,
    0xBA, 0x4B, 0x00, 0xA0, 0xC9, 0x3E, 0xC9, 0x3B,
];

/// Microsoft Basic Data: EBD0A0A2-B9E5-4433-87C0-68B6B72699C7
const GUID_MICROSOFT: [u8; 16] = [
    0xA2, 0xA0, 0xD0, 0xEB, 0xE5, 0xB9, 0x33, 0x44,
    0x87, 0xC0, 0x68, 0xB6, 0xB7, 0x26, 0x99, 0xC7,
];

/// Linux filesystem: 0FC63DAF-8483-4772-8E79-3D69D8477DE4
const GUID_LINUX: [u8; 16] = [
    0xAF, 0x3D, 0xC6, 0x0F, 0x83, 0x84, 0x72, 0x47,
    0x8E, 0x79, 0x3D, 0x69, 0xD8, 0x47, 0x7D, 0xE4,
];

/// Linux swap: 0657FD6D-A4AB-43C4-84E5-0933C84B4F4F
const GUID_LINUX_SWAP: [u8; 16] = [
    0x6D, 0xFD, 0x57, 0x06, 0xAB, 0xA4, 0xC4, 0x43,
    0x84, 0xE5, 0x09, 0x33, 0xC8, 0x4B, 0x4F, 0x4F,
];

/// BIOS boot: 21686148-6449-6E6F-744E-656564454649
const GUID_BIOS_BOOT: [u8; 16] = [
    0x48, 0x61, 0x68, 0x21, 0x49, 0x64, 0x6F, 0x6E,
    0x74, 0x4E, 0x65, 0x65, 0x64, 0x45, 0x46, 0x49,
];

fn определить_тип_по_guid(guid: &[u8; 16]) -> ТипРаздела {
    if *guid == GUID_EFI_SYSTEM { ТипРаздела::EFISystem }
    else if *guid == GUID_MICROSOFT { ТипРаздела::Microsoft }
    else if *guid == GUID_LINUX { ТипРаздела::Linux }
    else if *guid == GUID_LINUX_SWAP { ТипРаздела::LinuxSwap }
    else if *guid == GUID_BIOS_BOOT { ТипРаздела::BiosBoot }
    else { ТипРаздела::Неизвестно }
}

fn нулевой_guid(guid: &[u8; 16]) -> bool {
    guid.iter().all(|&b| b == 0)
}

// ==========================================================================
// Главная точка: разобрать таблицу разделов диска
// ==========================================================================

/// Прочитать сектор 0 (защитный MBR), затем сектор 1 (GPT-заголовок).
/// Если магия GPT присутствует — разобрать массив записей. Иначе — MBR.
pub fn прочитать_таблицу(хба: &ахки::ИнфоAHCI, порт: u8) -> Option<ТаблицаРазделов> {
    let лба0_phys = ахки::прочитать_секторы(хба, порт, 0, 1)?;
    let mbr_сиг = unsafe { core::ptr::read_volatile((лба0_phys + 510) as *const u16) };
    освободить_страницу(лба0_phys);
    if mbr_сиг != СИГНАТУРА_MBR {
        println!("[ИНФО] Разделы: MBR-сигнатура отсутствует в секторе 0 порта {}", порт);
        return None;
    }

    // Попробуем GPT (сектор 1).
    let лба1_phys = ахки::прочитать_секторы(хба, порт, 1, 1)?;
    let заголовок: ЗаголовокGPT = unsafe { core::ptr::read_unaligned(лба1_phys as *const ЗаголовокGPT) };

    if заголовок.магия == МАГИЯ_GPT {
        let запись_лба = заголовок.запись_лба;
        let количество = заголовок.количество_записей;
        let размер_записи = заголовок.размер_записи;
        освободить_страницу(лба1_phys);
        return разобрать_gpt(хба, порт, запись_лба, количество, размер_записи);
    }
    освободить_страницу(лба1_phys);

    // GPT нет — разбираем MBR. (Этап 3.4 на legacy: только GPT/UEFI; MBR пока заглушка.)
    println!("[ИНФО] Разделы: GPT-сигнатура отсутствует — это MBR (разбор пока не реализован)");
    None
}

fn разобрать_gpt(
    хба: &ахки::ИнфоAHCI,
    порт: u8,
    запись_лба: u64,
    количество: u32,
    размер_записи: u32,
) -> Option<ТаблицаРазделов> {
    if размер_записи as usize > 256 || размер_записи < 128 {
        println!("[ВНИМАНИЕ] Разделы GPT: подозрительный размер записи {} байт", размер_записи);
        return None;
    }
    let записей_в_секторе = (512u32 / размер_записи) as usize;
    let нужно_секторов = ((количество as usize + записей_в_секторе - 1) / записей_в_секторе).max(1);
    // Обрабатываем по одному сектору, не больше 8 за раз (4 КиБ буфер).
    let макс_секторов_за_раз: usize = 8;
    let mut таблица = ТаблицаРазделов {
        gpt: true,
        количество: 0,
        разделы: [None; РАЗДЕЛОВ_МАКС],
    };
    let mut обработано: u32 = 0;
    let mut сектор: u64 = запись_лба;

    while обработано < количество {
        let сейчас = (нужно_секторов - сектор as usize + запись_лба as usize)
            .min(макс_секторов_за_раз) as u16;
        if сейчас == 0 { break; }
        let phys = ахки::прочитать_секторы(хба, порт, сектор, сейчас)?;
        for i in 0..(сейчас as u32 * записей_в_секторе as u32) {
            if обработано >= количество { break; }
            let оффсет = (i as u64) * размер_записи as u64;
            let запись: ЗаписьGPT = unsafe {
                core::ptr::read_unaligned((phys + оффсет) as *const ЗаписьGPT)
            };
            обработано += 1;
            if нулевой_guid(&запись.тип_guid) { continue; }
            let nраз = таблица.количество as usize;
            if nраз >= РАЗДЕЛОВ_МАКС { break; }
            let раз = Раздел {
                номер: (nраз as u8) + 1,
                лба_начало: запись.лба_начало,
                лба_конец: запись.лба_конец,
                тип: определить_тип_по_guid(&запись.тип_guid),
                guid_типа: запись.тип_guid,
                guid_раздела: запись.раздел_guid,
                имя: запись.имя,
                флаги: запись.флаги,
            };
            таблица.разделы[nраз] = Some(раз);
            таблица.количество += 1;
        }
        освободить_страницу(phys);
        сектор += сейчас as u64;
        if обработано >= количество { break; }
    }
    Some(таблица)
}

fn освободить_страницу(phys: u64) {
    let _ = crate::память::физическая::АЛЛОКАТОР
        .lock()
        .освободить_страницу(crate::память::ФизАдрес::новый(phys));
}

/// Распечатать список найденных разделов.
pub fn распечатать_таблицу(таблица: &ТаблицаРазделов, размер_сектора: u32) {
    let формат = if таблица.gpt { "GPT" } else { "MBR" };
    println!("[ИНФО] Разделы ({}): найдено {} ", формат, таблица.количество);
    for раз in таблица.разделы.iter().flatten() {
        let mut имя = [0u8; 36];
        let n = раз.имя_строкой(&mut имя);
        let имя_str = core::str::from_utf8(&имя[..n]).unwrap_or("?");
        println!(
            "       #{}: LBA {}..{}, {} МиБ, {}, имя «{}»",
            раз.номер,
            раз.лба_начало,
            раз.лба_конец,
            раз.размер_мб(размер_сектора),
            раз.тип.имя(),
            имя_str,
        );
    }
}
