// Драйвер 8259 PIC (Programmable Interrupt Controller).
//
// На IBM PC / QEMU есть две каскадированные микросхемы 8259:
//   PIC1 на портах 0x20 (команда) / 0x21 (данные) — ведущий, IRQ 0..7
//   PIC2 на портах 0xA0 (команда) / 0xA1 (данные) — ведомый,  IRQ 8..15
//
// По умолчанию PIC1 выдаёт прерывания на векторах 8..15, что пересекается
// с исключениями процессора (Double Fault, GP). Поэтому первое, что нужно
// сделать — перепрограммировать ведущего на 0x20 (32), ведомого на 0x28 (40).
//
// Все идентификаторы и сообщения — на русском.

#![allow(dead_code)]

use core::arch::asm;

const PIC1_КОМАНДА: u16 = 0x20;
const PIC1_ДАННЫЕ: u16 = 0x21;
const PIC2_КОМАНДА: u16 = 0xA0;
const PIC2_ДАННЫЕ: u16 = 0xA1;

const ICW1_INIT: u8 = 0x10;
const ICW1_ICW4: u8 = 0x01;
const ICW4_8086: u8 = 0x01;
const КОМАНДА_EOI: u8 = 0x20;

unsafe fn вывести_порт(порт: u16, значение: u8) {
    unsafe {
        asm!("out dx, al", in("dx") порт, in("al") значение);
    }
}

unsafe fn ввести_порт(порт: u16) -> u8 {
    let значение: u8;
    unsafe {
        asm!("in al, dx", out("al") значение, in("dx") порт);
    }
    значение
}

unsafe fn пауза_io() {
    // Запись в неиспользуемый порт даёт небольшую задержку — некоторым
    // старым PIC это нужно между ICW.
    unsafe { вывести_порт(0x80, 0) };
}

/// Перепрограммировать оба PIC: ведущий на 0x20, ведомый на 0x28.
/// После этого все IRQ маскированы — драйверы должны явно их размаскировать
/// через `снять_маску_ирк()`.
pub unsafe fn перенастроить() {
    unsafe {
        // ICW1 — начало инициализации.
        вывести_порт(PIC1_КОМАНДА, ICW1_INIT | ICW1_ICW4);
        пауза_io();
        вывести_порт(PIC2_КОМАНДА, ICW1_INIT | ICW1_ICW4);
        пауза_io();

        // ICW2 — базовый вектор.
        вывести_порт(PIC1_ДАННЫЕ, 0x20);
        пауза_io();
        вывести_порт(PIC2_ДАННЫЕ, 0x28);
        пауза_io();

        // ICW3 — каскадная связь.
        вывести_порт(PIC1_ДАННЫЕ, 4); // PIC2 на IRQ 2 ведущего
        пауза_io();
        вывести_порт(PIC2_ДАННЫЕ, 2); // ведомый на каскаде 2
        пауза_io();

        // ICW4 — режим 8086.
        вывести_порт(PIC1_ДАННЫЕ, ICW4_8086);
        пауза_io();
        вывести_порт(PIC2_ДАННЫЕ, ICW4_8086);
        пауза_io();

        // Маскируем всё.
        вывести_порт(PIC1_ДАННЫЕ, 0xFF);
        вывести_порт(PIC2_ДАННЫЕ, 0xFF);
    }
}

/// Снять маску с конкретного IRQ.
pub unsafe fn снять_маску_ирк(ирк: u8) {
    let (порт, бит) = if ирк < 8 {
        (PIC1_ДАННЫЕ, ирк)
    } else {
        (PIC2_ДАННЫЕ, ирк - 8)
    };
    unsafe {
        let маска = ввести_порт(порт);
        вывести_порт(порт, маска & !(1 << бит));
    }
}

/// Поставить маску на конкретный IRQ (отключить).
pub unsafe fn поставить_маску_ирк(ирк: u8) {
    let (порт, бит) = if ирк < 8 {
        (PIC1_ДАННЫЕ, ирк)
    } else {
        (PIC2_ДАННЫЕ, ирк - 8)
    };
    unsafe {
        let маска = ввести_порт(порт);
        вывести_порт(порт, маска | (1 << бит));
    }
}

/// Подтвердить обработку прерывания (EOI). Вызывается в конце ASM-трамплина.
pub fn подтвердить(вектор: u8) {
    unsafe {
        if вектор >= 0x28 {
            // Прерывание от ведомого PIC — нужно EOI обоим.
            вывести_порт(PIC2_КОМАНДА, КОМАНДА_EOI);
        }
        вывести_порт(PIC1_КОМАНДА, КОМАНДА_EOI);
    }
}
