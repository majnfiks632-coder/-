// Управление 4-уровневыми таблицами страниц на x86_64.
//
// Адресное пространство x86_64 имеет 4 уровня:
//
//     виртуальный адрес 48 бит
//     ┌──────┬──────┬──────┬──────┬──────────────┐
//     │ PML4 │ PDPT │  PD  │  PT  │  смещение    │
//     │  9   │  9   │  9   │  9   │     12       │
//     └──────┴──────┴──────┴──────┴──────────────┘
//
// На этом этапе мы:
//   * читаем текущий PML4 из регистра CR3;
//   * предоставляем безопасный API map/unmap/translate;
//   * новые таблицы выделяем из физического аллокатора;
//   * физические адреса читаем через идентификационное отображение
//     первых 4 ГиБ, установленное стартовым стабом ядра.
//
// Все диагностические сообщения и имена идентификаторов — на русском.

#![allow(dead_code)]

use core::arch::asm;
use core::ptr;

use crate::память::виртуальная::{ТаблицаСтраниц, ФлагиСтраницы};
use crate::память::ошибка::ОшибкаПамяти;
use crate::память::{ВиртАдрес, ФизАдрес, РАЗМЕР_СТРАНИЦЫ};
use crate::память::физическая::АЛЛОКАТОР;

/// Бит «присутствует» в записи.
const БИТ_ПРИСУТСТВУЕТ: u64 = 1 << 0;
/// Бит «записываемая».
const БИТ_ЗАПИСЬ: u64 = 1 << 1;
/// Бит «доступна пользователю».
const БИТ_ПОЛЬЗОВАТЕЛЬ: u64 = 1 << 2;
/// Бит «без кэширования».
const БИТ_БЕЗ_КЭША: u64 = 1 << 4;
/// Бит «глобальная».
const БИТ_ГЛОБАЛЬНАЯ: u64 = 1 << 8;
/// Бит «огромная страница» (на уровне PD — это страница 2 МиБ).
const БИТ_ОГРОМНАЯ: u64 = 1 << 7;
/// Бит NX (запрет выполнения), верхний бит записи.
const БИТ_НИКОГДА_ИСПОЛНИТЬ: u64 = 1 << 63;

/// Маска физического адреса в записи: биты 12..51.
const МАСКА_ФИЗ: u64 = 0x000F_FFFF_FFFF_F000;

/// Структура — ссылка на текущую активную 4-уровневую таблицу страниц
/// (тот PML4, на который указывает CR3).
pub struct АктивнаяТаблица;

impl АктивнаяТаблица {
    /// Получить ссылку на активную таблицу. Безопасно — мы не передаём владение,
    /// но любые изменения через `отобразить`/`снять_отображение` обязаны быть
    /// согласованы с состоянием системы (пока ядро однопоточное — это безопасно).
    pub fn новая() -> Self {
        Self
    }

    fn cr3() -> u64 {
        let значение: u64;
        unsafe {
            asm!("mov {}, cr3", out(reg) значение, options(nomem, nostack, preserves_flags));
        }
        значение & МАСКА_ФИЗ
    }
}

/// Преобразовать архитектурно-нейтральные флаги в биты записи x86_64.
fn флаги_в_биты(флаги: ФлагиСтраницы) -> u64 {
    let mut биты: u64 = 0;
    if флаги.содержит(ФлагиСтраницы::ПРИСУТСТВУЕТ) {
        биты |= БИТ_ПРИСУТСТВУЕТ;
    }
    if флаги.содержит(ФлагиСтраницы::ЗАПИСЬ) {
        биты |= БИТ_ЗАПИСЬ;
    }
    if флаги.содержит(ФлагиСтраницы::ПОЛЬЗОВАТЕЛЬ) {
        биты |= БИТ_ПОЛЬЗОВАТЕЛЬ;
    }
    if флаги.содержит(ФлагиСтраницы::БЕЗ_КЭША) {
        биты |= БИТ_БЕЗ_КЭША;
    }
    if флаги.содержит(ФлагиСтраницы::ГЛОБАЛЬНАЯ) {
        биты |= БИТ_ГЛОБАЛЬНАЯ;
    }
    if !флаги.содержит(ФлагиСтраницы::ИСПОЛНЕНИЕ) {
        биты |= БИТ_НИКОГДА_ИСПОЛНИТЬ;
    }
    биты
}

/// Получить указатель на таблицу из физического адреса (через идентичное
/// отображение). Корректно только пока физический адрес < 4 ГиБ.
unsafe fn таблица_по_физ(физ: u64) -> *mut [u64; 512] {
    физ as *mut [u64; 512]
}

/// Прочитать запись таблицы.
unsafe fn читать_запись(таблица: *const [u64; 512], индекс: usize) -> u64 {
    debug_assert!(индекс < 512);
    let указатель = unsafe { (&(*таблица)[индекс]) as *const u64 };
    unsafe { ptr::read_volatile(указатель) }
}

/// Записать запись таблицы.
unsafe fn записать_запись(таблица: *mut [u64; 512], индекс: usize, значение: u64) {
    debug_assert!(индекс < 512);
    let указатель = unsafe { (&mut (*таблица)[индекс]) as *mut u64 };
    unsafe { ptr::write_volatile(указатель, значение) };
}

/// Сбросить TLB для конкретного виртуального адреса.
fn сбросить_tlb(адрес: ВиртАдрес) {
    unsafe {
        asm!("invlpg [{}]", in(reg) адрес.значение(), options(nostack, preserves_flags));
    }
}

/// Извлечь PML4-индекс из виртуального адреса.
const fn индекс_pml4(адрес: u64) -> usize {
    ((адрес >> 39) & 0x1FF) as usize
}
const fn индекс_pdpt(адрес: u64) -> usize {
    ((адрес >> 30) & 0x1FF) as usize
}
const fn индекс_pd(адрес: u64) -> usize {
    ((адрес >> 21) & 0x1FF) as usize
}
const fn индекс_pt(адрес: u64) -> usize {
    ((адрес >> 12) & 0x1FF) as usize
}

impl ТаблицаСтраниц for АктивнаяТаблица {
    fn отобразить(
        &mut self,
        винт: ВиртАдрес,
        физ: ФизАдрес,
        флаги: ФлагиСтраницы,
    ) -> Result<(), ОшибкаПамяти> {
        if !винт.выравнен_на_страницу() || !физ.выравнен_на_страницу() {
            return Err(ОшибкаПамяти::НеВыровнен);
        }
        let биты_страницы = флаги_в_биты(флаги | ФлагиСтраницы::ПРИСУТСТВУЕТ);
        // Промежуточные таблицы должны быть «открытыми» для чтения и пользователя
        // (если флаги это разрешают). Запись/исполнение определяются листовой записью.
        let биты_промежуточные =
            БИТ_ПРИСУТСТВУЕТ | БИТ_ЗАПИСЬ
            | (if флаги.содержит(ФлагиСтраницы::ПОЛЬЗОВАТЕЛЬ) { БИТ_ПОЛЬЗОВАТЕЛЬ } else { 0 });

        let pml4 = АктивнаяТаблица::cr3();

        let pdpt = unsafe { ход_или_создать(pml4, индекс_pml4(винт.значение()), биты_промежуточные)? };
        let pd = unsafe { ход_или_создать(pdpt, индекс_pdpt(винт.значение()), биты_промежуточные)? };
        // Если в PD стоит «огромная страница» — мы не поддерживаем смешение здесь.
        let запись_pd = unsafe {
            читать_запись(таблица_по_физ(pd), индекс_pd(винт.значение()))
        };
        if запись_pd & БИТ_ПРИСУТСТВУЕТ != 0 && запись_pd & БИТ_ОГРОМНАЯ != 0 {
            return Err(ОшибкаПамяти::АдресВнеДиапазона);
        }
        let pt = unsafe { ход_или_создать(pd, индекс_pd(винт.значение()), биты_промежуточные)? };

        unsafe {
            let таблица = таблица_по_физ(pt);
            let индекс = индекс_pt(винт.значение());
            let существующая = читать_запись(таблица, индекс);
            if существующая & БИТ_ПРИСУТСТВУЕТ != 0 {
                return Err(ОшибкаПамяти::АдресВнеДиапазона);
            }
            let значение = (физ.значение() & МАСКА_ФИЗ) | биты_страницы;
            записать_запись(таблица, индекс, значение);
        }
        сбросить_tlb(винт);
        Ok(())
    }

    fn снять_отображение(&mut self, винт: ВиртАдрес) -> Result<ФизАдрес, ОшибкаПамяти> {
        if !винт.выравнен_на_страницу() {
            return Err(ОшибкаПамяти::НеВыровнен);
        }
        let pml4 = АктивнаяТаблица::cr3();
        let pdpt = unsafe { ход(pml4, индекс_pml4(винт.значение()))? };
        let pd = unsafe { ход(pdpt, индекс_pdpt(винт.значение()))? };
        let pt = unsafe { ход(pd, индекс_pd(винт.значение()))? };

        unsafe {
            let таблица = таблица_по_физ(pt);
            let индекс = индекс_pt(винт.значение());
            let значение = читать_запись(таблица, индекс);
            if значение & БИТ_ПРИСУТСТВУЕТ == 0 {
                return Err(ОшибкаПамяти::АдресВнеДиапазона);
            }
            записать_запись(таблица, индекс, 0);
            сбросить_tlb(винт);
            Ok(ФизАдрес::новый(значение & МАСКА_ФИЗ))
        }
    }

    fn перевести(&self, винт: ВиртАдрес) -> Option<ФизАдрес> {
        let pml4 = АктивнаяТаблица::cr3();
        unsafe {
            let запись_pml4 = читать_запись(таблица_по_физ(pml4), индекс_pml4(винт.значение()));
            if запись_pml4 & БИТ_ПРИСУТСТВУЕТ == 0 {
                return None;
            }
            let pdpt = запись_pml4 & МАСКА_ФИЗ;
            let запись_pdpt = читать_запись(таблица_по_физ(pdpt), индекс_pdpt(винт.значение()));
            if запись_pdpt & БИТ_ПРИСУТСТВУЕТ == 0 {
                return None;
            }
            // PDPT может быть «огромной» страницей 1 ГиБ; на этом этапе не поддерживаем.
            if запись_pdpt & БИТ_ОГРОМНАЯ != 0 {
                let база = запись_pdpt & МАСКА_ФИЗ;
                let смещение = винт.значение() & 0x3FFF_FFFF;
                return Some(ФизАдрес::новый(база + смещение));
            }
            let pd = запись_pdpt & МАСКА_ФИЗ;
            let запись_pd = читать_запись(таблица_по_физ(pd), индекс_pd(винт.значение()));
            if запись_pd & БИТ_ПРИСУТСТВУЕТ == 0 {
                return None;
            }
            // PD-уровень: огромная страница 2 МиБ — это наша начальная карта ядра.
            if запись_pd & БИТ_ОГРОМНАЯ != 0 {
                let база = запись_pd & МАСКА_ФИЗ;
                let смещение = винт.значение() & 0x1F_FFFF;
                return Some(ФизАдрес::новый(база + смещение));
            }
            let pt = запись_pd & МАСКА_ФИЗ;
            let запись_pt = читать_запись(таблица_по_физ(pt), индекс_pt(винт.значение()));
            if запись_pt & БИТ_ПРИСУТСТВУЕТ == 0 {
                return None;
            }
            let база = запись_pt & МАСКА_ФИЗ;
            let смещение = винт.значение() & 0xFFF;
            Some(ФизАдрес::новый(база + смещение))
        }
    }
}

/// Спуск по уровню. Если запись не присутствует — выделить новую таблицу
/// из физического аллокатора, обнулить и записать в родительскую запись.
unsafe fn ход_или_создать(
    родитель_физ: u64,
    индекс: usize,
    биты_промежуточные: u64,
) -> Result<u64, ОшибкаПамяти> {
    let таблица = unsafe { таблица_по_физ(родитель_физ) };
    let существующая = unsafe { читать_запись(таблица, индекс) };
    if существующая & БИТ_ПРИСУТСТВУЕТ != 0 {
        if существующая & БИТ_ОГРОМНАЯ != 0 {
            return Err(ОшибкаПамяти::АдресВнеДиапазона);
        }
        return Ok(существующая & МАСКА_ФИЗ);
    }
    // Выделяем новую страницу под таблицу.
    let новая = АЛЛОКАТОР.lock().выделить_страницу()?;
    // Обнуляем её через идентичное отображение.
    unsafe {
        let указатель = новая.значение() as *mut u64;
        for смещение in 0..(РАЗМЕР_СТРАНИЦЫ / 8) {
            ptr::write_volatile(указатель.add(смещение), 0);
        }
    }
    let значение = (новая.значение() & МАСКА_ФИЗ) | биты_промежуточные;
    unsafe { записать_запись(таблица, индекс, значение) };
    Ok(новая.значение())
}

/// Спуск по уровню без создания. Используется в `снять_отображение`.
unsafe fn ход(родитель_физ: u64, индекс: usize) -> Result<u64, ОшибкаПамяти> {
    let таблица = unsafe { таблица_по_физ(родитель_физ) };
    let значение = unsafe { читать_запись(таблица, индекс) };
    if значение & БИТ_ПРИСУТСТВУЕТ == 0 {
        return Err(ОшибкаПамяти::АдресВнеДиапазона);
    }
    Ok(значение & МАСКА_ФИЗ)
}

/// Самопроверка виртуальной памяти. Выделяет физическую страницу,
/// отображает её на свободный высокий виртуальный адрес, пишет/читает,
/// снимает отображение и освобождает страницу.
pub fn самопроверка() -> Result<(), ОшибкаПамяти> {
    // Берём виртуальный адрес внутри идентифицированных 0..4 ГиБ,
    // за пределами области, отображённой огромными страницами 2 МиБ
    // (мы используем последний свободный 4-КиБ слот выше 4 ГиБ-1).
    //
    // На текущем этапе ядра идентичная карта покрывает 0..4 ГиБ через
    // 2-МиБ страницы; там нет 4-КиБ записей PT, и пытаться отобразить
    // на 4-КиБ страницу внутри них нельзя (запись PD «огромная»).
    //
    // Поэтому используем виртуальный адрес 0x1_0000_0000 (4 ГиБ ровно),
    // который не покрыт начальной картой и абсолютно свободен.
    let винт = ВиртАдрес::новый(0x0001_0000_0000);
    let физ = АЛЛОКАТОР.lock().выделить_страницу()?;

    let mut таблица = АктивнаяТаблица::новая();
    таблица.отобразить(
        винт,
        физ,
        ФлагиСтраницы::ПРИСУТСТВУЕТ | ФлагиСтраницы::ЗАПИСЬ,
    )?;

    // Записать в страницу через виртуальный адрес и прочитать обратно.
    unsafe {
        let указатель = винт.значение() as *mut u64;
        ptr::write_volatile(указатель, 0xDEAD_BEEF_D0BA_0BE5);
        let назад = ptr::read_volatile(указатель);
        if назад != 0xDEAD_BEEF_D0BA_0BE5 {
            return Err(ОшибкаПамяти::АдресВнеДиапазона);
        }
    }

    // Проверить трансляцию.
    let переведённый = таблица.перевести(винт);
    if переведённый != Some(физ) {
        return Err(ОшибкаПамяти::АдресВнеДиапазона);
    }

    let освобождённый = таблица.снять_отображение(винт)?;
    АЛЛОКАТОР.lock().освободить_страницу(освобождённый)?;
    Ok(())
}
