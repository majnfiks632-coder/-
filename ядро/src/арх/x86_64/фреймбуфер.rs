// Графический драйвер: пиксельный framebuffer (VBE/GOP) + текстовая консоль
// поверх него. Используется, когда загрузчик передал нам адрес и геометрию
// линейного буфера (через тег framebuffer Multiboot2 или через структуру
// собственного загрузчика).
//
// Особенности:
//   * Поддерживаем только режим RGB 32 bpp (4 байта на пиксель). Этого
//     достаточно для VBE 0x4118 и для multiboot2 framebuffer от GRUB.
//   * Шрифт «Дубина 8×16» с кодировкой ДубКод используем точно тот же,
//     что VGA-консоль — кириллица, рамки и псевдографика отрисовываются
//     одной и той же таблицей.
//   * Пишем «толстым» способом: каждый символ — 9×16 пикселей (8 пикселей
//     глифа + 1 пиксель отступа справа), курсор — нижнее подчёркивание.
//   * При достижении нижней строки буфер прокручивается вверх через
//     `core::ptr::copy` (быстрая инлайн-копия для всего экрана).

use core::ptr;
use spin::Mutex;

use crate::арх::x86_64::шрифт_дубина::ШРИФТ;
use crate::кодировка;
use crate::печать::НосительПечати;

/// Высота глифа в пикселях.
const ВЫСОТА_ГЛИФА: usize = 16;
/// Ширина глифа в пикселях (8 + 1 на межсимвольный интервал).
const ШИРИНА_ГЛИФА: usize = 9;

/// Активный экран: либо `None` (графика не подключена), либо параметры буфера.
static ЭКРАН: Mutex<Option<Экран>> = Mutex::new(None);

/// Описание линейного framebuffer'а и состояния консоли.
pub struct Экран {
    адрес: *mut u32,
    шаг_в_пикселях: usize,
    ширина_пкс: usize,
    высота_пкс: usize,
    /// Размеры в символах (производные от пикселей и шрифта).
    столбцов: usize,
    строк: usize,
    /// Y-смещение начала консольной области (под панелью). При прокрутке
    /// этот регион остаётся неподвижным.
    нач_y_консоли: usize,
    /// Текущая позиция курсора в символах (относительно нач_y_консоли).
    столбец: usize,
    строка: usize,
    /// Цвета.
    передний: u32,
    задний: u32,
}

// SAFETY: framebuffer — это область видеопамяти, доступ к ней синхронизирован
// внешним `Mutex`. Сырой указатель не разделяется между потоками вне `lock()`.
unsafe impl Send for Экран {}

impl Экран {
    fn записать_пиксель(&self, x: usize, y: usize, цвет: u32) {
        if x >= self.ширина_пкс || y >= self.высота_пкс {
            return;
        }
        let смещение = y * self.шаг_в_пикселях + x;
        unsafe {
            ptr::write_volatile(self.адрес.add(смещение), цвет);
        }
    }

    fn заполнить(&self, цвет: u32) {
        for y in 0..self.высота_пкс {
            for x in 0..self.ширина_пкс {
                self.записать_пиксель(x, y, цвет);
            }
        }
    }

    fn заполнить_прямоугольник(
        &self,
        x0: usize,
        y0: usize,
        ширина: usize,
        высота: usize,
        цвет: u32,
    ) {
        let x1 = (x0 + ширина).min(self.ширина_пкс);
        let y1 = (y0 + высота).min(self.высота_пкс);
        for y in y0..y1 {
            for x in x0..x1 {
                self.записать_пиксель(x, y, цвет);
            }
        }
    }

    fn рамка(&self, x0: usize, y0: usize, ширина: usize, высота: usize, цвет: u32) {
        if ширина < 2 || высота < 2 {
            return;
        }
        for x in x0..(x0 + ширина).min(self.ширина_пкс) {
            self.записать_пиксель(x, y0, цвет);
            self.записать_пиксель(x, y0 + высота - 1, цвет);
        }
        for y in y0..(y0 + высота).min(self.высота_пкс) {
            self.записать_пиксель(x0, y, цвет);
            self.записать_пиксель(x0 + ширина - 1, y, цвет);
        }
    }

    fn нарисовать_глиф(&self, x: usize, y: usize, код: u8, передний: u32, задний: u32) {
        let глиф = &ШРИФТ[код as usize];
        for (стр, &байт) in глиф.iter().enumerate() {
            let py = y + стр;
            if py >= self.высота_пкс {
                break;
            }
            for бит in 0..8 {
                let px = x + бит;
                if px >= self.ширина_пкс {
                    break;
                }
                let маска = 0x80u8 >> бит;
                let цвет = if (байт & маска) != 0 { передний } else { задний };
                self.записать_пиксель(px, py, цвет);
            }
            // Дополнительный пиксельный столбец (межсимвольный отступ),
            // чтобы соседние глифы не сливались.
            if x + 8 < self.ширина_пкс {
                self.записать_пиксель(x + 8, py, задний);
            }
        }
    }

    /// Сдвинуть консольную область на один глиф вверх. Панель (всё, что выше
    /// `нач_y_консоли`) остаётся неподвижной, а нижняя строка очищается.
    fn прокрутить_вверх(&mut self) {
        let нач = self.нач_y_консоли;
        if нач + ВЫСОТА_ГЛИФА >= self.высота_пкс {
            return;
        }
        let шаг = self.шаг_в_пикселях;
        let всего_строк_консоли = self.высота_пкс - нач;
        let сдвиг = ВЫСОТА_ГЛИФА * шаг;
        unsafe {
            let начало = self.адрес.add(нач * шаг);
            let источник = self.адрес.add((нач + ВЫСОТА_ГЛИФА) * шаг);
            let копировать = (всего_строк_консоли - ВЫСОТА_ГЛИФА) * шаг;
            ptr::copy(источник, начало, копировать);
            let _ = сдвиг;
        }
        // Очищаем последнюю символьную строку.
        let нач_y = self.высота_пкс - ВЫСОТА_ГЛИФА;
        for y in нач_y..self.высота_пкс {
            for x in 0..self.ширина_пкс {
                self.записать_пиксель(x, y, self.задний);
            }
        }
    }

    fn перевод_строки(&mut self) {
        self.столбец = 0;
        if self.строка + 1 >= self.строк {
            self.прокрутить_вверх();
        } else {
            self.строка += 1;
        }
    }

    fn вывести_код(&mut self, код: u8) {
        match код {
            b'\n' => self.перевод_строки(),
            b'\r' => self.столбец = 0,
            b'\t' => {
                let шаг = 4;
                let нов = ((self.столбец / шаг) + 1) * шаг;
                let нов = нов.min(self.столбцов.saturating_sub(1));
                while self.столбец < нов {
                    self.вывести_код(b' ');
                }
            }
            _ => {
                if self.столбец >= self.столбцов {
                    self.перевод_строки();
                }
                let px = self.столбец * ШИРИНА_ГЛИФА;
                let py = self.нач_y_консоли + self.строка * ВЫСОТА_ГЛИФА;
                self.нарисовать_глиф(px, py, код, self.передний, self.задний);
                self.столбец += 1;
            }
        }
    }
}

impl НосительПечати for Экран {
    fn записать_строку(&mut self, текст: &str) {
        for сим in текст.chars() {
            let код = кодировка::в_дубкод(сим);
            self.вывести_код(код);
        }
    }
}

/// Подключить framebuffer как активный носитель печати.
/// Возвращает `Ok(())` если режим поддерживается (32 bpp, RGB).
pub fn инициализировать(
    адрес: u64,
    шаг_байт: u32,
    ширина: u32,
    высота: u32,
    бит_на_пиксель: u8,
) -> Result<(), &'static str> {
    if бит_на_пиксель != 32 {
        return Err("framebuffer поддерживается только при 32 битах на пиксель");
    }
    if ширина < 32 || высота < 32 {
        return Err("слишком маленькое разрешение framebuffer");
    }
    let шаг_в_пикселях = (шаг_байт / 4) as usize;
    if шаг_в_пикселях < ширина as usize {
        return Err("шаг framebuffer меньше ширины — нелинейный буфер не поддерживается");
    }
    // Резервируем верхние 24 пикселя под панель и округляем нач_y_консоли
    // вверх до кратного ВЫСОТА_ГЛИФА, чтобы строки попадали ровно.
    let начало_панели: usize = 24;
    let нач_y_консоли = ((начало_панели + ВЫСОТА_ГЛИФА - 1) / ВЫСОТА_ГЛИФА) * ВЫСОТА_ГЛИФА;
    let свободно_по_y = (высота as usize).saturating_sub(нач_y_консоли);
    let экран = Экран {
        адрес: адрес as *mut u32,
        шаг_в_пикселях,
        ширина_пкс: ширина as usize,
        высота_пкс: высота as usize,
        столбцов: ширина as usize / ШИРИНА_ГЛИФА,
        строк: свободно_по_y / ВЫСОТА_ГЛИФА,
        нач_y_консоли,
        столбец: 0,
        строка: 0,
        // Светло-зелёный на чёрном — повторяет атрибуты VGA-консоли.
        передний: 0x00C0FFC0,
        задний: 0x00000000,
    };
    экран.заполнить(0x00000000);
    рамка_рабочего_стола(&экран);
    *ЭКРАН.lock() = Some(экран);
    Ok(())
}

/// Активен ли графический экран.
pub fn активен() -> bool {
    ЭКРАН.lock().is_some()
}

/// Доступ к экрану под мьютексом для прочих операций (рисование окон).
pub fn буфер() -> &'static Mutex<Option<Экран>> {
    &ЭКРАН
}

/// Нарисовать декоративную рамку «рабочего стола» — узкая полоска по периметру.
fn рамка_рабочего_стола(экран: &Экран) {
    // Тёмно-синяя «крышка» сверху на 24 пикселя — это будущая панель задач.
    экран.заполнить_прямоугольник(0, 0, экран.ширина_пкс, 24, 0x00102060);
    // Тонкая граница по краю всего экрана.
    экран.рамка(0, 0, экран.ширина_пкс, экран.высота_пкс, 0x00404080);
    // Текст-надпись в верхней панели рисуется уже из главный.rs (после
    // инициализации — там удобнее, чтобы видеть прогресс).
}

/// Нарисовать заголовок в верхней «панели». Вызывается главным ядром.
pub fn нарисовать_панель(текст: &str) {
    let mut слот = ЭКРАН.lock();
    let Some(экран) = слот.as_mut() else { return };
    экран.заполнить_прямоугольник(0, 0, экран.ширина_пкс, 24, 0x00102060);
    let передний = 0x00E0E0FF;
    let задний = 0x00102060;
    let mut x = 8usize;
    for сим in текст.chars() {
        let код = кодировка::в_дубкод(сим);
        экран.нарисовать_глиф(x, 4, код, передний, задний);
        x += ШИРИНА_ГЛИФА;
        if x + ШИРИНА_ГЛИФА >= экран.ширина_пкс {
            break;
        }
    }
}

/// Нарисовать демонстрационное окно «о системе» в правой части экрана.
pub fn нарисовать_окно_о_системе() {
    let mut слот = ЭКРАН.lock();
    let Some(экран) = слот.as_mut() else { return };
    let шx = (экран.ширина_пкс as i32 - 320 - 16).max(0) as usize;
    let шy = 48usize;
    let шш = 320usize;
    let шв = 200usize;
    // Тень.
    экран.заполнить_прямоугольник(шx + 4, шy + 4, шш, шв, 0x00101020);
    // Окно: серый фон, тёмная рамка, синий заголовок.
    экран.заполнить_прямоугольник(шx, шy, шш, шв, 0x00C8C8D8);
    экран.заполнить_прямоугольник(шx, шy, шш, 18, 0x00204080);
    экран.рамка(шx, шy, шш, шв, 0x00202040);
    // Заголовок окна (8×16 шрифт).
    let передний = 0x00FFFFFF;
    let задний = 0x00204080;
    let заголовок = "О системе ДубинаОС";
    let mut x = шx + 6;
    for сим in заголовок.chars() {
        let код = кодировка::в_дубкод(сим);
        экран.нарисовать_глиф(x, шy + 1, код, передний, задний);
        x += ШИРИНА_ГЛИФА;
    }
    // Содержимое окна: несколько строк.
    let передний = 0x00102030;
    let задний = 0x00C8C8D8;
    let строки = [
        "Версия 0.1.0",
        "Архитектура: x86_64",
        "Графика: VBE/GOP framebuffer",
        "Шрифт: Дубина 8x16 (кириллица)",
        "Файловая система: ДубФС (ОЗУ)",
        "Оболочка: дубина:>",
        "",
        "Это первое окно, нарисованное",
        "ядром поверх framebuffer.",
    ];
    for (i, стр) in строки.iter().enumerate() {
        let py = шy + 24 + i * ВЫСОТА_ГЛИФА;
        if py + ВЫСОТА_ГЛИФА > шy + шв - 6 {
            break;
        }
        let mut x = шx + 8;
        for сим in стр.chars() {
            let код = кодировка::в_дубкод(сим);
            экран.нарисовать_глиф(x, py, код, передний, задний);
            x += ШИРИНА_ГЛИФА;
            if x + ШИРИНА_ГЛИФА > шx + шш - 6 {
                break;
            }
        }
    }
}
