/// Состояние регистров, переданное из ASM-трамплина в Rust-обработчик.
/// Порядок строго соответствует порядку push'ей в идт.s.
#[repr(C)]
pub struct КадрПрерывания {
    pub r15: u64, pub r14: u64, pub r13: u64, pub r12: u64,
    pub r11: u64, pub r10: u64, pub r9: u64, pub r8: u64,
    pub rbp: u64, pub rdi: u64, pub rsi: u64, pub rdx: u64,
    pub rcx: u64, pub rbx: u64, pub rax: u64,
    pub номер_вектора: u64,
    pub код_ошибки: u64,
    // Аппаратный кадр (CPU кладёт его автоматически):
    pub rip: u64,
    pub cs: u64,
    pub rflags: u64,
    pub rsp_польз: u64,
    pub ss: u64,
}

/// Высокоуровневый обработчик исключения, вызываемый из ASM-трамплина.
#[no_mangle]
pub extern "C" fn _dub_exception_handler(кадр: &mut КадрПрерывания) {
    let номер = кадр.номер_вектора as usize;
    let имя = if номер < 32 {
        НАЗВАНИЕ_ИСКЛЮЧЕНИЯ[номер]
    } else {
        "Неизвестное исключение"
    };

    crate::println!();
    crate::println!("‼ ИСКЛЮЧЕНИЕ ЯДРА #{} — {}", номер, имя);
    crate::println!(
        "  RIP = {:#018x}   CS  = {:#06x}   RFLAGS = {:#018x}",
        { кадр.rip }, { кадр.cs }, { кадр.rflags }
    );
    crate::println!("  Код ошибки = {:#018x}", { кадр.код_ошибки });
    if номер == 14 {
        // #PF имеет специфический CR2 — адрес, вызвавший ошибку.
        let cr2: u64;
        unsafe { core::arch::asm!("mov {}, cr2", out(reg) cr2) };
        crate::println!("  CR2 (виновный адрес) = {:#018x}", cr2);
    }
    crate::println!(
        "  RAX={:016x}  RBX={:016x}  RCX={:016x}  RDX={:016x}",
        { кадр.rax }, { кадр.rbx }, { кадр.rcx }, { кадр.rdx }
    );
    crate::println!(
        "  RSI={:016x}  RDI={:016x}  RBP={:016x}  RSP={:016x}",
        { кадр.rsi }, { кадр.rdi }, { кадр.rbp }, { кадр.rsp_польз }
    );
    crate::println!();
    crate::println!("Ядро остановлено из-за необработанного исключения.");
    crate::арх::x86_64::халт_навсегда();
}

/// Высокоуровневый обработчик IRQ, вызываемый из ASM-трамплина.
#[no_mangle]
pub extern "C" fn _dub_irq_handler(кадр: &mut КадрПрерывания) {
    let вектор = кадр.номер_вектора as u8;
    crate::прерывания::маршрутизатор::обработать_ирк(вектор, кадр);
    // Послать EOI 8259-PIC.
    super::pic::подтвердить(вектор);
}

/// Установить таблицу IDT — заполнить все 32 исключения и 16 IRQ-векторов.
pub unsafe fn инициализировать() {
    let селектор = гдт::СЕЛЕКТОР_КОД_ЯДРА;

    let трамплины_искл: [Трамплин; 32] = [
        _dub_exc_0, _dub_exc_1, _dub_exc_2, _dub_exc_3,
        _dub_exc_4, _dub_exc_5, _dub_exc_6, _dub_exc_7,
        _dub_exc_8, _dub_exc_9, _dub_exc_10, _dub_exc_11,
        _dub_exc_12, _dub_exc_13, _dub_exc_14, _dub_exc_0, // 15 — резерв
        _dub_exc_16, _dub_exc_17, _dub_exc_18, _dub_exc_19,
        _dub_exc_20,
        _dub_exc_0, _dub_exc_0, _dub_exc_0, _dub_exc_0,
        _dub_exc_0, _dub_exc_0, _dub_exc_0, _dub_exc_0,
        _dub_exc_0, _dub_exc_0, _dub_exc_0,
    ];

    for (вектор, трамплин) in трамплины_искл.iter().enumerate() {
        unsafe {
            let ist = if вектор == 8 { 1 } else { 0 }; // #DF — на стек IST1
            ИДТ[вектор].установить(*трамплин, селектор, ist, 0);
        }
    }

    let трамплины_ирк: [Трамплин; 16] = [
        _dub_irq_0, _dub_irq_1, _dub_irq_2, _dub_irq_3,
        _dub_irq_4, _dub_irq_5, _dub_irq_6, _dub_irq_7,
        _dub_irq_8, _dub_irq_9, _dub_irq_10, _dub_irq_11,
        _dub_irq_12, _dub_irq_13, _dub_irq_14, _dub_irq_15,
    ];
    for (i, трамплин) in трамплины_ирк.iter().enumerate() {
        let вектор = 32 + i;
        unsafe {
            ИДТ[вектор].установить(*трамплин, селектор, 0, 0);
        }
    }

    let указатель = УказательИдт {
        предел: (size_of::<[ЗаписьИдт; ВСЕГО_ВЕКТОРОВ]>() - 1) as u16,
        база: unsafe { &raw const ИДТ as *const _ as u64 },
    };

    unsafe {
        core::arch::asm!("lidt [{}]", in(reg) &указатель);
    }
}
