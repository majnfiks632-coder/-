// Таблица дескрипторов прерываний (IDT) для x86_64.
//
// Архитектура x86_64 имеет 256 векторов прерываний:
//   0..31  — исключения (выдаются процессором при ошибках)
//   32..47 — IRQ от 8259 PIC (мы их перенастроим в pic.rs)
//   48..255 — программные прерывания и сисвызовы
//
// Каждая запись IDT — 16 байт. Содержит указатель на «трамплин»
// (низкоуровневую заглушку на ассемблере), которая сохраняет регистры
// и зовёт высокоуровневый обработчик на Rust.
//
// Все идентификаторы и сообщения об ошибках — на русском.

#![allow(dead_code)]

use core::mem::size_of;

use super::гдт;

/// Тип — низкоуровневая ASM-трамплин-функция для прерывания.
type Трамплин = unsafe extern "C" fn();

/// Запись IDT (16 байт).
#[repr(C, packed)]
#[derive(Clone, Copy)]
struct ЗаписьИдт {
    смещение_низ: u16,    // биты 0..15 адреса обработчика
    селектор: u16,         // селектор сегмента кода ядра
    ist: u8,               // биты 0..2 — индекс IST (0 = не использовать)
    атрибуты: u8,          // тип, DPL, P
    смещение_сред: u16,    // биты 16..31
    смещение_верх: u32,    // биты 32..63
    зарезервировано: u32,
}

impl ЗаписьИдт {
    const fn пустая() -> Self {
        Self {
            смещение_низ: 0,
            селектор: 0,
            ist: 0,
            атрибуты: 0,
            смещение_сред: 0,
            смещение_верх: 0,
            зарезервировано: 0,
        }
    }

    fn установить(&mut self, обработчик: Трамплин, селектор: u16, ist: u8, dpl: u8) {
        let адрес = обработчик as u64;
        self.смещение_низ = (адрес & 0xFFFF) as u16;
        self.смещение_сред = ((адрес >> 16) & 0xFFFF) as u16;
        self.смещение_верх = ((адрес >> 32) & 0xFFFF_FFFF) as u32;
        self.селектор = селектор;
        self.ist = ist & 0x7;
        // 0xE = 64-битная ловушка прерывания (interrupt gate), P=1, DPL.
        self.атрибуты = 0x8E | ((dpl & 0x3) << 5);
        self.зарезервировано = 0;
    }
}

#[repr(C, packed)]
struct УказательИдт {
    предел: u16,
    база: u64,
}

const ВСЕГО_ВЕКТОРОВ: usize = 256;
static mut ИДТ: [ЗаписьИдт; ВСЕГО_ВЕКТОРОВ] = [ЗаписьИдт::пустая(); ВСЕГО_ВЕКТОРОВ];

