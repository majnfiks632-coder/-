// Глобальная таблица дескрипторов (GDT) и сегмент состояния задачи (TSS)
// для x86_64.
//
// Структура GDT:
//   [0] нулевой дескриптор (обязателен по спецификации)
//   [1] код ядра    — long mode, ring 0
//   [2] данные ядра — long mode, ring 0
//   [3] код пользователя    — long mode, ring 3 (для будущих процессов)
//   [4] данные пользователя — long mode, ring 3
//   [5..6] TSS — двойной 16-байтовый дескриптор (long-mode требование)
//
// TSS используется для:
//   * RSP0 — стек ядра, на который CPU автоматически переключается при
//     прерывании из ring 3.
//   * IST[1] — отдельный стек для двойных ошибок (#DF), чтобы при сломанном
//     ядерном стеке всё равно можно было обработать ошибку.
//
// Все идентификаторы и сообщения — на русском.

#![allow(dead_code)]

use core::mem::size_of;

const ВСЕГО_ЗАПИСЕЙ: usize = 7;

/// Селекторы (значения для регистров CS/SS/...):
pub const СЕЛЕКТОР_КОД_ЯДРА: u16 = 0x08; // индекс 1, ring 0
pub const СЕЛЕКТОР_ДАННЫЕ_ЯДРА: u16 = 0x10; // индекс 2, ring 0
pub const СЕЛЕКТОР_КОД_ПОЛЬЗОВАТЕЛЯ: u16 = 0x18 | 3; // индекс 3, ring 3
pub const СЕЛЕКТОР_ДАННЫЕ_ПОЛЬЗОВАТЕЛЯ: u16 = 0x20 | 3; // индекс 4, ring 3
pub const СЕЛЕКТОР_TSS: u16 = 0x28; // индекс 5

const РАЗМЕР_СТЕКА_IST: usize = 16 * 1024;

#[repr(C, align(16))]
struct СтекIST {
    данные: [u8; РАЗМЕР_СТЕКА_IST],
}

static mut СТЕК_ДВОЙНОЙ_ОШИБКИ: СтекIST = СтекIST {
    данные: [0; РАЗМЕР_СТЕКА_IST],
};

#[repr(C, packed)]
struct ТссЗапись {
    зарезервировано1: u32,
    rsp0: u64,
    rsp1: u64,
    rsp2: u64,
    зарезервировано2: u64,
    ist1: u64,
    ist2: u64,
    ist3: u64,
    ist4: u64,
    ist5: u64,
    ist6: u64,
    ist7: u64,
    зарезервировано3: u64,
    зарезервировано4: u16,
    смещение_iomap: u16,
}

static mut TSS: ТссЗапись = ТссЗапись {
    зарезервировано1: 0,
    rsp0: 0,
    rsp1: 0,
    rsp2: 0,
    зарезервировано2: 0,
    ist1: 0,
    ist2: 0,
    ist3: 0,
    ist4: 0,
    ist5: 0,
    ist6: 0,
    ist7: 0,
    зарезервировано3: 0,
    зарезервировано4: 0,
    смещение_iomap: size_of::<ТссЗапись>() as u16,
};

#[repr(C, packed)]
struct ГдтУказатель {
    предел: u16,
    база: u64,
}

static mut ГДТ: [u64; ВСЕГО_ЗАПИСЕЙ] = [0; ВСЕГО_ЗАПИСЕЙ];

/// Установить полную GDT с TSS и переключиться на неё.
pub unsafe fn инициализировать() {
    // Заполняем стек двойной ошибки указателем на верхушку.
    let верх_ist = unsafe {
        let основание = &raw const СТЕК_ДВОЙНОЙ_ОШИБКИ.данные as *const u8 as u64;
        основание + РАЗМЕР_СТЕКА_IST as u64
    };
    unsafe {
        TSS.ist1 = верх_ist;
    }

    // Стандартные дескрипторы long-mode сегментов.
    // Биты:
    //   44 = S (1 = code/data)
    //   47 = P (present)
    //   53 = L (1 = long mode)
    //   41 = RW (writable for data, readable for code)
    //   43 = E (1 = code, 0 = data)
    //   45-46 = DPL (0 = ring 0, 3 = ring 3)
    let код_ядра: u64 = 0x00AF_9A00_0000_FFFF; // P, S, code, R, L
    let данные_ядра: u64 = 0x00CF_9200_0000_FFFF; // P, S, data, W
    let код_польз: u64 = 0x00AF_FA00_0000_FFFF; // ring 3 code
    let данные_польз: u64 = 0x00CF_F200_0000_FFFF; // ring 3 data

    // Дескриптор TSS — занимает 2 слота по 8 байт.
    let tss_адрес = &raw const TSS as *const ТссЗапись as u64;
    let tss_предел = (size_of::<ТссЗапись>() - 1) as u64;

    // Низшие 8 байт дескриптора TSS:
    //   биты 0..15: предел[0..15]
    //   биты 16..39: база[0..23]
    //   биты 40..47: тип = 0x89 (доступный 64-битный TSS, P=1)
    //   биты 48..51: предел[16..19]
    //   биты 52..55: флаги = 0
    //   биты 56..63: база[24..31]
    let tss_низ: u64 = (tss_предел & 0xFFFF)
        | ((tss_адрес & 0x00FF_FFFF) << 16)
        | (0x89_u64 << 40)
        | (((tss_предел >> 16) & 0xF) << 48)
        | (((tss_адрес >> 24) & 0xFF) << 56);
    let tss_верх: u64 = (tss_адрес >> 32) & 0xFFFF_FFFF;

    unsafe {
        ГДТ[0] = 0;
        ГДТ[1] = код_ядра;
        ГДТ[2] = данные_ядра;
        ГДТ[3] = код_польз;
        ГДТ[4] = данные_польз;
        ГДТ[5] = tss_низ;
        ГДТ[6] = tss_верх;
    }

    let указатель = ГдтУказатель {
        предел: (size_of::<[u64; ВСЕГО_ЗАПИСЕЙ]>() - 1) as u16,
        база: &raw const ГДТ as *const _ as u64,
    };

    unsafe {
        core::arch::asm!(
            // Загружаем GDTR
            "lgdt [{0}]",
            // Перезагружаем CS через дальний возврат на новый сегмент кода ядра.
            "push {1}",
            "lea rax, [rip + 2f]",
            "push rax",
            "retfq",
            "2:",
            // Перезагружаем сегментные регистры данных.
            "mov ax, {2:x}",
            "mov ds, ax",
            "mov es, ax",
            "mov fs, ax",
            "mov gs, ax",
            "mov ss, ax",
            // Загружаем TSS.
            "mov ax, {3:x}",
            "ltr ax",
            in(reg) &указатель,
            in(reg) СЕЛЕКТОР_КОД_ЯДРА as u64,
            in(reg) СЕЛЕКТОР_ДАННЫЕ_ЯДРА,
            in(reg) СЕЛЕКТОР_TSS,
            out("rax") _,
        );
    }
}

/// Установить указатель на ядерный стек, на который CPU будет переключаться
/// при прерываниях из колец пользователя. Вызывается планировщиком при смене
/// активного потока.
pub unsafe fn установить_rsp0(новый_rsp: u64) {
    unsafe {
        TSS.rsp0 = новый_rsp;
    }
}
