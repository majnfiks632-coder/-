// Системный таймер ядра — сидит на IRQ0 и тикает 100 раз в секунду.
// На каждом тике увеличивает глобальный счётчик и дёргает вытесняющий
// планировщик (`потоки::планировщик::тик_таймера()`), который при
// необходимости запросит у IRQ-трамплина переключение потока.
//
// Все идентификаторы и сообщения — на русском.

#![allow(dead_code)]

use core::sync::atomic::{AtomicU64, Ordering};

use super::идт::РезультатПереключения;

const ЧАСТОТА_ТИКА_ГЦ: u32 = 100;

/// Глобальный счётчик тиков с момента загрузки.
pub static ТИКИ: AtomicU64 = AtomicU64::new(0);

/// Можно ли уже дёргать планировщик из таймера (нужно, чтобы первые тики
/// до завершения инициализации потоков и idle-потока не вызывали switch).
static ВЫТЕСНЕНИЕ_ВКЛЮЧЕНО: AtomicU64 = AtomicU64::new(0);

/// Инициализирует PIT и снимает маску с IRQ0.
///
/// В режиме APIC: маршрут IRQ0 уже запрограммирован в IO APIC; маску снимает
/// `главный::инициализировать_апик`. Здесь только заводим PIT.
/// В режиме legacy 8259 PIC: дополнительно снимаем маску с IRQ0 в PIC.
pub fn инициализировать() {
    unsafe {
        super::pit::инициализировать(ЧАСТОТА_ТИКА_ГЦ);
        if !super::лапик::активен() {
            super::pic::снять_маску_ирк(0);
        }
    }
}

/// Включить вытесняющий планировщик. До этой точки `тик()` только считает
/// тики, не пытаясь переключать контекст.
pub fn включить_вытеснение() {
    ВЫТЕСНЕНИЕ_ВКЛЮЧЕНО.store(1, Ordering::Release);
}

/// Вызывается из маршрутизатора прерываний на каждом IRQ0.
///
/// Возвращает решение о переключении потоков (или пустую структуру, если
/// переключение не нужно). ASM-трамплин IRQ0 интерпретирует это решение.
pub fn тик() -> РезультатПереключения {
    ТИКИ.fetch_add(1, Ordering::Relaxed);
    if ВЫТЕСНЕНИЕ_ВКЛЮЧЕНО.load(Ordering::Acquire) == 0 {
        return РезультатПереключения::без_переключения();
    }
    crate::потоки::планировщик::тик_таймера()
}

/// Текущее количество миллисекунд с момента загрузки (приблизительно).
pub fn миллисекунды() -> u64 {
    let тиков = ТИКИ.load(Ordering::Relaxed);
    (тиков * 1000) / ЧАСТОТА_ТИКА_ГЦ as u64
}

/// Активное ожидание заданного числа тиков.
pub fn задержка_тиков(сколько: u64) {
    let начало = ТИКИ.load(Ordering::Relaxed);
    while ТИКИ.load(Ordering::Relaxed) < начало + сколько {
        unsafe { core::arch::asm!("hlt", options(nomem, nostack)) };
    }
}
