// Драйвер VGA-консоли в текстовом режиме 80×25.
//
// VGA-буфер: 16-битные ячейки [атрибут (8 бит) | символ (8 бит)] по адресу 0xB8000.
// Шрифт VGA-генератора заменяется нашим собственным «Дубина 8×16», что позволяет
// показывать кириллицу прямо в текстовом режиме без перехода в графический.
// Каждая ячейка хранит код в нашей собственной кодировке ДубКод (см. crate::кодировка).

use core::ptr;
use spin::Mutex;

use crate::арх::x86_64::шрифт_дубина::ШРИФТ;
use crate::кодировка;
use crate::печать::НосительПечати;

const ШИРИНА: usize = 80;
const ВЫСОТА: usize = 25;
const ВИДЕО_БУФЕР: usize = 0xB8000;
const VGA_ШРИФТ_БУФЕР: usize = 0xA0000;

// Регистры VGA CRTC, через которые задаётся позиция аппаратного курсора.
// 0x3D4 — индексный регистр, 0x3D5 — регистр данных. Индексы 0x0E / 0x0F
// хранят старший / младший байт линейного смещения курсора в текстовом
// режиме 80×25 (offset = строка * 80 + столбец).
const CRTC_ИНДЕКС: u16 = 0x3D4;
const CRTC_ДАННЫЕ: u16 = 0x3D5;
const CRTC_КУРСОР_СТАРШИЙ: u8 = 0x0E;
const CRTC_КУРСОР_МЛАДШИЙ: u8 = 0x0F;
const CRTC_КУРСОР_НАЧАЛО: u8 = 0x0A; // регистр Cursor Start (форма курсора)
const CRTC_КУРСОР_КОНЕЦ: u8 = 0x0B; // регистр Cursor End

#[allow(dead_code)]
#[derive(Copy, Clone)]
#[repr(u8)]
pub enum Цвет {
    Чёрный = 0,
    Синий = 1,
    Зелёный = 2,
    Голубой = 3,
    Красный = 4,
    Малиновый = 5,
    Коричневый = 6,
    Светлосерый = 7,
    Тёмносерый = 8,
    СветлоСиний = 9,
    СветлоЗелёный = 10,
    СветлоГолубой = 11,
    СветлоКрасный = 12,
    Розовый = 13,
    Жёлтый = 14,
    Белый = 15,
}

#[derive(Copy, Clone)]
#[repr(transparent)]
pub struct Атрибут(u8);

impl Атрибут {
    pub const fn новый(передний: Цвет, задний: Цвет) -> Self {
        Self((задний as u8) << 4 | (передний as u8))
    }
}

pub struct ВгaКонсоль {
    столбец: usize,
    строка: usize,
    атрибут: Атрибут,
    готова: bool,
}

static ВГА: Mutex<ВгaКонсоль> = Mutex::new(ВгaКонсоль {
    столбец: 0,
    строка: 0,
    атрибут: Атрибут::новый(Цвет::СветлоЗелёный, Цвет::Чёрный),
    готова: false,
});

pub fn буфер_vga() -> &'static Mutex<ВгaКонсоль> {
    &ВГА
}

/// Полная инициализация VGA-консоли:
/// 1) Загружает наш собственный шрифт «Дубина 8×16» в VGA character generator.
/// 2) Включает консоль и очищает буфер.
/// 3) Включает аппаратный курсор и ставит его в позицию (0, 0).
pub fn инициализировать() {
    unsafe { загрузить_шрифт_дубина() };
    unsafe { включить_аппаратный_курсор() };
    let mut к = ВГА.lock();
    к.готова = true;
    к.очистить();
}

/// Записать байт в порт ввода-вывода.
#[inline]
unsafe fn выв8(порт: u16, байт: u8) {
    use core::arch::asm;
    unsafe {
        asm!("out dx, al",
            in("dx") порт,
            in("al") байт,
            options(nomem, nostack, preserves_flags));
    }
}

/// Прочитать байт из порта ввода-вывода.
#[inline]
unsafe fn вв8(порт: u16) -> u8 {
    use core::arch::asm;
    let значение: u8;
    unsafe {
        asm!("in al, dx",
            out("al") значение,
            in("dx") порт,
            options(nomem, nostack, preserves_flags));
    }
    значение
}

/// Включает аппаратный курсор VGA (типичная форма «нижнее подчёркивание»:
/// scanline 14..15 для шрифта 8×16). После этой функции курсор виден и его
/// позицию можно менять через [`обновить_аппаратный_курсор`].
unsafe fn включить_аппаратный_курсор() {
    unsafe {
        // Cursor Start: бит 5 = 0 (курсор включён), биты 0..4 = начальная скан-линия.
        выв8(CRTC_ИНДЕКС, CRTC_КУРСОР_НАЧАЛО);
        let старт = вв8(CRTC_ДАННЫЕ) & 0xC0;
        выв8(CRTC_ИНДЕКС, CRTC_КУРСОР_НАЧАЛО);
        выв8(CRTC_ДАННЫЕ, старт | 14);

        // Cursor End: биты 0..4 = конечная скан-линия.
        выв8(CRTC_ИНДЕКС, CRTC_КУРСОР_КОНЕЦ);
        let конец = вв8(CRTC_ДАННЫЕ) & 0xE0;
        выв8(CRTC_ИНДЕКС, CRTC_КУРСОР_КОНЕЦ);
        выв8(CRTC_ДАННЫЕ, конец | 15);
    }
}

/// Двигает аппаратный (мигающий) курсор VGA в указанную позицию.
/// Должно вызываться при каждом изменении логической позиции в буфере,
/// иначе мигающий курсор «отрывается» от реально печатаемого текста.
fn обновить_аппаратный_курсор(строка: usize, столбец: usize) {
    let позиция: u16 = (строка * ШИРИНА + столбец) as u16;
    unsafe {
        выв8(CRTC_ИНДЕКС, CRTC_КУРСОР_МЛАДШИЙ);
        выв8(CRTC_ДАННЫЕ, (позиция & 0xFF) as u8);
        выв8(CRTC_ИНДЕКС, CRTC_КУРСОР_СТАРШИЙ);
        выв8(CRTC_ДАННЫЕ, ((позиция >> 8) & 0xFF) as u8);
    }
}

/// Загружает наш шрифт в plane 2 видеопамяти VGA. Стандартный приём:
///  - сохранить состояние Sequencer и Graphics Controller;
///  - переключиться в линейный доступ к plane 2 по адресу 0xA0000;
///  - записать туда `[16 байт глифа] * 256` (формат VGA для 8×16 шрифта — на самом
///    32 байта на глиф, но верхняя половина не используется в режимах 8×16,
///    мы пишем нули в неё);
///  - вернуть прежний режим текстового доступа.
///
/// Описание процедуры основано на стандарте IBM VGA / Bochs VGABIOS — портов 0x3C4
/// (Sequencer) и 0x3CE (Graphics Controller).
///
/// # Безопасность
/// Должно вызываться один раз на ранней инициализации, до того как другие
/// потоки могут писать в VGA-буфер.
unsafe fn загрузить_шрифт_дубина() {
    // --- 1. Запомнить настройки Sequencer/GC ---
    unsafe {
        выв8(0x3C4, 0x02);
    }
    let сохр_seq2 = unsafe { вв8(0x3C5) };
    unsafe {
        выв8(0x3C4, 0x04);
    }
    let сохр_seq4 = unsafe { вв8(0x3C5) };

    unsafe {
        выв8(0x3CE, 0x04);
    }
    let сохр_gc4 = unsafe { вв8(0x3CF) };
    unsafe {
        выв8(0x3CE, 0x05);
    }
    let сохр_gc5 = unsafe { вв8(0x3CF) };
    unsafe {
        выв8(0x3CE, 0x06);
    }
    let сохр_gc6 = unsafe { вв8(0x3CF) };

    // --- 2. Переключиться в режим записи в plane 2 (font plane) ---
    // Sequencer: Map mask = 0x04, Memory mode = 0x06 (последовательный, без чётности)
    unsafe {
        выв8(0x3C4, 0x02);
        выв8(0x3C5, 0x04);
    }
    unsafe {
        выв8(0x3C4, 0x04);
        выв8(0x3C5, 0x06);
    }
    // Graphics Controller: Read Map Select = 2, Graphics Mode = 0, Misc = 0x04
    // (mapping at 0xA0000, 64K)
    unsafe {
        выв8(0x3CE, 0x04);
        выв8(0x3CF, 0x02);
    }
    unsafe {
        выв8(0x3CE, 0x05);
        выв8(0x3CF, 0x00);
    }
    unsafe {
        выв8(0x3CE, 0x06);
        выв8(0x3CF, 0x04);
    }

    // --- 3. Записать наш шрифт ---
    // VGA отводит 32 байта на глиф (для совместимости с режимами до 8×32).
    // Мы пишем 16 байт глифа и забиваем оставшиеся 16 нулями.
    let база = VGA_ШРИФТ_БУФЕР as *mut u8;
    for код in 0..256usize {
        let глиф = &ШРИФТ[код];
        for ряд in 0..16 {
            unsafe {
                ptr::write_volatile(база.add(код * 32 + ряд), глиф[ряд]);
            }
        }
        for ряд in 16..32 {
            unsafe {
                ptr::write_volatile(база.add(код * 32 + ряд), 0);
            }
        }
    }

    // --- 4. Вернуть Sequencer/GC в режим текстового доступа ---
    unsafe {
        выв8(0x3C4, 0x02);
        выв8(0x3C5, сохр_seq2);
    }
    unsafe {
        выв8(0x3C4, 0x04);
        выв8(0x3C5, сохр_seq4);
    }
    unsafe {
        выв8(0x3CE, 0x04);
        выв8(0x3CF, сохр_gc4);
    }
    unsafe {
        выв8(0x3CE, 0x05);
        выв8(0x3CF, сохр_gc5);
    }
    unsafe {
        выв8(0x3CE, 0x06);
        выв8(0x3CF, сохр_gc6);
    }
}

impl ВгaКонсоль {
    fn записать_ячейку(&self, строка: usize, столбец: usize, символ: u8) {
        let указатель = (ВИДЕО_БУФЕР + (строка * ШИРИНА + столбец) * 2) as *mut u16;
        let значение = (self.атрибут.0 as u16) << 8 | (символ as u16);
        unsafe {
            ptr::write_volatile(указатель, значение);
        }
    }

    pub fn очистить(&mut self) {
        for стр in 0..ВЫСОТА {
            for ст in 0..ШИРИНА {
                self.записать_ячейку(стр, ст, b' ');
            }
        }
        self.строка = 0;
        self.столбец = 0;
        self.обновить_курсор();
    }

    /// Синхронизирует аппаратный (мигающий) курсор VGA с текущей
    /// логической позицией консоли. Без этого вызова мигающий курсор
    /// останется в той позиции, куда его поставил BIOS/QEMU.
    fn обновить_курсор(&self) {
        if !self.готова {
            return;
        }
        обновить_аппаратный_курсор(self.строка, self.столбец);
    }

    fn перенос_строки(&mut self) {
        self.столбец = 0;
        self.строка += 1;
        if self.строка >= ВЫСОТА {
            self.прокрутить();
        }
    }

    fn прокрутить(&mut self) {
        for стр in 1..ВЫСОТА {
            for ст in 0..ШИРИНА {
                let исток = (ВИДЕО_БУФЕР + (стр * ШИРИНА + ст) * 2) as *const u16;
                let приёмник = (ВИДЕО_БУФЕР + ((стр - 1) * ШИРИНА + ст) * 2) as *mut u16;
                unsafe {
                    ptr::write_volatile(приёмник, ptr::read_volatile(исток));
                }
            }
        }
        for ст in 0..ШИРИНА {
            self.записать_ячейку(ВЫСОТА - 1, ст, b' ');
        }
        self.строка = ВЫСОТА - 1;
    }

    fn записать_сим(&mut self, сим: char) {
        if !self.готова {
            return;
        }
        match сим {
            '\n' => self.перенос_строки(),
            '\r' => self.столбец = 0,
            '\t' => {
                let следующий = (self.столбец + 8) & !7;
                while self.столбец < следующий && self.столбец < ШИРИНА {
                    self.записать_ячейку(self.строка, self.столбец, b' ');
                    self.столбец += 1;
                }
            }
            _ => {
                let байт = кодировка::в_дубкод(сим);
                self.записать_ячейку(self.строка, self.столбец, байт);
                self.столбец += 1;
                if self.столбец >= ШИРИНА {
                    self.перенос_строки();
                }
            }
        }
    }
}

impl НосительПечати for ВгaКонсоль {
    fn записать_строку(&mut self, текст: &str) {
        for сим in текст.chars() {
            self.записать_сим(сим);
        }
        // После записи всей строки одной операцией обновляем аппаратный
        // курсор — быстрее, чем после каждого символа.
        self.обновить_курсор();
    }
}
