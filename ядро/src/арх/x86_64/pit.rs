// Программируемый интервальный таймер 8254 (PIT).
//
// PIT работает на частоте 1.193182 МГц. Делитель = 1193182 / желаемая_Гц.
//
// Все идентификаторы и сообщения — на русском.

#![allow(dead_code)]

use core::arch::asm;

const PIT_КАНАЛ_0: u16 = 0x40;
const PIT_КОМАНДА: u16 = 0x43;
const ЧАСТОТА_ОСНОВЫ_ГЦ: u32 = 1_193_182;

unsafe fn вывести_порт(порт: u16, значение: u8) {
    unsafe { asm!("out dx, al", in("dx") порт, in("al") значение) };
}

/// Настроить PIT канал 0 на повторяющиеся прерывания нужной частоты.
/// IRQ0 поднимется ровно `гц` раз в секунду.
pub unsafe fn инициализировать(гц: u32) {
    let делитель = (ЧАСТОТА_ОСНОВЫ_ГЦ / гц) as u16;
    unsafe {
        // Команда: канал 0, lobyte/hibyte, режим 3 (квадрат), бин.
        вывести_порт(PIT_КОМАНДА, 0x36);
        вывести_порт(PIT_КАНАЛ_0, (делитель & 0xFF) as u8);
        вывести_порт(PIT_КАНАЛ_0, (делитель >> 8) as u8);
    }
}
