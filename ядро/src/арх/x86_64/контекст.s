/*
 * Переключение контекста потока на x86_64.
 *
 * Сигнатура: extern "C" fn _переключить_контекст(старый: *mut u64, новый: u64)
 *
 *     rdi  = указатель, по которому нужно сохранить текущий RSP
 *     rsi  = новый RSP, который нужно загрузить
 *
 * Сохраняем callee-saved регистры (rbx, rbp, r12, r13, r14, r15) в стек,
 * пишем текущий RSP по [rdi], загружаем новый RSP из rsi и восстанавливаем
 * callee-saved регистры. После `ret` управление переходит на ту инструкцию,
 * которая была сохранена в стеке нового потока.
 *
 * Все регистры, не входящие в callee-saved, считаются «затёртыми» — таково
 * соглашение System V x86_64 ABI, и эта функция фактически выглядит как
 * обычный вызов с точки зрения вызывающего.
 *
 * Для свежесозданного потока его стек должен быть подготовлен так, чтобы
 * на верхушке лежали (от меньших адресов к большим):
 *     r15, r14, r13, r12, rbx, rbp, адрес_возврата=точка_входа.
 * Тогда первое переключение в этот поток через `ret` начнёт выполнение
 * точки входа.
 */
/*
 * Имена внешних символов на ASCII — таково ограничение ассемблера и
 * extern "C". Сами имена в коде на Rust остаются на русском (через
 * обёрточные функции).
 */
.section .text
.global _dub_switch_context
.type _dub_switch_context, @function
_dub_switch_context:
    push rbp
    push rbx
    push r12
    push r13
    push r14
    push r15
    mov [rdi], rsp
    mov rsp, rsi
    pop r15
    pop r14
    pop r13
    pop r12
    pop rbx
    pop rbp
    ret
.size _dub_switch_context, . - _dub_switch_context

# ------------------------------------------------------------
# Трамплин нового потока: первое, что исполняется в свежесозданном
# потоке после `ret` из `_dub_switch_context`. На верхушке стека
# в этот момент лежат:
#     [rsp+0] = аргумент (для передачи в rdi)
#     [rsp+8] = адрес функции точки входа
# Снимаем их и вызываем функцию. Точка входа объявлена как ! и не
# должна возвращаться; на случай ошибки — ud2.
.global _dub_thread_trampoline
.type _dub_thread_trampoline, @function
_dub_thread_trampoline:
    pop rdi
    pop rax
    call rax
    ud2
.size _dub_thread_trampoline, . - _dub_thread_trampoline
