/*
 * ДубинаОС — переключение контекста потока на x86_64 через единый
 * iretq-совместимый кадр.
 *
 * На каждом потоке мы сохраняем СТРОГО ОДИН формат:
 *
 *     Низшие адреса
 *     [r15][r14][r13][r12][r11][r10][r9][r8][rbp][rdi][rsi][rdx][rcx][rbx][rax] <- 15 ОПР
 *     [вектор][код_ошибки]                                                       <- псевдо
 *     [rip][cs][rflags][rsp][ss]                                                 <- iretq-хвост
 *     Высшие адреса
 *
 * Размер кадра: 22 × 8 = 176 байт. Совпадает с тем, что складывает
 * IRQ-трамплин в `идт.s` (макрос `SAVE_REGS` плюс пара push'ей вектора и
 * кода ошибки плюс пять слов, которые CPU кладёт автоматически на
 * прерывании). Это ключевая идея «единого кадра» как в KTRAP_FRAME у NT:
 * любой поток можно резюмировать одной и той же последовательностью
 * `pop GPR; add rsp,16; iretq`, независимо от того, как он был остановлен —
 * кооперативно через `уступить()` или принудительно через таймер.
 *
 * Имена внешних символов — ASCII (требование `extern "C"` в Rust); сам
 * код и комментарии — на русском.
 */
.section .text
.code64

/*
 * extern "C" fn _dub_switch_to(старый: *mut u64, новый: u64);
 *
 *   rdi  = указатель, по которому надо записать сохранённый RSP
 *          текущего потока;
 *   rsi  = новый RSP — указывает на начало (низ) iretq-кадра потока,
 *          который надо запустить.
 *
 * Поведение:
 *   1. Запрещаем прерывания на время переключения (атомарность).
 *   2. Снимаем со стека адрес возврата вызывающего и строим из текущего
 *      состояния полный iretq-кадр (как будто мы были вытеснены IRQ0 в
 *      этой точке).
 *   3. Сохраняем итоговый RSP по `[rdi]`, загружаем новый RSP из `rsi`.
 *   4. Идём по общему пути восстановления: pop 15 GPR → пропуск vec/err →
 *      iretq, после чего управление переходит на сохранённый RIP нового
 *      потока с восстановленными RFLAGS (IF=1) и пользовательским RSP.
 */
.global _dub_switch_to
.type _dub_switch_to, @function
_dub_switch_to:
    cli                              # переключение — атомарное
    pop r11                          # r11 = RIP вызывающего (адрес после `call`)
    mov r10, rsp                     # r10 = RSP вызывающего после возврата

    # iretq-хвост. CPU ожидает (низшие → высшие): RIP, CS, RFLAGS, RSP, SS.
    # На стек кладём в обратном порядке.
    push 0x10                        # SS — селектор данных ядра
    push r10                         # RSP_after_iretq = RSP вызывающего
    push 0x202                       # RFLAGS: IF=1, бит 1 = 1 (зарезервирован)
    push 0x08                        # CS — селектор кода ядра
    push r11                         # RIP = адрес возврата вызывающего

    push 0                           # код ошибки (псевдо)
    push 0                           # вектор (псевдо)

    # 15 GPR в том же порядке, что в `SAVE_REGS` макросе идт.s.
    push rax
    push rbx
    push rcx
    push rdx
    push rsi
    push rdi
    push rbp
    push r8
    push r9
    push r10
    push r11
    push r12
    push r13
    push r14
    push r15

    mov [rdi], rsp                   # сохранили RSP в дескрипторе текущего
    mov rsp, rsi                     # переключились на стек нового потока

    # Общий путь возврата: pop 15 GPR + пропуск vec/err + iretq.
    pop r15
    pop r14
    pop r13
    pop r12
    pop r11
    pop r10
    pop r9
    pop r8
    pop rbp
    pop rdi
    pop rsi
    pop rdx
    pop rcx
    pop rbx
    pop rax
    add rsp, 16                      # пропускаем vec + err
    iretq
.size _dub_switch_to, . - _dub_switch_to

/*
 * Трамплин запуска нового потока. Когда ядро впервые «возвращается»
 * через iretq в свежесозданный поток, инструкция RIP = `_dub_thread_trampoline`.
 *
 * Подсистема `потоки::подготовить_кадр` строит фрейм так, чтобы:
 *   * R15 содержал адрес функции точки входа (`extern "C" fn(u64) -> !`);
 *   * R14 содержал аргумент;
 *   * RFLAGS в кадре имел IF=1 (после iretq прерывания включены).
 *
 * Тут только переносим аргумент в RDI (System V ABI) и вызываем точку
 * входа. Если она вернётся (а не должна — её тип `!`), ловим `ud2` —
 * получим разборную панику ядра, а не «уехали в кусты».
 */
.global _dub_thread_trampoline
.type _dub_thread_trampoline, @function
_dub_thread_trampoline:
    mov rdi, r14                     # аргумент (System V: 1-й параметр)
    call r15                         # точка входа
    ud2                              # никогда не должно сюда дойти
.size _dub_thread_trampoline, . - _dub_thread_trampoline
