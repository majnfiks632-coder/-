global_asm!(include_str!("идт.s"));

extern "C" {
    fn _dub_switch_to(старый: *mut u64, новый: u64);
    fn _dub_thread_trampoline();
}

/// Переключение контекста потока через единый iretq-кадр.
///
/// Сохраняет полное состояние текущего потока (15 ОПР + RFLAGS + RIP) в
/// формате, совместимом с тем, что складывает IRQ-трамплин, записывает
/// итоговый RSP по `*старый`, загружает `новый` и через `iretq` передаёт
/// управление в новый поток.
///
/// # Безопасность
/// Вызывающий обязан гарантировать, что `старый` указывает на поле `rsp`
/// текущего дескриптора потока, а `новый` — корректный RSP, указывающий на
/// заранее подготовленный 176-байтный кадр (см. `потоки::подготовить_кадр`
/// и `контекст.s`).
pub unsafe fn переключить_контекст(старый: *mut u64, новый: u64) {
    unsafe { _dub_switch_to(старый, новый) }
}

/// Адрес ассемблерного трамплина новой нити (используется для построения
/// начального iretq-кадра в `потоки::подготовить_кадр`).
pub fn адрес_трамплина_потока() -> u64 {
    _dub_thread_trampoline as *const () as u64
}

/// Ранняя инициализация архитектуры. На этом этапе:
///  - Инициализируется последовательный порт COM1 для отладочного вывода.
///  - VGA-буфер очищается и переходит в режим прямого доступа.
///
/// Ничего более глобального ещё не делаем (нет IDT, нет прерываний — это в следующих этапах).
pub fn ранняя_инициализация() {
    последовательный::инициализировать();
    видео::инициализировать();
}

/// Вариант ранней инициализации для UEFI-загрузки: VGA legacy I/O пропускаем,
/// потому что современные UEFI-машины могут вообще не отображать VGA-буфер
/// в физическую память. Вывод пойдёт через COM1 (UART) и framebuffer.
pub fn ранняя_инициализация_без_vga() {
    последовательный::инициализировать();
}

/// Выполняет переданное замыкание один раз для каждого активного носителя печати.
/// Используется макросом `print!`/`println!`.
///
/// Если активен графический framebuffer — пишем в него вместо текстового VGA;
/// COM1 пишем всегда (он независим и используется для CI-логов).
pub fn с_носителями_печати<Ф: FnMut(&mut dyn НосительПечати)>(mut ф: Ф) {
    {
        let мутекс = последовательный::порт_com1();
        let mut посл = мутекс.lock();
        ф(&mut *посл);
    }
    // В графическом режиме рисуем в framebuffer; иначе — в текстовый VGA.
    {
        let мутекс = фреймбуфер::буфер();
        let mut слот = мутекс.lock();
        if let Some(экран) = слот.as_mut() {
            ф(&mut *экран);
            return;
        }
    }
    {
        let мутекс = видео::буфер_vga();
        let mut вгa = мутекс.lock();
        ф(&mut *вгa);
    }
}

/// Безусловное и бесконечное «зависание» процессора с минимальным энергопотреблением.
pub fn халт_навсегда() -> ! {
    loop {
        unsafe {
            core::arch::asm!("cli; hlt", options(nomem, nostack, preserves_flags));
        }
    }
}

/// Передать прерывание зарегистрированному драйверу по имени.
/// Вызывается маршрутизатором прерываний. Использует `try_lock`, чтобы IRQ
/// никогда не повис в ожидании, если ядро удерживает реестр под обычным
/// потоком.
pub fn отправить_ирк_драйверу(имя: &str) {
    let мутекс = crate::драйверы::глобальный_реестр();
    if let Some(mut реестр) = мутекс.try_lock() {
        if let Some(драйвер) = реестр.найти_изм(имя) {
            драйвер.обработать_прерывание();
        }
    }
}
