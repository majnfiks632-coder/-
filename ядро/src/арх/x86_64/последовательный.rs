// Драйвер последовательного порта 8250/16550 (UART). Используется для отладочного вывода.

use core::arch::asm;
use spin::Mutex;

use crate::печать::НосительПечати;

/// Базовый адрес ввода/вывода COM1.
const COM1: u16 = 0x3F8;

/// Глобальный экземпляр порта.
static ПОРТ_COM1: Mutex<ПоследовательныйПорт> = Mutex::new(ПоследовательныйПорт::новый(COM1));

pub fn порт_com1() -> &'static Mutex<ПоследовательныйПорт> {
    &ПОРТ_COM1
}

/// Инициализирует COM1: отключает прерывания, ставит делитель скорости 38400 бод (DLAB=3),
/// 8N1, включает FIFO, RTS/DSR.
pub fn инициализировать() {
    ПОРТ_COM1.lock().инициализировать();
}

/// Программная модель UART 16550.
pub struct ПоследовательныйПорт {
    основа: u16,
    готов: bool,
}

impl ПоследовательныйПорт {
    pub const fn новый(основа: u16) -> Self {
        Self { основа, готов: false }
    }

    pub fn инициализировать(&mut self) {
        unsafe {
            запись_в_порт(self.основа + 1, 0x00); // отключить прерывания
            запись_в_порт(self.основа + 3, 0x80); // включить DLAB
            запись_в_порт(self.основа + 0, 0x03); // делитель = 3 (38400 бод)
            запись_в_порт(self.основа + 1, 0x00);
            запись_в_порт(self.основа + 3, 0x03); // 8 бит, без чётности, 1 стоп
            запись_в_порт(self.основа + 2, 0xC7); // FIFO, очистка, 14-байтовый порог
            запись_в_порт(self.основа + 4, 0x0B); // RTS/DSR, OUT2
        }
        self.готов = true;
    }

    fn ждать_готовности(&self) {
        while unsafe { чтение_порта(self.основа + 5) } & 0x20 == 0 {
            // ждём, пока transmit holding register не освободится
        }
    }

    pub fn записать_байт(&mut self, байт: u8) {
        if !self.готов {
            return;
        }
        // Преобразуем "\n" в "\r\n" — терминалы ожидают полный CR/LF.
        if байт == b'\n' {
            self.ждать_готовности();
            unsafe {
                запись_в_порт(self.основа, b'\r');
            }
        }
        self.ждать_готовности();
        unsafe {
            запись_в_порт(self.основа, байт);
        }
    }
}

impl НосительПечати for ПоследовательныйПорт {
    fn записать_строку(&mut self, текст: &str) {
        for б in текст.bytes() {
            self.записать_байт(б);
        }
    }
}

#[inline]
unsafe fn запись_в_порт(порт: u16, значение: u8) {
    unsafe {
        asm!("out dx, al", in("dx") порт, in("al") значение, options(nomem, nostack, preserves_flags));
    }
}

#[inline]
unsafe fn чтение_порта(порт: u16) -> u8 {
    let значение: u8;
    unsafe {
        asm!("in al, dx", out("al") значение, in("dx") порт, options(nomem, nostack, preserves_flags));
    }
    значение
}
