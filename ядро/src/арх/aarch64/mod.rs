// Архитектурно-зависимый код для aarch64 (ARMv8). Скелет — будет дорабатываться в
// отдельных этапах дорожной карты.

#[path = "uart_pl011.rs"]
pub mod uart_pl011;

use crate::печать::НосительПечати;
use core::arch::global_asm;

// Подключаем ассемблерную точку входа aarch64.
global_asm!(include_str!("вход.s"));

pub fn ранняя_инициализация() {
    uart_pl011::инициализировать();
}

/// Парный с x86_64 вариант для UEFI-загрузки. На aarch64 нет legacy VGA,
/// поэтому он функционально не отличается от обычного — но единое API
/// нужно, чтобы общий код в `ядро/src/главный.rs` собирался под обе архи.
pub fn ранняя_инициализация_без_vga() {
    uart_pl011::инициализировать();
}

pub fn с_носителями_печати<Ф: FnMut(&mut dyn НосительПечати)>(mut ф: Ф) {
    let мутекс = uart_pl011::порт();
    let mut порт = мутекс.lock();
    ф(&mut *порт);
}

/// Заглушка для совместимости c x86_64 API. На aarch64 у `cpuid` нет аналога,
/// и SMEP/SMAP/UMIP — это термины из мира x86. Реальные защёлки
/// (`SCTLR_EL1.WXN`, `TCR_EL1.E0PD0/E0PD1`, `PXN/UXN` в трансляции страниц)
/// будут включаться отдельно в этапе подключения MMU EL1.
pub fn халт_навсегда() -> ! {
    loop {
        unsafe {
            core::arch::asm!("wfi", options(nomem, nostack, preserves_flags));
        }
    }
}
