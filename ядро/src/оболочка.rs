fn команда_задать(с: &mut Оболочка, аргументы: &str) {
    if аргументы.is_empty() {
        команда_показать(с);
        return;
    }
    // Поддерживаем оба варианта: `задать имя значение` и `задать имя=значение`.
    let (имя, значение) = if let Some((л, п)) = аргументы.split_once('=') {
        (л.trim(), п.trim())
    } else if let Some(пробел) = аргументы.find(char::is_whitespace) {
        (аргументы[..пробел].trim(), аргументы[пробел..].trim())
    } else {
        (аргументы.trim(), "")
    };
    if имя.is_empty() {
        crate::println!("Использование: задать ИМЯ ЗНАЧЕНИЕ  (или: задать ИМЯ=ЗНАЧЕНИЕ)");
        return;
    }
    let значение_строка = значение.to_string();
    if let Some(существующая) = с.переменные.iter_mut().find(|(к, _)| к == имя) {
        существующая.1 = значение_строка;
    } else {
        с.переменные.push((имя.to_string(), значение_строка));
    }
    crate::println!("Задано: {}={}", имя, значение);
}

