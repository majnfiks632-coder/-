// Оболочка ядра (этап 8 дорожной карты).
//
// Простой однострочный командный интерпретатор. Читает клавиши из очереди
// драйвера PS/2 (через `драйверы::клавиатура::взять_клавишу`), накапливает
// строку, по Enter разбирает её и выполняет встроенную команду.
//
// Особенности:
// * Никаких аллокаций кучи — буфер ввода фиксированного размера в стеке состояния.
// * Команды — латиницей (US-QWERTY ввод; русская раскладка появится в этапе 14).
// * Сообщения и приглашение — на русском.
// * Уважает отладочное окно: пока F12 открыто, оболочка не трогает клавиатуру.
//
// Архитектура: только x86_64 (зависит от PS/2 и VGA-консоли).

#![allow(dead_code)]

use core::sync::atomic::Ordering;
use spin::Mutex;

use crate::драйверы::клавиатура::{self, Клавиша};

/// Максимальная длина строки ввода (в байтах ASCII). Если пользователь набирает
/// больше — лишние символы игнорируются.
const МАКС_ДЛИНА: usize = 256;

pub struct Оболочка {
    буфер: [u8; МАКС_ДЛИНА],
    длина: usize,
    приветствие_напечатано: bool,
}

impl Оболочка {
    pub const fn новая() -> Self {
        Self {
            буфер: [0; МАКС_ДЛИНА],
            длина: 0,
            приветствие_напечатано: false,
        }
    }
}

static ОБОЛОЧКА: Mutex<Оболочка> = Mutex::new(Оболочка::новая());

/// Опросная процедура: вызывается из главного цикла ядра. Если оболочка
/// активна (отладочное окно закрыто), вычитает накопившиеся клавиши и
/// обрабатывает их. Печатает приглашение при первом вызове.
pub fn обновить() {
    // Если открыто отладочное окно — оно «съедает» клавиатуру, оболочка молчит.
    if crate::отладка::окно::активно() {
        return;
    }

    let mut состояние = ОБОЛОЧКА.lock();

    if !состояние.приветствие_напечатано {
        крате_печать_приветствия();
        напечатать_приглашение();
        состояние.приветствие_напечатано = true;
    }

    while let Some(клавиша) = клавиатура::взять_клавишу() {
        обработать_клавишу(&mut состояние, клавиша);
    }
}

fn обработать_клавишу(с: &mut Оболочка, клавиша: Клавиша) {
    match клавиша {
        Клавиша::Символ(символ) if символ.is_ascii() && символ != '\n' && символ != '\r' => {
            if с.длина < МАКС_ДЛИНА - 1 {
                с.буфер[с.длина] = символ as u8;
                с.длина += 1;
                crate::print!("{}", символ);
            }
        }
        Клавиша::Возврат => {
            if с.длина > 0 {
                с.длина -= 1;
                // BS, пробел, BS — стандартный приём в текстовом терминале.
                crate::print!("\u{8} \u{8}");
            }
        }
        Клавиша::Ввод => {
            crate::println!();
            // Скопируем строку из буфера, чтобы освободить состояние перед
            // выполнением команды (некоторые команды печатают много, а
            // отдельные — могут захотеть взять блокировку оболочки).
            let длина = с.длина;
            let mut копия: [u8; МАКС_ДЛИНА] = [0; МАКС_ДЛИНА];
            копия[..длина].copy_from_slice(&с.буфер[..длина]);
            с.длина = 0;

            // Освободим блокировку оболочки на время выполнения.
            // (текущий API не позволяет напрямую — придётся передавать без неё.)
            // Поскольку обновить() лочит и зовёт обработать_клавишу, здесь у
            // нас уже эксклюзивный доступ. Команды не пытаются взять lock на
            // ОБОЛОЧКА, так что просто вызываем выполнить.
            let строка = core::str::from_utf8(&копия[..длина]).unwrap_or("");
            выполнить(строка);
            напечатать_приглашение();
        }
        Клавиша::ПробелТабуляции => {
            // Табуляции пока не поддерживаем (автодополнение — этап 14).
        }
        _ => {
            // Стрелки/F-клавиши/неизвестные — игнорируем.
        }
    }
}

fn крате_печать_приветствия() {
    crate::println!();
    crate::println!("ДубинаОС оболочка (этап 8). Введите 'help' для списка команд.");
}

fn напечатать_приглашение() {
    crate::print!("дубина> ");
}

fn выполнить(строка: &str) {
    let строка = строка.trim();
    if строка.is_empty() {
        return;
    }
    let (команда, аргументы) = разрезать(строка);
    match команда {
        "help" | "?" | "справка" => команда_справка(),
        "version" | "версия" => команда_версия(),
        "echo" | "эхо" => команда_эхо(аргументы),
        "clear" | "cls" | "очистить" => команда_очистить(),
        "mem" | "память" => команда_память(),
        "threads" | "потоки" => команда_потоки(),
        "uptime" | "time" | "время" => команда_время(),
        "panic" | "паника" => команда_паника(аргументы),
        "reboot" | "перезагрузка" => команда_перезагрузка(),
        иное => crate::println!(
            "Неизвестная команда: '{}'. Наберите 'help' для списка.",
            иное
        ),
    }
}

fn разрезать(строка: &str) -> (&str, &str) {
    let байты = строка.as_bytes();
    if let Some(пробел) = байты.iter().position(|&b| b == b' ' || b == b'\t') {
        let команда = &строка[..пробел];
        let хвост = строка[пробел..].trim_start();
        (команда, хвост)
    } else {
        (строка, "")
    }
}

fn команда_справка() {
    crate::println!("Встроенные команды (английские и русские синонимы):");
    crate::println!("  help / справка       — этот список");
    crate::println!("  version / версия     — версия ядра");
    crate::println!("  echo <текст>         — напечатать аргументы");
    crate::println!("  clear / очистить     — очистить экран");
    crate::println!("  mem / память         — статистика памяти");
    crate::println!("  threads / потоки     — состояние планировщика");
    crate::println!("  uptime / время       — время работы (тики PIT)");
    crate::println!("  panic <текст>        — вызвать панику ядра (для теста)");
    crate::println!("  reboot / перезагрузка — перезагрузить машину");
}

fn команда_версия() {
    crate::println!("ДубинаОС, ядро v0.1");
    crate::println!("Лицензия: GPL-3.0-or-later");
    crate::println!("Архитектура: x86_64");
}

fn команда_эхо(аргументы: &str) {
    crate::println!("{}", аргументы);
}

fn команда_очистить() {
    {
        let mut к = crate::арх::x86_64::видео::буфер_vga().lock();
        к.очистить();
    }
    // После очистки экран чистый — приглашение напечатается основным циклом.
}

fn команда_память() {
    let аллокатор = crate::память::физическая::АЛЛОКАТОР.lock();
    let всего = аллокатор.всего_байтов();
    let свободно = аллокатор.свободно_байтов();
    let занято = всего.saturating_sub(свободно);
    drop(аллокатор);
    crate::println!(
        "Физическая память: всего {} КиБ, занято {} КиБ, свободно {} КиБ",
        всего / 1024,
        занято / 1024,
        свободно / 1024
    );
    let (выделено_кучи, всего_кучи) = crate::память::куча::КУЧА.статистика();
    crate::println!(
        "Куча ядра: выделено {} Б из {} Б",
        выделено_кучи,
        всего_кучи
    );
}

fn команда_потоки() {
    crate::println!(
        "Активных потоков: {}",
        crate::потоки::планировщик::количество_потоков()
    );
    crate::println!(
        "Текущий поток: {}",
        crate::потоки::планировщик::текущий().0
    );
}

fn команда_время() {
    let тики = crate::арх::x86_64::таймер::ТИКИ.load(Ordering::Relaxed);
    let мс = crate::арх::x86_64::таймер::миллисекунды();
    crate::println!("Тиков с момента старта: {} (~{} мс)", тики, мс);
}

fn команда_паника(аргументы: &str) {
    if аргументы.is_empty() {
        panic!("намеренная паника из оболочки");
    } else {
        panic!("намеренная паника из оболочки: {}", аргументы);
    }
}

fn команда_перезагрузка() {
    crate::println!("Перезагрузка через PS/2 контроллер…");
    // Стандартный приём: запись 0xFE в порт 0x64 заставит контроллер 8042
    // дёрнуть линию RESET процессора.
    unsafe {
        core::arch::asm!(
            "mov al, 0xFE",
            "out 0x64, al",
            options(nomem, nostack, preserves_flags),
        );
    }
    // На случай, если 8042 не сработал — тройная ошибка и halt.
    crate::арх::x86_64::халт_навсегда();
}
