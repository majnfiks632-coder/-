// Простой парсер арифметики: + - * /, скобки, целые числа i64.
// Возвращает (значение, остаток-строки-после-выражения).
fn вычислить(вход: &str) -> Result<(i64, &str), &'static str> {
    let вход = вход.trim_start();
    let (л, остаток) = вычислить_терм(вход)?;
    разбор_доп(л, остаток)
}

fn разбор_доп(mut л: i64, mut вход: &str) -> Result<(i64, &str), &'static str> {
    loop {
        вход = вход.trim_start();
        let символ = match вход.chars().next() {
            Some(с) => с,
            None => return Ok((л, вход)),
        };
        if символ != '+' && символ != '-' {
            return Ok((л, вход));
        }
        let (п, остаток) = вычислить_терм(&вход[1..])?;
        if символ == '+' {
            л += п;
        } else {
            л -= п;
        }
        вход = остаток;
    }
}

fn вычислить_терм(вход: &str) -> Result<(i64, &str), &'static str> {
    let вход = вход.trim_start();
    let (л, остаток) = вычислить_фактор(вход)?;
    разбор_мул(л, остаток)
}

fn разбор_мул(mut л: i64, mut вход: &str) -> Result<(i64, &str), &'static str> {
    loop {
        вход = вход.trim_start();
        let символ = match вход.chars().next() {
            Some(с) => с,
            None => return Ok((л, вход)),
        };
        if символ != '*' && символ != '/' {
            return Ok((л, вход));
        }
        let (п, остаток) = вычислить_фактор(&вход[1..])?;
        if символ == '*' {
            л = л.saturating_mul(п);
        } else {
            if п == 0 {
                return Err("деление на ноль");
            }
            л /= п;
        }
        вход = остаток;
    }
}

fn вычислить_фактор(вход: &str) -> Result<(i64, &str), &'static str> {
    let вход = вход.trim_start();
    let mut символы = вход.chars();
    let первый = символы.next().ok_or("пустое выражение")?;
    if первый == '(' {
        let (значение, остаток) = вычислить(&вход[1..])?;
        let остаток = остаток.trim_start();
        let mut итер = остаток.chars();
        match итер.next() {
            Some(')') => Ok((значение, &остаток[1..])),
            _ => Err("ожидалась ')'"),
        }
    } else if первый == '-' {
        let (з, о) = вычислить_фактор(&вход[1..])?;
        Ok((-з, о))
    } else if первый.is_ascii_digit() {
        let mut длина = 0usize;
        for б in вход.bytes() {
            if !(б.is_ascii_digit()) {
                break;
            }
            длина += 1;
        }
        let число: i64 = вход[..длина].parse().map_err(|_| "число вне диапазона")?;
        Ok((число, &вход[длина..]))
    } else {
        Err("ожидалось число или скобка")
    }
}

