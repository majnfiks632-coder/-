fn команда_список(с: &Оболочка, аргументы: &str) {
    if !crate::файлсистема::готова() {
        crate::println!("ДубФС ещё не смонтирована.");
        return;
    }
    let путь_аргумент = аргументы.trim();
    let путь = if путь_аргумент.is_empty() {
        с.текущий_каталог.clone()
    } else {
        crate::файлсистема::нормализовать(&с.текущий_каталог, путь_аргумент)
    };
    match crate::файлсистема::прочитать_каталог(&путь) {
        Ok(записи) => {
            if записи.is_empty() {
                crate::println!("(пусто) {}", путь);
                return;
            }
            crate::println!("{}:", путь);
            for элемент in записи {
                crate::println!(
                    "  [{}]  {}",
                    crate::файлсистема::буква_типа(элемент.тип),
                    элемент.имя
                );
            }
        }
        Err(ошибка) => crate::println!("сп: {}: {}", путь, ошибка),
    }
}

