fn выдать_края(с: &Оболочка, аргументы: &str, голова: bool) {
    if !crate::файлсистема::готова() {
        crate::println!("ДубФС ещё не смонтирована.");
        return;
    }
    let имя = if голова { "голова" } else { "хвост" };
    let (первый, остаток) = разрезать(аргументы);
    let (количество, путь_аргумент) = if let Some(число) = первый.strip_prefix("-n") {
        (
            число.trim().parse::<usize>().unwrap_or(10),
            остаток.trim().to_string(),
        )
    } else if первый.starts_with('-') {
        match первый[1..].parse::<usize>() {
            Ok(n) => (n, остаток.trim().to_string()),
            Err(_) => (10usize, аргументы.trim().to_string()),
        }
    } else {
        (10usize, аргументы.trim().to_string())
    };
    if путь_аргумент.is_empty() {
        crate::println!("Использование: {} [-N] ПУТЬ", имя);
        return;
    }
    let путь = crate::файлсистема::нормализовать(&с.текущий_каталог, &путь_аргумент);
    let данные = match crate::файлсистема::прочитать_файл(&путь, 64 * 1024) {
        Ok(в) => в,
        Err(ошибка) => {
            crate::println!("{}: {}: {}", имя, путь, ошибка);
            return;
        }
    };
    let текст = match core::str::from_utf8(&данные) {
        Ok(т) => т,
        Err(_) => {
            crate::println!("{}: {}: файл не UTF-8", имя, путь);
            return;
        }
    };
    let строки: Vec<&str> = текст.lines().collect();
    let всего = строки.len();
    if голова {
        for s in строки.iter().take(количество) {
            crate::println!("{}", s);
        }
    } else {
        let начало = всего.saturating_sub(количество);
        for s in &строки[начало..] {
            crate::println!("{}", s);
        }
    }
}

