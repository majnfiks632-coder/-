fn команда_задать(с: &mut Оболочка, аргументы: &str) {
    if аргументы.is_empty() {
        команда_показать(с);
        return;
    }
    // Поддерживаем оба варианта: `задать имя значение` и `задать имя=значение`.
    let (имя, значение) = if let Some((л, п)) = аргументы.split_once('=') {
        (л.trim(), п.trim())
    } else if let Some(пробел) = аргументы.find(char::is_whitespace) {
        (аргументы[..пробел].trim(), аргументы[пробел..].trim())
    } else {
        (аргументы.trim(), "")
    };
    if имя.is_empty() {
        crate::println!("Использование: задать ИМЯ ЗНАЧЕНИЕ  (или: задать ИМЯ=ЗНАЧЕНИЕ)");
        return;
    }
    let значение_строка = значение.to_string();
    if let Some(существующая) = с.переменные.iter_mut().find(|(к, _)| к == имя) {
        существующая.1 = значение_строка;
    } else {
        с.переменные.push((имя.to_string(), значение_строка));
    }
    crate::println!("Задано: {}={}", имя, значение);
}

fn команда_удалить(с: &mut Оболочка, аргументы: &str) {
    let имя = аргументы.trim();
    if имя.is_empty() {
        crate::println!("Использование: удалить ИМЯ");
        return;
    }
    if let Some(индекс) = с.переменные.iter().position(|(к, _)| к == имя) {
        с.переменные.remove(индекс);
        crate::println!("Удалено: {}", имя);
    } else {
        crate::println!("Переменная '{}' не задана.", имя);
    }
}

fn команда_показать(с: &Оболочка) {
    if с.переменные.is_empty() {
        crate::println!("(пользовательских переменных нет)");
    } else {
        for (к, з) in &с.переменные {
            crate::println!("{}={}", к, з);
        }
    }
    crate::println!();
    crate::println!("Автоматические:");
    crate::println!("  ВЕРСИЯ=0.1.0");
    crate::println!("  АРХ=x86_64");
    crate::println!(
        "  ПОТОКОВ={}",
        crate::потоки::планировщик::количество_потоков()
    );
    crate::println!("  ВРЕМЯ={}", crate::арх::x86_64::таймер::миллисекунды());
}

