/// Одна запись истории: фиксированный буфер + длина.
#[derive(Copy, Clone)]
struct ЗаписьИстории {
    буфер: [u8; МАКС_ДЛИНА],
    длина: usize,
}

impl ЗаписьИстории {
    const fn пустая() -> Self {
        Self {
            буфер: [0; МАКС_ДЛИНА],
            длина: 0,
        }
    }
}

pub struct Оболочка {
    /// Текущий буфер ввода (то, что пользователь сейчас печатает).
    буфер: [u8; МАКС_ДЛИНА],
    /// Сколько байт в буфере уже занято.
    длина: usize,
    /// Признак того, что приветствие уже напечатано при первом обновлении.
    приветствие_напечатано: bool,
    /// Кольцевой буфер истории (последние команды). 0 — самая старая запись.
    история: [ЗаписьИстории; ГЛУБИНА_ИСТОРИИ],
    /// Сколько записей в истории заполнено (0..=ГЛУБИНА_ИСТОРИИ).
    история_заполнено: usize,
    /// Куда писать следующую запись истории (индекс в `история`).
    история_следующая: usize,
    /// Текущая позиция при листании историей.
    история_курсор: Option<usize>,
    /// Пользовательские переменные оболочки.
    переменные: Vec<(String, String)>,
    /// Текущий каталог оболочки (всегда абсолютный, начинается с `/`).
    текущий_каталог: String,
}

impl Оболочка {
    pub const fn новая() -> Self {
        Self {
            буфер: [0; МАКС_ДЛИНА],
            длина: 0,
            приветствие_напечатано: false,
            история: [ЗаписьИстории::пустая(); ГЛУБИНА_ИСТОРИИ],
            история_заполнено: 0,
            история_следующая: 0,
            история_курсор: None,
            переменные: Vec::new(),
            текущий_каталог: String::new(),
        }
    }
}

static ОБОЛОЧКА: Mutex<Оболочка> = Mutex::new(Оболочка::новая());

/// Опросная процедура: вызывается из главного цикла ядра. Если оболочка
/// активна (отладочное окно закрыто), вычитает накопившиеся клавиши и
/// обрабатывает их. Печатает приглашение при первом вызове.
pub fn обновить() {
    if crate::отладка::окно::активно() {
        return;
    }

    let mut состояние = ОБОЛОЧКА.lock();

    if !состояние.приветствие_напечатано {
        крате_печать_приветствия();
        if состояние.текущий_каталог.is_empty() {
            состояние.текущий_каталог = "/дом".to_string();
        }
        напечатать_приглашение_с_каталогом(&состояние.текущий_каталог);
        состояние.приветствие_напечатано = true;
    }

    while let Some(клавиша) = клавиатура::взять_клавишу() {
        обработать_клавишу(&mut состояние, клавиша);
    }
}

fn обработать_клавишу(с: &mut Оболочка, клавиша: Клавиша) {
    match клавиша {
        Клавиша::Символ(символ) if символ.is_ascii() && символ != '\n' && символ != '\r' => {
            if с.длина < МАКС_ДЛИНА - 1 {
                с.буфер[с.длина] = символ as u8;
                с.длина += 1;
                с.история_курсор = None;
                crate::print!("{}", символ);
            }
        }
        Клавиша::Возврат => {
            if с.длина > 0 {
                с.длина -= 1;
                с.история_курсор = None;
                crate::print!("\u{8} \u{8}");
            }
        }
        Клавиша::Ввод => {
            crate::println!();
            let длина = с.длина;
            let mut копия: [u8; МАКС_ДЛИНА] = [0; МАКС_ДЛИНА];
            копия[..длина].copy_from_slice(&с.буфер[..длина]);
            с.длина = 0;
            с.история_курсор = None;

            let строка = core::str::from_utf8(&копия[..длина]).unwrap_or("");
            let обрезанная = строка.trim();
            if !обрезанная.is_empty() {
                добавить_в_историю(с, обрезанная);
            }
            // Копируем строку, чтобы не держать заём на буфер при выполнении.
            let локальная = обрезанная.to_string();
            выполнить_строку(с, &локальная);
            напечатать_приглашение_с_каталогом(&с.текущий_каталог);
        }
        Клавиша::Стрелка(Стрелка::Вверх) => {
            let следующий = match с.история_курсор {
                None if с.история_заполнено > 0 => Some(0),
                Some(к) if к + 1 < с.история_заполнено => Some(к + 1),
                существующий => существующий,
            };
            if следующий != с.история_курсор {
                с.история_курсор = следующий;
                if let Some(к) = следующий {
                    показать_из_истории(с, к);
                }
            }
        }
        Клавиша::Стрелка(Стрелка::Вниз) => {
            let следующий = match с.история_курсор {
                Some(0) => None,
                Some(к) => Some(к - 1),
                None => None,
            };
            if следующий != с.история_курсор {
                с.история_курсор = следующий;
                match следующий {
                    Some(к) => показать_из_истории(с, к),
                    None => очистить_текущую_строку(с),
                }
            }
        }
        Клавиша::Стрелка(_) => {}
        Клавиша::ПробелТабуляции => обработать_таб(с),
        _ => {}
    }
}

fn добавить_в_историю(с: &mut Оболочка, строка: &str) {
    let байты = строка.as_bytes();
    let длина = байты.len().min(МАКС_ДЛИНА - 1);

    if с.история_заполнено > 0 {
        let индекс_последней = (с.история_следующая + ГЛУБИНА_ИСТОРИИ - 1) % ГЛУБИНА_ИСТОРИИ;
        let последняя = &с.история[индекс_последней];
        if последняя.длина == длина && последняя.буфер[..длина] == байты[..длина] {
            return;
        }
    }

    let индекс = с.история_следующая;
    с.история[индекс].буфер[..длина].copy_from_slice(&байты[..длина]);
    с.история[индекс].длина = длина;
    с.история_следующая = (с.история_следующая + 1) % ГЛУБИНА_ИСТОРИИ;
    if с.история_заполнено < ГЛУБИНА_ИСТОРИИ {
        с.история_заполнено += 1;
    }
}

fn очистить_текущую_строку(с: &mut Оболочка) {
    while с.длина > 0 {
        с.длина -= 1;
        crate::print!("\u{8} \u{8}");
    }
}

fn показать_из_истории(с: &mut Оболочка, смещение: usize) {
    if смещение >= с.история_заполнено {
        return;
    }
    let индекс_свежей = (с.история_следующая + ГЛУБИНА_ИСТОРИИ - 1) % ГЛУБИНА_ИСТОРИИ;
    let индекс = (индекс_свежей + ГЛУБИНА_ИСТОРИИ - смещение) % ГЛУБИНА_ИСТОРИИ;
    let длина = с.история[индекс].длина;

    очистить_текущую_строку(с);

    с.буфер[..длина].copy_from_slice(&с.история[индекс].буфер[..длина]);
    с.длина = длина;
    if let Ok(текст) = core::str::from_utf8(&с.буфер[..длина]) {
        crate::print!("{}", текст);
    }
}

/// Tab-автодополнение: дополняем последнее слово в текущем буфере, если
/// оно совпадает с началом известной команды. Несколько вариантов —
/// печатаем их и оставляем общий префикс.
fn обработать_таб(с: &mut Оболочка) {
    let текущее = match core::str::from_utf8(&с.буфер[..с.длина]) {
        Ok(т) => т,
        Err(_) => return,
    };

    // Находим начало последнего слова (после последнего пробела).
    let начало_слова = текущее
        .rfind(|c: char| c == ' ' || c == '\t' || c == '|' || c == ';')
        .map(|i| i + 1)
        .unwrap_or(0);
    let слово = &текущее[начало_слова..];
    if слово.is_empty() {
        return;
    }

    // Собираем все команды, чьи имена начинаются с `слово`.
    let совпадения: Vec<&&str> = ИМЕНА_КОМАНД
        .iter()
        .filter(|и| и.starts_with(слово))
        .collect();

    match совпадения.len() {
        0 => {}
        1 => {
            // Полное дополнение.
            let полное = совпадения[0];
            let остаток = &полное[слово.len()..];
            // Дописываем недостающие байты в буфер и на экран.
            for &байт in остаток.as_bytes() {
                if с.длина < МАКС_ДЛИНА - 1 {
                    с.буфер[с.длина] = байт;
                    с.длина += 1;
                }
            }
            crate::print!("{}", остаток);
        }
        _ => {
            // Несколько вариантов: печатаем их новой строкой и
            // подбираем общий префикс.
            let общий = общий_префикс(&совпадения, слово.len());
            if общий.len() > слово.len() {
                let добавок = &общий[слово.len()..];
                for &байт in добавок.as_bytes() {
                    if с.длина < МАКС_ДЛИНА - 1 {
                        с.буфер[с.длина] = байт;
                        с.длина += 1;
                    }
                }
                crate::print!("{}", добавок);
            } else {
                crate::println!();
                for имя in &совпадения {
                    crate::print!("  {}", имя);
                }
                crate::println!();
                напечатать_приглашение_с_каталогом(&с.текущий_каталог);
                // Перепечатываем текущий буфер.
                if let Ok(текст) = core::str::from_utf8(&с.буфер[..с.длина]) {
                    crate::print!("{}", текст);
                }
            }
        }
    }
}

fn общий_префикс<'а>(варианты: &[&&'а str], минимум: usize) -> &'а str {
    if варианты.is_empty() {
        return "";
    }
    let первая = варианты[0];
    let mut длина = первая.len();
    for &&следующая in &варианты[1..] {
        let общая = первая
            .as_bytes()
            .iter()
            .zip(следующая.as_bytes())
            .take_while(|(a, b)| a == b)
            .count();
        if общая < длина {
            длина = общая;
        }
    }
    if длина < минимум {
        длина = минимум;
    }
    &первая[..длина]
}

fn крате_печать_приветствия() {
    crate::println!();
    crate::println!("ДубинаОС оболочка (этап 8). Введите 'справка' для списка команд.");
}

fn напечатать_приглашение_с_каталогом(каталог: &str) {
    if каталог.is_empty() || каталог == "/" {
        crate::print!("дубина:/> ");
    } else {
        crate::print!("дубина:{}> ", каталог);
    }
}

