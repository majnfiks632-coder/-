// Оболочка ядра (этап 8 дорожной карты).
//
// Простой однострочный командный интерпретатор. Читает клавиши из очереди
// драйвера PS/2 (через `драйверы::клавиатура::взять_клавишу`), накапливает
// строку, по Enter разбирает её и выполняет встроенные команды.
//
// Возможности (этап 8 закрыт почти полностью):
// * Команды и их синонимы — латиницей и кириллицей одновременно
//   (`ls` ↔ `сп`, `ps` ↔ `процессы`, `top` ↔ `мониторинг`, `cd` ↔ `сд` и др.).
// * Стрелки ↑/↓ листают историю последних 16 команд.
// * Tab дополняет имя команды (если совпадение единственное —
//   подставляет, если несколько — печатает варианты).
// * Переменные оболочки: `задать имя значение`, `удалить имя`,
//   `показать` / `env`. Подстановка `$имя` происходит в аргументах
//   до выполнения. Несколько имён доступны автоматически:
//   `$ВЕРСИЯ`, `$АРХ`, `$ПОТОКОВ`, `$ВРЕМЯ`.
// * Конвейеры `cmd1 | cmd2 | cmd3` — вывод предыдущей команды
//   передаётся следующей как стандартный вход. Реализовано через
//   глобальный «захват печати» в `crate::печать`.
// * Последовательность команд через `;` (`команда1 ; команда2`).
// * Фильтры `поиск <подстрока>` и `сосчитать` для работы с конвейерами.
// * Сообщения и приглашение — на русском.
// * Уважает отладочное окно: пока F12 открыто, оболочка не трогает клавиатуру.
//
// Архитектура: только x86_64 (зависит от PS/2 и VGA-консоли).

