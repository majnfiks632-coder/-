fn дерево_рекурсивно(путь: &str, отступ: &str, глубина: usize) {
    // Защита от бесконечной рекурсии: предельная глубина 8.
    if глубина >= 8 {
        crate::println!("{}…(глубина >8, обрезано)", отступ);
        return;
    }
    let записи = match crate::файлсистема::прочитать_каталог(путь) {
        Ok(в) => в,
        Err(ошибка) => {
            crate::println!("{}{}: {}", отступ, путь, ошибка);
            return;
        }
    };
    for элемент in записи {
        let маркер = match элемент.тип {
            dubina_fs::Тип::Каталог => '\u{f0}',
            dubina_fs::Тип::Файл => '\u{14}',
        };
        crate::println!("{}{} {}", отступ, маркер, элемент.имя);
        if матчится_каталог(элемент.тип) {
            let следующий = if путь == "/" {
                alloc::format!("/{}", элемент.имя)
            } else {
                alloc::format!("{}/{}", путь, элемент.имя)
            };
            let новый_отступ = alloc::format!("{}  ", отступ);
            дерево_рекурсивно(&следующий, &новый_отступ, глубина + 1);
        }
    }
}

