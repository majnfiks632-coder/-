// Единый протокол информации о загрузке («Дубина-Прото»).
//
// Любой загрузчик ДубинаОС (UEFI x86_64, наш собственный MBR+Stage2,
// Multiboot2 через GRUB) кладёт в память структуру `ИнфоЗагрузки`
// и передаёт ядру в `_yadro_start(магия, инфо)` пару (магия, указатель).
//
// Магия `МАГИЯ_ДУБ_ПРОТО` отличает этот протокол от устаревших
// `Multiboot2` и «голого» прыжка из своего Stage2 без памяти/framebuffer.
// Старые пути продолжают работать (см. `главный.rs::подключить_графику_если_есть`).

#![allow(dead_code)]

/// Магия, которую UEFI-загрузчик и любой будущий «настоящий» загрузчик
/// ДубинаОС кладут в RDI при вызове `_yadro_start`.
pub const МАГИЯ_ДУБ_ПРОТО: u64 = 0xD0BA_0BE5_DBBA_0001;

/// Версия протокола. Несовместимое изменение — увеличиваем.
pub const ВЕРСИЯ_ПРОТОКОЛА: u32 = 1;

/// Источник загрузки.
pub const ИСТОЧНИК_UEFI: u32 = 1;
pub const ИСТОЧНИК_СВОЙ_BIOS: u32 = 2;
pub const ИСТОЧНИК_MULTIBOOT2: u32 = 3;

/// Тип записи карты памяти.
pub const ОБЛАСТЬ_ДОСТУПНА: u32 = 1;
pub const ОБЛАСТЬ_ЗАРЕЗЕРВИРОВАНА: u32 = 2;
pub const ОБЛАСТЬ_ACPI_ВОССТАНОВИМАЯ: u32 = 3;
pub const ОБЛАСТЬ_ACPI_NVS: u32 = 4;
pub const ОБЛАСТЬ_ПЛОХАЯ: u32 = 5;
pub const ОБЛАСТЬ_ЯДРО: u32 = 6; // используется загрузчиком: куда положили ядро
pub const ОБЛАСТЬ_ИНФО: u32 = 7; // используется загрузчиком: где лежит ИнфоЗагрузки

/// Формат пикселя framebuffer.
pub const ФБ_ФОРМАТ_RGB: u32 = 1; // 8-bit R, G, B, X
pub const ФБ_ФОРМАТ_BGR: u32 = 2; // 8-bit B, G, R, X (типично для UEFI)
pub const ФБ_ФОРМАТ_МАСКА: u32 = 3; // bit-маски в полях ниже
pub const ФБ_ФОРМАТ_BLT_ONLY: u32 = 4; // CPU-доступа нет

/// Одна запись карты памяти.
#[repr(C, align(8))]
#[derive(Debug, Clone, Copy)]
pub struct ОбластьПамяти {
    pub начало: u64,
    pub длина: u64,
    pub тип: u32,
    pub _резерв: u32,
}

impl ОбластьПамяти {
    pub const fn пустая() -> Self {
        Self {
            начало: 0,
            длина: 0,
            тип: 0,
            _резерв: 0,
        }
    }
}

/// Главная структура boot info, передаваемая ядру.
///
/// Поле `размер` равно размеру самой структуры в байтах. Это позволяет
/// добавлять новые поля в конце без поломки существующих ядер: они увидят
/// `размер` меньше своего и просто не будут читать новые хвостовые поля.
#[repr(C, align(8))]
#[derive(Debug, Clone, Copy)]
pub struct ИнфоЗагрузки {
    pub магия: u64,
    pub версия: u32,
    pub размер: u32,

    // ----- Источник -----
    pub источник: u32, // ИСТОЧНИК_*
    pub _резерв1: u32,

    // ----- Framebuffer -----
    pub фб_адрес: u64,
    pub фб_размер: u64,        // в байтах
    pub фб_ширина: u32,        // в пикселях
    pub фб_высота: u32,        // в пикселях
    pub фб_шаг_пикселей: u32,  // PixelsPerScanLine (UEFI), может быть >ширины
    pub фб_бит_на_пиксель: u32, // обычно 32
    pub фб_формат: u32,        // ФБ_ФОРМАТ_*
    pub _резерв_фб: u32,

    // ----- Карта памяти -----
    /// Указатель на массив `ОбластьПамяти`. 0 = карта недоступна.
    pub карта_памяти: u64,
    pub карта_памяти_элементов: u32,
    pub карта_памяти_размер_элемента: u32,

    // ----- ACPI -----
    /// Физический адрес ACPI 2.0 RSDP (или 1.0, если 2.0 нет). 0 = нет ACPI.
    pub rsdp: u64,

    // ----- Где лежит само ядро (информационно) -----
    pub ядро_физический: u64,
    pub ядро_длина: u64,
}

impl ИнфоЗагрузки {
    pub const fn пустая() -> Self {
        Self {
            магия: МАГИЯ_ДУБ_ПРОТО,
            версия: ВЕРСИЯ_ПРОТОКОЛА,
            размер: core::mem::size_of::<Self>() as u32,
            источник: 0,
            _резерв1: 0,
            фб_адрес: 0,
            фб_размер: 0,
            фб_ширина: 0,
            фб_высота: 0,
            фб_шаг_пикселей: 0,
            фб_бит_на_пиксель: 0,
            фб_формат: 0,
            _резерв_фб: 0,
            карта_памяти: 0,
            карта_памяти_элементов: 0,
            карта_памяти_размер_элемента: 0,
            rsdp: 0,
            ядро_физический: 0,
            ядро_длина: 0,
        }
    }

    /// Безопасно прочитать структуру по физическому/виртуальному адресу.
    /// Возвращает `None`, если магия или версия не совпали.
    ///
    /// # Безопасность
    /// `адрес` должен указывать на валидную память, доступную для чтения.
    pub unsafe fn прочитать(адрес: u64) -> Option<Self> {
        if адрес == 0 || (адрес & 0b111) != 0 {
            return None;
        }
        let указатель = адрес as *const Self;
        let магия = unsafe { core::ptr::read_unaligned(&(*указатель).магия) };
        if магия != МАГИЯ_ДУБ_ПРОТО {
            return None;
        }
        let версия = unsafe { core::ptr::read_unaligned(&(*указатель).версия) };
        if версия == 0 || версия > ВЕРСИЯ_ПРОТОКОЛА {
            return None;
        }
        Some(unsafe { core::ptr::read_unaligned(указатель) })
    }

    /// Итератор по карте памяти. Пустой, если карты нет.
    pub fn области(&self) -> impl Iterator<Item = ОбластьПамяти> + '_ {
        let база = self.карта_памяти;
        let шаг = self.карта_памяти_размер_элемента as usize;
        let n = self.карта_памяти_элементов as usize;
        (0..n).map(move |i| {
            let указатель = (база as usize + i * шаг) as *const ОбластьПамяти;
            unsafe { core::ptr::read_unaligned(указатель) }
        })
    }
}
