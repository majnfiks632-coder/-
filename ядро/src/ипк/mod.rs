// Межпроцессное общение (ИПК) ядра.
//
// На этом этапе реализован простой обмен сообщениями через порты:
//   * Порт — это типизированная очередь сообщений, у каждого свой ИдПорта.
//   * `отправить(порт, сообщение)` — кладёт сообщение в хвост очереди порта;
//     если кто-то ждёт на этом порту — будит его.
//   * `принять(порт)` — извлекает сообщение из головы; если очередь пуста,
//     поток блокируется и уступает планировщику.
//   * Ёмкость каждого порта ограничена (не даём бесконечно расти буферам).
//
// Все идентификаторы и сообщения — на русском.

#![allow(dead_code)]

use alloc::collections::{BTreeMap, VecDeque};
use alloc::vec::Vec;
use core::sync::atomic::{AtomicU64, Ordering};

use spin::Mutex;

use crate::потоки::{планировщик, ИдПотока};

/// Идентификатор порта.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct ИдПорта(pub u64);

/// Сообщение фиксированного формата. На текущем этапе — 4 машинных слова
/// плюс полезная нагрузка-буфер. В будущем — обмен capability.
#[derive(Debug, Clone)]
pub struct Сообщение {
    /// Кто отправил.
    pub отправитель: ИдПотока,
    /// Кодовое значение (тег).
    pub код: u64,
    /// Произвольная полезная нагрузка.
    pub полезная_нагрузка: Vec<u8>,
}

/// Ошибки ИПК.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ОшибкаИПК {
    НетПорта,
    ОчередьПереполнена,
    ПортЗакрыт,
}

impl core::fmt::Display for ОшибкаИПК {
    fn fmt(&self, ф: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        let т = match self {
            ОшибкаИПК::НетПорта => "порт не найден",
            ОшибкаИПК::ОчередьПереполнена => "очередь сообщений порта переполнена",
            ОшибкаИПК::ПортЗакрыт => "порт закрыт",
        };
        ф.write_str(т)
    }
}

/// Один порт с очередью сообщений.
struct Порт {
    очередь: VecDeque<Сообщение>,
    /// Идентификаторы потоков, ожидающих сообщение.
    ожидающие: VecDeque<ИдПотока>,
    /// Максимальный размер очереди.
    ёмкость: usize,
    /// Закрыт ли порт (после `закрыть()` принять/отправить — ошибка).
    закрыт: bool,
}

impl Порт {
    fn новый(ёмкость: usize) -> Self {
        Self {
            очередь: VecDeque::new(),
            ожидающие: VecDeque::new(),
            ёмкость,
            закрыт: false,
        }
    }
}

/// Глобальная таблица портов.
struct Состояние {
    порты: BTreeMap<u64, Порт>,
    следующий_ид: u64,
}

static СЛЕДУЮЩИЙ_ИД: AtomicU64 = AtomicU64::new(1);
static ТАБЛИЦА: Mutex<Состояние> = Mutex::new(Состояние {
    порты: BTreeMap::new(),
    следующий_ид: 1,
});

/// Создать новый порт с заданной ёмкостью очереди.
pub fn создать_порт(ёмкость: usize) -> ИдПорта {
    let ид = СЛЕДУЮЩИЙ_ИД.fetch_add(1, Ordering::Relaxed);
    let mut с = ТАБЛИЦА.lock();
    с.порты.insert(ид, Порт::новый(ёмкость));
    ИдПорта(ид)
}

/// Закрыть порт. Все ожидающие будут разбужены, дальнейшие операции вернут ошибку.
pub fn закрыть_порт(порт: ИдПорта) -> Result<(), ОшибкаИПК> {
    let mut с = ТАБЛИЦА.lock();
    let п = с.порты.get_mut(&порт.0).ok_or(ОшибкаИПК::НетПорта)?;
    п.закрыт = true;
    п.ожидающие.clear();
    Ok(())
}

/// Послать сообщение в порт. Если очередь полна — ошибка `ОчередьПереполнена`.
pub fn отправить(порт: ИдПорта, сообщение: Сообщение) -> Result<(), ОшибкаИПК> {
    let mut с = ТАБЛИЦА.lock();
    let п = с.порты.get_mut(&порт.0).ok_or(ОшибкаИПК::НетПорта)?;
    if п.закрыт {
        return Err(ОшибкаИПК::ПортЗакрыт);
    }
    if п.очередь.len() >= п.ёмкость {
        return Err(ОшибкаИПК::ОчередьПереполнена);
    }
    п.очередь.push_back(сообщение);
    // Будить ожидающих — на текущем кооперативном этапе достаточно
    // удалить их из списка ожидания, реальное возвращение в очередь
    // готовых будет происходить в `принять` после уступления.
    let _ = п.ожидающие.pop_front();
    Ok(())
}

/// Принять сообщение из порта. Если сообщений нет — поток уступает и
/// будет периодически возвращаться сюда, пока не появится сообщение.
pub fn принять(порт: ИдПорта) -> Result<Сообщение, ОшибкаИПК> {
    loop {
        // Под мутексом — попытаться извлечь.
        {
            let mut с = ТАБЛИЦА.lock();
            let п = с.порты.get_mut(&порт.0).ok_or(ОшибкаИПК::НетПорта)?;
            if п.закрыт {
                return Err(ОшибкаИПК::ПортЗакрыт);
            }
            if let Some(сообщение) = п.очередь.pop_front() {
                return Ok(сообщение);
            }
            // Зарегистрироваться ожидающим (для статистики и будущего
            // вытесняющего планировщика).
            п.ожидающие.push_back(планировщик::текущий());
        }
        планировщик::уступить();
    }
}

/// Попытка принять без блокировки. Возвращает None если сообщений нет.
pub fn принять_не_блокируя(порт: ИдПорта) -> Result<Option<Сообщение>, ОшибкаИПК> {
    let mut с = ТАБЛИЦА.lock();
    let п = с.порты.get_mut(&порт.0).ok_or(ОшибкаИПК::НетПорта)?;
    if п.закрыт {
        return Err(ОшибкаИПК::ПортЗакрыт);
    }
    Ok(п.очередь.pop_front())
}

/// Сколько сообщений сейчас лежит в порту.
pub fn длина_очереди(порт: ИдПорта) -> Result<usize, ОшибкаИПК> {
    let с = ТАБЛИЦА.lock();
    let п = с.порты.get(&порт.0).ok_or(ОшибкаИПК::НетПорта)?;
    Ok(п.очередь.len())
}
