#![allow(dead_code)]

use crate::ипк::{ОшибкаИПК, Сообщение};
use crate::способности::{ИдСпособности, ОшибкаСпособности, Объект, Права};
use crate::потоки::планировщик;

/// Объединённая ошибка сисвызовов.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ОшибкаСисвызова {
    Способность(ОшибкаСпособности),
    ИПК(ОшибкаИПК),
}

impl core::fmt::Display for ОшибкаСисвызова {
    fn fmt(&self, ф: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        match self {
            ОшибкаСисвызова::Способность(е) => write!(ф, "способность: {}", е),
            ОшибкаСисвызова::ИПК(е) => write!(ф, "ИПК: {}", е),
        }
    }
}

impl From<ОшибкаСпособности> for ОшибкаСисвызова {
    fn from(е: ОшибкаСпособности) -> Self {
        ОшибкаСисвызова::Способность(е)
    }
}

impl From<ОшибкаИПК> for ОшибкаСисвызова {
    fn from(е: ОшибкаИПК) -> Self {
        ОшибкаСисвызова::ИПК(е)
    }
}

/// сисв_создать_порт(ёмкость) -> ИдСпособности
///
/// Создаёт новый порт и регистрирует способность с полными правами
/// (ОТПРАВКА | ПРИЁМ | ЗАКРЫТИЕ).
pub fn сисв_создать_порт(ёмкость: usize) -> ИдСпособности {
    let порт = crate::ипк::создать_порт(ёмкость);
    crate::способности::выдать(
        Объект::Порт(порт),
        Права::ОТПРАВКА | Права::ПРИЁМ | Права::ЗАКРЫТИЕ,
    )
}

/// сисв_отправить(способность, код, нагрузка)
pub fn сисв_отправить(
    способность: ИдСпособности,
    код: u64,
    полезная_нагрузка: alloc::vec::Vec<u8>,
) -> Result<(), ОшибкаСисвызова> {
    let порт = crate::способности::проверить_порт(способность, Права::ОТПРАВКА)?;
    let сообщение = Сообщение {
        отправитель: планировщик::текущий(),
        код,
        полезная_нагрузка,
    };
    crate::ипк::отправить(порт, сообщение)?;
    Ok(())
}

/// сисв_принять(способность) -> Сообщение
pub fn сисв_принять(способность: ИдСпособности) -> Result<Сообщение, ОшибкаСисвызова> {
    let порт = crate::способности::проверить_порт(способность, Права::ПРИЁМ)?;
    Ok(crate::ипк::принять(порт)?)
}

/// сисв_закрыть(способность)
pub fn сисв_закрыть(способность: ИдСпособности) -> Result<(), ОшибкаСисвызова> {
    let порт = crate::способности::проверить_порт(способность, Права::ЗАКРЫТИЕ)?;
    crate::ипк::закрыть_порт(порт)?;
    Ok(())
}

/// сисв_уступить()
pub fn сисв_уступить() {
    планировщик::уступить();
}

/// сисв_завершить() — не возвращается.
pub fn сисв_завершить() -> ! {
    планировщик::завершить()
}

/// Создать «ограниченную» копию способности — с подмножеством прав.
/// Возвращает новый идентификатор.
pub fn сисв_ограничить_способность(
    исходная: ИдСпособности,
    разрешённые: Права,
) -> Result<ИдСпособности, ОшибкаСисвызова> {
    let существующая = crate::способности::получить(исходная)
        .ok_or(ОшибкаСпособности::НетСпособности)?;
    // Маска: новые права = исходные ∩ разрешённые.
    let итог = Права::из_бит(существующая.права.биты() & разрешённые.биты());
    Ok(crate::способности::выдать(существующая.объект, итог))
}
