// Кольцевой журнал логов в памяти ядра.
//
// Все строки, выведенные через `println!` / `print!`, дублируются в этот
// буфер. Отладочное окно (F12) читает из него и рисует на экране.
//
// Реализация: один большой кольцевой байт-буфер, без разделения на строки.
// Это даёт простоту (не нужно перевыделять память при переполнении) и
// корректную работу с длинными строками. Чтение разбивает на строки в момент
// рисования.
//
// Все идентификаторы и сообщения — на русском.

#![allow(dead_code)]

use core::sync::atomic::{AtomicBool, Ordering};
use spin::Mutex;

/// Размер буфера в байтах (≈400 строк по 80 символов).
const РАЗМЕР_БУФЕРА: usize = 32 * 1024;

pub struct КольцевойЖурнал {
    данные: [u8; РАЗМЕР_БУФЕРА],
    /// Индекс следующей записи. Растёт без ограничения (wrapping_add).
    позиция: usize,
    /// Сколько байт всего записано (для определения, заполнен ли буфер).
    всего_записано: usize,
}

impl КольцевойЖурнал {
    const fn новый() -> Self {
        Self {
            данные: [b' '; РАЗМЕР_БУФЕРА],
            позиция: 0,
            всего_записано: 0,
        }
    }

    pub fn записать(&mut self, текст: &str) {
        for &байт in текст.as_bytes() {
            self.данные[self.позиция % РАЗМЕР_БУФЕРА] = байт;
            self.позиция = self.позиция.wrapping_add(1);
            self.всего_записано = self.всего_записано.saturating_add(1);
        }
    }

    /// Длина «активной» части буфера (≤ РАЗМЕР_БУФЕРА).
    pub fn длина(&self) -> usize {
        self.всего_записано.min(РАЗМЕР_БУФЕРА)
    }

    /// Прочитать байт по логическому смещению (0 = самое старое).
    pub fn байт(&self, смещение: usize) -> u8 {
        let длина = self.длина();
        if смещение >= длина {
            return 0;
        }
        let начало = if self.всего_записано <= РАЗМЕР_БУФЕРА {
            0
        } else {
            self.позиция % РАЗМЕР_БУФЕРА
        };
        self.данные[(начало + смещение) % РАЗМЕР_БУФЕРА]
    }

    /// Скопировать `длина` последних байт в `выход`. Возвращает скольких реально хватило.
    pub fn скопировать_хвост(&self, выход: &mut [u8]) -> usize {
        let доступно = self.длина();
        let нужно = выход.len().min(доступно);
        let стартовое_смещение = доступно - нужно;
        for i in 0..нужно {
            выход[i] = self.байт(стартовое_смещение + i);
        }
        нужно
    }
}

static ЖУРНАЛ: Mutex<КольцевойЖурнал> = Mutex::new(КольцевойЖурнал::новый());
static ВКЛЮЧЁН: AtomicBool = AtomicBool::new(true);

/// Включить или выключить запись в журнал. Используется отладочным окном,
/// чтобы при перерисовке самого окна не зациклиться через журнал.
pub fn установить_включён(значение: bool) {
    ВКЛЮЧЁН.store(значение, Ordering::Relaxed);
}

pub fn включён() -> bool {
    ВКЛЮЧЁН.load(Ordering::Relaxed)
}

/// Записать строку в журнал. Использует `try_lock` — если кто-то держит
/// журнал, тихо пропустим запись. Это безопасно, потому что журнал — лишь
/// диагностический.
pub fn записать(текст: &str) {
    if !включён() {
        return;
    }
    if let Some(mut журнал) = ЖУРНАЛ.try_lock() {
        журнал.записать(текст);
    }
}

pub fn журнал() -> &'static Mutex<КольцевойЖурнал> {
    &ЖУРНАЛ
}
