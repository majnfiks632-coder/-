// Подсистема потоков ядра.
//
// На данном этапе — простая кооперативная многопоточность:
//   * каждый поток имеет свой стек, точку входа и сохранённый RSP;
//   * планировщик хранит очередь готовых потоков;
//   * `уступить()` снимает текущий поток с CPU и передаёт управление
//     следующему готовому;
//   * прерывания таймера и вытесняющий планировщик — отдельный этап.
//
// Все идентификаторы и сообщения — на русском.

#![allow(dead_code)]

#[path = "планировщик.rs"]
pub mod планировщик;

use alloc::boxed::Box;
use alloc::vec::Vec;

/// Уникальный идентификатор потока. 0 зарезервирован для главного потока ядра.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct ИдПотока(pub u64);

/// Состояние потока.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum СостояниеПотока {
    /// Готов к запуску, лежит в очереди готовых.
    Готов,
    /// Сейчас исполняется на CPU.
    Исполняется,
    /// Ждёт внешнего события (IPC, таймер). На текущем этапе не используется.
    Спит,
    /// Завершился, его ресурсы можно переиспользовать.
    Мёртв,
}

/// Размер стека одного потока — 64 КиБ.
pub const РАЗМЕР_СТЕКА: usize = 64 * 1024;

/// Дескриптор потока.
pub struct Поток {
    /// Идентификатор.
    pub ид: ИдПотока,
    /// Текущее состояние.
    pub состояние: СостояниеПотока,
    /// Сохранённый указатель стека (RSP) — корректен только когда поток не выполняется.
    pub rsp: u64,
    /// Сама память стека (Box, чтобы Drop освобождал).
    стек: Option<Box<[u8]>>,
    /// Имя потока (для диагностики).
    pub имя: &'static str,
}

impl Поток {
    /// Создать главный поток ядра. Стек у него уже есть (это стартовый стек ядра),
    /// мы только заводим дескриптор.
    pub fn главный() -> Self {
        Self {
            ид: ИдПотока(0),
            состояние: СостояниеПотока::Исполняется,
            rsp: 0, // сохранится при первом уступлении
            стек: None,
            имя: "главный",
        }
    }

    /// Создать новый поток ядра, который начнёт исполнение с функции `вход`.
    /// `вход` принимает `аргумент` (указатель на любую структуру) и не возвращается.
    pub fn новый(
        ид: ИдПотока,
        имя: &'static str,
        вход: extern "C" fn(u64) -> !,
        аргумент: u64,
    ) -> Self {
        let mut память: Vec<u8> = alloc::vec![0u8; РАЗМЕР_СТЕКА];
        // На x86_64 стек растёт вниз: верхушка = (база + размер).
        // Зарезервируем место под кадр инициализации.
        let верх = unsafe { память.as_mut_ptr().add(РАЗМЕР_СТЕКА) };
        // Выравниваем верхушку на 16 байт (требование SysV ABI),
        // потом смещаем ещё на 8 байт чтобы после `ret` был выровнен на 16.
        let верх = ((верх as usize) & !0xF) - 8;
        let начальный_rsp = подготовить_кадр(верх, вход, аргумент);

        Self {
            ид,
            состояние: СостояниеПотока::Готов,
            rsp: начальный_rsp as u64,
            стек: Some(память.into_boxed_slice()),
            имя,
        }
    }
}

/// Подготовить начальный стек для нового потока. Кладём:
///   [r15=0, r14=0, r13=0, r12=0, rbx=0, rbp=0, return = трамплин_потока,
///    saved_arg = аргумент, saved_entry = вход]
///
/// `_переключить_контекст` после первого переключения сделает 6 pop'ов
/// и `ret`, что приведёт нас в `трамплин_потока`. Трамплин снимает
/// со стека сохранённые `аргумент` и `вход`, и зовёт точку входа.
#[cfg(target_arch = "x86_64")]
fn подготовить_кадр(верх: usize, вход: extern "C" fn(u64) -> !, аргумент: u64) -> usize {
    let mut указатель = верх;
    // saved_entry
    указатель -= 8;
    unsafe { core::ptr::write_volatile(указатель as *mut u64, вход as u64) };
    // saved_arg
    указатель -= 8;
    unsafe { core::ptr::write_volatile(указатель as *mut u64, аргумент) };
    // return -> ассемблерный трамплин (определён в контекст.s)
    указатель -= 8;
    unsafe {
        core::ptr::write_volatile(
            указатель as *mut u64,
            crate::арх::x86_64::адрес_трамплина_потока(),
        )
    };
    // rbp
    указатель -= 8;
    unsafe { core::ptr::write_volatile(указатель as *mut u64, 0) };
    // rbx
    указатель -= 8;
    unsafe { core::ptr::write_volatile(указатель as *mut u64, 0) };
    // r12
    указатель -= 8;
    unsafe { core::ptr::write_volatile(указатель as *mut u64, 0) };
    // r13
    указатель -= 8;
    unsafe { core::ptr::write_volatile(указатель as *mut u64, 0) };
    // r14
    указатель -= 8;
    unsafe { core::ptr::write_volatile(указатель as *mut u64, 0) };
    // r15
    указатель -= 8;
    unsafe { core::ptr::write_volatile(указатель as *mut u64, 0) };
    указатель
}

#[cfg(not(target_arch = "x86_64"))]
fn подготовить_кадр(верх: usize, _вход: extern "C" fn(u64) -> !, _аргумент: u64) -> usize {
    верх
}


