// Подсистема потоков ядра.
//
// Этап «вытесняющий планировщик в стиле Windows-NT»:
//   * каждый поток имеет свой 64-КиБ стек, точку входа, аргумент и
//     сохранённый RSP в формате единого iretq-кадра (см. `арх/x86_64/контекст.s`);
//   * у каждого потока есть базовый и текущий приоритет (0..31, как в NT),
//     а также «квант» в тиках таймера и счётчик буста после пробуждения
//     из ожидания ИПК;
//   * планировщик `планировщик.rs` хранит 32 очереди готовых (по одной на
//     приоритет), маску занятых уровней и указатель на idle-поток;
//   * IRQ0 (PIT @100 Гц) дёргает `планировщик::тик_таймера()`, который
//     уменьшает квант, понижает приоритет «прожорливым» потокам и при
//     необходимости меняет текущий поток на лучшего готового.
//
// Все идентификаторы и сообщения — на русском.

#![allow(dead_code)]

#[path = "планировщик.rs"]
pub mod планировщик;

use alloc::boxed::Box;
use alloc::vec::Vec;

/// Уникальный идентификатор потока. 0 зарезервирован для главного потока ядра.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct ИдПотока(pub u64);

/// Состояния потока в стиле NT-планировщика.
///
/// * `Готов` — лежит в одной из очередей готовности и ждёт CPU.
/// * `Выполняется` — сейчас на CPU.
/// * `Ожидание` — ждёт сообщения, IPC-таймера и т.п. (не в очередях готовности).
/// * `Завершён` — поток дошёл до `завершить()`, его слот можно переиспользовать.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum СостояниеПотока {
    Готов,
    Выполняется,
    Ожидание,
    Завершён,
}

/// Сколько уровней приоритета поддерживает планировщик.
/// Совпадает с количеством уровней NT-планировщика.
pub const ВСЕГО_ПРИОРИТЕТОВ: u8 = 32;

/// Граница: приоритеты `>=` этого значения считаются «реального времени»
/// (как в NT — там это 16..31). Они не подвергаются понижению при выработке
/// полного кванта.
pub const ГРАНИЦА_РЕАЛВРЕМЯ: u8 = 16;

/// Приоритет idle-потока — самый низкий.
pub const ПРИОРИТЕТ_IDLE: u8 = 0;

/// Базовый приоритет для обычных потоков ядра (как `NORMAL_PRIORITY_CLASS`
/// у Windows). Главный поток и системные службы стартуют отсюда.
pub const ПРИОРИТЕТ_ОБЫЧНЫЙ: u8 = 8;

/// Длина кванта обычного потока в тиках таймера (PIT @ 100 Гц = 10 мс/тик).
/// Соотносится с «короткий квант» NT (~10 мс на рабочей станции).
pub const КВАНТ_ОБЫЧНЫЙ_ТИКОВ: u32 = 1;

/// Длина кванта потока реального времени.
pub const КВАНТ_РЕАЛВРЕМЯ_ТИКОВ: u32 = 2;

/// Размер стека одного потока — 64 КиБ.
pub const РАЗМЕР_СТЕКА: usize = 64 * 1024;

/// Дескриптор потока.
pub struct Поток {
    /// Идентификатор.
    pub ид: ИдПотока,
    /// Текущее состояние.
    pub состояние: СостояниеПотока,
    /// Сохранённый указатель стека (RSP). Действителен только когда поток
    /// не выполняется. Указывает на начало (низшие адреса) полного 176-байтного
    /// iretq-кадра, см. `арх/x86_64/контекст.s`.
    pub rsp: u64,
    /// Сама память стека (`Box`, чтобы Drop её освобождал).
    стек: Option<Box<[u8]>>,
    /// Имя потока (для диагностики).
    pub имя: &'static str,

    /// Базовый приоритет — задан при создании, не меняется со временем.
    /// `0` — idle-поток, `8` — обычный, `16+` — реального времени.
    pub базовый_приоритет: u8,
    /// Текущий приоритет — может опускаться (когда поток вырабатывает квант
    /// полностью) или подниматься (после пробуждения из ИПК), но никогда
    /// ниже базового.
    pub текущий_приоритет: u8,
    /// Сколько тиков таймера осталось в текущем кванте.
    pub квант_остался: u32,
    /// Сколько тиков ещё держится буст после пробуждения из ожидания.
    pub тиков_буста: u8,
}

impl Поток {
    /// Создать главный поток ядра. Стек у него уже есть (это стартовый стек ядра),
    /// мы только заводим дескриптор.
    pub fn главный() -> Self {
        Self {
            ид: ИдПотока(0),
            состояние: СостояниеПотока::Выполняется,
            rsp: 0, // сохранится при первом уступлении
            стек: None,
            имя: "главный",
            базовый_приоритет: ПРИОРИТЕТ_ОБЫЧНЫЙ,
            текущий_приоритет: ПРИОРИТЕТ_ОБЫЧНЫЙ,
            квант_остался: КВАНТ_ОБЫЧНЫЙ_ТИКОВ,
            тиков_буста: 0,
        }
    }

    /// Создать новый поток ядра, который начнёт исполнение с функции `вход`.
    ///
    /// `вход` принимает `аргумент` (произвольное 64-битное значение, обычно
    /// указатель на структуру) и не возвращается.
    ///
    /// `приоритет` ограничивается диапазоном `0..ВСЕГО_ПРИОРИТЕТОВ`. Для
    /// обычной кооперативной/системной нагрузки используйте
    /// `ПРИОРИТЕТ_ОБЫЧНЫЙ`.
    pub fn новый(
        ид: ИдПотока,
        имя: &'static str,
        вход: extern "C" fn(u64) -> !,
        аргумент: u64,
        приоритет: u8,
    ) -> Self {
        let приоритет = приоритет.min(ВСЕГО_ПРИОРИТЕТОВ - 1);
        let мут_квант = if приоритет >= ГРАНИЦА_РЕАЛВРЕМЯ {
            КВАНТ_РЕАЛВРЕМЯ_ТИКОВ
        } else {
            КВАНТ_ОБЫЧНЫЙ_ТИКОВ
        };

        let mut память: Vec<u8> = alloc::vec![0u8; РАЗМЕР_СТЕКА];
        // На x86_64 стек растёт вниз: верхушка = база + размер.
        let верх_стека = unsafe { память.as_mut_ptr().add(РАЗМЕР_СТЕКА) };
        // Выравниваем верхушку на 16 байт (требование SysV ABI),
        // потом смещаем ещё на 8 байт чтобы после `ret`/`call` был выровнен на 16.
        let верх_стека = ((верх_стека as usize) & !0xF) - 8;
        let начальный_rsp = подготовить_кадр(верх_стека, вход, аргумент);

        Self {
            ид,
            состояние: СостояниеПотока::Готов,
            rsp: начальный_rsp as u64,
            стек: Some(память.into_boxed_slice()),
            имя,
            базовый_приоритет: приоритет,
            текущий_приоритет: приоритет,
            квант_остался: мут_квант,
            тиков_буста: 0,
        }
    }
}

/// Подготовить начальный 176-байтный iretq-совместимый кадр на стеке нового
/// потока. Кадр выглядит так (низшие → высшие адреса):
///
/// ```text
///   [r15][r14][r13][r12][r11][r10][r9][r8][rbp][rdi][rsi][rdx][rcx][rbx][rax]
///   [vec][err]
///   [rip][cs][rflags][rsp_after][ss]
/// ```
///
/// * `R15 = вход` (трамплин использует это как адрес функции точки входа);
/// * `R14 = аргумент` (трамплин копирует это в RDI = 1-й параметр SysV);
/// * остальные ОПР = 0;
/// * vec/err = 0 (псевдо);
/// * rip = адрес `_dub_thread_trampoline`;
/// * cs = `СЕЛЕКТОР_КОД_ЯДРА (0x08)`;
/// * rflags = `0x202` (IF=1, бит 1 = 1 — после iretq прерывания включены);
/// * rsp_after = `верх_стека` (после iretq RSP сразу укажет на свежую вершину);
/// * ss = `СЕЛЕКТОР_ДАННЫЕ_ЯДРА (0x10)`.
///
/// Возвращает указатель на низшую границу кадра (значение, которое надо
/// сохранить в `Поток::rsp`).
#[cfg(target_arch = "x86_64")]
fn подготовить_кадр(верх_стека: usize, вход: extern "C" fn(u64) -> !, аргумент: u64) -> usize {
    // Идём от высоких адресов к низким — порядок «сверху вниз» соответствует
    // тому, как стек растёт после серии push'ей.
    let mut указатель = верх_стека;

    // ----- iretq-хвост (CPU кладёт его сам, мы имитируем) -----
    // SS
    указатель -= 8;
    unsafe { core::ptr::write_volatile(указатель as *mut u64, 0x10) };
    // RSP_after_iretq — указывает на верхушку (после iretq).
    указатель -= 8;
    unsafe { core::ptr::write_volatile(указатель as *mut u64, верх_стека as u64) };
    // RFLAGS: IF=1, бит 1 (зарезервированный) = 1.
    указатель -= 8;
    unsafe { core::ptr::write_volatile(указатель as *mut u64, 0x202) };
    // CS
    указатель -= 8;
    unsafe { core::ptr::write_volatile(указатель as *mut u64, 0x08) };
    // RIP — указатель на ASM-трамплин, который запустит `вход(аргумент)`.
    указатель -= 8;
    unsafe {
        core::ptr::write_volatile(
            указатель as *mut u64,
            crate::арх::x86_64::адрес_трамплина_потока(),
        )
    };

    // ----- Псевдо-вектор и код ошибки -----
    // err
    указатель -= 8;
    unsafe { core::ptr::write_volatile(указатель as *mut u64, 0) };
    // vec
    указатель -= 8;
    unsafe { core::ptr::write_volatile(указатель as *mut u64, 0) };

    // ----- 15 ОПР, в порядке pop'а (последний pop — r15, первый — rax) -----
    // Так как pop в `_dub_switch_to`/IRQ-эпилоге идёт `pop r15` первым,
    // то в стеке (по возрастанию RSP при popе) сначала лежит r15.
    // Значит при build-time мы пушим в обратном порядке: rax первым (на
    // высших адресах), r15 последним (на нижних).
    let опр_значения: [u64; 15] = [
        0,                  // rax
        0,                  // rbx
        0,                  // rcx
        0,                  // rdx
        0,                  // rsi
        0,                  // rdi
        0,                  // rbp
        0,                  // r8
        0,                  // r9
        0,                  // r10
        0,                  // r11
        0,                  // r12
        0,                  // r13
        аргумент,           // r14 — аргумент (трамплин: `mov rdi, r14`)
        вход as u64,        // r15 — точка входа (трамплин: `call r15`)
    ];
    for &значение in &опр_значения {
        указатель -= 8;
        unsafe { core::ptr::write_volatile(указатель as *mut u64, значение) };
    }

    указатель
}

#[cfg(not(target_arch = "x86_64"))]
fn подготовить_кадр(верх: usize, _вход: extern "C" fn(u64) -> !, _аргумент: u64) -> usize {
    верх
}
