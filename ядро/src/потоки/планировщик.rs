// Кооперативный планировщик потоков ядра.
//
// Простая FIFO-очередь готовых потоков. `уступить()` снимает текущий
// поток, выбирает следующий из головы очереди и переключается на него.
// Если очередь пуста — продолжает текущий поток.
//
// Все идентификаторы и сообщения — на русском.

#![allow(dead_code)]

use alloc::collections::VecDeque;
use alloc::vec::Vec;
use core::sync::atomic::{AtomicU64, Ordering};

use spin::Mutex;

use super::{ИдПотока, Поток, СостояниеПотока};

/// Глобальный счётчик идентификаторов потоков (0 — главный).
static СЛЕДУЮЩИЙ_ИД: AtomicU64 = AtomicU64::new(1);

/// Состояние планировщика.
struct Состояние {
    /// Все известные потоки (главный лежит на индексе 0).
    потоки: Vec<Поток>,
    /// Очередь готовых потоков (индексы в `потоки`).
    готовые: VecDeque<usize>,
    /// Индекс текущего исполняющегося потока.
    текущий: usize,
}

impl Состояние {
    const fn пустое() -> Self {
        Self {
            потоки: Vec::new(),
            готовые: VecDeque::new(),
            текущий: 0,
        }
    }
}

static ПЛАНИРОВЩИК: Mutex<Состояние> = Mutex::new(Состояние::пустое());

/// Инициализировать планировщик: заводим главный поток.
pub fn инициализировать() {
    let mut с = ПЛАНИРОВЩИК.lock();
    if !с.потоки.is_empty() {
        return;
    }
    с.потоки.push(Поток::главный());
    с.текущий = 0;
}

/// Создать новый поток ядра. Возвращает его идентификатор.
pub fn создать(
    имя: &'static str,
    вход: extern "C" fn(u64) -> !,
    аргумент: u64,
) -> ИдПотока {
    let ид = ИдПотока(СЛЕДУЮЩИЙ_ИД.fetch_add(1, Ordering::Relaxed));
    let поток = Поток::новый(ид, имя, вход, аргумент);

    let mut с = ПЛАНИРОВЩИК.lock();
    let индекс = с.потоки.len();
    с.потоки.push(поток);
    с.готовые.push_back(индекс);
    ид
}

/// Кооперативно уступить процессор следующему готовому потоку.
pub fn уступить() {
    // Получаем нужные указатели под защитой мутекса, отпускаем мутекс,
    // и только потом переключаем контекст. Иначе в новом потоке
    // мутекс не разблокируется.
    let (старый_rsp_ptr, новый_rsp): (*mut u64, u64) = {
        let mut с = ПЛАНИРОВЩИК.lock();
        if с.готовые.is_empty() {
            return; // нет других готовых — ничего не делаем
        }
        // Если текущий не «мёртв» — вернём его в конец очереди.
        let текущий = с.текущий;
        let следующий = match с.готовые.pop_front() {
            Some(и) => и,
            None => return,
        };
        if текущий != следующий {
            if с.потоки[текущий].состояние == СостояниеПотока::Исполняется {
                с.потоки[текущий].состояние = СостояниеПотока::Готов;
                с.готовые.push_back(текущий);
            }
            с.потоки[следующий].состояние = СостояниеПотока::Исполняется;
            с.текущий = следующий;

            let старый_rsp = (&mut с.потоки[текущий].rsp) as *mut u64;
            let новый_rsp = с.потоки[следующий].rsp;
            (старый_rsp, новый_rsp)
        } else {
            // переключаемся на самих себя — ничего не делаем
            return;
        }
    };

    #[cfg(target_arch = "x86_64")]
    unsafe {
        crate::арх::x86_64::переключить_контекст(старый_rsp_ptr, новый_rsp);
    }

    // На других архитектурах кооперативный планировщик пока не поддерживает
    // настоящее переключение — потоки исполняются последовательно.
    #[cfg(not(target_arch = "x86_64"))]
    {
        let _ = (старый_rsp_ptr, новый_rsp);
    }
}

/// Завершить текущий поток. Не возвращается.
pub fn завершить() -> ! {
    {
        let mut с = ПЛАНИРОВЩИК.lock();
        let текущий = с.текущий;
        с.потоки[текущий].состояние = СостояниеПотока::Мёртв;
    }
    loop {
        уступить();
        // Если других потоков нет — мы будем здесь зависать. Ядро
        // на этом этапе остановится в последнем мёртвом потоке.
        // В будущем этот случай обработает планировщик с idle-потоком.
        unsafe {
            core::arch::asm!("pause", options(nostack, preserves_flags, nomem));
        }
    }
}

/// Получить идентификатор текущего потока.
pub fn текущий() -> ИдПотока {
    let с = ПЛАНИРОВЩИК.lock();
    с.потоки[с.текущий].ид
}

/// Узнать число живых потоков (для статистики).
pub fn количество_потоков() -> usize {
    let с = ПЛАНИРОВЩИК.lock();
    с.потоки
        .iter()
        .filter(|п| п.состояние != СостояниеПотока::Мёртв)
        .count()
}

/// Принудительно отметить главный поток как готовый-исполняется
/// (используется после первой инициализации).
pub fn отметить_главный_исполняется() {
    let mut с = ПЛАНИРОВЩИК.lock();
    if let Some(главный) = с.потоки.get_mut(0) {
        главный.состояние = СостояниеПотока::Исполняется;
    }
}
