// Вытесняющий планировщик потоков ядра в стиле Windows-NT.
//
// Архитектура (10 пунктов из плана):
//   1. 32 уровня приоритета (`ВСЕГО_ПРИОРИТЕТОВ` в `mod.rs`):
//        0..15  — динамические (обычные потоки),
//        16..31 — реального времени.
//   2. Многоуровневая очередь готовности: одна `VecDeque<usize>` на каждый
//      приоритет плюс 32-битная маска занятых уровней. Выбор следующего —
//      `bsr(маска)`, то есть «самый высокий непустой приоритет».
//   3. Round-robin внутри одного приоритета: pop_front / push_back.
//   4. Квант 10 мс (1 тик PIT @ 100 Гц), для реального времени — 20 мс.
//   5. Понижение приоритета на 1 при выработке полного кванта (но не ниже
//      базового). Реал-time не понижается.
//   6. Boost при пробуждении из ИПК: +2 на 2 кванта, потом возврат к базовому.
//   7. Idle-поток на приоритете 0 — крутит HLT.
//   8. Состояния `Готов / Выполняется / Ожидание / Завершён` (в `mod.rs`).
//   9. Вытеснение через IRQ0 — `тик_таймера()` возвращает решение
//      ASM-трамплину (см. `арх/x86_64/идт.s`).
//  10. `для_каждого_потока` отдаёт расширенную информацию для команды
//      оболочки `потоки` в стиле Диспетчера задач.
//
// Все идентификаторы и сообщения — на русском.

#![allow(dead_code)]

use alloc::collections::VecDeque;
use alloc::vec::Vec;
use core::sync::atomic::{AtomicU64, Ordering};

use spin::Mutex;

use super::{
    ИдПотока, Поток, СостояниеПотока, ВСЕГО_ПРИОРИТЕТОВ, ГРАНИЦА_РЕАЛВРЕМЯ, КВАНТ_ОБЫЧНЫЙ_ТИКОВ,
    КВАНТ_РЕАЛВРЕМЯ_ТИКОВ, ПРИОРИТЕТ_IDLE, ПРИОРИТЕТ_ОБЫЧНЫЙ,
};

#[cfg(target_arch = "x86_64")]
use crate::арх::x86_64::идт::РезультатПереключения;

/// Глобальный счётчик идентификаторов потоков (0 — главный).
static СЛЕДУЮЩИЙ_ИД: AtomicU64 = AtomicU64::new(1);

/// Сколько тиков держится буст после пробуждения.
const ТИКОВ_БУСТА: u8 = 2;

/// Размер буста в уровнях приоритета.
const ВЕЛИЧИНА_БУСТА: u8 = 2;

/// Состояние планировщика. Защищается одним `spin::Mutex` — однопроцессорная
/// модель, без локов нижнего уровня.
struct Состояние {
    /// Все известные потоки. Главный лежит на индексе 0; idle — на 1
    /// (после вызова `завести_idle`).
    потоки: Vec<Поток>,
    /// 32 очереди готовности: `очереди[p]` хранит индексы потоков
    /// приоритета `p` в порядке round-robin.
    очереди: [VecDeque<usize>; ВСЕГО_ПРИОРИТЕТОВ as usize],
    /// Битовая маска: бит `p` установлен ⇔ `очереди[p]` непуста.
    /// Самый высокий установленный бит — приоритет лучшего готового потока.
    готовая_маска: u32,
    /// Индекс текущего исполняющегося потока в `потоки`.
    текущий: usize,
    /// Индекс idle-потока (или `usize::MAX`, пока не заведён).
    idle: usize,
}

impl Состояние {
    const fn пустое() -> Self {
        const ПУСТАЯ: VecDeque<usize> = VecDeque::new();
        Self {
            потоки: Vec::new(),
            очереди: [ПУСТАЯ; ВСЕГО_ПРИОРИТЕТОВ as usize],
            готовая_маска: 0,
            текущий: 0,
            idle: usize::MAX,
        }
    }

    /// Поставить поток в хвост очереди его текущего приоритета.
    fn поставить_в_очередь(&mut self, индекс: usize) {
        let уровень = self.потоки[индекс].текущий_приоритет as usize;
        self.очереди[уровень].push_back(индекс);
        self.готовая_маска |= 1u32 << уровень;
    }

    /// Снять с головы очереди приоритета `p`. Если очередь пустеет — гасит бит маски.
    fn снять_из_очереди(&mut self, приоритет: u8) -> Option<usize> {
        let уровень = приоритет as usize;
        let индекс = self.очереди[уровень].pop_front()?;
        if self.очереди[уровень].is_empty() {
            self.готовая_маска &= !(1u32 << уровень);
        }
        Some(индекс)
    }

    /// Найти приоритет лучшего готового потока (или `None`, если всё пусто).
    fn лучший_готовый(&self) -> Option<u8> {
        if self.готовая_маска == 0 {
            None
        } else {
            // 31 - leading_zeros = индекс самого старшего установленного бита.
            Some((31 - self.готовая_маска.leading_zeros()) as u8)
        }
    }

    /// Снять «лучший готовый» поток для запуска. Если очередей нет — `None`.
    fn вынуть_лучшего(&mut self) -> Option<usize> {
        let уровень = self.лучший_готовый()?;
        self.снять_из_очереди(уровень)
    }

    /// Длина кванта для приоритета — реал-time дольше, обычные короче.
    fn квант_для(приоритет: u8) -> u32 {
        if приоритет >= ГРАНИЦА_РЕАЛВРЕМЯ {
            КВАНТ_РЕАЛВРЕМЯ_ТИКОВ
        } else {
            КВАНТ_ОБЫЧНЫЙ_ТИКОВ
        }
    }
}

static ПЛАНИРОВЩИК: Mutex<Состояние> = Mutex::new(Состояние::пустое());

/// Инициализировать планировщик: заводим главный поток.
/// idle-поток заводится отдельным вызовом `завести_idle()` после того,
/// как куча и архитектурная подсистема готовы.
pub fn инициализировать() {
    let mut с = ПЛАНИРОВЩИК.lock();
    if !с.потоки.is_empty() {
        return;
    }
    с.потоки.push(Поток::главный());
    с.текущий = 0;
}

/// Завести idle-поток. Должен вызываться один раз после `инициализировать()`
/// и до включения вытеснения. Idle сидит на приоритете 0 и крутит `hlt`.
pub fn завести_idle() {
    let нужно_создавать = {
        let с = ПЛАНИРОВЩИК.lock();
        с.idle == usize::MAX
    };
    if !нужно_создавать {
        return;
    }
    extern "C" fn точка_входа_idle(_аргумент: u64) -> ! {
        loop {
            #[cfg(target_arch = "x86_64")]
            unsafe {
                core::arch::asm!("hlt", options(nomem, nostack, preserves_flags));
            }
            #[cfg(not(target_arch = "x86_64"))]
            core::hint::spin_loop();
        }
    }
    let ид = ИдПотока(СЛЕДУЮЩИЙ_ИД.fetch_add(1, Ordering::Relaxed));
    let поток = Поток::новый(ид, "простой", точка_входа_idle, 0, ПРИОРИТЕТ_IDLE);
    let mut с = ПЛАНИРОВЩИК.lock();
    let индекс = с.потоки.len();
    с.потоки.push(поток);
    с.idle = индекс;
    с.поставить_в_очередь(индекс);
}

/// Создать новый поток ядра с приоритетом `ПРИОРИТЕТ_ОБЫЧНЫЙ`.
/// Возвращает его идентификатор.
pub fn создать(имя: &'static str, вход: extern "C" fn(u64) -> !, аргумент: u64) -> ИдПотока {
    создать_с_приоритетом(имя, вход, аргумент, ПРИОРИТЕТ_ОБЫЧНЫЙ)
}

/// Создать новый поток ядра с заданным приоритетом (`0..ВСЕГО_ПРИОРИТЕТОВ`).
pub fn создать_с_приоритетом(
    имя: &'static str,
    вход: extern "C" fn(u64) -> !,
    аргумент: u64,
    приоритет: u8,
) -> ИдПотока {
    let ид = ИдПотока(СЛЕДУЮЩИЙ_ИД.fetch_add(1, Ordering::Relaxed));
    let поток = Поток::новый(ид, имя, вход, аргумент, приоритет);

    let mut с = ПЛАНИРОВЩИК.lock();
    let индекс = с.потоки.len();
    с.потоки.push(поток);
    с.поставить_в_очередь(индекс);
    ид
}

/// Кооперативно уступить процессор. Если есть готовый поток приоритета
/// >= нашего — переключаемся на него; иначе остаёмся.
pub fn уступить() {
    let (старый_rsp_ptr, новый_rsp): (*mut u64, u64) = {
        let mut с = ПЛАНИРОВЩИК.lock();
        let текущий = с.текущий;
        let наш_приоритет = с.потоки[текущий].текущий_приоритет;

        let лучший = match с.лучший_готовый() {
            Some(уровень) => уровень,
            None => return, // некому уступить
        };

        // Если все готовые ниже нас по приоритету — не уступаем
        // (но idle-потоку всегда уступаем — у нас точно приоритет ≥ 0).
        if лучший < наш_приоритет && с.потоки[текущий].состояние == СостояниеПотока::Выполняется {
            return;
        }

        let следующий = match с.снять_из_очереди(лучший) {
            Some(и) => и,
            None => return,
        };
        if следующий == текущий {
            return;
        }

        if с.потоки[текущий].состояние == СостояниеПотока::Выполняется {
            с.потоки[текущий].состояние = СостояниеПотока::Готов;
            с.поставить_в_очередь(текущий);
        }

        с.потоки[следующий].состояние = СостояниеПотока::Выполняется;
        с.потоки[следующий].квант_остался = Состояние::квант_для(с.потоки[следующий].текущий_приоритет);
        с.текущий = следующий;

        let старый_rsp = (&mut с.потоки[текущий].rsp) as *mut u64;
        let новый_rsp = с.потоки[следующий].rsp;
        (старый_rsp, новый_rsp)
    };

    #[cfg(target_arch = "x86_64")]
    unsafe {
        crate::арх::x86_64::переключить_контекст(старый_rsp_ptr, новый_rsp);
    }

    #[cfg(not(target_arch = "x86_64"))]
    {
        let _ = (старый_rsp_ptr, новый_rsp);
    }
}

/// Перевести текущий поток в состояние `Ожидание` и уступить.
/// Поток не вернётся в очередь готовности, пока его не разбудит
/// `пробудить()`.
pub fn заснуть() {
    let (старый_rsp_ptr, новый_rsp): (*mut u64, u64) = {
        let mut с = ПЛАНИРОВЩИК.lock();
        let текущий = с.текущий;
        с.потоки[текущий].состояние = СостояниеПотока::Ожидание;

        // Должен быть хоть кто-то готовый (как минимум idle).
        let лучший = match с.лучший_готовый() {
            Some(уровень) => уровень,
            None => {
                // Аномалия: даже idle-потока нет. Возвращаемся как есть, чтобы
                // не зависнуть с ИПК-сообщением — делаем поток снова Выполняется.
                с.потоки[текущий].состояние = СостояниеПотока::Выполняется;
                return;
            }
        };
        let следующий = match с.снять_из_очереди(лучший) {
            Some(и) => и,
            None => {
                с.потоки[текущий].состояние = СостояниеПотока::Выполняется;
                return;
            }
        };
        с.потоки[следующий].состояние = СостояниеПотока::Выполняется;
        с.потоки[следующий].квант_остался =
            Состояние::квант_для(с.потоки[следующий].текущий_приоритет);
        с.текущий = следующий;

        let старый_rsp = (&mut с.потоки[текущий].rsp) as *mut u64;
        let новый_rsp = с.потоки[следующий].rsp;
        (старый_rsp, новый_rsp)
    };

    #[cfg(target_arch = "x86_64")]
    unsafe {
        crate::арх::x86_64::переключить_контекст(старый_rsp_ptr, новый_rsp);
    }

    #[cfg(not(target_arch = "x86_64"))]
    {
        let _ = (старый_rsp_ptr, новый_rsp);
    }
}

/// Пробудить поток по идентификатору: если он в `Ожидание`, перевести в
/// `Готов` и поднять буст. Возвращает `true`, если поток был пробуждён.
///
/// Пробуждение из ожидания ИПК поднимает приоритет на `ВЕЛИЧИНА_БУСТА`
/// (но не выше `ВСЕГО_ПРИОРИТЕТОВ - 1`) на `ТИКОВ_БУСТА` тиков таймера —
/// это аналог Windows `IO_PRIORITY_BOOST` для I/O-потоков.
pub fn пробудить(тид: ИдПотока) -> bool {
    let mut с = ПЛАНИРОВЩИК.lock();
    let индекс = match с.потоки.iter().position(|п| п.ид == тид) {
        Some(и) => и,
        None => return false,
    };
    if с.потоки[индекс].состояние != СостояниеПотока::Ожидание {
        return false;
    }
    let базовый = с.потоки[индекс].базовый_приоритет;
    let новый = (базовый.saturating_add(ВЕЛИЧИНА_БУСТА)).min(ВСЕГО_ПРИОРИТЕТОВ - 1);
    с.потоки[индекс].текущий_приоритет = новый;
    с.потоки[индекс].тиков_буста = ТИКОВ_БУСТА;
    с.потоки[индекс].состояние = СостояниеПотока::Готов;
    с.поставить_в_очередь(индекс);
    true
}

/// Завершить текущий поток. Не возвращается.
pub fn завершить() -> ! {
    {
        let mut с = ПЛАНИРОВЩИК.lock();
        let текущий = с.текущий;
        с.потоки[текущий].состояние = СостояниеПотока::Завершён;
    }
    loop {
        уступить();
        // На случай отсутствия готовых — гасим CPU до следующего прерывания.
        #[cfg(target_arch = "x86_64")]
        unsafe {
            core::arch::asm!("hlt", options(nomem, nostack, preserves_flags));
        }
        #[cfg(not(target_arch = "x86_64"))]
        core::hint::spin_loop();
    }
}

/// Получить идентификатор текущего потока.
pub fn текущий() -> ИдПотока {
    let с = ПЛАНИРОВЩИК.lock();
    с.потоки[с.текущий].ид
}

/// Узнать число живых (не завершённых) потоков (для статистики).
pub fn количество_потоков() -> usize {
    let с = ПЛАНИРОВЩИК.lock();
    с.потоки
        .iter()
        .filter(|п| п.состояние != СостояниеПотока::Завершён)
        .count()
}

/// Информация об одном потоке для команды оболочки `потоки` (Диспетчер задач).
#[derive(Debug, Clone, Copy)]
pub struct СводкаПотока {
    pub ид: ИдПотока,
    pub имя: &'static str,
    pub состояние: СостояниеПотока,
    pub базовый_приоритет: u8,
    pub текущий_приоритет: u8,
    pub квант_остался: u32,
    pub тиков_буста: u8,
}

/// Пройти по всем потокам и вызвать `посетитель(сводка)` для каждого.
pub fn для_каждого_потока(mut посетитель: impl FnMut(СводкаПотока)) {
    let с = ПЛАНИРОВЩИК.lock();
    for поток in &с.потоки {
        посетитель(СводкаПотока {
            ид: поток.ид,
            имя: поток.имя,
            состояние: поток.состояние,
            базовый_приоритет: поток.базовый_приоритет,
            текущий_приоритет: поток.текущий_приоритет,
            квант_остался: поток.квант_остался,
            тиков_буста: поток.тиков_буста,
        });
    }
}

/// Принудительно отметить главный поток как `Выполняется` (используется
/// после первой инициализации).
pub fn отметить_главный_исполняется() {
    let mut с = ПЛАНИРОВЩИК.lock();
    if let Some(главный) = с.потоки.get_mut(0) {
        главный.состояние = СостояниеПотока::Выполняется;
        if главный.квант_остался == 0 {
            главный.квант_остался = Состояние::квант_для(главный.текущий_приоритет);
        }
    }
}

/// Вызывается из IRQ0 на каждом тике таймера.
///
/// 1. Снижает счётчик буста (если был) и возвращает приоритет к базовому,
///    когда буст истёк.
/// 2. Уменьшает квант текущего потока на 1.
/// 3. Если квант обнулился:
///       — для не-реал-time потоков понижает текущий приоритет на 1
///         (но не ниже базового);
///       — обновляет квант на новый;
///       — если есть готовый поток с приоритетом >= нашего — переключается
///         на него; иначе — продолжаем сами.
///
/// Возвращает `РезультатПереключения` для ASM-трамплина: либо просьбу
/// переключиться (`новый_rsp != 0`), либо пустую структуру.
#[cfg(target_arch = "x86_64")]
pub fn тик_таймера() -> РезультатПереключения {
    // try_lock — чтобы не зависнуть, если кто-то уже держит lock в обычном
    // контексте (например, посередине `создать()`). Один потерянный тик
    // не страшен; вытеснение наступит на следующем.
    let mut с = match ПЛАНИРОВЩИК.try_lock() {
        Some(s) => s,
        None => return РезультатПереключения::без_переключения(),
    };

    // Снижаем буст у всех потоков (а не только у текущего): простая модель
    // «таймер декремента» одинаковая для всех.
    for поток in с.потоки.iter_mut() {
        if поток.тиков_буста > 0 {
            поток.тиков_буста -= 1;
            if поток.тиков_буста == 0 {
                поток.текущий_приоритет = поток.базовый_приоритет;
            }
        }
    }

    let индекс = с.текущий;
    if с.потоки[индекс].состояние != СостояниеПотока::Выполняется {
        // Текущий уже не должен быть на CPU (например, заснул прямо перед IRQ).
        return РезультатПереключения::без_переключения();
    }
    if с.потоки[индекс].квант_остался > 0 {
        с.потоки[индекс].квант_остался -= 1;
    }
    if с.потоки[индекс].квант_остался > 0 {
        return РезультатПереключения::без_переключения();
    }

    // Квант истёк. Понижаем приоритет (не ниже базового, и не для реал-time).
    let базовый = с.потоки[индекс].базовый_приоритет;
    let текущий_приор = с.потоки[индекс].текущий_приоритет;
    let новый_приор = if текущий_приор >= ГРАНИЦА_РЕАЛВРЕМЯ {
        текущий_приор
    } else if текущий_приор > базовый {
        текущий_приор - 1
    } else {
        базовый
    };
    с.потоки[индекс].текущий_приоритет = новый_приор;
    с.потоки[индекс].квант_остался = Состояние::квант_для(новый_приор);

    // Кто на ринге сейчас лучше нас?
    let лучший = match с.лучший_готовый() {
        Some(уровень) => уровень,
        None => return РезультатПереключения::без_переключения(),
    };
    if лучший < новый_приор {
        // Все готовые ниже — продолжаем себя (на свежем кванте).
        return РезультатПереключения::без_переключения();
    }

    // Переключаемся.
    let следующий = match с.снять_из_очереди(лучший) {
        Some(и) => и,
        None => return РезультатПереключения::без_переключения(),
    };
    if следующий == индекс {
        // Сами и были выбраны — ставим себя обратно в очередь и продолжаем.
        с.поставить_в_очередь(индекс);
        return РезультатПереключения::без_переключения();
    }

    // Текущий → в очередь готовности (если ещё «Выполняется»).
    с.потоки[индекс].состояние = СостояниеПотока::Готов;
    с.поставить_в_очередь(индекс);

    // Следующий → на CPU.
    с.потоки[следующий].состояние = СостояниеПотока::Выполняется;
    с.потоки[следующий].квант_остался =
        Состояние::квант_для(с.потоки[следующий].текущий_приоритет);
    с.текущий = следующий;

    let куда_сохранить = (&mut с.потоки[индекс].rsp) as *mut u64 as u64;
    let новый_rsp = с.потоки[следующий].rsp;

    РезультатПереключения {
        новый_rsp,
        куда_сохранить,
    }
}

