// Кодировка «ДубКод 1.0» — однобайтовая кодировка ДубинаОС.
//
// Раскладка:
//   0x00-0x1F: управляющие коды (как в ASCII).
//   0x20-0x7E: видимые ASCII-символы (полностью совместимы с US-ASCII).
//   0x7F:      DEL.
//   0x80-0x9F: 32 заглавные буквы кириллицы А..Я.
//   0xA0:      Ё.
//   0xA1-0xC0: 32 строчные буквы кириллицы а..я.
//   0xC1:      ё.
//   0xC2:      №.
//   0xC3-0xCF: резерв.
//   0xD0-0xDA: псевдографика рамок (╔╗╚╝═║╠╣╦╩╬).
//   0xDB-0xFF: резерв (пока пробел).

/// Преобразует один Юникод-символ в байт ДубКода.
/// Если соответствия нет — возвращает `0x3F` ('?').
pub fn в_дубкод(сим: char) -> u8 {
    let код = сим as u32;

    // Управляющие
    if код < 0x80 {
        return код as u8;
    }

    match сим {
        // Кириллица заглавная
        'А' => 0x80, 'Б' => 0x81, 'В' => 0x82, 'Г' => 0x83,
        'Д' => 0x84, 'Е' => 0x85, 'Ж' => 0x86, 'З' => 0x87,
        'И' => 0x88, 'Й' => 0x89, 'К' => 0x8A, 'Л' => 0x8B,
        'М' => 0x8C, 'Н' => 0x8D, 'О' => 0x8E, 'П' => 0x8F,
        'Р' => 0x90, 'С' => 0x91, 'Т' => 0x92, 'У' => 0x93,
        'Ф' => 0x94, 'Х' => 0x95, 'Ц' => 0x96, 'Ч' => 0x97,
        'Ш' => 0x98, 'Щ' => 0x99, 'Ъ' => 0x9A, 'Ы' => 0x9B,
        'Ь' => 0x9C, 'Э' => 0x9D, 'Ю' => 0x9E, 'Я' => 0x9F,
        'Ё' => 0xA0,

        // Кириллица строчная
        'а' => 0xA1, 'б' => 0xA2, 'в' => 0xA3, 'г' => 0xA4,
        'д' => 0xA5, 'е' => 0xA6, 'ж' => 0xA7, 'з' => 0xA8,
        'и' => 0xA9, 'й' => 0xAA, 'к' => 0xAB, 'л' => 0xAC,
        'м' => 0xAD, 'н' => 0xAE, 'о' => 0xAF, 'п' => 0xB0,
        'р' => 0xB1, 'с' => 0xB2, 'т' => 0xB3, 'у' => 0xB4,
        'ф' => 0xB5, 'х' => 0xB6, 'ц' => 0xB7, 'ч' => 0xB8,
        'ш' => 0xB9, 'щ' => 0xBA, 'ъ' => 0xBB, 'ы' => 0xBC,
        'ь' => 0xBD, 'э' => 0xBE, 'ю' => 0xBF, 'я' => 0xC0,
        'ё' => 0xC1,

        '№' => 0xC2,

        // Псевдографика
        '╔' => 0xD0, '╗' => 0xD1, '╚' => 0xD2, '╝' => 0xD3,
        '═' => 0xD4, '║' => 0xD5,
        '╠' => 0xD6, '╣' => 0xD7, '╦' => 0xD8, '╩' => 0xD9, '╬' => 0xDA,

        // Распространённые приближённые соответствия
        '\u{2014}' | '\u{2013}' => b'-', // тире → дефис
        '\u{00A0}' => b' ',               // неразрывный пробел
        '\u{00AB}' | '\u{00BB}' => b'"',  // « » → "
        '\u{201C}' | '\u{201D}' => b'"',  // " "
        '\u{2018}' | '\u{2019}' => b'\'', // ' '
        '\u{2026}' => b'.',               // …

        _ => b'?',
    }
}

#[cfg(test)]
mod тесты {
    use super::*;

    #[test]
    fn ascii_проходит() {
        assert_eq!(в_дубкод('A'), b'A');
        assert_eq!(в_дубкод('z'), b'z');
        assert_eq!(в_дубкод(' '), b' ');
        assert_eq!(в_дубкод('?'), b'?');
    }

    #[test]
    fn кириллица_заглавная() {
        assert_eq!(в_дубкод('А'), 0x80);
        assert_eq!(в_дубкод('Я'), 0x9F);
        assert_eq!(в_дубкод('Ё'), 0xA0);
    }

    #[test]
    fn кириллица_строчная() {
        assert_eq!(в_дубкод('а'), 0xA1);
        assert_eq!(в_дубкод('я'), 0xC0);
        assert_eq!(в_дубкод('ё'), 0xC1);
    }

    #[test]
    fn рамки() {
        assert_eq!(в_дубкод('╔'), 0xD0);
        assert_eq!(в_дубкод('╝'), 0xD3);
        assert_eq!(в_дубкод('═'), 0xD4);
        assert_eq!(в_дубкод('║'), 0xD5);
    }
}
