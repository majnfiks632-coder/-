// Таблица способностей ядра.
//
// Способность — это типизированный хэндл к объекту ядра (порту, потоку,
// странице, куску памяти) с набором прав, которые разрешены владельцу
// этой способности. Любой системный вызов, обращающийся к объекту,
// проверяет, что у вызывающего есть способность с нужными правами.
//
// На этом этапе у нас единая глобальная таблица — будет потом разделена
// на пространства способностей по процессам.
//
// Все идентификаторы и сообщения — на русском.

#![allow(dead_code)]

use alloc::collections::BTreeMap;
use core::sync::atomic::{AtomicU64, Ordering};

use spin::Mutex;

use crate::ипк::ИдПорта;

/// Идентификатор способности (хэндл).
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct ИдСпособности(pub u64);

/// Объект, на который ссылается способность.
#[derive(Debug, Clone, Copy)]
pub enum Объект {
    Порт(ИдПорта),
    Поток(crate::потоки::ИдПотока),
}

/// Права над объектом.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub struct Права(u32);

impl Права {
    pub const ПУСТО: Self = Self(0);
    pub const ОТПРАВКА: Self = Self(1 << 0);
    pub const ПРИЁМ: Self = Self(1 << 1);
    pub const ЗАКРЫТИЕ: Self = Self(1 << 2);
    pub const УПРАВЛЕНИЕ: Self = Self(1 << 3);
    pub const ВСЕ: Self = Self(0xFFFF_FFFF);

    pub const fn содержит(self, другие: Права) -> bool {
        (self.0 & другие.0) == другие.0
    }

    pub const fn биты(self) -> u32 {
        self.0
    }

    pub const fn из_бит(биты: u32) -> Self {
        Self(биты)
    }
}

impl core::ops::BitOr for Права {
    type Output = Self;
    fn bitor(self, другие: Self) -> Self {
        Self(self.0 | другие.0)
    }
}

/// Запись в таблице способностей.
#[derive(Debug, Clone, Copy)]
pub struct Способность {
    pub объект: Объект,
    pub права: Права,
}

/// Ошибки операций со способностями.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ОшибкаСпособности {
    НетСпособности,
    НетПрав,
    НеТотТип,
}

impl core::fmt::Display for ОшибкаСпособности {
    fn fmt(&self, ф: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        let т = match self {
            ОшибкаСпособности::НетСпособности => "способность не найдена в таблице",
            ОшибкаСпособности::НетПрав => "у способности нет нужных прав",
            ОшибкаСпособности::НеТотТип => "способность ссылается на объект другого типа",
        };
        ф.write_str(т)
    }
}

static СЛЕДУЮЩИЙ_ИД: AtomicU64 = AtomicU64::new(1);
static ТАБЛИЦА: Mutex<BTreeMap<u64, Способность>> = Mutex::new(BTreeMap::new());

/// Зарегистрировать новую способность с заданными объектом и правами.
pub fn выдать(объект: Объект, права: Права) -> ИдСпособности {
    let ид = СЛЕДУЮЩИЙ_ИД.fetch_add(1, Ordering::Relaxed);
    ТАБЛИЦА.lock().insert(
        ид,
        Способность { объект, права },
    );
    ИдСпособности(ид)
}

/// Получить способность по идентификатору.
pub fn получить(ид: ИдСпособности) -> Option<Способность> {
    ТАБЛИЦА.lock().get(&ид.0).copied()
}

/// Удалить способность.
pub fn отобрать(ид: ИдСпособности) -> Option<Способность> {
    ТАБЛИЦА.lock().remove(&ид.0)
}

/// Проверить и извлечь идентификатор порта из способности.
pub fn проверить_порт(
    ид: ИдСпособности,
    нужные_права: Права,
) -> Result<ИдПорта, ОшибкаСпособности> {
    let способность = получить(ид).ok_or(ОшибкаСпособности::НетСпособности)?;
    if !способность.права.содержит(нужные_права) {
        return Err(ОшибкаСпособности::НетПрав);
    }
    match способность.объект {
        Объект::Порт(порт) => Ok(порт),
        _ => Err(ОшибкаСпособности::НеТотТип),
    }
}
