#![allow(dead_code)]

use core::fmt::Write;
use core::ptr;
use core::sync::atomic::{AtomicBool, AtomicUsize, Ordering};

use crate::драйверы::клавиатура;
use crate::журнал;
use crate::кодировка;

const ШИРИНА: usize = 80;
const ВЫСОТА: usize = 25;
const ВИДЕО_БУФЕР: usize = 0xB8000;
const СТРОК_ВНУТРИ: usize = ВЫСОТА - 3; // 25 − 1 заголовок − 1 рамка − 1 статус.

const АТР_ЗАГОЛОВКА: u8 = 0x4F; // белый на красном
const АТР_ТЕКСТА: u8 = 0x07; // светлосерый на чёрном
const АТР_РАМКИ: u8 = 0x0E; // жёлтый на чёрном
const АТР_СТАТУСА: u8 = 0x70; // чёрный на белом

static mut СНИМОК: [u16; ШИРИНА * ВЫСОТА] = [0; ШИРИНА * ВЫСОТА];
static АКТИВНО: AtomicBool = AtomicBool::new(false);
static ОТСТУП: AtomicUsize = AtomicUsize::new(0);

pub fn активно() -> bool {
    АКТИВНО.load(Ordering::Relaxed)
}

/// Главная процедура отладки: вызывается из главного цикла ядра, обрабатывает
/// флаги клавиатуры (F12/PgUp/PgDn/Esc) и перерисовывает окно при изменениях.
pub fn обновить() {
    let f12 = клавиатура::взять_флаг_f12();
    let esc = клавиатура::взять_флаг_esc();
    let pgup = клавиатура::взять_флаг_pgup();
    let pgdn = клавиатура::взять_флаг_pgdn();

    if f12 {
        if активно() {
            закрыть();
        } else {
            открыть();
        }
    }

    if !активно() {
        return;
    }

    if esc {
        закрыть();
        return;
    }

    if pgup {
        let n = ОТСТУП.load(Ordering::Relaxed);
        ОТСТУП.store(n + 5, Ordering::Relaxed);
        перерисовать();
    } else if pgdn {
        let n = ОТСТУП.load(Ordering::Relaxed);
        ОТСТУП.store(n.saturating_sub(5), Ordering::Relaxed);
        перерисовать();
    }
}

fn открыть() {
    unsafe {
        for i in 0..(ШИРИНА * ВЫСОТА) {
            let ук = (ВИДЕО_БУФЕР + i * 2) as *const u16;
            СНИМОК[i] = ptr::read_volatile(ук);
        }
    }
    журнал::установить_включён(false);
    ОТСТУП.store(0, Ordering::Relaxed);
    АКТИВНО.store(true, Ordering::Relaxed);
    перерисовать();
}

fn закрыть() {
    АКТИВНО.store(false, Ordering::Relaxed);
    unsafe {
        for i in 0..(ШИРИНА * ВЫСОТА) {
            let ук = (ВИДЕО_БУФЕР + i * 2) as *mut u16;
            ptr::write_volatile(ук, СНИМОК[i]);
        }
    }
    журнал::установить_включён(true);
}

fn ячейка(строка: usize, столбец: usize, символ: u8, атрибут: u8) {
    if строка >= ВЫСОТА || столбец >= ШИРИНА {
        return;
    }
    let ук = (ВИДЕО_БУФЕР + (строка * ШИРИНА + столбец) * 2) as *mut u16;
    let значение = (атрибут as u16) << 8 | (символ as u16);
    unsafe { ptr::write_volatile(ук, значение) }
}

fn записать_строку_текста(строка: usize, начало: usize, текст: &str, атрибут: u8) {
    let mut столбец = начало;
    for сим in текст.chars() {
        if столбец >= ШИРИНА {
            break;
        }
        ячейка(строка, столбец, кодировка::в_дубкод(сим), атрибут);
        столбец += 1;
    }
}

fn заполнить_строку(строка: usize, символ: u8, атрибут: u8) {
    for с in 0..ШИРИНА {
        ячейка(строка, с, символ, атрибут);
    }
}

/// Прочитать журнал и собрать массив `(начало, конец)` для каждой строки,
/// нумерация от хвоста к голове (0 = самая свежая).
const МАКС_СТРОК: usize = 200;
fn собрать_строки(буфер: &[u8], длина: usize) -> ([(usize, usize); МАКС_СТРОК], usize) {
    let mut строки: [(usize, usize); МАКС_СТРОК] = [(0, 0); МАКС_СТРОК];
    let mut число = 0usize;
    let mut конец = длина;
    let mut i = длина;
    while i > 0 && число < МАКС_СТРОК {
        i -= 1;
        if буфер[i] == b'\n' {
            строки[число] = (i + 1, конец);
            число += 1;
            конец = i;
        }
    }
    if конец > 0 && число < МАКС_СТРОК {
        строки[число] = (0, конец);
        число += 1;
    }
    (строки, число)
}

fn рендерить_строку(строка_окна: usize, исходник: &[u8], нач: usize, кон: usize) {
    заполнить_строку(строка_окна, b' ', АТР_ТЕКСТА);
    // Раскодируем UTF-8 до символов и выводим через ДубКод.
    let срез = &исходник[нач..кон];
    let mut столбец = 0usize;
    let mut поз = 0usize;
    while поз < срез.len() && столбец < ШИРИНА {
        let байт = срез[поз];
        if байт < 0x80 {
            ячейка(строка_окна, столбец, кодировка::в_дубкод(байт as char), АТР_ТЕКСТА);
            поз += 1;
            столбец += 1;
            continue;
        }
        // UTF-8 многобайтовый — определим длину последовательности.
        let длина_посл = if байт & 0b1110_0000 == 0b1100_0000 {
            2
        } else if байт & 0b1111_0000 == 0b1110_0000 {
            3
        } else if байт & 0b1111_1000 == 0b1111_0000 {
            4
        } else {
            1
        };
        if поз + длина_посл > срез.len() {
            break;
        }
        let символ = core::str::from_utf8(&срез[поз..поз + длина_посл])
            .ok()
            .and_then(|с| с.chars().next())
            .unwrap_or('?');
        ячейка(строка_окна, столбец, кодировка::в_дубкод(символ), АТР_ТЕКСТА);
        поз += длина_посл;
        столбец += 1;
    }
}

fn перерисовать() {
    // Заголовок.
    заполнить_строку(0, b' ', АТР_ЗАГОЛОВКА);
    записать_строку_текста(
        0,
        1,
        "ОТЛАДКА ДубинаОС  -  F12=выход  PgUp/PgDn=прокрутка  Esc=закрыть",
        АТР_ЗАГОЛОВКА,
    );

    // Содержимое журнала.
    let mut буфер: [u8; 4096] = [0; 4096];
    let длина = {
        let ж = журнал::журнал().lock();
        ж.скопировать_хвост(&mut буфер)
    };
    let (строки, число_строк) = собрать_строки(&буфер, длина);

    let отступ = ОТСТУП.load(Ordering::Relaxed)
        .min(число_строк.saturating_sub(1));

    // Самая свежая строка — внизу окна.
    for ряд_окна in 0..СТРОК_ВНУТРИ {
        let индекс = отступ + (СТРОК_ВНУТРИ - 1 - ряд_окна);
        let строка_окна = 1 + ряд_окна;
        if индекс < число_строк {
            let (нач, кон) = строки[индекс];
            рендерить_строку(строка_окна, &буфер, нач, кон);
        } else {
            заполнить_строку(строка_окна, b' ', АТР_ТЕКСТА);
        }
    }

    // Рамка.
    заполнить_строку(ВЫСОТА - 2, кодировка::в_дубкод('═'), АТР_РАМКИ);

    // Статус.
    заполнить_строку(ВЫСОТА - 1, b' ', АТР_СТАТУСА);
    let mut буф_статуса: ПисательВБуфер = ПисательВБуфер::новый();
    let _ = write!(
        буф_статуса,
        " Журнал: {} строк | смещение от хвоста: {} | F12 - закрыть",
        число_строк, отступ
    );
    let текст = буф_статуса.как_строка();
    записать_строку_текста(ВЫСОТА - 1, 0, текст, АТР_СТАТУСА);
}

/// Простой ноль-аллокаторный писатель в стек-буфер 80 байт.
struct ПисательВБуфер {
    буф: [u8; 80],
    позиция: usize,
}

impl ПисательВБуфер {
    fn новый() -> Self {
        Self { буф: [0; 80], позиция: 0 }
    }

    fn как_строка(&self) -> &str {
        core::str::from_utf8(&self.буф[..self.позиция]).unwrap_or("")
    }
}

impl Write for ПисательВБуфер {
    fn write_str(&mut self, s: &str) -> core::fmt::Result {
        for &б in s.as_bytes() {
            if self.позиция >= self.буф.len() {
                break;
            }
            self.буф[self.позиция] = б;
            self.позиция += 1;
        }
        Ok(())
    }
}
