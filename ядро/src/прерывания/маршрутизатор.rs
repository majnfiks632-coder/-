// Маршрутизатор IRQ → обработчик.
//
// Когда срабатывает аппаратное прерывание, ASM-трамплин вызывает Rust-функцию
// `обработать_ирк(вектор, кадр)`. Она:
//   1) Конвертирует вектор → IRQ-номер.
//   2) Если на этот IRQ привязан таймер ядра — дёргает планировщик.
//   3) Если привязан драйвер — вызывает `драйвер.обработать_прерывание()`.
//   4) Если ничего не привязано — печатает «непривязанное прерывание».
//
// Все идентификаторы и сообщения — на русском.

#![allow(dead_code)]

use core::sync::atomic::{AtomicU64, Ordering};

use spin::Mutex;

#[cfg(target_arch = "x86_64")]
use crate::арх::x86_64::идт::КадрПрерывания;

#[cfg(not(target_arch = "x86_64"))]
pub struct КадрПрерывания;

/// Максимум 16 IRQ (8259 PIC).
const ВСЕГО_ИРК: usize = 16;

/// Ссылка на драйвер, привязанный к данному IRQ.
#[derive(Clone, Copy)]
struct Привязка {
    имя_драйвера: &'static str,
}

static ПРИВЯЗКИ: Mutex<[Option<Привязка>; ВСЕГО_ИРК]> = Mutex::new([None; ВСЕГО_ИРК]);

/// Счётчики срабатываний по каждому IRQ — для диагностики.
static СЧЁТЧИКИ: [AtomicU64; ВСЕГО_ИРК] = [
    AtomicU64::new(0), AtomicU64::new(0), AtomicU64::new(0), AtomicU64::new(0),
    AtomicU64::new(0), AtomicU64::new(0), AtomicU64::new(0), AtomicU64::new(0),
    AtomicU64::new(0), AtomicU64::new(0), AtomicU64::new(0), AtomicU64::new(0),
    AtomicU64::new(0), AtomicU64::new(0), AtomicU64::new(0), AtomicU64::new(0),
];

/// Привязать драйвер к IRQ-номеру (0..15).
pub fn привязать_ирк(ирк: u8, имя_драйвера: &'static str) -> Result<(), &'static str> {
    if (ирк as usize) >= ВСЕГО_ИРК {
        return Err("IRQ вне диапазона 0..15");
    }
    let mut таблица = ПРИВЯЗКИ.lock();
    if таблица[ирк as usize].is_some() {
        return Err("IRQ уже привязан");
    }
    таблица[ирк as usize] = Some(Привязка { имя_драйвера });
    Ok(())
}

/// Возвращает количество срабатываний данного IRQ — для диагностики.
pub fn количество_срабатываний(ирк: u8) -> u64 {
    if (ирк as usize) >= ВСЕГО_ИРК {
        return 0;
    }
    СЧЁТЧИКИ[ирк as usize].load(Ordering::Relaxed)
}

/// Вызывается из ASM-трамплина при срабатывании любого IRQ.
///
/// Возвращает `РезультатПереключения` — IRQ-трамплин использует его, чтобы
/// при необходимости переключить контекст (вытесняющий планировщик).
#[cfg(target_arch = "x86_64")]
pub fn обработать_ирк(
    вектор: u8,
    _кадр: &mut КадрПрерывания,
) -> crate::арх::x86_64::идт::РезультатПереключения {
    let ирк = вектор.wrapping_sub(0x20);
    if (ирк as usize) >= ВСЕГО_ИРК {
        return crate::арх::x86_64::идт::РезультатПереключения::без_переключения();
    }
    СЧЁТЧИКИ[ирк as usize].fetch_add(1, Ordering::Relaxed);

    let mut решение = crate::арх::x86_64::идт::РезультатПереключения::без_переключения();

    // IRQ0 — таймер; всегда дёргаем планировщик. Решение он же и возвращает.
    if ирк == 0 {
        решение = crate::арх::x86_64::таймер::тик();
    }

    // Найти драйвер, привязанный к IRQ.
    let имя = {
        let таблица = ПРИВЯЗКИ.lock();
        таблица[ирк as usize].map(|п| п.имя_драйвера)
    };
    if let Some(имя) = имя {
        crate::арх::x86_64::отправить_ирк_драйверу(имя);
    }

    решение
}

#[cfg(not(target_arch = "x86_64"))]
pub fn обработать_ирк(_вектор: u8, _кадр: &mut КадрПрерывания) {}
