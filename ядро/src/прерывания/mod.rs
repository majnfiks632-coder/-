// Подсистема прерываний.
//
// Архитектурно-независимый интерфейс для обработки внешних прерываний (IRQ).
// Конкретная реализация на x86_64 живёт в `арх::x86_64::идт` и `арх::x86_64::pic`.
//
// Все идентификаторы и сообщения — на русском.

#![allow(dead_code)]

#[path = "маршрутизатор.rs"]
pub mod маршрутизатор;

/// Включить аппаратные прерывания (sti на x86_64).
#[cfg(target_arch = "x86_64")]
pub fn включить() {
    unsafe { core::arch::asm!("sti", options(nomem, nostack)) };
}

/// Выключить аппаратные прерывания (cli на x86_64).
#[cfg(target_arch = "x86_64")]
pub fn выключить() {
    unsafe { core::arch::asm!("cli", options(nomem, nostack)) };
}

#[cfg(not(target_arch = "x86_64"))]
pub fn включить() {}

#[cfg(not(target_arch = "x86_64"))]
pub fn выключить() {}
