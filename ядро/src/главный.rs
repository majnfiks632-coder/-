/// Точка входа ядра. Вызывается из ассемблерного загрузочного стаба.
///
/// Имя символа `_yadro_start` — ASCII (требование `#[no_mangle]`); внутреннее имя на
/// русском языке для соблюдения общего стиля.
///
/// # Аргументы
/// * `магия` — магическое число, переданное загрузчиком
///   (Multiboot2: `0x36D76289`; собственный загрузчик ДубинаОС: `0xD0BA_0BE5`)
/// * `инфо` — указатель на информационную структуру загрузчика
///
/// # Гарантии
/// Никогда не возвращается: либо запускает планировщик, либо паникует.
#[no_mangle]
pub extern "C" fn _yadro_start(магия: u64, инфо: u64) -> ! {
    начало_ядра(магия, инфо)
}

fn начало_ядра(магия: u64, инфо: u64) -> ! {
    // Инициализация архитектурных средств вывода (VGA + UART)
    арх::ранняя_инициализация();

    приветствие(магия, инфо);

    // Этап 2.1: инициализация физического аллокатора страниц.
    инициализировать_физическую_память(магия, инфо);

    // Этап 2.2: проверить виртуальную память (только x86_64 пока).
    #[cfg(target_arch = "x86_64")]
    самопроверка_виртуальной_памяти();

    // Этап 2.3: ядерная куча — после неё работают alloc::Box / Vec / String.
    инициализировать_ядерную_кучу();

    // Этап 2.4: кооперативная многопоточность.
    #[cfg(target_arch = "x86_64")]
    самопроверка_потоков();

    // Этап 2.5: межпроцессное общение через порты.
    #[cfg(target_arch = "x86_64")]
    самопроверка_ипк();

    // Этап 2.6: способности и системные вызовы.
    #[cfg(target_arch = "x86_64")]
    самопроверка_способностей();

    // Этап 3: GDT с TSS, IDT, PIC, PIT, каркас драйверов.
    #[cfg(target_arch = "x86_64")]
    инициализировать_прерывания_и_драйверы();

    #[cfg(target_arch = "x86_64")]
    самопроверка_таймера_и_драйверов();

    // Этап 4: PS/2-клавиатура и отладочное окно (F12).
    #[cfg(target_arch = "x86_64")]
    инициализировать_клавиатуру_и_отладку();

    println!();
    #[cfg(target_arch = "x86_64")]
    {
        println!("Ядро готово. F12 — отладочное окно с журналом.");
        println!("Иначе — оболочка ядра, наберите 'help' или 'справка'.");
    }
    #[cfg(not(target_arch = "x86_64"))]
    {
        println!("Ядро готово. (Оболочка и отладочное окно — пока только x86_64.)");
    }
    println!();

    // Главный цикл: ждём прерываний, обновляем отладочное окно и оболочку.
    #[cfg(target_arch = "x86_64")]
    главный_цикл();

    #[cfg(not(target_arch = "x86_64"))]
    арх::халт_навсегда();
}

#[cfg(target_arch = "x86_64")]
fn главный_цикл() -> ! {
    loop {
        отладка::окно::обновить();
        оболочка::обновить();
        // Спим до следующего прерывания.
        unsafe { core::arch::asm!("hlt", options(nomem, nostack)) };
    }
}

fn инициализировать_физическую_память(магия: u64, инфо: u64) {
    println!("[ИНФО] Инициализация подсистемы памяти…");

    let мб2 = магия == мультизагрузка2::МАГИЯ;
    if мб2 && инфо != 0 {
        // Читаем карту памяти от GRUB / qemu -kernel.
        // SAFETY: указатель валиден по контракту Multiboot2.
        let инфо_стр = unsafe { мультизагрузка2::ИнфоMultiboot2::новая(инфо) };
        match инфо_стр {
            Ok(инфо_стр) => {
                let mut аллокатор = память::физическая::АЛЛОКАТОР.lock();
                let mut областей_доступно: usize = 0;
                let mut байтов_доступно: u64 = 0;
                for область in инфо_стр.карта_памяти() {
                    if область.тип_области == мультизагрузка2::ОБЛАСТЬ_ДОСТУПНА {
                        // Не используем первые 1 МиБ — там MBR/BIOS-структуры,
                        // и не используем диапазон ядра 1..2 МиБ.
                        let база = область.база.max(0x20_0000);
                        if база >= область.база + область.длина {
                            continue;
                        }
                        let длина = область.база + область.длина - база;
                        аллокатор.добавить_область(база, длина);
                        областей_доступно += 1;
                        байтов_доступно += длина;
                    }
                }
                println!(
                    "[OK]   Карта памяти Multiboot2: доступных областей {}, всего {} МиБ",
                    областей_доступно,
                    байтов_доступно / (1024 * 1024)
                );
            }
            Err(ошибка) => {
                println!("[ОШИБКА] Multiboot2 информация повреждена: {}", ошибка);
                использовать_резервную_карту();
            }
        }
    } else {
        // Для собственного загрузчика и неизвестных путей пока используем
        // консервативную резервную карту: 64 МиБ, начиная с 2 МиБ.
        // Полноценная карта E820 от своего загрузчика — задача следующего шага.
        println!("[ИНФО] Загрузчик не передал карту памяти — используем резервную");
        использовать_резервную_карту();
    }

    {
        let аллокатор = память::физическая::АЛЛОКАТОР.lock();
        let всего = аллокатор.всего_байтов();
        let свободно = аллокатор.свободно_байтов();
        println!(
            "[OK]   Физический аллокатор: всего {} МиБ, свободно {} МиБ ({} страниц по 4 КиБ)",
            всего / (1024 * 1024),
            свободно / (1024 * 1024),
            аллокатор.свободно_страниц()
        );
    }
    память::физическая::пометить_инициализированным();

    // Простейшая самопроверка: выделим и освободим страницу.
    самопроверка_аллокатора();
}

fn использовать_резервную_карту() {
    let mut аллокатор = память::физическая::АЛЛОКАТОР.lock();
    // Резервная карта: 64 МиБ от 2 МиБ (то есть до 66 МиБ).
    аллокатор.добавить_область(0x20_0000, 64 * 1024 * 1024);
}

fn инициализировать_ядерную_кучу() {
    println!("[ИНФО] Инициализация ядерной кучи (free-list, 2 МиБ)…");
    match память::куча::инициализировать_кучу() {
        Ok(()) => {
            let (выделено, всего) = память::куча::КУЧА.статистика();
            println!(
                "[OK]   Куча: {} КиБ всего, {} байт занято",
                всего / 1024,
                выделено
            );
        }
        Err(ошибка) => {
            println!("[ОШИБКА] Не удалось инициализировать кучу: {}", ошибка);
            return;
        }
    }
    самопроверка_кучи();
}

fn самопроверка_кучи() {
    use alloc::boxed::Box;
    use alloc::string::String;
    use alloc::vec::Vec;

    let коробка = Box::new(0xD0BA_0BE5_u32);
    if *коробка != 0xD0BA_0BE5 {
        println!("[ОШИБКА] Самопроверка кучи: Box вернул не то значение");
        return;
    }
    let mut вектор: Vec<u32> = Vec::with_capacity(16);
    for i in 0..16u32 {
        вектор.push(i * i);
    }
    let сумма: u32 = вектор.iter().sum();
    let ожидаемая: u32 = (0..16u32).map(|i| i * i).sum();
    if сумма != ожидаемая {
        println!("[ОШИБКА] Самопроверка кучи: Vec суммирует неверно");
        return;
    }
    let mut строка = String::new();
    строка.push_str("Привет, ");
    строка.push_str("ДубинаОС!");
    if строка != "Привет, ДубинаОС!" {
        println!("[ОШИБКА] Самопроверка кучи: String склеена неверно");
        return;
    }
    println!(
        "[OK]   Самопроверка кучи: Box, Vec(сумма квадратов 0..16 = {}), String — работают",
        сумма
    );
}

#[cfg(target_arch = "x86_64")]
fn самопроверка_потоков() {
    use core::sync::atomic::{AtomicU32, Ordering};

    println!("[ИНФО] Самопроверка потоков (кооперативный планировщик)…");
    потоки::планировщик::инициализировать();

    static СЧЁТЧИК: AtomicU32 = AtomicU32::new(0);

    extern "C" fn рабочий(аргумент: u64) -> ! {
        let мой_номер = аргумент as u32;
        for _шаг in 0..3 {
            let значение = СЧЁТЧИК.fetch_add(1, Ordering::SeqCst) + 1;
            print!("[ПОТОК {}] значение счётчика = {} ", мой_номер, значение);
            потоки::планировщик::уступить();
        }
        потоки::планировщик::завершить();
    }

    let _а = потоки::планировщик::создать("работник-1", рабочий, 1);
    let _б = потоки::планировщик::создать("работник-2", рабочий, 2);
    let _в = потоки::планировщик::создать("работник-3", рабочий, 3);

    // Главный поток уступает несколько раз — каждый из работников сделает по 3 шага.
    for _ in 0..12 {
        потоки::планировщик::уступить();
    }
    println!();

    let итог = СЧЁТЧИК.load(Ordering::SeqCst);
    if итог == 9 {
        println!(
            "[OK]   Потоки: 3 потока × 3 шага = {} увеличений счётчика, переключение работает",
            итог
        );
    } else {
        println!(
            "[ОШИБКА] Потоки: ожидалось 9 увеличений, получено {}",
            итог
        );
    }
}

#[cfg(target_arch = "x86_64")]
fn самопроверка_ипк() {
    use core::sync::atomic::{AtomicU64, AtomicU8, Ordering};

    println!("[ИНФО] Самопроверка ИПК (порты, очереди сообщений)…");

    static ПОРТ: AtomicU64 = AtomicU64::new(0);
    static ПОЛУЧЕНО: AtomicU8 = AtomicU8::new(0);
    static СУММА: AtomicU64 = AtomicU64::new(0);

    let порт_ид = ипк::создать_порт(16);
    ПОРТ.store(порт_ид.0, Ordering::SeqCst);

    extern "C" fn получатель(_аргумент: u64) -> ! {
        let порт = ипк::ИдПорта(ПОРТ.load(Ordering::SeqCst));
        for _ in 0..3 {
            match ипк::принять(порт) {
                Ok(сообщение) => {
                    let значение = u64::from_le_bytes(
                        сообщение.полезная_нагрузка[..8]
                            .try_into()
                            .unwrap_or([0; 8]),
                    );
                    СУММА.fetch_add(значение, Ordering::SeqCst);
                    ПОЛУЧЕНО.fetch_add(1, Ordering::SeqCst);
                }
                Err(ошибка) => {
                    println!("[ОШИБКА получателя] {}", ошибка);
                    break;
                }
            }
        }
        потоки::планировщик::завершить();
    }

    extern "C" fn отправитель(_аргумент: u64) -> ! {
        let порт = ипк::ИдПорта(ПОРТ.load(Ordering::SeqCst));
        for значение in [10u64, 20, 30] {
            let мой_ид = потоки::планировщик::текущий();
            let сообщение = ипк::Сообщение {
                отправитель: мой_ид,
                код: 0,
                полезная_нагрузка: значение.to_le_bytes().to_vec(),
            };
            if let Err(ошибка) = ипк::отправить(порт, сообщение) {
                println!("[ОШИБКА отправителя] {}", ошибка);
                break;
            }
            потоки::планировщик::уступить();
        }
        потоки::планировщик::завершить();
    }

    let _ = потоки::планировщик::создать("получатель", получатель, 0);
    let _ = потоки::планировщик::создать("отправитель", отправитель, 0);

    // Главный поток уступает достаточно раз, чтобы оба работника завершились.
    for _ in 0..30 {
        потоки::планировщик::уступить();
    }

    let получено = ПОЛУЧЕНО.load(Ordering::SeqCst);
    let сумма = СУММА.load(Ordering::SeqCst);
    if получено == 3 && сумма == 60 {
        println!(
            "[OK]   ИПК: получено сообщений {} из 3, сумма значений {} (10+20+30=60)",
            получено, сумма
        );
    } else {
        println!(
            "[ОШИБКА] ИПК: получено {}, сумма {} (ожидалось 3 и 60)",
            получено, сумма
        );
    }
}

#[cfg(target_arch = "x86_64")]
fn самопроверка_способностей() {
    use способности::Права;

    println!("[ИНФО] Самопроверка способностей и системных вызовов…");

    let мастер = сисвызовы::сисв_создать_порт(8);

    // Урезанная способность — только отправка.
    let только_отправка =
        match сисвызовы::сисв_ограничить_способность(мастер, Права::ОТПРАВКА) {
            Ok(идс) => идс,
            Err(е) => {
                println!("[ОШИБКА] Не удалось ограничить способность: {}", е);
                return;
            }
        };

    // 1. Проверяем что только_отправка не может принять.
    let попытка_приёма = сисвызовы::сисв_принять(только_отправка);
    let ожидаемая_ошибка_приёма = matches!(
        попытка_приёма,
        Err(сисвызовы::ОшибкаСисвызова::Способность(
            способности::ОшибкаСпособности::НетПрав
        ))
    );

    // 2. Через мастер-способность отправляем сообщение.
    let нагрузка: alloc::vec::Vec<u8> = "привет из сисвызова".as_bytes().to_vec();
    let длина_нагрузки = нагрузка.len();
    let отправка_успех = сисвызовы::сисв_отправить(только_отправка, 42, нагрузка).is_ok();

    // 3. Через мастер принимаем — должно прийти.
    let приём = сисвызовы::сисв_принять(мастер);
    let приём_успех = matches!(приём, Ok(ref с) if с.код == 42 && с.полезная_нагрузка.len() == длина_нагрузки);

    // 4. Закрытие порта через мастер.
    let закрытие_успех = сисвызовы::сисв_закрыть(мастер).is_ok();
    // 5. После закрытия отправка через подспособность должна вернуть ошибку.
    let после_закрытия = сисвызовы::сисв_отправить(только_отправка, 0, alloc::vec![]);
    let закрытие_отказ = matches!(
        после_закрытия,
        Err(сисвызовы::ОшибкаСисвызова::ИПК(ипк::ОшибкаИПК::ПортЗакрыт))
    );

    if ожидаемая_ошибка_приёма
        && отправка_успех
        && приём_успех
        && закрытие_успех
        && закрытие_отказ
    {
        println!(
            "[OK]   Способности: отказ при отсутствии ПРИЁМА — работает,"
        );
        println!(
            "       полный путь отправка→приём через мастер-способность — работает,"
        );
        println!(
            "       закрытие порта через ЗАКРЫТИЕ — работает, отказ после закрытия — работает"
        );
    } else {
        println!(
            "[ОШИБКА] Способности: ож_приём_отказ={} отправка={} приём={} закр={} закр_отказ={}",
            ожидаемая_ошибка_приёма, отправка_успех, приём_успех, закрытие_успех, закрытие_отказ
        );
    }
}

#[cfg(target_arch = "x86_64")]
fn инициализировать_прерывания_и_драйверы() {
    println!("[ИНФО] Инициализация GDT/TSS, IDT, PIC, таймера…");
    unsafe {
        арх::x86_64::гдт::инициализировать();
        арх::x86_64::идт::инициализировать();
        арх::x86_64::pic::перенастроить();
    }
    арх::x86_64::таймер::инициализировать();
    println!(
        "[OK]   GDT с TSS установлен (5 сегментов + TSS), IDT с 32 исключениями + 16 IRQ"
    );
    println!(
        "[OK]   8259 PIC перенастроен на векторы 0x20-0x2F, PIT канал-0 = 100 Гц"
    );

    // Регистрируем «таймерный» драйвер ядра — он будет получать тики IRQ0
    // через маршрутизатор. И ещё один тестовый — для проверки каркаса.
    let мой_таймер = alloc::boxed::Box::new(драйверы::ТестовыйДрайвер::новый("таймер-ядра"));
    let _ = драйверы::зарегистрировать(мой_таймер);
    let _ = прерывания::маршрутизатор::привязать_ирк(0, "таймер-ядра");

    println!(
        "[OK]   Каркас драйверов: зарегистрирован «таймер-ядра», IRQ0 → драйвер"
    );

    // Включаем аппаратные прерывания. Дальше будут тикать IRQ0.
    прерывания::включить();
}

#[cfg(target_arch = "x86_64")]
fn самопроверка_таймера_и_драйверов() {
    println!("[ИНФО] Самопроверка таймера и каркаса драйверов…");

    let начало_тиков = арх::x86_64::таймер::ТИКИ
        .load(core::sync::atomic::Ordering::Relaxed);

    // Активно ждём ~250 мс (25 тиков на 100 Гц).
    арх::x86_64::таймер::задержка_тиков(25);

    let конец_тиков = арх::x86_64::таймер::ТИКИ
        .load(core::sync::atomic::Ordering::Relaxed);
    let прошло = конец_тиков - начало_тиков;

    let срабатываний_ирк0 = прерывания::маршрутизатор::количество_срабатываний(0);
    let драйверов_зарегистрировано = драйверы::глобальный_реестр().lock().количество();

    if прошло >= 20 && срабатываний_ирк0 >= 20 && драйверов_зарегистрировано >= 1 {
        println!(
            "[OK]   Таймер: {} тиков (~{} мс), IRQ0 поднят {} раз, драйверов в реестре: {}",
            прошло,
            прошло * 10,
            срабатываний_ирк0,
            драйверов_зарегистрировано
        );
    } else {
        println!(
            "[ОШИБКА] Таймер/драйверы: прошло={} срабатываний_ирк0={} драйверов={}",
            прошло, срабатываний_ирк0, драйверов_зарегистрировано
        );
    }
}

#[cfg(target_arch = "x86_64")]
fn инициализировать_клавиатуру_и_отладку() {
    use драйверы::Драйвер;
    println!("[ИНФО] Регистрация драйвера PS/2-клавиатуры…");

    let mut драйвер = alloc::boxed::Box::new(
        драйверы::клавиатура::ДрайверКлавиатуры::новый()
    );
    if let Err(е) = драйвер.инициализировать() {
        println!("[ОШИБКА] Не удалось инициализировать клавиатуру: {}", е);
        return;
    }
    if let Err(е) = драйверы::зарегистрировать(драйвер) {
        println!("[ОШИБКА] Не удалось зарегистрировать клавиатуру: {}", е);
        return;
    }
    if let Err(е) = прерывания::маршрутизатор::привязать_ирк(1, "клавиатура-ps2") {
        println!("[ОШИБКА] Не удалось привязать IRQ1: {}", е);
        return;
    }
    unsafe { арх::x86_64::pic::снять_маску_ирк(1) };

    println!(
        "[OK]   Клавиатура: драйвер «клавиатура-ps2» зарегистрирован, IRQ1 включен"
    );
    println!(
        "[OK]   Отладочное окно: горячая клавиша F12 (выход — F12 или Esc)"
    );
}

#[cfg(target_arch = "x86_64")]
fn самопроверка_виртуальной_памяти() {
    println!("[ИНФО] Самопроверка виртуальной памяти (4-уровневые таблицы x86_64)…");
    match арх::x86_64::страницы::самопроверка() {
        Ok(()) => println!("[OK]   Виртуальная память: отображение/чтение/запись/снятие — работают"),
        Err(ошибка) => println!("[ОШИБКА] Виртуальная память: {}", ошибка),
    }
}

fn самопроверка_аллокатора() {
    let mut аллокатор = память::физическая::АЛЛОКАТОР.lock();
    match аллокатор.выделить_страницу() {
        Ok(страница) => {
            print!(
                "[OK]   Самопроверка: выделена страница 0x{:X}, ",
                страница.значение()
            );
            match аллокатор.освободить_страницу(страница) {
                Ok(()) => println!("освобождена успешно"),
                Err(ошибка) => println!("ошибка освобождения: {}", ошибка),
            }
        }
        Err(ошибка) => {
            println!("[ОШИБКА] Самопроверка аллокатора: {}", ошибка);
        }
    }
}

/// Печатает приветственный баннер. Виден через VGA-консоль и последовательный порт.
fn приветствие(магия: u64, инфо: u64) {
    let архитектура: &str = {
        #[cfg(target_arch = "x86_64")]
        { "x86_64 (long mode)" }
        #[cfg(target_arch = "aarch64")]
        { "aarch64 (ARMv8)" }
    };

    println!();
    println!("╔══════════════════════════════════════════════════╗");
    println!("║                                                  ║");
    println!("║              Д У Б И Н А   О С                   ║");
    println!("║                                                  ║");
    println!("║         Версия 0.1.0 — этап «Фундамент»          ║");
    println!("║                                                  ║");
    println!("╚══════════════════════════════════════════════════╝");
    println!();
    println!("[OK] Архитектура: {}", архитектура);

    #[cfg(target_arch = "x86_64")]
    {
        println!("[OK] Идентификационное отображение 0..4 ГиБ установлено");
        println!("[OK] GDT с 64-битным сегментом загружен");
    }

    println!("[ИНФО] Магия загрузчика: 0x{:016X}", магия);
    println!("[ИНФО] Указатель информации:  0x{:016X}", инфо);
    println!();
    if магия == 0x36D76289 {
        println!("[ИНФО] Загружено через Multiboot2 (GRUB или qemu -kernel)");
    } else if магия == 0xD0BA_0BE5 {
        println!("[ИНФО] Загружено через собственный загрузчик ДубинаОС (MBR + Stage2)");
    } else if магия == 0 {
        println!("[ИНФО] Загружено напрямую (qemu -kernel без заголовка)");
    } else {
        println!("[ВНИМАНИЕ] Неизвестный загрузчик (магия = 0x{:X})", магия);
    }
    println!();
}
