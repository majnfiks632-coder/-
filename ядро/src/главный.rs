/// Маленькая самопроверка многоуровневой очереди готовности: создаём три
/// потока с приоритетами 8/12/16 и убеждаемся, что высокоприоритетный
/// получил больше шагов до того, как остальные отработали свои кванты.
///
/// Эта проверка запускается ДО включения вытеснения — то есть мы
/// тестируем именно структуру «32 очереди + битовая маска» через
/// кооперативные `уступить()`. Полноценный preemption-тест проводится в
/// QEMU (CI ловит баннер «вытеснение работает»).
#[cfg(target_arch = "x86_64")]
fn самопроверка_приоритетов() {
    use core::sync::atomic::{AtomicU64, Ordering};

    static ШАГИ_8: AtomicU64 = AtomicU64::new(0);
    static ШАГИ_12: AtomicU64 = AtomicU64::new(0);
    static ШАГИ_16: AtomicU64 = AtomicU64::new(0);

    extern "C" fn рабочий_тест(аргумент: u64) -> ! {
        let счётчик: &AtomicU64 = match аргумент {
            8 => &ШАГИ_8,
            12 => &ШАГИ_12,
            16 => &ШАГИ_16,
            _ => &ШАГИ_8,
        };
        for _ in 0..5 {
            счётчик.fetch_add(1, Ordering::Relaxed);
            потоки::планировщик::уступить();
        }
        потоки::планировщик::завершить();
    }

    let _ = потоки::планировщик::создать_с_приоритетом("приор-8", рабочий_тест, 8, 8);
    let _ = потоки::планировщик::создать_с_приоритетом("приор-12", рабочий_тест, 12, 12);
    let _ = потоки::планировщик::создать_с_приоритетом("приор-16", рабочий_тест, 16, 16);

    // Уступаем достаточно раз, чтобы все три отработали по 5 шагов.
    for _ in 0..40 {
        потоки::планировщик::уступить();
    }

    let s8 = ШАГИ_8.load(Ordering::Relaxed);
    let s12 = ШАГИ_12.load(Ordering::Relaxed);
    let s16 = ШАГИ_16.load(Ordering::Relaxed);
    if s16 == 5 && s12 == 5 && s8 == 5 {
        println!(
            "[OK]   Приоритеты: 3 уровня (8/12/16), все по 5 шагов — round-robin внутри уровня и старшинство между уровнями работают"
        );
    } else {
        println!(
            "[ОШИБКА] Приоритеты: ожидалось 5/5/5 шагов на 8/12/16, получено {}/{}/{}",
            s8, s12, s16
        );
    }
}

/// Этап 2.7. Инициализация ACPI.
///
/// Ищем RSDP в трёх источниках, в порядке предпочтения:
///  1. ИнфоЗагрузки.rsdp (UEFI-загрузчик уже нашёл его в Configuration Table).
///  2. EBDA (Extended BIOS Data Area, 1 КиБ ниже 0xA0000).
///  3. BIOS-ROM (диапазон 0xE0000..0xFFFFF).
/// Способы 2 и 3 — только для Legacy/Multiboot2: на UEFI без CSM EBDA пуста.
#[cfg(target_arch = "x86_64")]
fn инициализировать_акпи(магия: u64, инфо: u64) {
    println!("[ИНФО] Поиск ACPI RSDP…");

    let mut найденный_rsdp: u64 = 0;
    let mut источник = "не найдено";

    // (1) Из UEFI-загрузчика через ДубПрото.
    if магия == инфо_загрузки::МАГИЯ_ДУБ_ПРОТО && инфо != 0 {
        if let Some(данные) = unsafe { инфо_загрузки::ИнфоЗагрузки::прочитать(инфо) } {
            if данные.rsdp != 0 {
                найденный_rsdp = данные.rsdp;
                источник = "UEFI ConfigTable";
            }
        }
    }

    // (2) EBDA: первые 1024 байта по адресу из 0x40E (16-битный сегмент << 4).
    if найденный_rsdp == 0 {
        if let Some(а) = unsafe { сканировать_rsdp_в_ebda() } {
            найденный_rsdp = а;
            источник = "EBDA";
        }
    }

    // (3) BIOS-ROM 0xE0000..0xFFFFF.
    if найденный_rsdp == 0 {
        if let Some(а) = unsafe { сканировать_rsdp_в_bios(0xE_0000, 0x10_0000) } {
            найденный_rsdp = а;
            источник = "BIOS ROM";
        }
    }

    if найденный_rsdp == 0 {
        println!(
            "[ВНИМАНИЕ] RSDP не найден — ACPI недоступен (продолжаем без APIC/PCIe)"
        );
        return;
    }
    println!(
        "[OK]   RSDP @ 0x{:X} (источник: {})",
        найденный_rsdp, источник
    );

    let таблицы = match unsafe { акпи::инициализировать(найденный_rsdp) } {
        Some(т) => т,
        None => {
            println!("[ВНИМАНИЕ] RSDP найден, но контрольные суммы не сошлись");
            return;
        }
    };
    акпи::распечатать_сводку(&таблицы);
    акпи::установить(таблицы);
}

/// Просканировать диапазон [начало, конец) на наличие сигнатуры RSDP.
/// RSDP всегда выровнен на 16 байт. Возвращает физический адрес или None.
///
/// # Безопасность
/// Регион должен быть отображён identity-mapping (что у нас сделано в
/// первых 4 ГиБ). При наличии MMIO-устройств ниже 1 МиБ это всё равно
/// безопасно — мы только читаем.
#[cfg(target_arch = "x86_64")]
unsafe fn сканировать_rsdp_в_bios(начало: u64, конец: u64) -> Option<u64> {
    let mut адрес = начало;
    while адрес + 8 <= конец {
        let маркер: [u8; 8] = unsafe {
            core::ptr::read_volatile(адрес as *const [u8; 8])
        };
        if маркер == акпи::СИГ_RSDP {
            // Проверим базовую контрольную сумму.
            let mut сумма: u8 = 0;
            for i in 0..20 {
                сумма = сумма.wrapping_add(unsafe {
                    core::ptr::read_volatile((адрес + i) as *const u8)
                });
            }
            if сумма == 0 {
                return Some(адрес);
            }
        }
        адрес += 16;
    }
    None
}

/// Прочитать адрес EBDA из BDA (BIOS Data Area, 0x40E) и просканировать
/// первые 1024 байта.
///
/// # Безопасность
/// см. `сканировать_rsdp_в_bios`.
#[cfg(target_arch = "x86_64")]
unsafe fn сканировать_rsdp_в_ebda() -> Option<u64> {
    let сегмент_ebda = unsafe { core::ptr::read_volatile(0x40E as *const u16) } as u64;
    if сегмент_ebda == 0 {
        return None;
    }
    let база = сегмент_ebda << 4;
    if база < 0x80_000 || база >= 0xA_0000 {
        return None;
    }
    unsafe { сканировать_rsdp_в_bios(база, база + 1024) }
}

/// Этап 2.8. Инициализация PCI/PCIe.
///
/// Если ACPI выдал MCFG — выбираем ECAM. Иначе — legacy CF8/CFC.
/// Затем выводим список всех устройств с их class:subclass:prog_if.
#[cfg(target_arch = "x86_64")]
fn инициализировать_pci() {
    println!("[ИНФО] Перечисление шин PCI/PCIe…");
    let mut выбран_ecam = false;
    if let Some(таблицы) = акпи::описание() {
        акпи::перечислить_pcie_сегменты(&таблицы, |база, _сег, _шб, шк| {
            if !выбран_ecam {
                писиай::использовать_ecam(база, шк);
                выбран_ecam = true;
            }
        });
    }
    if !выбран_ecam {
        писиай::использовать_legacy();
        println!("[ИНФО] PCI: используем legacy CF8/CFC (MCFG отсутствует)");
    } else {
        println!("[ИНФО] PCI: используем PCIe ECAM (память)");
    }
    писиай::распечатать_список();
}

/// Этап 3.1. Поднимаем AHCI HBA и перечисляем подключённые порты.
///
/// На QEMU/q35 это найдёт встроенный SATA-контроллер; на ASUS X552E —
/// встроенный SATA-чип AMD. Если AHCI не найден, тихо пропускаем.
#[cfg(target_arch = "x86_64")]
fn инициализировать_ahci() {
    if ахки::найти().is_none() {
        println!("[ИНФО] AHCI: контроллер не найден на шине PCI");
        return;
    }
    let Some(хба) = ахки::инициализировать() else { return };

    // Для каждого активного порта запускаем IDENTIFY, чтобы узнать модель,
    // серийник и размер диска. Тестовое чтение — первый сектор (LBA 0).
    for номер in 0..32u8 {
        if хба.реализованные_порты & (1u32 << номер) == 0 { continue; }
        if !ахки::порт_активен(&хба, номер) { continue; }
        let диск = ахки::идентифицировать(&хба, номер);
        if let Some(d) = диск {
            // Прочитать первый сектор (MBR) и распечатать сигнатуру 0xAA55.
            if let Some(буф_phys) = ахки::прочитать_секторы(&хба, номер, 0, 1) {
                unsafe {
                    let сиг = core::ptr::read_volatile((буф_phys + 510) as *const u16);
                    println!(
                        "[OK]   AHCI порт {}: первый сектор прочитан, MBR-сигнатура 0x{:04X} ({})",
                        номер, сиг,
                        if сиг == 0xAA55 { "валидная" } else { "пусто/иное" }
                    );
                }
                let _ = crate::память::физическая::АЛЛОКАТОР
                    .lock()
                    .освободить_страницу(crate::память::ФизАдрес::новый(буф_phys));
            } else {
                println!("[ВНИМАНИЕ] AHCI порт {}: чтение первого сектора не удалось", d.номер_порта);
            }
            // Этап 3.4: разобрать таблицу разделов (GPT / protective MBR).
            if let Some(таблица) = разделы::прочитать_таблицу(&хба, номер) {
                разделы::распечатать_таблицу(&таблица, d.размер_сектора);
                // Найти ESP и попробовать открыть FAT32-том на ней.
                for раз in таблица.разделы.iter().flatten() {
                    if раз.тип == разделы::ТипРаздела::EFISystem {
                        if let Some(том) = фат32::открыть_том(&хба, номер, раз.лба_начало) {
                            фат32::распечатать_корень(&хба, номер, &том);
                        }
                        break;
                    }
                }
            }
        }
    }
}

/// Этап 2.9. Перевод подсистемы прерываний с 8259 PIC на APIC (LAPIC + IO APIC).
///
/// Условия включения: ACPI MADT присутствует, найден IO APIC, нет «принудительного»
/// флага legacy_pic. На QEMU `q35`/реальном железе (включая ASUS X552E) это
/// выполняется. Иначе остаёмся на 8259 PIC.
///
/// Что делает:
///   1) Вызывает `лапик::инициализировать` (включает APIC + замаскивает 8259).
///   2) Вызывает `иоапик::инициализировать` (маскирует все redirection entries).
///   3) Программирует маршруты для legacy IRQ0 (PIT) и IRQ1 (PS/2 KBD)
///      с учётом ISO-переопределений из ACPI.
///   4) Размаскирует только PIT — клавиатура размаскируется при регистрации
///      её драйвера ниже по коду.
#[cfg(target_arch = "x86_64")]
fn инициализировать_апик() {
    let Some(таблицы) = акпи::описание() else {
        println!("[ИНФО] APIC: ACPI отсутствует — остаёмся на 8259 PIC");
        return;
    };
    if таблицы.адрес_lapic == 0 || таблицы.количество_ioapic == 0 {
        println!("[ИНФО] APIC: MADT без LAPIC/IOAPIC — остаёмся на 8259 PIC");
        return;
    }
    // 1) LAPIC.
    unsafe { арх::x86_64::лапик::инициализировать(таблицы.адрес_lapic) };
    println!(
        "[OK]   LAPIC включён @ 0x{:X}, ID = {}",
        таблицы.адрес_lapic,
        арх::x86_64::лапик::ид()
    );

    // 2) IO APIC (берём первый — для X552E этого достаточно).
    let mut ioapic_addr: u32 = 0;
    let mut gsi_base: u32 = 0;
    акпи::перечислить_ioapic(&таблицы, |_id, addr, gsi| {
        if ioapic_addr == 0 {
            ioapic_addr = addr;
            gsi_base = gsi;
        }
    });
    if ioapic_addr == 0 {
        println!("[ВНИМАНИЕ] APIC: IO APIC не найден в MADT");
        return;
    }
    unsafe { арх::x86_64::иоапик::инициализировать(ioapic_addr, gsi_base) };
    let (ver, max) = арх::x86_64::иоапик::версия_максимум_записей();
    println!(
        "[OK]   IO APIC @ 0x{:X}, GSI base {}, версия 0x{:02X}, записей {}",
        ioapic_addr, gsi_base, ver, max + 1
    );

    // 3) Маршрутизация legacy-IRQ.
    //    Вектор IRQ0 = 0x20 (как в PIC после перенастройки),
    //    Вектор IRQ1 = 0x21.
    let apic_id = арх::x86_64::лапик::ид() as u8;
    маршрут_legacy_irq(0, 0x20, apic_id);
    маршрут_legacy_irq(1, 0x21, apic_id);

    // 4) Размаскируем IRQ0 — таймер. IRQ1 размаскируется драйвером KBD ниже.
    let gsi0 = акпи::переопределение_gsi(0).unwrap_or(0);
    арх::x86_64::иоапик::снять_маску(gsi0);

    println!("[OK]   APIC: PIT (IRQ0) маршрут на vec 0x20, PS/2 KBD (IRQ1) на vec 0x21");
}

/// Программирует одну запись redirection table в IO APIC для legacy-IRQ.
/// Если ACPI указал переопределение GSI/полярность — учитывает.
#[cfg(target_arch = "x86_64")]
fn маршрут_legacy_irq(legacy_irq: u8, вектор: u8, apic_id: u8) {
    let mut gsi: u32 = legacy_irq as u32;
    let mut полярность: u8 = 0; // active high
    let mut триггер: u8 = 0;    // edge
    if let Some(таблицы) = акпи::описание() {
        акпи::перечислить_iso(&таблицы, |ист, г, ф| {
            if ист == legacy_irq {
                gsi = г;
                let p = ф & 0x3;
                let t = (ф >> 2) & 0x3;
                if p == 0b11 { полярность = 1; }
                if t == 0b11 { триггер = 1; }
            }
        });
    }
    let mut запись = арх::x86_64::иоапик::ЗаписьМаршрутизации::простая(вектор, apic_id);
    запись.полярность = полярность;
    запись.триггер = триггер;
    запись.маска = true; // размаскирует драйвер
    арх::x86_64::иоапик::задать_маршрут(gsi, запись);
}

#[cfg(target_arch = "x86_64")]
fn инициализировать_прерывания_и_драйверы() {
    println!("[ИНФО] Инициализация GDT/TSS, IDT, PIC, таймера…");
    unsafe {
        арх::x86_64::гдт::инициализировать();
        арх::x86_64::идт::инициализировать();
        // PIC перенастраивается всегда: даже в режиме APIC он должен быть
        // на правильных векторах перед маскированием — иначе spurious-IRQ
        // могут попасть в исключения.
        арх::x86_64::pic::перенастроить();
    }
    // Этап 2.9: пробуем перейти на APIC (LAPIC + IOAPIC).
    инициализировать_апик();
    арх::x86_64::таймер::инициализировать();
    println!(
        "[OK]   GDT с TSS установлен (5 сегментов + TSS), IDT с 32 исключениями + 16 IRQ"
    );
    println!(
        "[OK]   8259 PIC перенастроен на векторы 0x20-0x2F, PIT канал-0 = 100 Гц"
    );

    // Регистрируем «таймерный» драйвер ядра — он будет получать тики IRQ0
    // через маршрутизатор. И ещё один тестовый — для проверки каркаса.
    let мой_таймер = alloc::boxed::Box::new(драйверы::ТестовыйДрайвер::новый("таймер-ядра"));
    let _ = драйверы::зарегистрировать(мой_таймер);
    let _ = прерывания::маршрутизатор::привязать_ирк(0, "таймер-ядра");

    println!(
        "[OK]   Каркас драйверов: зарегистрирован «таймер-ядра», IRQ0 → драйвер"
    );

    // Включаем аппаратные прерывания. Дальше будут тикать IRQ0.
    прерывания::включить();
}

#[cfg(target_arch = "x86_64")]
fn самопроверка_таймера_и_драйверов() {
    println!("[ИНФО] Самопроверка таймера и каркаса драйверов…");

    let начало_тиков = арх::x86_64::таймер::ТИКИ
        .load(core::sync::atomic::Ordering::Relaxed);

    // Активно ждём ~250 мс (25 тиков на 100 Гц).
    арх::x86_64::таймер::задержка_тиков(25);

    let конец_тиков = арх::x86_64::таймер::ТИКИ
        .load(core::sync::atomic::Ordering::Relaxed);
    let прошло = конец_тиков - начало_тиков;

    let срабатываний_ирк0 = прерывания::маршрутизатор::количество_срабатываний(0);
    let драйверов_зарегистрировано = драйверы::глобальный_реестр().lock().количество();

    if прошло >= 20 && срабатываний_ирк0 >= 20 && драйверов_зарегистрировано >= 1 {
        println!(
            "[OK]   Таймер: {} тиков (~{} мс), IRQ0 поднят {} раз, драйверов в реестре: {}",
            прошло,
            прошло * 10,
            срабатываний_ирк0,
            драйверов_зарегистрировано
        );
    } else {
        println!(
            "[ОШИБКА] Таймер/драйверы: прошло={} срабатываний_ирк0={} драйверов={}",
            прошло, срабатываний_ирк0, драйверов_зарегистрировано
        );
    }
}

#[cfg(target_arch = "x86_64")]
fn инициализировать_клавиатуру_и_отладку() {
    use драйверы::Драйвер;
    println!("[ИНФО] Регистрация драйвера PS/2-клавиатуры…");

    let mut драйвер = alloc::boxed::Box::new(
        драйверы::клавиатура::ДрайверКлавиатуры::новый()
    );
    if let Err(е) = драйвер.инициализировать() {
        println!("[ОШИБКА] Не удалось инициализировать клавиатуру: {}", е);
        return;
    }
    if let Err(е) = драйверы::зарегистрировать(драйвер) {
        println!("[ОШИБКА] Не удалось зарегистрировать клавиатуру: {}", е);
        return;
    }
    if let Err(е) = прерывания::маршрутизатор::привязать_ирк(1, "клавиатура-ps2") {
        println!("[ОШИБКА] Не удалось привязать IRQ1: {}", е);
        return;
    }
    if арх::x86_64::лапик::активен() {
        // В режиме APIC: размаскируем IRQ1 в IO APIC (GSI с учётом ISO).
        let gsi = акпи::переопределение_gsi(1).unwrap_or(1);
        арх::x86_64::иоапик::снять_маску(gsi);
    } else {
        unsafe { арх::x86_64::pic::снять_маску_ирк(1) };
    }

    println!(
        "[OK]   Клавиатура: драйвер «клавиатура-ps2» зарегистрирован, IRQ1 включен"
    );
    println!(
        "[OK]   Отладочное окно: горячая клавиша F12 (выход — F12 или Esc)"
    );
}

#[cfg(target_arch = "x86_64")]
fn самопроверка_виртуальной_памяти() {
    println!("[ИНФО] Самопроверка виртуальной памяти (4-уровневые таблицы x86_64)…");
    match арх::x86_64::страницы::самопроверка() {
        Ok(()) => println!("[OK]   Виртуальная память: отображение/чтение/запись/снятие — работают"),
        Err(ошибка) => println!("[ОШИБКА] Виртуальная память: {}", ошибка),
    }
}

fn самопроверка_аллокатора() {
    let mut аллокатор = память::физическая::АЛЛОКАТОР.lock();
    match аллокатор.выделить_страницу() {
        Ok(страница) => {
            print!(
                "[OK]   Самопроверка: выделена страница 0x{:X}, ",
                страница.значение()
            );
            match аллокатор.освободить_страницу(страница) {
                Ok(()) => println!("освобождена успешно"),
                Err(ошибка) => println!("ошибка освобождения: {}", ошибка),
            }
        }
        Err(ошибка) => {
            println!("[ОШИБКА] Самопроверка аллокатора: {}", ошибка);
        }
    }
}

/// Печатает приветственный баннер. Виден через VGA-консоль и последовательный порт.
fn приветствие(магия: u64, инфо: u64) {
    let архитектура: &str = {
        #[cfg(target_arch = "x86_64")]
        { "x86_64 (long mode)" }
        #[cfg(target_arch = "aarch64")]
        { "aarch64 (ARMv8)" }
    };

    println!();
    println!("╔══════════════════════════════════════════════════╗");
    println!("║                                                  ║");
    println!("║              Д У Б И Н А   О С                   ║");
    println!("║                                                  ║");
    println!("║         Версия 0.1.0 — этап «Фундамент»          ║");
    println!("║                                                  ║");
    println!("╚══════════════════════════════════════════════════╝");
    println!();
    println!("[OK] Архитектура: {}", архитектура);

    #[cfg(target_arch = "x86_64")]
    {
        println!("[OK] Идентификационное отображение 0..4 ГиБ установлено");
        println!("[OK] GDT с 64-битным сегментом загружен");
    }

    println!("[ИНФО] Магия загрузчика: 0x{:016X}", магия);
    println!("[ИНФО] Указатель информации:  0x{:016X}", инфо);
    println!();
    if магия == 0x36D76289 {
        println!("[ИНФО] Загружено через Multiboot2 (GRUB или qemu -kernel)");
    } else if магия == 0xD0BA_0BE5 {
        println!("[ИНФО] Загружено через собственный загрузчик ДубинаОС (MBR + Stage2)");
    } else if магия == инфо_загрузки::МАГИЯ_ДУБ_ПРОТО {
        println!("[ИНФО] Загружено через UEFI-загрузчик ДубинаОС (ДубПрото v1)");
    } else if магия == 0 {
        println!("[ИНФО] Загружено напрямую (qemu -kernel без заголовка)");
    } else {
        println!("[ВНИМАНИЕ] Неизвестный загрузчик (магия = 0x{:X})", магия);
    }
    println!();
}
