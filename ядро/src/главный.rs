#[cfg(target_arch = "x86_64")]
fn самопроверка_ипк() {
    use core::sync::atomic::{AtomicU64, AtomicU8, Ordering};

    println!("[ИНФО] Самопроверка ИПК (порты, очереди сообщений)…");

    static ПОРТ: AtomicU64 = AtomicU64::new(0);
    static ПОЛУЧЕНО: AtomicU8 = AtomicU8::new(0);
    static СУММА: AtomicU64 = AtomicU64::new(0);

    let порт_ид = ипк::создать_порт(16);
    ПОРТ.store(порт_ид.0, Ordering::SeqCst);

    extern "C" fn получатель(_аргумент: u64) -> ! {
        let порт = ипк::ИдПорта(ПОРТ.load(Ordering::SeqCst));
        for _ in 0..3 {
            match ипк::принять(порт) {
                Ok(сообщение) => {
                    let значение = u64::from_le_bytes(
                        сообщение.полезная_нагрузка[..8]
                            .try_into()
                            .unwrap_or([0; 8]),
                    );
                    СУММА.fetch_add(значение, Ordering::SeqCst);
                    ПОЛУЧЕНО.fetch_add(1, Ordering::SeqCst);
                }
                Err(ошибка) => {
                    println!("[ОШИБКА получателя] {}", ошибка);
                    break;
                }
            }
        }
        потоки::планировщик::завершить();
    }

    extern "C" fn отправитель(_аргумент: u64) -> ! {
        let порт = ипк::ИдПорта(ПОРТ.load(Ordering::SeqCst));
        for значение in [10u64, 20, 30] {
            let мой_ид = потоки::планировщик::текущий();
            let сообщение = ипк::Сообщение {
                отправитель: мой_ид,
                код: 0,
                полезная_нагрузка: значение.to_le_bytes().to_vec(),
            };
            if let Err(ошибка) = ипк::отправить(порт, сообщение) {
                println!("[ОШИБКА отправителя] {}", ошибка);
                break;
            }
            потоки::планировщик::уступить();
        }
        потоки::планировщик::завершить();
    }

    let _ = потоки::планировщик::создать("получатель", получатель, 0);
    let _ = потоки::планировщик::создать("отправитель", отправитель, 0);

    // Главный поток уступает достаточно раз, чтобы оба работника завершились.
    for _ in 0..30 {
        потоки::планировщик::уступить();
    }

    let получено = ПОЛУЧЕНО.load(Ordering::SeqCst);
    let сумма = СУММА.load(Ordering::SeqCst);
    if получено == 3 && сумма == 60 {
        println!(
            "[OK]   ИПК: получено сообщений {} из 3, сумма значений {} (10+20+30=60)",
            получено, сумма
        );
    } else {
        println!(
            "[ОШИБКА] ИПК: получено {}, сумма {} (ожидалось 3 и 60)",
            получено, сумма
        );
    }
}

#[cfg(target_arch = "x86_64")]
fn самопроверка_способностей() {
    use способности::Права;

    println!("[ИНФО] Самопроверка способностей и системных вызовов…");

    let мастер = сисвызовы::сисв_создать_порт(8);

    // Урезанная способность — только отправка.
    let только_отправка =
        match сисвызовы::сисв_ограничить_способность(мастер, Права::ОТПРАВКА) {
            Ok(идс) => идс,
            Err(е) => {
                println!("[ОШИБКА] Не удалось ограничить способность: {}", е);
                return;
            }
        };

    // 1. Проверяем что только_отправка не может принять.
    let попытка_приёма = сисвызовы::сисв_принять(только_отправка);
    let ожидаемая_ошибка_приёма = matches!(
        попытка_приёма,
        Err(сисвызовы::ОшибкаСисвызова::Способность(
            способности::ОшибкаСпособности::НетПрав
        ))
    );

    // 2. Через мастер-способность отправляем сообщение.
    let нагрузка: alloc::vec::Vec<u8> = "привет из сисвызова".as_bytes().to_vec();
    let длина_нагрузки = нагрузка.len();
    let отправка_успех = сисвызовы::сисв_отправить(только_отправка, 42, нагрузка).is_ok();

    // 3. Через мастер принимаем — должно прийти.
    let приём = сисвызовы::сисв_принять(мастер);
    let приём_успех = matches!(приём, Ok(ref с) if с.код == 42 && с.полезная_нагрузка.len() == длина_нагрузки);

    // 4. Закрытие порта через мастер.
    let закрытие_успех = сисвызовы::сисв_закрыть(мастер).is_ok();
    // 5. После закрытия отправка через подспособность должна вернуть ошибку.
    let после_закрытия = сисвызовы::сисв_отправить(только_отправка, 0, alloc::vec![]);
    let закрытие_отказ = matches!(
        после_закрытия,
        Err(сисвызовы::ОшибкаСисвызова::ИПК(ипк::ОшибкаИПК::ПортЗакрыт))
    );

    if ожидаемая_ошибка_приёма
        && отправка_успех
        && приём_успех
        && закрытие_успех
        && закрытие_отказ
    {
        println!(
            "[OK]   Способности: отказ при отсутствии ПРИЁМА — работает,"
        );
        println!(
            "       полный путь отправка→приём через мастер-способность — работает,"
        );
        println!(
            "       закрытие порта через ЗАКРЫТИЕ — работает, отказ после закрытия — работает"
        );
    } else {
        println!(
            "[ОШИБКА] Способности: ож_приём_отказ={} отправка={} приём={} закр={} закр_отказ={}",
            ожидаемая_ошибка_приёма, отправка_успех, приём_успех, закрытие_успех, закрытие_отказ
        );
    }
}

