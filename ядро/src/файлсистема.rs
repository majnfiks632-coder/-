// Подсистема ФС ядра: ОЗУ-блочное устройство + смонтированная ДубФС.
//
// Этот модуль склеивает воедино крейт `dubina-fs` (вся логика журналируемой
// ДубФС) и ядро. На текущем этапе у нас ещё нет драйвера IDE/SATA/AHCI и
// настоящего диска, поэтому ФС живёт в ОЗУ: при старте мы:
//
//   1) выделяем `Vec<u8>` фиксированного размера (по умолчанию ~1 МиБ),
//   2) форматируем его как ДубФС (`ДубФС::создать(...)`),
//   3) разворачиваем демонстрационное дерево каталогов
//      (`/дом`, `/система`, `/устройства`, `/временно`, файл `/сведения`),
//   4) кладём смонтированную ФС в глобальный `Mutex` — оболочка её видит.
//
// Так оболочка получает живые `сп`/`сд`/`вывести` без внешнего диска: при
// перезагрузке всё пересоздаётся заново. Когда появится драйвер настоящего
// блочного устройства, достаточно будет реализовать тот же трейт
// `dubina_fs::блок::БлокУстройство` для него и подменить `БлокОЗУ`.
//
// Архитектура: только x86_64 (как и оболочка).

use alloc::string::{String, ToString};
use alloc::vec;
use alloc::vec::Vec;
use core::sync::atomic::{AtomicBool, Ordering};

use dubina_fs::блок::{БлокУстройство, РАЗМЕР_БЛОКА};
use dubina_fs::ошибки::ОшибкаВвода;
use dubina_fs::{ДубФС, ОшибкаФС, ПараметрыСоздания, Резюме, Тип};
use spin::{Mutex, Once};

/// Размер ОЗУ-диска в блоках. 256 блоков × 4 КиБ = 1 МиБ — хватает для
/// демонстрации каталогов и небольших файлов.
const БЛОКОВ_НА_ДИСКЕ: u64 = 256;

/// Корневое ОЗУ-блочное устройство ядра. Хранится за `Once`, чтобы можно
/// было получить `&'static`-ссылку (этого требует `ДубФС<'устр>`).
static УСТРОЙСТВО: Once<БлокОЗУ> = Once::new();

/// Обёртка-Sync для смонтированной ФС.
///
/// Внутри `ДубФС<'static>` лежит `&'static dyn БлокУстройство`. Сам трейт
/// `БлокУстройство` не требует `Sync`, поэтому компилятор по умолчанию
/// помечает такую ссылку как `!Sync` и не даёт положить её в `static`.
///
/// На практике наша единственная реализация — `БлокОЗУ` — потокобезопасна
/// (внутри `spin::Mutex<Vec<u8>>`). Все обращения к ФС у нас идут через
/// внешний `Mutex` ниже, поэтому одновременный доступ к одному `ДубФС`
/// невозможен. Этого достаточно, чтобы вручную обещать компилятору `Sync`.
struct ХранилищеФС(Mutex<Option<ДубФС<'static>>>);
unsafe impl Sync for ХранилищеФС {}

/// Смонтированная ФС. `None` означает «ещё не инициализирована».
static СМОНТИРОВАНА: ХранилищеФС = ХранилищеФС(Mutex::new(None));

/// Признак того, что монтирование уже пройдено хотя бы раз. Нужен только
/// чтобы оболочка различала «ФС не готова, ядро не инициализировало её»
/// от «ФС была, но временно занята другим вызовом».
static ИНИЦИАЛИЗИРОВАНА: AtomicBool = AtomicBool::new(false);

/// ОЗУ-имитация блочного устройства, потокобезопасная (`Sync`).
///
/// Стандартная `БлокУстройствоВПамяти` из крейта использует `RefCell`, она
/// не `Sync` и не годится для `static`. Здесь та же идея, но с `spin::Mutex`.
pub struct БлокОЗУ {
    байт_на_блок: usize,
    блоков: u64,
    данные: Mutex<Vec<u8>>,
}

impl БлокОЗУ {
    fn новое(блоков: u64) -> Self {
        let размер = (блоков as usize)
            .checked_mul(РАЗМЕР_БЛОКА)
            .expect("размер ОЗУ-диска переполняет usize");
        Self {
            байт_на_блок: РАЗМЕР_БЛОКА,
            блоков,
            данные: Mutex::new(vec![0u8; размер]),
        }
    }

    fn проверить_номер(&self, номер: u64) -> Result<(), ОшибкаВвода> {
        if номер >= self.блоков {
            Err(ОшибкаВвода::НесуществующийБлок)
        } else {
            Ok(())
        }
    }
}

impl БлокУстройство for БлокОЗУ {
    fn размер_блока(&self) -> usize {
        self.байт_на_блок
    }

    fn всего_блоков(&self) -> u64 {
        self.блоков
    }

    fn прочитать_блок(&self, номер: u64, буфер: &mut [u8]) -> Result<(), ОшибкаВвода> {
        self.проверить_номер(номер)?;
        if буфер.len() != self.байт_на_блок {
            return Err(ОшибкаВвода::ОшибкаЧтения);
        }
        let данные = self.данные.lock();
        let начало = (номер as usize) * self.байт_на_блок;
        буфер.copy_from_slice(&данные[начало..начало + self.байт_на_блок]);
        Ok(())
    }

    fn записать_блок(&self, номер: u64, данные: &[u8]) -> Result<(), ОшибкаВвода> {
        self.проверить_номер(номер)?;
        if данные.len() != self.байт_на_блок {
            return Err(ОшибкаВвода::ОшибкаЗаписи);
        }
        let mut диск = self.данные.lock();
        let начало = (номер as usize) * self.байт_на_блок;
        диск[начало..начало + self.байт_на_блок].copy_from_slice(данные);
        Ok(())
    }

    fn синхронизировать(&self) -> Result<(), ОшибкаВвода> {
        // Записи в ОЗУ всегда синхронны — ничего не делаем.
        Ok(())
    }
}

