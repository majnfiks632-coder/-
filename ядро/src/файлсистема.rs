/// Привести относительный путь к абсолютному, разрешив `.`/`..`.
/// `текущий` считается абсолютным; если в нём `.` или `..` — это ошибка
/// уровня вызывающего, нормализуем снова на всякий случай.
pub fn нормализовать(текущий: &str, путь: &str) -> String {
    let собранный = if путь.starts_with('/') {
        путь.to_string()
    } else {
        let mut с = текущий.to_string();
        if !с.ends_with('/') {
            с.push('/');
        }
        с.push_str(путь);
        с
    };
    let mut части: Vec<&str> = Vec::new();
    for сегмент in собранный.split('/') {
        match сегмент {
            "" | "." => continue,
            ".." => {
                части.pop();
            }
            иное => части.push(иное),
        }
    }
    if части.is_empty() {
        "/".to_string()
    } else {
        let mut итог = String::with_capacity(собранный.len());
        for ч in &части {
            итог.push('/');
            итог.push_str(ч);
        }
        итог
    }
}

/// Удобный способ описать тип записи в выдаче `сп`.
pub fn буква_типа(тип: Тип) -> char {
    match тип {
        Тип::Каталог => 'к',
        Тип::Файл => 'ф',
    }
}
