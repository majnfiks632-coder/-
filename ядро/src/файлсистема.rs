/// Создать ОЗУ-диск, отформатировать его как ДубФС, смонтировать и разложить
/// демонстрационное дерево. Идемпотентна: повторные вызовы возвращают сразу.
pub fn инициализировать() {
    if ИНИЦИАЛИЗИРОВАНА.load(Ordering::Acquire) {
        return;
    }

    crate::println!("[ИНФО] Создание ОЗУ-диска {} блоков по {} Б…", БЛОКОВ_НА_ДИСКЕ, РАЗМЕР_БЛОКА);
    let устр = УСТРОЙСТВО.call_once(|| БлокОЗУ::новое(БЛОКОВ_НА_ДИСКЕ));

    let параметры = ПараметрыСоздания {
        всего_блоков: 0, // 0 = «весь диск»
        всего_inodes: 0, // 0 = «1 inode на ~16 блоков»
        журнал_длина: 32,
        метка: "ДубФС-ОЗУ".to_string(),
        время_создания: 0,
    };

    let mut фс = match ДубФС::создать(устр, параметры) {
        Ok(ф) => ф,
        Err(ошибка) => {
            crate::println!("[ОШИБКА] Не удалось создать ДубФС: {}", ошибка);
            return;
        }
    };

    if let Err(ошибка) = разложить_демо(&mut фс) {
        crate::println!("[ОШИБКА] Не удалось наполнить ДубФС демо-файлами: {}", ошибка);
    }

    match фс.статистика() {
        Ok(с) => crate::println!(
            "[OK]   ДубФС смонтирована: {} блоков, свободно {} блоков, инодов {}/{}",
            с.всего_блоков,
            с.свободных_блоков,
            с.всего_inodes - с.свободных_inodes,
            с.всего_inodes
        ),
        Err(_) => crate::println!("[OK]   ДубФС смонтирована"),
    }

    *СМОНТИРОВАНА.0.lock() = Some(фс);
    ИНИЦИАЛИЗИРОВАНА.store(true, Ordering::Release);
}

fn разложить_демо(фс: &mut ДубФС<'static>) -> Резюме<()> {
    // Каталоги верхнего уровня.
    for каталог in &["/дом", "/система", "/устройства", "/временно"] {
        фс.создать_каталог(каталог, 0)?;
    }

    let сведения =
        "ДубинаОС, версия 0.1.0\n\
         Архитектура: x86_64\n\
         Файловая система: ДубФС (журнал, BLAKE3-контрольные суммы)\n\
         Эта ФС живёт в ОЗУ — после перезагрузки она пересоздаётся.\n";
    фс.создать_файл("/сведения", 0)?;
    фс.записать_файл("/сведения", 0, сведения.as_bytes())?;

    let приветствие =
        "Здравствуй! Ты в каталоге /дом. Команды оболочки:\n\
         сп [путь]  — список (как ls)\n\
         сд путь    — сменить каталог (как cd)\n\
         тут        — текущий каталог (как pwd)\n\
         вывести путь — напечатать содержимое файла (как cat)\n";
    фс.создать_файл("/дом/приветствие", 0)?;
    фс.записать_файл("/дом/приветствие", 0, приветствие.as_bytes())?;

    let задачи =
        "TODO для ДубинаОС:\n\
         * этап 6 — бэкенд компилятора Дубины x86_64\n\
         * этап 7 — стандартная библиотека\n\
         * этап 9 — KASAN-аналог и фаззинг\n\
         * этап 10 — графика (VBE/GOP, окна)\n\
         * этап 13 — сетевой стек\n";
    фс.создать_файл("/дом/задачи", 0)?;
    фс.записать_файл("/дом/задачи", 0, задачи.as_bytes())?;

    let версия_система = "ДубинаОС 0.1.0 (этап 8 закрыт; этапы 6/7/9..15 в работе)\n";
    фс.создать_файл("/система/версия", 0)?;
    фс.записать_файл("/система/версия", 0, версия_система.as_bytes())?;

    let примечание =
        "Каталог /устройства резервируется под виртуальные файлы устройств\n\
         (клавиатура, видео, последовательный порт). Появится в этапе 4.\n";
    фс.создать_файл("/устройства/README", 0)?;
    фс.записать_файл("/устройства/README", 0, примечание.as_bytes())?;

    // Латинский путь — чтобы CI и пользователь могли проверить `cat` без
    // необходимости вводить кириллицу через PS/2 (через sendkey QEMU
    // удобно отправлять только латинские раскладочные коды).
    let readme =
        "DubinaOS in-RAM ДубФС demo file.\n\
         Try: ls /, cd /дом, ls, cat readme.txt, df, mkdir myroom\n\
         The filesystem lives in RAM and resets on reboot.\n";
    фс.создать_файл("/readme.txt", 0)?;
    фс.записать_файл("/readme.txt", 0, readme.as_bytes())?;

    Ok(())
}

/// Готова ли ФС к работе.
pub fn готова() -> bool {
    ИНИЦИАЛИЗИРОВАНА.load(Ordering::Acquire)
}

/// Запись каталога — то, что отдаёт `прочитать_каталог`.
pub struct ЭлементКаталога {
    pub имя: String,
    pub тип: Тип,
    pub размер: u64,
}

/// Прочитать содержимое каталога по абсолютному пути.
pub fn прочитать_каталог(путь: &str) -> Резюме<Vec<ЭлементКаталога>> {
    let mut слот = СМОНТИРОВАНА.0.lock();
    let фс = слот.as_mut().ok_or(ОшибкаФС::Внутренняя("ФС не смонтирована"))?;
    let записи = фс.прочитать_каталог(путь)?;
    let mut итог = Vec::with_capacity(записи.len());
    for (имя, инод, тип) in записи {
        let размер = размер_по_иноду(фс, инод).unwrap_or(0);
        итог.push(ЭлементКаталога { имя, тип, размер });
    }
    Ok(итог)
}

/// Возвращает размер inode (для каталога — суммарный размер записей).
fn размер_по_иноду(_фс: &mut ДубФС<'static>, _инод: u64) -> Резюме<u64> {
    // У ДубФС нет публичного API «размер по номеру inode», но есть
    // прочитать_файл с произвольным смещением. Для отображения это не
    // критично — возвращаем 0, чтобы не делать лишних чтений.
    Ok(0)
}

/// Прочитать содержимое файла целиком (но не больше `максимум` байт).
pub fn прочитать_файл(путь: &str, максимум: usize) -> Резюме<Vec<u8>> {
    let mut слот = СМОНТИРОВАНА.0.lock();
    let фс = слот.as_mut().ok_or(ОшибкаФС::Внутренняя("ФС не смонтирована"))?;
    // Для простоты читаем порциями, пока не получим короткое чтение.
    let mut итог = Vec::new();
    let mut смещение: u64 = 0;
    loop {
        let нужно = (максимум - итог.len()).min(512);
        if нужно == 0 {
            break;
        }
        let порция = фс.прочитать_файл(путь, смещение, нужно)?;
        if порция.is_empty() {
            break;
        }
        смещение += порция.len() as u64;
        итог.extend_from_slice(&порция);
        if порция.len() < нужно {
            break;
        }
    }
    Ok(итог)
}

/// Записать содержимое файла, создав его при необходимости.
pub fn записать_файл(путь: &str, данные: &[u8]) -> Резюме<()> {
    let mut слот = СМОНТИРОВАНА.0.lock();
    let фс = слот.as_mut().ok_or(ОшибкаФС::Внутренняя("ФС не смонтирована"))?;
    if let Err(ошибка) = фс.создать_файл(путь, 0) {
        if !matches!(ошибка, ОшибкаФС::УжеСуществует) {
            return Err(ошибка);
        }
    }
    фс.записать_файл(путь, 0, данные)
}

/// Создать каталог по пути.
pub fn создать_каталог(путь: &str) -> Резюме<()> {
    let mut слот = СМОНТИРОВАНА.0.lock();
    let фс = слот.as_mut().ok_or(ОшибкаФС::Внутренняя("ФС не смонтирована"))?;
    фс.создать_каталог(путь, 0).map(|_| ())
}

/// Удалить файл или пустой каталог.
pub fn удалить(путь: &str) -> Резюме<()> {
    let mut слот = СМОНТИРОВАНА.0.lock();
    let фс = слот.as_mut().ok_or(ОшибкаФС::Внутренняя("ФС не смонтирована"))?;
    фс.удалить(путь)
}

/// Дать снимок статистики ФС.
pub fn статистика() -> Резюме<dubina_fs::Статистика> {
    let mut слот = СМОНТИРОВАНА.0.lock();
    let фс = слот.as_mut().ok_or(ОшибкаФС::Внутренняя("ФС не смонтирована"))?;
    фс.статистика()
}

