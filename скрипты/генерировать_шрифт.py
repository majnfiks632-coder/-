#!/usr/bin/env python3
# ДубинаОС
# Генератор шрифта «Дубина 8×16» из текстового описания.
#
# Каждый глиф описывается 16 строками по 8 символов:
#   '.' — пиксель выключен, любой непробельный символ != '.' — пиксель включён.
#
# Глиф объявляется строкой `ГЛИФ <hex_код>  # необязательный_комментарий`.
# Между глифами должно быть ровно 16 строк рисунка.

import sys, os, pathlib

КАТАЛОГ = pathlib.Path(__file__).resolve().parent.parent
ИСТОЧНИК = КАТАЛОГ / "ядро" / "src" / "арх" / "x86_64" / "шрифт_дубина.txt"
ВЫХОД   = КАТАЛОГ / "ядро" / "src" / "арх" / "x86_64" / "шрифт_дубина.rs"


def разобрать(путь):
    глифы = {}  # код → bytes(16)
    текущий_код = None
    текущие_строки = []
    текущий_коммент = ""
    with путь.open(encoding="utf-8") as ф:
        for номер, строка_сырья in enumerate(ф, 1):
            строка = строка_сырья.rstrip("\n")
            обрезанная = строка.strip()
            if not обрезанная or обрезанная.startswith("//"):
                if обрезанная:
                    continue
                # пустая строка завершает глиф если уже 16 строк
                continue
            if обрезанная.startswith("ГЛИФ"):
                if текущий_код is not None:
                    if len(текущие_строки) != 16:
                        raise SystemExit(
                            f"Глиф {текущий_код:#04x} должен содержать 16 строк, "
                            f"а содержит {len(текущие_строки)}"
                        )
                    глифы[текущий_код] = собрать_глиф(текущие_строки)
                части = обрезанная.split(maxsplit=2)
                if len(части) < 2:
                    raise SystemExit(f"Строка {номер}: ожидается «ГЛИФ <код>»")
                текущий_код = int(части[1], 16)
                текущий_коммент = части[2] if len(части) > 2 else ""
                текущие_строки = []
            else:
                # это пиксельная строка
                pix = обрезанная
                if len(pix) < 8:
                    pix = pix + "." * (8 - len(pix))
                pix = pix[:8]
                текущие_строки.append(pix)
    if текущий_код is not None:
        if len(текущие_строки) != 16:
            raise SystemExit(
                f"Глиф {текущий_код:#04x} должен содержать 16 строк, "
                f"а содержит {len(текущие_строки)}"
            )
        глифы[текущий_код] = собрать_глиф(текущие_строки)
    return глифы


def собрать_глиф(строки):
    байты = bytearray(16)
    for ряд, рисунок in enumerate(строки):
        байт = 0
        for столбец in range(8):
            if столбец < len(рисунок) and рисунок[столбец] != '.':
                байт |= 1 << (7 - столбец)
        байты[ряд] = байт
    return bytes(байты)


def записать(глифы, выход):
    пустой = bytes(16)
    with выход.open("w", encoding="utf-8") as ф:
        ф.write("// ДубинаОС\n")
        ф.write("// Авторские права (C) 2026, Команда ДубинаОС\n")
        ф.write("// Лицензия: GPL-3.0-or-later\n")
        ф.write("//\n")
        ф.write("// Шрифт «Дубина 8×16» — собран автоматически из шрифт_дубина.txt.\n")
        ф.write("// Не редактируйте этот файл вручную; правьте текстовое описание.\n\n")
        ф.write("/// 256 глифов по 16 байт каждый. ASCII-подобный нижний диапазон 0..0x7F\n")
        ф.write("/// и кириллица 0x80..0xC3 + рамки 0xD0..0xDA — наша кодировка ДубКод.\n")
        ф.write("pub static ШРИФТ: [[u8; 16]; 256] = [\n")
        for код in range(256):
            данные = глифы.get(код, пустой)
            пиксели = " ".join(f"0x{b:02X}," for b in данные)
            метка = ""
            ф.write(f"    /* 0x{код:02X} */ [{пиксели}],\n")
        ф.write("];\n")


def главная():
    если_нет_файла = not ИСТОЧНИК.exists()
    if если_нет_файла:
        sys.exit(f"Не найден файл описания шрифта: {ИСТОЧНИК}")
    глифы = разобрать(ИСТОЧНИК)
    записать(глифы, ВЫХОД)
    print(f"Готово: {ВЫХОД} ({len(глифы)} глифов)")


if __name__ == "__main__":
    главная()
