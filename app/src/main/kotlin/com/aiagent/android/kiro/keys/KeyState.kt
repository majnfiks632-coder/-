package com.aiagent.android.kiro.keys

/**
 * Состояние одного ключа в пуле.
 *
 *  - [HEALTHY] — рабочий ключ, его можно отдавать любому потребителю.
 *  - [UNSTABLE] — недавно возвращал ошибки. Может использоваться, но
 *    в последнюю очередь (когда [HEALTHY] заняты или их вообще нет).
 *  - [DEAD] — отвалился окончательно (401/403 от провайдера или серия
 *    transient-ошибок). Перепроверяется фоновым health-check'ом.
 *  - [RESERVE] — явно помечен пользователем как "запасной на чёрный день".
 *    Никогда не выдаётся саб-агентам, выдаётся только когда все
 *    [HEALTHY] и [UNSTABLE] заняты или мертвы.
 *
 * Состояние [RESERVE] не пересекается с тремя другими — оно конечное
 * до тех пор, пока пользователь сам не снимет флажок.
 */
enum class KeyState {
    HEALTHY,
    UNSTABLE,
    DEAD,
    RESERVE,
}
