// Лексер языка «Дубина».
//
// Особенности:
//   - входной поток в UTF-8;
//   - идентификаторы могут содержать любые буквы Юникода (XID_Start / XID_Continue
//     приближённо: основной проверкой `char::is_alphabetic`);
//   - комментарии начинаются с `#` и идут до конца строки;
//   - блоки открываются `:`, закрываются `;` на отдельной строке;
//   - русские ключевые слова распознаются по таблице.

use crate::ошибки::{Ошибка, Положение};

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ВидТокена {
    // Литералы
    Идентификатор(String),
    ЦелоеЧисло(u64),
    Десятичное(String),         // храним как строку, чтобы не терять точность
    Дробь(u64, u64),            // числитель / знаменатель
    Строка(String),
    Логическое(bool),
    Пусто,

    // Ключевые слова
    Класс,
    Функция,
    Пусть,
    Изм,
    Константа,
    Если,
    Иначе,
    Пока,
    Цикл,
    Для,
    В,
    Прервать,
    Продолжить,
    Вернуть,
    Структура,
    Перечисление,
    Черта,
    Реализация,
    Использовать,
    Модуль,
    Публичная,
    Приватная,
    Сам,
    Новый,
    Как,
    Где,
    И,
    Или,
    Не,
    Совпадение,
    Выбор,
    Асинх,
    Ждать,

    // Знаки препинания и операторы
    ДвоеточиеОткрытие,    // ":" в конце строки — открывает блок
    ТочкаЗапятой,         // ";" — закрывает блок
    Запятая,
    Точка,
    КругСлева,
    КругСправа,
    КвадрСлева,
    КвадрСправа,
    ФигурСлева,
    ФигурСправа,
    Стрелка,              // "->"
    Вопрос,               // "?"
    Двойной_Вопрос,       // "??"

    // Арифметические
    Плюс,
    Минус,
    Умножить,
    Делить,
    Остаток,
    Степень,              // **

    // Сравнение
    Равно,                // =
    ДваРавно,             // ==
    НеРавно,              // !=
    Меньше,
    Больше,
    МеньшеРавно,
    БольшеРавно,

    // Составное присваивание
    ПлюсРавно,
    МинусРавно,
    УмнРавно,
    ДелРавно,
    ОстРавно,

    // Особое
    КонецФайла,
}

#[derive(Debug, Clone)]
pub struct Токен {
    pub вид: ВидТокена,
    pub положение: Положение,
}

#[derive(Clone)]
pub struct Лексер<'и> {
    исходник: &'и str,
    байт_позиция: usize,
    строка: u32,
    столбец: u32,
}

impl<'и> Лексер<'и> {
    pub fn новый(исходник: &'и str) -> Self {
        Self { исходник, байт_позиция: 0, строка: 1, столбец: 1 }
    }

    fn положение(&self) -> Положение {
        Положение { строка: self.строка, столбец: self.столбец }
    }

    fn заглянуть(&self) -> Option<char> {
        self.исходник[self.байт_позиция..].chars().next()
    }

    fn заглянуть2(&self) -> Option<char> {
        let mut итератор = self.исходник[self.байт_позиция..].chars();
        итератор.next();
        итератор.next()
    }

    fn принять(&mut self) -> Option<char> {
        let c = self.заглянуть()?;
        let длина = c.len_utf8();
        self.байт_позиция += длина;
        if c == '\n' {
            self.строка += 1;
            self.столбец = 1;
        } else {
            self.столбец += 1;
        }
        Some(c)
    }

    fn пропустить_пробелы_и_комментарии(&mut self) {
        loop {
            match self.заглянуть() {
                Some(c) if c.is_whitespace() => {
                    self.принять();
                }
                Some('#') => {
                    while let Some(c) = self.принять() {
                        if c == '\n' {
                            break;
                        }
                    }
                }
                _ => break,
            }
        }
    }

    pub fn следующий_токен(&mut self) -> Result<Токен, Ошибка> {
        self.пропустить_пробелы_и_комментарии();
        let начало = self.положение();
        let Some(c) = self.заглянуть() else {
            return Ok(Токен { вид: ВидТокена::КонецФайла, положение: начало });
        };

        // Идентификатор / ключевое слово
        if c.is_alphabetic() || c == '_' {
            return self.читать_идентификатор(начало);
        }

        // Число
        if c.is_ascii_digit() {
            return self.читать_число(начало);
        }

        // Строка
        if c == '"' {
            return self.читать_строку(начало);
        }

        // Знаки препинания / операторы
        self.читать_оператор(начало)
    }

    fn читать_идентификатор(&mut self, начало: Положение) -> Result<Токен, Ошибка> {
        let байт_от = self.байт_позиция;
        while let Some(c) = self.заглянуть() {
            if c.is_alphanumeric() || c == '_' {
                self.принять();
            } else {
                break;
            }
        }
        let текст = &self.исходник[байт_от..self.байт_позиция];

        let вид = match текст {
            "Класс" => ВидТокена::Класс,
            "функция" => ВидТокена::Функция,
            "пусть" => ВидТокена::Пусть,
            "изм" => ВидТокена::Изм,
            "константа" => ВидТокена::Константа,
            "Если" | "если" => ВидТокена::Если,
            "иначе" => ВидТокена::Иначе,
            "пока" | "Пока" => ВидТокена::Пока,
            "цикл" => ВидТокена::Цикл,
            "для" => ВидТокена::Для,
            "в" => ВидТокена::В,
            "прервать" => ВидТокена::Прервать,
            "продолжить" => ВидТокена::Продолжить,
            "вернуть" => ВидТокена::Вернуть,
            "структура" => ВидТокена::Структура,
            "перечисление" => ВидТокена::Перечисление,
            "черта" => ВидТокена::Черта,
            "реализация" => ВидТокена::Реализация,
            "использовать" => ВидТокена::Использовать,
            "модуль" => ВидТокена::Модуль,
            "публичная" | "публ" => ВидТокена::Публичная,
            "приватная" => ВидТокена::Приватная,
            "сам" => ВидТокена::Сам,
            "новый" => ВидТокена::Новый,
            "как" => ВидТокена::Как,
            "где" => ВидТокена::Где,
            "и" => ВидТокена::И,
            "или" => ВидТокена::Или,
            "не" => ВидТокена::Не,
            "совпадение" => ВидТокена::Совпадение,
            "выбор" => ВидТокена::Выбор,
            "асинх" => ВидТокена::Асинх,
            "ждать" => ВидТокена::Ждать,
            "правда" | "да" => ВидТокена::Логическое(true),
            "ложь" | "нет" => ВидТокена::Логическое(false),
            "пусто" => ВидТокена::Пусто,
            _ => ВидТокена::Идентификатор(текст.to_string()),
        };

        Ok(Токен { вид, положение: начало })
    }

    fn читать_число(&mut self, начало: Положение) -> Result<Токен, Ошибка> {
        let байт_от = self.байт_позиция;
        // Поддержка 0x..., 0b..., 0o...
        let первая = self.принять().unwrap();
        if первая == '0' {
            if let Some(c2) = self.заглянуть() {
                match c2 {
                    'x' | 'X' => return self.читать_число_основания(начало, 16),
                    'b' | 'B' => return self.читать_число_основания(начало, 2),
                    'o' | 'O' => return self.читать_число_основания(начало, 8),
                    _ => {}
                }
            }
        }
        // Десятичное
        while let Some(c) = self.заглянуть() {
            if c.is_ascii_digit() || c == '_' {
                self.принять();
            } else {
                break;
            }
        }

        // Если дальше точка и цифра — это десятичное
        if self.заглянуть() == Some('.') && self.заглянуть2().map_or(false, |c| c.is_ascii_digit()) {
            self.принять(); // точка
            while let Some(c) = self.заглянуть() {
                if c.is_ascii_digit() || c == '_' {
                    self.принять();
                } else {
                    break;
                }
            }
            // Может быть e/E экспонента
            if matches!(self.заглянуть(), Some('e') | Some('E')) {
                self.принять();
                if matches!(self.заглянуть(), Some('+') | Some('-')) {
                    self.принять();
                }
                while let Some(c) = self.заглянуть() {
                    if c.is_ascii_digit() {
                        self.принять();
                    } else {
                        break;
                    }
                }
            }
            let текст = &self.исходник[байт_от..self.байт_позиция];
            return Ok(Токен { вид: ВидТокена::Десятичное(текст.to_string()), положение: начало });
        }

        // Если дальше "/" и цифра — это дробь
        if self.заглянуть() == Some('/') && self.заглянуть2().map_or(false, |c| c.is_ascii_digit()) {
            let числитель: u64 = self.исходник[байт_от..self.байт_позиция]
                .replace('_', "")
                .parse()
                .map_err(|_| Ошибка::новая(начало, "не могу разобрать числитель"))?;
            self.принять(); // "/"
            let знам_от = self.байт_позиция;
            while let Some(c) = self.заглянуть() {
                if c.is_ascii_digit() || c == '_' {
                    self.принять();
                } else {
                    break;
                }
            }
            let знаменатель: u64 = self.исходник[знам_от..self.байт_позиция]
                .replace('_', "")
                .parse()
                .map_err(|_| Ошибка::новая(начало, "не могу разобрать знаменатель"))?;
            return Ok(Токен { вид: ВидТокена::Дробь(числитель, знаменатель), положение: начало });
        }

        let текст = &self.исходник[байт_от..self.байт_позиция];
        let значение: u64 = текст
            .replace('_', "")
            .parse()
            .map_err(|_| Ошибка::новая(начало, "не могу разобрать число"))?;
        Ok(Токен { вид: ВидТокена::ЦелоеЧисло(значение), положение: начало })
    }

    fn читать_число_основания(&mut self, начало: Положение, основа: u32) -> Result<Токен, Ошибка> {
        self.принять(); // x/b/o
        let от = self.байт_позиция;
        while let Some(c) = self.заглянуть() {
            if c.is_digit(основа) || c == '_' {
                self.принять();
            } else {
                break;
            }
        }
        let текст: String = self.исходник[от..self.байт_позиция].replace('_', "");
        let значение = u64::from_str_radix(&текст, основа)
            .map_err(|_| Ошибка::новая(начало, format!("не могу разобрать число в основе {}", основа)))?;
        Ok(Токен { вид: ВидТокена::ЦелоеЧисло(значение), положение: начало })
    }

    fn читать_строку(&mut self, начало: Положение) -> Result<Токен, Ошибка> {
        self.принять(); // "
        let mut текст = String::new();
        loop {
            match self.принять() {
                None => return Err(Ошибка::новая(начало, "незакрытая строковая литерала")),
                Some('"') => break,
                Some('\\') => match self.принять() {
                    Some('n') => текст.push('\n'),
                    Some('t') => текст.push('\t'),
                    Some('r') => текст.push('\r'),
                    Some('\\') => текст.push('\\'),
                    Some('"') => текст.push('"'),
                    Some(c) => return Err(Ошибка::новая(начало, format!("неизвестная escape-последовательность \\{}", c))),
                    None => return Err(Ошибка::новая(начало, "оборванная escape-последовательность")),
                },
                Some(c) => текст.push(c),
            }
        }
        Ok(Токен { вид: ВидТокена::Строка(текст), положение: начало })
    }

    fn читать_оператор(&mut self, начало: Положение) -> Result<Токен, Ошибка> {
        let c = self.принять().unwrap();
        let вид = match c {
            ':' => ВидТокена::ДвоеточиеОткрытие,
            ';' => ВидТокена::ТочкаЗапятой,
            ',' => ВидТокена::Запятая,
            '.' => ВидТокена::Точка,
            '(' => ВидТокена::КругСлева,
            ')' => ВидТокена::КругСправа,
            '[' => ВидТокена::КвадрСлева,
            ']' => ВидТокена::КвадрСправа,
            '{' => ВидТокена::ФигурСлева,
            '}' => ВидТокена::ФигурСправа,
            '+' => {
                if self.заглянуть() == Some('=') { self.принять(); ВидТокена::ПлюсРавно } else { ВидТокена::Плюс }
            }
            '-' => {
                if self.заглянуть() == Some('=') { self.принять(); ВидТокена::МинусРавно }
                else if self.заглянуть() == Some('>') { self.принять(); ВидТокена::Стрелка }
                else { ВидТокена::Минус }
            }
            '*' => {
                if self.заглянуть() == Some('*') { self.принять(); ВидТокена::Степень }
                else if self.заглянуть() == Some('=') { self.принять(); ВидТокена::УмнРавно }
                else { ВидТокена::Умножить }
            }
            '/' => {
                if self.заглянуть() == Some('=') { self.принять(); ВидТокена::ДелРавно }
                else { ВидТокена::Делить }
            }
            '%' => {
                if self.заглянуть() == Some('=') { self.принять(); ВидТокена::ОстРавно }
                else { ВидТокена::Остаток }
            }
            '=' => {
                if self.заглянуть() == Some('=') { self.принять(); ВидТокена::ДваРавно }
                else { ВидТокена::Равно }
            }
            '!' => {
                if self.заглянуть() == Some('=') { self.принять(); ВидТокена::НеРавно }
                else { return Err(Ошибка::новая(начало, "ожидался '=' после '!'")); }
            }
            '<' => {
                if self.заглянуть() == Some('=') { self.принять(); ВидТокена::МеньшеРавно }
                else { ВидТокена::Меньше }
            }
            '>' => {
                if self.заглянуть() == Some('=') { self.принять(); ВидТокена::БольшеРавно }
                else { ВидТокена::Больше }
            }
            '?' => {
                if self.заглянуть() == Some('?') { self.принять(); ВидТокена::Двойной_Вопрос }
                else { ВидТокена::Вопрос }
            }
            _ => return Err(Ошибка::новая(начало, format!("неожиданный символ '{}'", c))),
        };
        Ok(Токен { вид, положение: начало })
    }
}

#[cfg(test)]
mod тесты {
    use super::*;

    fn собрать(исходник: &str) -> Vec<ВидТокена> {
        let mut л = Лексер::новый(исходник);
        let mut р = Vec::new();
        loop {
            let т = л.следующий_токен().unwrap();
            if matches!(т.вид, ВидТокена::КонецФайла) {
                break;
            }
            р.push(т.вид);
        }
        р
    }

    #[test]
    fn простые_токены() {
        let т = собрать("пусть имя = \"Мир\"");
        assert!(matches!(т[0], ВидТокена::Пусть));
        assert!(matches!(т[1], ВидТокена::Идентификатор(ref с) if с == "имя"));
        assert!(matches!(т[2], ВидТокена::Равно));
        assert!(matches!(т[3], ВидТокена::Строка(ref с) if с == "Мир"));
    }

    #[test]
    fn ключевые_слова() {
        let т = собрать("Если правда: иначе: ;");
        assert!(matches!(т[0], ВидТокена::Если));
        assert!(matches!(т[1], ВидТокена::Логическое(true)));
        assert!(matches!(т[2], ВидТокена::ДвоеточиеОткрытие));
        assert!(matches!(т[3], ВидТокена::Иначе));
    }

    #[test]
    fn числа() {
        let т = собрать("0 42 0xFF 0b1010 1/3 3.14");
        assert!(matches!(т[0], ВидТокена::ЦелоеЧисло(0)));
        assert!(matches!(т[1], ВидТокена::ЦелоеЧисло(42)));
        assert!(matches!(т[2], ВидТокена::ЦелоеЧисло(0xFF)));
        assert!(matches!(т[3], ВидТокена::ЦелоеЧисло(0b1010)));
        assert!(matches!(т[4], ВидТокена::Дробь(1, 3)));
        assert!(matches!(т[5], ВидТокена::Десятичное(ref с) if с == "3.14"));
    }

    #[test]
    fn комментарии_игнорируются() {
        let т = собрать("# это комментарий\nпусть x = 1");
        assert!(matches!(т[0], ВидТокена::Пусть));
        assert!(matches!(т[1], ВидТокена::Идентификатор(ref с) if с == "x"));
    }
}
