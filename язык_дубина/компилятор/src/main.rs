//   - лексер с поддержкой UTF-8 и русских ключевых слов;
//   - простой парсер, способный построить AST для программы Hello World;
//   - команда `дубина проверить <файл.дуб>` — проверяет, что файл синтаксически корректен.
//
// Полный конвейер (типизация, проверка заимствований, кодоген) — в следующих этапах.

#![allow(uncommon_codepoints, mixed_script_confusables, confusable_idents, non_camel_case_types, non_snake_case)]

#[path = "лексер.rs"]
mod лексер;
#[path = "аст.rs"]
mod аст;
#[path = "парсер.rs"]
mod парсер;
#[path = "ошибки.rs"]
mod ошибки;
#[path = "резолвер.rs"]
mod резолвер;

use std::env;
use std::fs;
use std::process::ExitCode;

fn использование() {
    eprintln!("Компилятор «Дубина» v0.1.0");
    eprintln!();
    eprintln!("Использование:");
    eprintln!("    дубина версия");
    eprintln!("    дубина токены <файл.дуб>          # вывести лексические токены");
    eprintln!("    дубина проверить <файл.дуб>      # проверить синтаксис и построить AST");
    eprintln!("    дубина проанализировать <файл.дуб> # резолвер имён (этап 6)");
}

fn main() -> ExitCode {
    let аргументы: Vec<String> = env::args().collect();
    if аргументы.len() < 2 {
        использование();
        return ExitCode::from(2);
    }

    match аргументы[1].as_str() {
        "версия" | "--версия" | "-V" => {
            println!("дубина {} (этап «Фундамент»)", env!("CARGO_PKG_VERSION"));
            ExitCode::SUCCESS
        }
        "токены" => {
            if аргументы.len() < 3 {
                использование();
                return ExitCode::from(2);
            }
            команда_токены(&аргументы[2])
        }
        "проверить" => {
            if аргументы.len() < 3 {
                использование();
                return ExitCode::from(2);
            }
            команда_проверить(&аргументы[2])
        }
        "проанализировать" => {
            if аргументы.len() < 3 {
                использование();
                return ExitCode::from(2);
            }
            команда_проанализировать(&аргументы[2])
        }
        неизвестно => {
            eprintln!("Неизвестная подкоманда: {}", неизвестно);
            использование();
            ExitCode::from(2)
        }
    }
}

fn команда_токены(путь: &str) -> ExitCode {
    let исходник = match fs::read_to_string(путь) {
        Ok(s) => s,
        Err(e) => {
            eprintln!("Не могу прочитать {}: {}", путь, e);
            return ExitCode::from(1);
        }
    };
    let mut лекс = лексер::Лексер::новый(&исходник);
    loop {
        match лекс.следующий_токен() {
            Ok(т) => {
                println!("{:?}", т);
                if matches!(т.вид, лексер::ВидТокена::КонецФайла) {
                    break;
                }
            }
            Err(е) => {
                eprintln!("Ошибка лексера: {}", е);
                return ExitCode::from(1);
            }
        }
    }
    ExitCode::SUCCESS
}

fn команда_проверить(путь: &str) -> ExitCode {
    let исходник = match fs::read_to_string(путь) {
        Ok(s) => s,
        Err(e) => {
            eprintln!("Не могу прочитать {}: {}", путь, e);
            return ExitCode::from(1);
        }
    };
    let mut п = парсер::Парсер::новый(&исходник);
    match п.разобрать_программу() {
        Ok(программа) => {
            println!("OK: программа синтаксически корректна.");
            println!("В программе {} объявлений верхнего уровня.", программа.объявления.len());
            for о in &программа.объявления {
                println!("  - {}", описание_объявления(о));
            }
            ExitCode::SUCCESS
        }
        Err(е) => {
            eprintln!("Ошибка: {}", е);
            ExitCode::from(1)
        }
    }
}

fn команда_проанализировать(путь: &str) -> ExitCode {
    let исходник = match fs::read_to_string(путь) {
        Ok(s) => s,
        Err(e) => {
            eprintln!("Не могу прочитать {}: {}", путь, e);
            return ExitCode::from(1);
        }
    };
    let mut п = парсер::Парсер::новый(&исходник);
    let программа = match п.разобрать_программу() {
        Ok(п) => п,
        Err(е) => {
            eprintln!("Ошибка парсера: {}", е);
            return ExitCode::from(1);
        }
    };
    match резолвер::проанализировать(&программа) {
        Ok(карта) => {
            println!("OK: имена резолвятся.");
            println!(
                "  верхнеуровневых функций: {}, классов: {}, привязанных идентификаторов: {}",
                карта.функции().len(),
                карта.классы().len(),
                карта.количество_идентификаторов(),
            );
            ExitCode::SUCCESS
        }
        Err(ошибки) => {
            for е in &ошибки {
                eprintln!("Ошибка резолва: {}", е);
            }
            ExitCode::from(1)
        }
    }
}

fn описание_объявления(о: &аст::ОбъявлениеВерхнегоУровня) -> String {
    match о {
        аст::ОбъявлениеВерхнегоУровня::Класс(к) => format!("Класс {}", к.имя),
        аст::ОбъявлениеВерхнегоУровня::Функция(ф) => {
            format!("функция {} ({} парам., {} возвр.)", ф.имя, ф.параметры.len(), ф.возвращаемые.len())
        }
        аст::ОбъявлениеВерхнегоУровня::Использование(и) => format!("использовать {}", и.путь.join(".")),
        аст::ОбъявлениеВерхнегоУровня::Выражение(_) => "выражение верхнего уровня".to_string(),
    }
}
