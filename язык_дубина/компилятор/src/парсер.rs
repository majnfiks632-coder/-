//
// На этом этапе («Фундамент») реализован минимальный набор для разбора программ
// уровня Hello World: использование, классы, функции с двумя списками скобок (параметры
// и возвращаемые), выражения с базовой ассоциативностью, условные операторы, циклы.

use crate::аст::*;
use crate::лексер::{Лексер, Токен, ВидТокена};
use crate::ошибки::{Ошибка, Положение};

pub struct Парсер<'и> {
    лексер: Лексер<'и>,
    текущий: Токен,
}

impl<'и> Парсер<'и> {
    pub fn новый(исходник: &'и str) -> Self {
        let mut лексер = Лексер::новый(исходник);
        let текущий = лексер.следующий_токен().expect("первый токен должен быть валиден");
        Self { лексер, текущий }
    }

    fn положение(&self) -> Положение {
        self.текущий.положение
    }

    fn вперёд(&mut self) -> Result<Токен, Ошибка> {
        let следующий = self.лексер.следующий_токен()?;
        Ok(core::mem::replace(&mut self.текущий, следующий))
    }

    fn ожидать(&mut self, ожидаемый: &ВидТокена) -> Result<Токен, Ошибка> {
        if std::mem::discriminant(&self.текущий.вид) == std::mem::discriminant(ожидаемый) {
            self.вперёд()
        } else {
            Err(Ошибка::новая(
                self.положение(),
                format!("ожидался {:?}, а встречен {:?}", ожидаемый, self.текущий.вид),
            ))
        }
    }

    fn проверить(&self, вид: &ВидТокена) -> bool {
        std::mem::discriminant(&self.текущий.вид) == std::mem::discriminant(вид)
    }

    pub fn разобрать_программу(&mut self) -> Result<Программа, Ошибка> {
        let mut объявления = Vec::new();
        while !matches!(self.текущий.вид, ВидТокена::КонецФайла) {
            объявления.push(self.разобрать_объявление_верхнего_уровня()?);
        }
        Ok(Программа { объявления })
    }

    fn разобрать_объявление_верхнего_уровня(&mut self) -> Result<ОбъявлениеВерхнегоУровня, Ошибка> {
        match &self.текущий.вид {
            ВидТокена::Использовать => self.разобрать_использование(),
            ВидТокена::Класс => self.разобрать_класс(),
            ВидТокена::Идентификатор(_) => {
                // Может быть объявлением функции (имя «(» ... «)» «(» ... «)» «:» ...)
                // или выражением (вызов, присваивание...). Различаем по lookahead на 2 токена.
                if self.это_объявление_функции()? {
                    let ф = self.разобрать_функцию()?;
                    Ok(ОбъявлениеВерхнегоУровня::Функция(ф))
                } else {
                    let в = self.разобрать_выражение()?;
                    Ok(ОбъявлениеВерхнегоУровня::Выражение(в))
                }
            }
            _ => {
                let в = self.разобрать_выражение()?;
                Ok(ОбъявлениеВерхнегоУровня::Выражение(в))
            }
        }
    }

    /// Эвристика: текущий токен — идентификатор. Заглядываем на нужное число токенов
    /// вперёд через клон лексера, чтобы определить, объявление это функции или
    /// просто выражение/вызов на верхнем уровне.
    ///
    /// Объявление функции имеет вид `имя(параметры)(возвращаемые):`. Признаком,
    /// который однозначно отличает определение от вызова, является вторая пара
    /// круглых скобок (после которой обязательно `:`).
    fn это_объявление_функции(&self) -> Result<bool, Ошибка> {
        let mut клон = self.лексер.clone();
        // Шаг 1: должна быть круглая открывающая скобка после имени.
        let т1 = клон.следующий_токен()?;
        if !matches!(т1.вид, ВидТокена::КругСлева) {
            return Ok(false);
        }
        // Шаг 2: пропускаем содержимое первых скобок.
        let mut уровень: u32 = 1;
        loop {
            let т = клон.следующий_токен()?;
            match т.вид {
                ВидТокена::КругСлева => уровень += 1,
                ВидТокена::КругСправа => {
                    уровень -= 1;
                    if уровень == 0 {
                        break;
                    }
                }
                ВидТокена::КонецФайла => return Ok(false),
                _ => {}
            }
        }
        // Шаг 3: после `)` должна быть ещё одна `(` для возвращаемых значений.
        let следующий = клон.следующий_токен()?;
        Ok(matches!(следующий.вид, ВидТокена::КругСлева))
    }

    fn разобрать_использование(&mut self) -> Result<ОбъявлениеВерхнегоУровня, Ошибка> {
        let поз = self.положение();
        self.ожидать(&ВидТокена::Использовать)?;
        let mut путь = Vec::new();
        let имя = self.ожидать_идентификатор()?;
        путь.push(имя);
        while self.проверить(&ВидТокена::Точка) {
            self.вперёд()?;
            путь.push(self.ожидать_идентификатор()?);
        }
        Ok(ОбъявлениеВерхнегоУровня::Использование(Использование { путь, положение: поз }))
    }

    fn ожидать_идентификатор(&mut self) -> Result<String, Ошибка> {
        match self.вперёд()?.вид {
            ВидТокена::Идентификатор(имя) => Ok(имя),
            иное => Err(Ошибка::новая(
                self.положение(),
                format!("ожидался идентификатор, а встречен {:?}", иное),
            )),
        }
    }

    fn разобрать_класс(&mut self) -> Result<ОбъявлениеВерхнегоУровня, Ошибка> {
        let поз = self.положение();
        self.ожидать(&ВидТокена::Класс)?;
        // Синтаксис: Класс:Имя:
        self.ожидать(&ВидТокена::ДвоеточиеОткрытие)?;
        let имя = self.ожидать_идентификатор()?;
        self.ожидать(&ВидТокена::ДвоеточиеОткрытие)?;
        let mut члены = Vec::new();
        while !self.проверить(&ВидТокена::ТочкаЗапятой) {
            if matches!(self.текущий.вид, ВидТокена::КонецФайла) {
                return Err(Ошибка::новая(self.положение(), "незакрытый класс"));
            }
            // Внутри класса — только функции (методы).
            let ф = self.разобрать_функцию()?;
            члены.push(ф);
        }
        self.ожидать(&ВидТокена::ТочкаЗапятой)?;
        Ok(ОбъявлениеВерхнегоУровня::Класс(ОбъявлениеКласса {
            имя,
            члены,
            положение: поз,
        }))
    }

    /// Синтаксис функции: `имя(параметры)(возвращаемые): тело ;`
    fn разобрать_функцию(&mut self) -> Result<ОбъявлениеФункции, Ошибка> {
        let поз = self.положение();
        let имя = self.ожидать_идентификатор()?;
        self.ожидать(&ВидТокена::КругСлева)?;
        let параметры = self.разобрать_параметры()?;
        self.ожидать(&ВидТокена::КругСправа)?;
        self.ожидать(&ВидТокена::КругСлева)?;
        let возвращаемые = self.разобрать_параметры()?;
        self.ожидать(&ВидТокена::КругСправа)?;
        self.ожидать(&ВидТокена::ДвоеточиеОткрытие)?;

        let mut тело = Vec::new();
        while !self.проверить(&ВидТокена::ТочкаЗапятой) {
            if matches!(self.текущий.вид, ВидТокена::КонецФайла) {
                return Err(Ошибка::новая(self.положение(), "незакрытая функция"));
            }
            тело.push(self.разобрать_утверждение()?);
        }
        self.ожидать(&ВидТокена::ТочкаЗапятой)?;

        Ok(ОбъявлениеФункции { имя, параметры, возвращаемые, тело, положение: поз })
    }

    fn разобрать_параметры(&mut self) -> Result<Vec<Параметр>, Ошибка> {
        let mut список = Vec::new();
        if self.проверить(&ВидТокена::КругСправа) {
            return Ok(список);
        }
        loop {
            список.push(self.разобрать_параметр()?);
            if self.проверить(&ВидТокена::Запятая) {
                self.вперёд()?;
            } else {
                break;
            }
        }
        Ok(список)
    }

    fn разобрать_параметр(&mut self) -> Result<Параметр, Ошибка> {
        let поз = self.положение();
        // Синтаксис: имя [двоеточие тип] -- НО двоеточие открывает блок, поэтому
        // тип идёт ДО имени (как ты предложила: `Строка имя`).
        // Если первый токен — идентификатор и второй — тоже идентификатор, считаем
        // первый типом.
        let первый = self.ожидать_идентификатор()?;
        if matches!(self.текущий.вид, ВидТокена::Идентификатор(_)) {
            let имя = self.ожидать_идентификатор()?;
            return Ok(Параметр { имя, тип: Some(первый), положение: поз });
        }
        Ok(Параметр { имя: первый, тип: None, положение: поз })
    }

    /// Утверждение в теле функции: присваивание, вызов, if/while/for/return.
    fn разобрать_утверждение(&mut self) -> Result<Выражение, Ошибка> {
        match &self.текущий.вид {
            ВидТокена::Если => self.разобрать_если(),
            ВидТокена::Пока => self.разобрать_пока(),
            ВидТокена::Цикл => self.разобрать_цикл(),
            ВидТокена::Вернуть => self.разобрать_вернуть(),
            ВидТокена::Прервать => {
                let поз = self.положение();
                self.вперёд()?;
                Ok(Выражение::Прервать(поз))
            }
            ВидТокена::Продолжить => {
                let поз = self.положение();
                self.вперёд()?;
                Ok(Выражение::Продолжить(поз))
            }
            _ => self.разобрать_выражение(),
        }
    }

    fn разобрать_если(&mut self) -> Result<Выражение, Ошибка> {
        let поз = self.положение();
        self.ожидать(&ВидТокена::Если)?;
        let условие = Box::new(self.разобрать_выражение()?);
        self.ожидать(&ВидТокена::ДвоеточиеОткрытие)?;
        let тогда = self.разобрать_тело_до_иначе_или_конца()?;

        let mut иначе = Vec::new();
        if self.проверить(&ВидТокена::Иначе) {
            self.вперёд()?;
            // `иначе Если ...` — вложенный if
            if self.проверить(&ВидТокена::Если) {
                иначе.push(self.разобрать_если()?);
                return Ok(Выражение::Если { условие, тогда, иначе, положение: поз });
            }
            self.ожидать(&ВидТокена::ДвоеточиеОткрытие)?;
            while !self.проверить(&ВидТокена::ТочкаЗапятой) {
                иначе.push(self.разобрать_утверждение()?);
            }
            self.ожидать(&ВидТокена::ТочкаЗапятой)?;
        }

        Ok(Выражение::Если { условие, тогда, иначе, положение: поз })
    }

    fn разобрать_тело_до_иначе_или_конца(&mut self) -> Result<Vec<Выражение>, Ошибка> {
        let mut тело = Vec::new();
        loop {
            if self.проверить(&ВидТокена::ТочкаЗапятой) {
                self.вперёд()?;
                return Ok(тело);
            }
            if self.проверить(&ВидТокена::Иначе) {
                return Ok(тело);
            }
            if matches!(self.текущий.вид, ВидТокена::КонецФайла) {
                return Err(Ошибка::новая(self.положение(), "незакрытый блок Если"));
            }
            тело.push(self.разобрать_утверждение()?);
        }
    }

    fn разобрать_пока(&mut self) -> Result<Выражение, Ошибка> {
        let поз = self.положение();
        self.ожидать(&ВидТокена::Пока)?;
        let условие = Box::new(self.разобрать_выражение()?);
        self.ожидать(&ВидТокена::ДвоеточиеОткрытие)?;
        let mut тело = Vec::new();
        while !self.проверить(&ВидТокена::ТочкаЗапятой) {
            тело.push(self.разобрать_утверждение()?);
        }
        self.ожидать(&ВидТокена::ТочкаЗапятой)?;
        Ok(Выражение::Пока { условие, тело, положение: поз })
    }

    fn разобрать_цикл(&mut self) -> Result<Выражение, Ошибка> {
        let поз = self.положение();
        self.ожидать(&ВидТокена::Цикл)?;
        let mut переменная = None;
        let mut диапазон = None;
        if matches!(self.текущий.вид, ВидТокена::Идентификатор(_)) {
            let имя = self.ожидать_идентификатор()?;
            переменная = Some(имя);
            self.ожидать(&ВидТокена::В)?;
            диапазон = Some(Box::new(self.разобрать_выражение()?));
        }
        self.ожидать(&ВидТокена::ДвоеточиеОткрытие)?;
        let mut тело = Vec::new();
        while !self.проверить(&ВидТокена::ТочкаЗапятой) {
            тело.push(self.разобрать_утверждение()?);
        }
        self.ожидать(&ВидТокена::ТочкаЗапятой)?;
        Ok(Выражение::Цикл { переменная, диапазон, тело, положение: поз })
    }

    fn разобрать_вернуть(&mut self) -> Result<Выражение, Ошибка> {
        let поз = self.положение();
        self.ожидать(&ВидТокена::Вернуть)?;
        let mut значения = Vec::new();
        if !matches!(self.текущий.вид, ВидТокена::ТочкаЗапятой)
            && !matches!(self.текущий.вид, ВидТокена::КонецФайла)
        {
            значения.push(self.разобрать_выражение()?);
            while self.проверить(&ВидТокена::Запятая) {
                self.вперёд()?;
                значения.push(self.разобрать_выражение()?);
            }
        }
        Ok(Выражение::Вернуть { значения, положение: поз })
    }

    /// Уровень присваивания (правая ассоциативность).
    pub fn разобрать_выражение(&mut self) -> Result<Выражение, Ошибка> {
        let левый = self.разобрать_или()?;
        if self.проверить(&ВидТокена::Равно) {
            let поз = self.положение();
            self.вперёд()?;
            let правый = self.разобрать_выражение()?;
            return Ok(Выражение::Присваивание {
                цель: Box::new(левый),
                значение: Box::new(правый),
                положение: поз,
            });
        }
        Ok(левый)
    }

    fn разобрать_или(&mut self) -> Result<Выражение, Ошибка> {
        let mut левый = self.разобрать_и()?;
        while self.проверить(&ВидТокена::Или) {
            let поз = self.положение();
            self.вперёд()?;
            let правый = self.разобрать_и()?;
            левый = Выражение::Бинарный {
                операция: БинарнаяОперация::Или,
                левый: Box::new(левый),
                правый: Box::new(правый),
                положение: поз,
            };
        }
        Ok(левый)
    }

    fn разобрать_и(&mut self) -> Result<Выражение, Ошибка> {
        let mut левый = self.разобрать_сравнение()?;
        while self.проверить(&ВидТокена::И) {
            let поз = self.положение();
            self.вперёд()?;
            let правый = self.разобрать_сравнение()?;
            левый = Выражение::Бинарный {
                операция: БинарнаяОперация::И,
                левый: Box::new(левый),
                правый: Box::new(правый),
                положение: поз,
            };
        }
        Ok(левый)
    }

    fn разобрать_сравнение(&mut self) -> Result<Выражение, Ошибка> {
        let левый = self.разобрать_слагаемое()?;
        let операция = match &self.текущий.вид {
            ВидТокена::ДваРавно => Some(БинарнаяОперация::Равно),
            ВидТокена::НеРавно => Some(БинарнаяОперация::НеРавно),
            ВидТокена::Меньше => Some(БинарнаяОперация::Меньше),
            ВидТокена::Больше => Some(БинарнаяОперация::Больше),
            ВидТокена::МеньшеРавно => Some(БинарнаяОперация::МеньшеРавно),
            ВидТокена::БольшеРавно => Some(БинарнаяОперация::БольшеРавно),
            _ => None,
        };
        if let Some(оп) = операция {
            let поз = self.положение();
            self.вперёд()?;
            let правый = self.разобрать_слагаемое()?;
            return Ok(Выражение::Бинарный {
                операция: оп,
                левый: Box::new(левый),
                правый: Box::new(правый),
                положение: поз,
            });
        }
        Ok(левый)
    }

    fn разобрать_слагаемое(&mut self) -> Result<Выражение, Ошибка> {
        let mut левый = self.разобрать_множитель()?;
        loop {
            let операция = match &self.текущий.вид {
                ВидТокена::Плюс => БинарнаяОперация::Плюс,
                ВидТокена::Минус => БинарнаяОперация::Минус,
                _ => break,
            };
            let поз = self.положение();
            self.вперёд()?;
            let правый = self.разобрать_множитель()?;
            левый = Выражение::Бинарный {
                операция,
                левый: Box::new(левый),
                правый: Box::new(правый),
                положение: поз,
            };
        }
        Ok(левый)
    }

    fn разобрать_множитель(&mut self) -> Result<Выражение, Ошибка> {
        let mut левый = self.разобрать_унарный()?;
        loop {
            let операция = match &self.текущий.вид {
                ВидТокена::Умножить => БинарнаяОперация::Умножить,
                ВидТокена::Делить => БинарнаяОперация::Делить,
                ВидТокена::Остаток => БинарнаяОперация::Остаток,
                _ => break,
            };
            let поз = self.положение();
            self.вперёд()?;
            let правый = self.разобрать_унарный()?;
            левый = Выражение::Бинарный {
                операция,
                левый: Box::new(левый),
                правый: Box::new(правый),
                положение: поз,
            };
        }
        Ok(левый)
    }

    fn разобрать_унарный(&mut self) -> Result<Выражение, Ошибка> {
        let поз = self.положение();
        match &self.текущий.вид {
            ВидТокена::Минус => {
                self.вперёд()?;
                let значение = Box::new(self.разобрать_унарный()?);
                Ok(Выражение::Унарный {
                    операция: УнарнаяОперация::Минус,
                    значение,
                    положение: поз,
                })
            }
            ВидТокена::Не => {
                self.вперёд()?;
                let значение = Box::new(self.разобрать_унарный()?);
                Ok(Выражение::Унарный {
                    операция: УнарнаяОперация::Не,
                    значение,
                    положение: поз,
                })
            }
            _ => self.разобрать_постфикс(),
        }
    }

    fn разобрать_постфикс(&mut self) -> Result<Выражение, Ошибка> {
        let mut выр = self.разобрать_первичное()?;
        loop {
            match &self.текущий.вид {
                ВидТокена::Точка => {
                    let поз = self.положение();
                    self.вперёд()?;
                    let имя = self.ожидать_идентификатор()?;
                    выр = Выражение::ДоступКЧлену { цель: Box::new(выр), имя, положение: поз };
                }
                ВидТокена::КругСлева => {
                    let поз = self.положение();
                    self.вперёд()?;
                    let mut аргументы = Vec::new();
                    if !self.проверить(&ВидТокена::КругСправа) {
                        аргументы.push(self.разобрать_выражение()?);
                        while self.проверить(&ВидТокена::Запятая) {
                            self.вперёд()?;
                            аргументы.push(self.разобрать_выражение()?);
                        }
                    }
                    self.ожидать(&ВидТокена::КругСправа)?;
                    выр = Выражение::Вызов { цель: Box::new(выр), аргументы, положение: поз };
                }
                _ => break,
            }
        }
        Ok(выр)
    }

    fn разобрать_первичное(&mut self) -> Result<Выражение, Ошибка> {
        let поз = self.положение();
        let токен = self.вперёд()?;
        match токен.вид {
            ВидТокена::ЦелоеЧисло(з) => Ok(Выражение::ЦелоеЧисло(з, поз)),
            ВидТокена::Десятичное(с) => Ok(Выражение::Десятичное(с, поз)),
            ВидТокена::Дробь(ч, з) => Ok(Выражение::Дробь(ч, з, поз)),
            ВидТокена::Строка(с) => Ok(Выражение::Строка(с, поз)),
            ВидТокена::Логическое(л) => Ok(Выражение::Логическое(л, поз)),
            ВидТокена::Пусто => Ok(Выражение::Пусто(поз)),
            ВидТокена::Идентификатор(имя) => Ok(Выражение::Идентификатор(имя, поз)),
            ВидТокена::КругСлева => {
                let выр = self.разобрать_выражение()?;
                self.ожидать(&ВидТокена::КругСправа)?;
                Ok(выр)
            }
            иное => Err(Ошибка::новая(
                поз,
                format!("неожиданный токен {:?} в начале выражения", иное),
            )),
        }
    }
}

