// Проверка типов языка «Дубина» (часть этапа 6 дорожной карты).
//
// Принимает разобранную `аст::Программа` и таблицу привязок имён от
// резолвера (`резолвер::КартаПривязок`). Проходит каждое выражение,
// выводит/проверяет его тип, сообщает несовместимости.
//
// **Что _уже_ проверяется**
//
// - литералы: целые, десятичные, дроби, строки, логические, пусто;
// - арифметика `+ - * / % степень` на (Цел, Цел), (Дес, Дес) и смешанных
//   числовых типах с расширением до Дес;
// - операторы сравнения `== != < > <= >=` — операнды должны иметь
//   совместимые типы, результат — Лог;
// - логические `и`, `или`, унарный `Не` — требуют Лог, возвращают Лог;
// - унарный минус — требует число, возвращает тот же тип;
// - условие `Если`/`Пока` обязано быть Лог;
// - вызов функции: количество аргументов должно совпадать; если у
//   параметра объявлен тип — тип аргумента должен совпадать;
// - присваивание локальной: первое присваивание фиксирует тип;
//   последующие должны ему соответствовать;
// - присваивание параметру: должно соответствовать его объявленному
//   типу (если он есть).
//
// **Что _ещё_ не проверяется (TODO этап-6.3)**
//
// - возвращаемые значения функций (нужна нормальная привязка
//   возвратных параметров в резолвере);
// - доступ к членам объектов (нужны полноценные типы классов);
// - тип возврата встроенных операторов с примитивными классами;
// - вывод типов в стиле Хиндли–Милнера (сейчас простой однопроходный).

#![allow(dead_code)]

use std::collections::HashMap;

use crate::аст;
use crate::ошибки::{Ошибка, Положение};
use crate::резолвер::{КартаПривязок, Привязка, ПутьФункции};

/// Поддерживаемые сейчас типы языка «Дубина».
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Тип {
    /// Целое число произвольной ширины (литералы вида `42`).
    Цел,
    /// Десятичное (литералы `1.5`, дроби `1/2` — тоже Дес).
    Дес,
    /// Строка UTF-8.
    Стр,
    /// Логическое: правда/ложь.
    Лог,
    /// Единичный тип — значение `пусто`.
    Пусто,
    /// «Не знаю»: параметр без аннотации, неинициализированная локальная.
    /// Распространяется по операциям, не порождая дополнительных ошибок.
    Неизвестный,
    /// «Уже сообщено об ошибке здесь» — заглушка, чтобы не плодить каскад.
    Ошибка,
}

impl Тип {
    pub fn как_строку(self) -> &'static str {
        match self {
            Тип::Цел => "Цел",
            Тип::Дес => "Дес",
            Тип::Стр => "Стр",
            Тип::Лог => "Лог",
            Тип::Пусто => "Пусто",
            Тип::Неизвестный => "?",
            Тип::Ошибка => "(ошибка)",
        }
    }

    pub fn числовой(self) -> bool {
        matches!(self, Тип::Цел | Тип::Дес)
    }
}

/// Распознать имя типа из аннотации параметра.
/// Возвращает Неизвестный, если имя нам неизвестно — это даёт
/// возможность пользователю объявить свои типы (классы), которые
/// мы пока не умеем проверять.
fn тип_из_имени(имя: &str) -> Тип {
    match имя {
        "Цел" | "Целое" | "Число" => Тип::Цел,
        "Дес" | "Десятичное" => Тип::Дес,
        "Стр" | "Строка" => Тип::Стр,
        "Лог" | "Логическое" => Тип::Лог,
        "Пусто" => Тип::Пусто,
        _ => Тип::Неизвестный,
    }
}

/// Результат проверки: либо ок, либо список ошибок (с координатами).
pub fn проверить(программа: &аст::Программа, карта: &КартаПривязок) -> Result<(), Vec<Ошибка>> {
    let mut т = Типизатор::новый(программа, карта);
    т.пройти_программу();
    if т.ошибки.is_empty() {
        Ok(())
    } else {
        Err(т.ошибки)
    }
}

/// Тип-контекст одной функции: уже известные типы её локальных переменных.
#[derive(Default)]
struct Локали {
    /// (индекс_локальной → её тип). Заполняется при первом присваивании.
    типы: HashMap<u32, Тип>,
}

struct Типизатор<'и> {
    программа: &'и аст::Программа,
    карта: &'и КартаПривязок,
    ошибки: Vec<Ошибка>,
    /// Локальные типы для каждой функции, по её пути.
    локали_по_функциям: HashMap<ПутьФункции, Локали>,
    /// Стек активных функций.
    активные: Vec<ПутьФункции>,
}

impl<'и> Типизатор<'и> {
    fn новый(программа: &'и аст::Программа, карта: &'и КартаПривязок) -> Self {
        Self {
            программа,
            карта,
            ошибки: Vec::new(),
            локали_по_функциям: HashMap::new(),
            активные: Vec::new(),
        }
    }

    fn пройти_программу(&mut self) {
        for (индекс, объявление) in self.программа.объявления.iter().enumerate() {
            match объявление {
                аст::ОбъявлениеВерхнегоУровня::Функция(ф) => {
                    self.пройти_функцию(ф, ПутьФункции::Свободная(индекс));
                }
                аст::ОбъявлениеВерхнегоУровня::Класс(к) => {
                    for (i_метода, метод) in к.члены.iter().enumerate() {
                        self.пройти_функцию(
                            метод,
                            ПутьФункции::Метод { класс: индекс, метод: i_метода },
                        );
                    }
                }
                аст::ОбъявлениеВерхнегоУровня::Использование(_) => {}
                аст::ОбъявлениеВерхнегоУровня::Выражение(в) => {
                    let _ = self.вывести(в);
                }
            }
        }
    }

    fn пройти_функцию(&mut self, ф: &аст::ОбъявлениеФункции, путь: ПутьФункции) {
        self.локали_по_функциям.entry(путь).or_default();
        self.активные.push(путь);
        for выражение in &ф.тело {
            let _ = self.вывести(выражение);
        }
        self.активные.pop();
    }

    /// Пытается определить тип выражения. Если возникает ошибка — фиксирует её
    /// в `self.ошибки` и возвращает `Тип::Ошибка` (чтобы не накрутить каскад).
    fn вывести(&mut self, в: &аст::Выражение) -> Тип {
        match в {
            аст::Выражение::ЦелоеЧисло(_, _) => Тип::Цел,
            аст::Выражение::Десятичное(_, _) => Тип::Дес,
            аст::Выражение::Дробь(_, _, _) => Тип::Дес,
            аст::Выражение::Строка(_, _) => Тип::Стр,
            аст::Выражение::Логическое(_, _) => Тип::Лог,
            аст::Выражение::Пусто(_) => Тип::Пусто,
            аст::Выражение::Идентификатор(_имя, положение) => self.тип_по_привязке(*положение),
            аст::Выражение::Бинарный { операция, левый, правый, положение } => {
                let лв = self.вывести(левый);
                let пр = self.вывести(правый);
                self.тип_бинарного(*операция, лв, пр, *положение)
            }
            аст::Выражение::Унарный { операция, значение, положение } => {
                let т = self.вывести(значение);
                self.тип_унарного(*операция, т, *положение)
            }
            аст::Выражение::Вызов { цель, аргументы, положение } => {
                self.тип_вызова(цель, аргументы, *положение)
            }
            аст::Выражение::ДоступКЧлену { цель, .. } => {
                let _ = self.вывести(цель);
                // TODO(этап-6.3): полноценные типы классов.
                Тип::Неизвестный
            }
            аст::Выражение::Присваивание { цель, значение, положение } => {
                let т_зн = self.вывести(значение);
                self.обработать_присваивание(цель, т_зн, *положение);
                т_зн
            }
            аст::Выражение::Если { условие, тогда, иначе, .. } => {
                let т = self.вывести(условие);
                self.требовать(т, Тип::Лог, "условие «Если»", позицию(условие));
                for в in тогда {
                    let _ = self.вывести(в);
                }
                for в in иначе {
                    let _ = self.вывести(в);
                }
                Тип::Пусто
            }
            аст::Выражение::Пока { условие, тело, .. } => {
                let т = self.вывести(условие);
                self.требовать(т, Тип::Лог, "условие «Пока»", позицию(условие));
                for в in тело {
                    let _ = self.вывести(в);
                }
                Тип::Пусто
            }
            аст::Выражение::Цикл { диапазон, тело, .. } => {
                if let Some(д) = диапазон {
                    let т = self.вывести(д);
                    if !matches!(т, Тип::Цел | Тип::Дес | Тип::Неизвестный | Тип::Ошибка) {
                        self.ошибка(
                            позицию(д),
                            format!(
                                "диапазон цикла должен быть числовым, а у выражения тип {}",
                                т.как_строку()
                            ),
                        );
                    }
                }
                for в in тело {
                    let _ = self.вывести(в);
                }
                Тип::Пусто
            }
            аст::Выражение::Вернуть { значения, .. } => {
                for з in значения {
                    let _ = self.вывести(з);
                }
                // TODO(этап-6.3): сравнить с возвратными параметрами функции.
                Тип::Пусто
            }
            аст::Выражение::Прервать(_) | аст::Выражение::Продолжить(_) => Тип::Пусто,
        }
    }

    fn тип_бинарного(
        &mut self,
        операция: аст::БинарнаяОперация,
        лв: Тип,
        пр: Тип,
        положение: Положение,
    ) -> Тип {
        use аст::БинарнаяОперация as Б;
        match операция {
            Б::Плюс | Б::Минус | Б::Умножить | Б::Делить | Б::Остаток | Б::Степень => {
                self.числовая_операция(операция, лв, пр, положение)
            }
            Б::Равно | Б::НеРавно => {
                self.сравнимы(лв, пр, положение, "==/!=");
                Тип::Лог
            }
            Б::Меньше | Б::Больше | Б::МеньшеРавно | Б::БольшеРавно => {
                self.числовое_сравнение(лв, пр, положение);
                Тип::Лог
            }
            Б::И | Б::Или => {
                self.требовать(лв, Тип::Лог, "оператор «и»/«или»", положение);
                self.требовать(пр, Тип::Лог, "оператор «и»/«или»", положение);
                Тип::Лог
            }
        }
    }

    fn числовая_операция(
        &mut self,
        _операция: аст::БинарнаяОперация,
        лв: Тип,
        пр: Тип,
        положение: Положение,
    ) -> Тип {
        if matches!(лв, Тип::Ошибка) || matches!(пр, Тип::Ошибка) {
            return Тип::Ошибка;
        }
        if matches!(лв, Тип::Неизвестный) || matches!(пр, Тип::Неизвестный) {
            // Дать самой инициативной стороне протолкнуть тип.
            return if лв.числовой() {
                лв
            } else if пр.числовой() {
                пр
            } else {
                Тип::Неизвестный
            };
        }
        if !лв.числовой() {
            self.ошибка(
                положение,
                format!(
                    "арифметика требует числовой левый операнд, а получили {}",
                    лв.как_строку()
                ),
            );
            return Тип::Ошибка;
        }
        if !пр.числовой() {
            self.ошибка(
                положение,
                format!(
                    "арифметика требует числовой правый операнд, а получили {}",
                    пр.как_строку()
                ),
            );
            return Тип::Ошибка;
        }
        // Цел + Дес → Дес.
        if matches!(лв, Тип::Дес) || matches!(пр, Тип::Дес) {
            Тип::Дес
        } else {
            Тип::Цел
        }
    }

    fn сравнимы(&mut self, лв: Тип, пр: Тип, положение: Положение, что: &str) {
        if matches!(лв, Тип::Ошибка | Тип::Неизвестный)
            || matches!(пр, Тип::Ошибка | Тип::Неизвестный)
        {
            return;
        }
        // Допустим Цел/Дес сравнения между собой как «числовые равны».
        let оба_числовые = лв.числовой() && пр.числовой();
        if лв != пр && !оба_числовые {
            self.ошибка(
                положение,
                format!(
                    "несовместимые типы для {}: {} и {}",
                    что,
                    лв.как_строку(),
                    пр.как_строку()
                ),
            );
        }
    }

    fn числовое_сравнение(&mut self, лв: Тип, пр: Тип, положение: Положение) {
        if matches!(лв, Тип::Ошибка | Тип::Неизвестный)
            || matches!(пр, Тип::Ошибка | Тип::Неизвестный)
        {
            return;
        }
        if !лв.числовой() || !пр.числовой() {
            self.ошибка(
                положение,
                format!(
                    "сравнение требует числовых операндов, а получили {} и {}",
                    лв.как_строку(),
                    пр.как_строку()
                ),
            );
        }
    }

    fn тип_унарного(
        &mut self,
        операция: аст::УнарнаяОперация,
        т: Тип,
        положение: Положение,
    ) -> Тип {
        use аст::УнарнаяОперация as У;
        match операция {
            У::Минус => {
                if matches!(т, Тип::Ошибка | Тип::Неизвестный) {
                    return т;
                }
                if !т.числовой() {
                    self.ошибка(
                        положение,
                        format!(
                            "унарный минус требует числовой операнд, а получили {}",
                            т.как_строку()
                        ),
                    );
                    return Тип::Ошибка;
                }
                т
            }
            У::Не => {
                self.требовать(т, Тип::Лог, "оператор «Не»", положение);
                Тип::Лог
            }
        }
    }

    fn тип_по_привязке(&mut self, положение: Положение) -> Тип {
        let Some(привязка) = self.карта.привязка(положение) else {
            return Тип::Ошибка;
        };
        match привязка {
            Привязка::Параметр { функция, индекс } => {
                self.тип_параметра(функция, индекс)
            }
            Привязка::Локальная { функция, индекс } => self
                .локали_по_функциям
                .get(&функция)
                .and_then(|л| л.типы.get(&индекс).copied())
                .unwrap_or(Тип::Неизвестный),
            Привязка::Функция(_) | Привязка::Класс(_) => {
                // Использование функции/класса как значения — пока не поддерживаем.
                // Отчёт об ошибке делать не будем: возможно, дальше есть Вызов.
                Тип::Неизвестный
            }
        }
    }

    fn тип_параметра(&self, функция: ПутьФункции, индекс: u32) -> Тип {
        let ф = self.функция_по_пути(функция);
        match ф {
            Some(ф) => {
                let п = ф.параметры.get(индекс as usize);
                match п.and_then(|п| п.тип.as_deref()) {
                    Some(имя) => тип_из_имени(имя),
                    None => Тип::Неизвестный,
                }
            }
            None => Тип::Ошибка,
        }
    }

    fn функция_по_пути(&self, путь: ПутьФункции) -> Option<&'и аст::ОбъявлениеФункции> {
        match путь {
            ПутьФункции::Свободная(i) => match self.программа.объявления.get(i) {
                Some(аст::ОбъявлениеВерхнегоУровня::Функция(ф)) => Some(ф),
                _ => None,
            },
            ПутьФункции::Метод { класс, метод } => match self.программа.объявления.get(класс) {
                Some(аст::ОбъявлениеВерхнегоУровня::Класс(к)) => к.члены.get(метод),
                _ => None,
            },
        }
    }

    fn тип_вызова(
        &mut self,
        цель: &аст::Выражение,
        аргументы: &[аст::Выражение],
        положение: Положение,
    ) -> Тип {
        // Тип-тип-тип.
        let привязка = if let аст::Выражение::Идентификатор(_, поз) = цель {
            self.карта.привязка(*поз)
        } else {
            None
        };

        // Сначала проверим типы аргументов всегда, чтобы дать ошибки внутри.
        let типы_аргументов: Vec<Тип> = аргументы.iter().map(|а| self.вывести(а)).collect();

        let Some(Привязка::Функция(индекс)) = привязка else {
            // Возможно, это вызов метода или динамической функции — в эту версию
            // мы это не проверяем, просто возвращаем Неизвестный.
            // Также сюда попадают вызовы, цель которых — не идентификатор.
            let _ = self.вывести(цель);
            return Тип::Неизвестный;
        };
        let Some(аст::ОбъявлениеВерхнегоУровня::Функция(ф)) = self.программа.объявления.get(индекс)
        else {
            return Тип::Ошибка;
        };

        if аргументы.len() != ф.параметры.len() {
            self.ошибка(
                положение,
                format!(
                    "функция «{}» ожидает {} аргументов, передано {}",
                    ф.имя,
                    ф.параметры.len(),
                    аргументы.len()
                ),
            );
            return Тип::Ошибка;
        }
        for (i, (т_арг, парам)) in типы_аргументов.iter().zip(ф.параметры.iter()).enumerate() {
            let ожид = парам.тип.as_deref().map(тип_из_имени).unwrap_or(Тип::Неизвестный);
            self.требовать_совместим(
                *т_арг,
                ожид,
                &format!("аргумент {} функции «{}»", i + 1, ф.имя),
                позицию(&аргументы[i]),
            );
        }

        // Тип результата: если у функции один возврат с типом — он. Иначе Пусто.
        if ф.возвращаемые.len() == 1 {
            ф.возвращаемые[0]
                .тип
                .as_deref()
                .map(тип_из_имени)
                .unwrap_or(Тип::Неизвестный)
        } else if ф.возвращаемые.is_empty() {
            Тип::Пусто
        } else {
            Тип::Неизвестный
        }
    }

    fn обработать_присваивание(
        &mut self,
        цель: &аст::Выражение,
        т_зн: Тип,
        положение_равно: Положение,
    ) {
        let аст::Выражение::Идентификатор(_, положение) = цель else {
            // x.y = ..., a[i] = ... — пропускаем (нужна типизация классов/массивов).
            let _ = self.вывести(цель);
            return;
        };
        let Some(привязка) = self.карта.привязка(*положение) else {
            return;
        };
        match привязка {
            Привязка::Локальная { функция, индекс } => {
                let локали = self.локали_по_функциям.entry(функция).or_default();
                if let Some(старый) = локали.типы.get(&индекс).copied() {
                    self.требовать_совместим(
                        т_зн,
                        старый,
                        "присваивание локальной",
                        положение_равно,
                    );
                } else {
                    локали.типы.insert(индекс, т_зн);
                }
            }
            Привязка::Параметр { функция, индекс } => {
                let ожид = self.тип_параметра(функция, индекс);
                self.требовать_совместим(
                    т_зн,
                    ожид,
                    "присваивание параметру",
                    положение_равно,
                );
            }
            Привязка::Функция(_) | Привязка::Класс(_) => {
                self.ошибка(
                    *положение,
                    "нельзя присвоить значение имени функции или класса".to_string(),
                );
            }
        }
    }

    fn требовать(&mut self, дано: Тип, ожид: Тип, что: &str, положение: Положение) {
        if matches!(дано, Тип::Ошибка | Тип::Неизвестный) {
            return;
        }
        if дано != ожид {
            self.ошибка(
                положение,
                format!(
                    "{} требует тип {}, а получили {}",
                    что,
                    ожид.как_строку(),
                    дано.как_строку()
                ),
            );
        }
    }

    fn требовать_совместим(&mut self, дано: Тип, ожид: Тип, что: &str, положение: Положение) {
        if matches!(дано, Тип::Ошибка | Тип::Неизвестный) || matches!(ожид, Тип::Неизвестный) {
            return;
        }
        if дано == ожид {
            return;
        }
        // Цел совместим с Дес (расширение).
        if ожид == Тип::Дес && дано == Тип::Цел {
            return;
        }
        self.ошибка(
            положение,
            format!(
                "{}: ожидали {}, а получили {}",
                что,
                ожид.как_строку(),
                дано.как_строку()
            ),
        );
    }

    fn ошибка(&mut self, положение: Положение, сообщение: String) {
        self.ошибки.push(Ошибка::новая(положение, сообщение));
    }
}

fn позицию(в: &аст::Выражение) -> Положение {
    match в {
        аст::Выражение::Идентификатор(_, п)
        | аст::Выражение::ЦелоеЧисло(_, п)
        | аст::Выражение::Десятичное(_, п)
        | аст::Выражение::Строка(_, п)
        | аст::Выражение::Логическое(_, п)
        | аст::Выражение::Пусто(п)
        | аст::Выражение::Прервать(п)
        | аст::Выражение::Продолжить(п) => *п,
        аст::Выражение::Дробь(_, _, п) => *п,
        аст::Выражение::Бинарный { положение, .. }
        | аст::Выражение::Унарный { положение, .. }
        | аст::Выражение::Вызов { положение, .. }
        | аст::Выражение::ДоступКЧлену { положение, .. }
        | аст::Выражение::Присваивание { положение, .. }
        | аст::Выражение::Если { положение, .. }
        | аст::Выражение::Пока { положение, .. }
        | аст::Выражение::Цикл { положение, .. }
        | аст::Выражение::Вернуть { положение, .. } => *положение,
    }
}

#[cfg(test)]
mod тесты {
    use super::*;
    use crate::парсер::Парсер;
    use crate::резолвер;

    fn проверить_строку(исх: &str) -> Result<(), Vec<Ошибка>> {
        let mut п = Парсер::новый(исх);
        let программа = п.разобрать_программу().expect("парсер ок");
        let карта = резолвер::проанализировать(&программа).expect("резолвер ок");
        проверить(&программа, &карта)
    }

    #[test]
    fn пустая_программа() {
        проверить_строку("").unwrap();
    }

    #[test]
    fn целая_арифметика() {
        проверить_строку("main()(р):\nр = 1 + 2\n;").unwrap();
    }

    #[test]
    fn смешанная_арифметика_цел_дес() {
        // Дес имеет приоритет.
        проверить_строку("main()(р):\nр = 1 + 1.5\n;").unwrap();
    }

    #[test]
    fn строка_плюс_число_ошибка() {
        let ошибки = проверить_строку("main()(р):\nр = \"эй\" + 1\n;").unwrap_err();
        assert!(ошибки.iter().any(|е| е.сообщение.contains("числовой левый операнд")));
    }

    #[test]
    fn сравнение_возвращает_лог() {
        проверить_строку(
            "main()(р):\n\
             р = 1 < 2\n\
             ;",
        )
        .unwrap();
    }

    #[test]
    fn если_требует_лог() {
        let ошибки = проверить_строку(
            "main()(р):\n\
             Если 1:\n\
             р = 1\n\
             ;\n\
             ;",
        )
        .unwrap_err();
        assert!(ошибки.iter().any(|е| е.сообщение.contains("«Если» требует тип Лог")));
    }

    #[test]
    fn пока_требует_лог() {
        let ошибки = проверить_строку(
            "main()(р):\n\
             пока \"эй\":\n\
             р = 1\n\
             ;\n\
             ;",
        )
        .unwrap_err();
        assert!(ошибки.iter().any(|е| е.сообщение.contains("«Пока» требует тип Лог")));
    }

    #[test]
    fn повторное_присваивание_другого_типа_ошибка() {
        let ошибки = проверить_строку(
            "main()(р):\n\
             х = 1\n\
             х = \"эй\"\n\
             р = х\n\
             ;",
        )
        .unwrap_err();
        assert!(ошибки.iter().any(|е| е.сообщение.contains("присваивание локальной")));
    }

    #[test]
    fn вызов_с_правильным_количеством_ок() {
        проверить_строку(
            "удвоить(Цел а)(Цел р):\n\
             р = а + а\n\
             ;\n\
             main()(Цел р):\n\
             р = удвоить(2)\n\
             ;",
        )
        .unwrap();
    }

    #[test]
    fn вызов_с_неверным_количеством_ошибка() {
        let ошибки = проверить_строку(
            "удвоить(Цел а)(Цел р):\n\
             р = а + а\n\
             ;\n\
             main()(Цел р):\n\
             р = удвоить(2, 3)\n\
             ;",
        )
        .unwrap_err();
        assert!(ошибки.iter().any(|е| е.сообщение.contains("ожидает 1 аргументов, передано 2")));
    }

    #[test]
    fn вызов_с_неверным_типом_аргумента_ошибка() {
        let ошибки = проверить_строку(
            "удвоить(Цел а)(Цел р):\n\
             р = а + а\n\
             ;\n\
             main()(Цел р):\n\
             р = удвоить(\"эй\")\n\
             ;",
        )
        .unwrap_err();
        assert!(ошибки.iter().any(|е| {
            е.сообщение.contains("аргумент 1") && е.сообщение.contains("ожидали Цел")
        }));
    }

    #[test]
    fn возврат_типа_функции_прокидывается_в_вызов() {
        let ошибки = проверить_строку(
            "вернуть_строку()(Стр р):\n\
             р = \"эй\"\n\
             ;\n\
             main()(Цел итог):\n\
             у = вернуть_строку()\n\
             итог = у + 1\n\
             ;",
        )
        .unwrap_err();
        assert!(ошибки.iter().any(|е| е.сообщение.contains("числовой левый операнд")));
    }

    #[test]
    fn логические_операции_ок() {
        проверить_строку(
            "main()(Лог р):\n\
             р = да и нет или 1 < 2\n\
             ;",
        )
        .unwrap();
    }

    #[test]
    fn и_требует_лог() {
        let ошибки = проверить_строку(
            "main()(Лог р):\n\
             р = 1 и 2\n\
             ;",
        )
        .unwrap_err();
        assert!(ошибки.iter().any(|е| е.сообщение.contains("«и»/«или» требует тип Лог")));
    }

    #[test]
    fn унарный_не_требует_лог() {
        let ошибки = проверить_строку(
            "main()(Лог р):\n\
             р = не 1\n\
             ;",
        )
        .unwrap_err();
        assert!(ошибки.iter().any(|е| е.сообщение.contains("«Не» требует тип Лог")));
    }

    #[test]
    fn неаннотированный_параметр_не_шумит() {
        // Параметр без типа = Неизвестный, любая операция допустима, ошибок быть не должно.
        проверить_строку(
            "f(а)(р):\n\
             р = а + 1\n\
             ;",
        )
        .unwrap();
    }
}
