// Реализация динамического целого `Число`. В этом файле — модель в памяти и арифметика.
//
// # Семантика
//
// Тип `Число` хранит беззнаковое целое число произвольной величины. В памяти оно
// занимает столько бит, сколько нужно для текущего значения, округлённое до степени
// двойки (1, 2, 4, 8, 16, 32, 64). Для значений > 64 бит используется куча.
//
// В первой реализации мы оптимизируем под малые значения: ёмкость хранится в одном
// поле, само значение — в u64 (для значений ≤ 64 бит) или в `alloc::vec::Vec<u64>` для
// произвольной точности.
//
// Когда в будущем компилятор сможет статически вывести максимальную ширину переменной,
// он будет генерировать код с фиксированной шириной без накладных расходов рантайма.

use core::cmp::Ordering;
use core::fmt;

/// Динамическое целое число с автоматическим расширением битности.
#[derive(Clone)]
pub struct Число {
    /// log2 ёмкости, округлённой до степени двойки. Например, для значения 4 (нужно 3 бита)
    /// ёмкость = 4 = 2², показатель = 2.
    показатель: u8,
    /// Текущее значение. Для значений до 64 бит — само число; для больших —
    /// смещение в куче (TODO в будущей версии).
    значение: u64,
}

impl Число {
    /// Создаёт новое `Число` со значением 0 и минимальной ёмкостью.
    #[inline]
    pub const fn ноль() -> Self {
        Self { показатель: 0, значение: 0 }
    }

    /// Создаёт `Число` из `u64`. Ёмкость подбирается автоматически как наименьшая степень
    /// двойки, помещающая значение.
    pub fn из_u64(значение: u64) -> Self {
        let показатель = вычислить_показатель(значение);
        Self { показатель, значение }
    }

    /// Возвращает текущее значение (только для значений до 64 бит).
    #[inline]
    pub fn в_u64(&self) -> u64 {
        self.значение
    }

    /// Возвращает количество бит, фактически выделенных под значение.
    /// Соответствует `2^показатель`. Минимум 1 бит.
    #[inline]
    pub fn ширина_в_битах(&self) -> u32 {
        1u32 << self.показатель as u32
    }

    /// Размер заголовка в битах (всегда 6 — хватает на показатель 0..63).
    pub const РАЗМЕР_ЗАГОЛОВКА: u32 = 6;

    /// Полный размер в битах — заголовок плюс значение.
    pub fn полный_размер_в_битах(&self) -> u32 {
        Self::РАЗМЕР_ЗАГОЛОВКА + self.ширина_в_битах()
    }

    /// Складывает два числа, при необходимости расширяя ёмкость.
    pub fn плюс(&self, другое: &Число) -> Число {
        let сумма = self.значение.wrapping_add(другое.значение);
        // Проверяем переполнение
        let было_переполнение = сумма < self.значение;
        if было_переполнение {
            // Строго говоря, для значений > 2^63 нужен bigint. В первой версии — паника.
            panic!("переполнение Число при сложении (>2^64), bigint ещё не реализован");
        }
        Число::из_u64(сумма)
    }

    /// Вычитание (если результат отрицателен — паника).
    pub fn минус(&self, другое: &Число) -> Число {
        if self.значение < другое.значение {
            panic!("вычитание привело к отрицательному результату; используйте знаковый тип");
        }
        Число::из_u64(self.значение - другое.значение)
    }

    /// Умножение.
    pub fn умножить(&self, другое: &Число) -> Число {
        let (произведение, переполнение) = self.значение.overflowing_mul(другое.значение);
        if переполнение {
            panic!("переполнение Число при умножении, bigint ещё не реализован");
        }
        Число::из_u64(произведение)
    }
}

impl PartialEq for Число {
    fn eq(&self, другое: &Self) -> bool {
        self.значение == другое.значение
    }
}
impl Eq for Число {}

impl PartialOrd for Число {
    fn partial_cmp(&self, другое: &Self) -> Option<Ordering> {
        Some(self.cmp(другое))
    }
}

impl Ord for Число {
    fn cmp(&self, другое: &Self) -> Ordering {
        self.значение.cmp(&другое.значение)
    }
}

impl fmt::Debug for Число {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(
            f,
            "Число({} | {} бит ёмкости, {} бит всего)",
            self.значение,
            self.ширина_в_битах(),
            self.полный_размер_в_битах()
        )
    }
}

impl fmt::Display for Число {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}", self.значение)
    }
}

/// Вычисляет показатель ёмкости для значения: наименьшее `k` такое что значение ≤ 2^(2^k) - 1.
///
/// Иными словами, для значения `v`:
///   - 0..=1   → k=0  (1 бит)
///   - 2..=3   → k=1  (2 бита)
///   - 4..=15  → k=2  (4 бита)  -- по запросу пользователя «4 → 2²»
///   - 16..=255 → k=3 (8 бит)
///   - 256..=65535 → k=4 (16 бит)
///   - и т.д.
pub fn вычислить_показатель(значение: u64) -> u8 {
    if значение <= 1 {
        return 0;
    }
    // Количество бит, нужное для значения = 64 - leading_zeros
    let нужно_бит = 64 - значение.leading_zeros();
    // Округляем до ближайшей степени двойки: 1,2,4,8,16,32,64
    let мощность = округлить_до_степени_двойки(нужно_бит);
    log2(мощность) as u8
}

/// Округляет вверх до ближайшей степени двойки (1, 2, 4, 8, 16, 32, 64).
fn округлить_до_степени_двойки(мин_бит: u32) -> u32 {
    if мин_бит <= 1 { return 1; }
    if мин_бит <= 2 { return 2; }
    if мин_бит <= 4 { return 4; }
    if мин_бит <= 8 { return 8; }
    if мин_бит <= 16 { return 16; }
    if мин_бит <= 32 { return 32; }
    64
}

fn log2(значение: u32) -> u32 {
    31 - значение.leading_zeros()
}

#[cfg(test)]
mod тесты {
    use super::*;

    #[test]
    fn проверка_показателя() {
        // По спецификации:
        //   значение 0 → ёмкость 2^0 = 1
        //   значение 4 → ёмкость 2^2 = 4
        //   значение 15 → ёмкость 2^4 = 16
        //   значение 100 → ёмкость 2^7 = 128
        assert_eq!(вычислить_показатель(0), 0);
        assert_eq!(вычислить_показатель(1), 0);
        assert_eq!(вычислить_показатель(2), 1);
        assert_eq!(вычислить_показатель(3), 1);
        assert_eq!(вычислить_показатель(4), 2);
        assert_eq!(вычислить_показатель(15), 2);
        assert_eq!(вычислить_показатель(16), 3);
        assert_eq!(вычислить_показатель(255), 3);
        assert_eq!(вычислить_показатель(256), 4);
        assert_eq!(вычислить_показатель(65535), 4);
        assert_eq!(вычислить_показатель(65536), 5);
    }

    #[test]
    fn ширина_в_битах() {
        assert_eq!(Число::из_u64(0).ширина_в_битах(), 1);
        assert_eq!(Число::из_u64(4).ширина_в_битах(), 4);
        assert_eq!(Число::из_u64(15).ширина_в_битах(), 4);
        assert_eq!(Число::из_u64(16).ширина_в_битах(), 8);
        assert_eq!(Число::из_u64(100).ширина_в_битах(), 8);
        assert_eq!(Число::из_u64(70_000).ширина_в_битах(), 32);
    }

    #[test]
    fn арифметика() {
        let а = Число::из_u64(5);
        let б = Число::из_u64(7);
        assert_eq!(а.плюс(&б).в_u64(), 12);
        assert_eq!(б.минус(&а).в_u64(), 2);
        assert_eq!(а.умножить(&б).в_u64(), 35);
    }
}
